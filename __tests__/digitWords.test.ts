import { describe, it, expect } from "vitest";
import { digitStreamOf } from "@/lib/vehicleTypeScan";

/**
 * 🔴 **كوهير بيكتب خانات اللوحة بصيغة عشرات ومثنى وجمع.**
 *
 * من جلسة شيت الأنواع (١٦ سبتمبر ٢٠٢٦، ٨٦ لوحة): **٢٤ من ٣١ فشل** سببهم
 * إن أرقام اللوحة **مش موجودة** في تيار الأرقام، فالقصّ بيفشل والخانة
 * بترجع فاضية (fail-closed). والموديل كان **سامع** الكلمة صح.
 *
 * تلات صيغ كانت بتتشال بالسكوت:
 *   ١) العشرات  — «ستين» «اربعين» «حداشر»   (`isUnit=false` ⇒ اترمت)
 *   ٢) المثنى   — «خمسيتين» «تمانيتين»       (مش في القاموس خالص)
 *   ٣) الجمع بعدّاد — «تلات سبعات»           (مش في القاموس خالص)
 */
describe("خانات اللوحة المنطوقة", () => {
  it("١) العشرات = خانتين", () => {
    expect(digitStreamOf("تمانية اتنين ستين")).toBe("8260");   // درد8260
    expect(digitStreamOf("خمسة اتنين اربعين")).toBe("5240");   // كحق5240
    expect(digitStreamOf("زيرو تمانية حداشر")).toBe("0811");   // عور0811
    expect(digitStreamOf("تسعين سبعة تمانية")).toBe("9078");   // وعن9078
    expect(digitStreamOf("ستة سبعة خمسين")).toBe("6750");      // صقك6750
  });

  it("٢) المثنى = الخانة مرتين", () => {
    expect(digitStreamOf("تلاتة اربعة خمسيتين")).toBe("3455");  // عيو3455
    expect(digitStreamOf("تمانيتين سبعين")).toBe("8870");       // يهم8870
    expect(digitStreamOf("واحد تمانية تسعتين")).toBe("1899");   // ودح1899
  });

  it("٣) الجمع بعدّاد = الخانة × العدّاد", () => {
    expect(digitStreamOf("تلات سبعات اربعة")).toBe("7774");     // وطح7774
    expect(digitStreamOf("اربع تلاتات")).toBe("3333");          // شكوى المالك القديمة
  });

  it("🛡️ ماتكسرش اللي كان شغّال", () => {
    expect(digitStreamOf("ستة تسعة اتنين اربعة")).toBe("6924");
    expect(digitStreamOf("واحد خمسة تمانية تلاتة")).toBe("1583");
    expect(digitStreamOf("اتنين تنين")).toBe("22");            // «اتنين» مش مثنى
    expect(digitStreamOf("تلاتين")).toBe("30");                // ٣٠ مش ٣٣
    expect(digitStreamOf("ستين")).toBe("60");                  // ٦٠ مش ٦٦
    expect(digitStreamOf("مرات ساعات ستات")).toBe("");         // جمع بلا عدّاد = مش أرقام
    expect(digitStreamOf("ونيت مصدومه جراج")).toBe("");
  });
});
