import { describe, it, expect } from "vitest";
import { sameCarTwin, EXACT_REPEAT_MS } from "@/lib/trialTwin";

/**
 * 🔴 **بلاغ المالك (٢٣ سبتمبر ٢٠٢٦): «بيكتب اللوحة مرتين».**
 *
 * لقطات الشاشة: `رره6232` **٣ مرات** ورا بعض · `ردق8637` ٣ · `رطص9784` ٣ ·
 * `رحج2976` ٣ · `رعب8713` مرتين — كلها **نفس اللوحة بالحرف**.
 *
 * السبب: لمّ التوائم بيشتغل بنافذة **١٢ ثانية**. الحد ده اتحط للتوائم
 * **المسخّمة** (`دطس2112` / `دطس2177`) عشان مايلمّش لوحتين حقيقيتين
 * متشابهتين. لكن لما اللوحة **نفسها بالحرف** بتتكرّر بعد ١٢ث — مثلاً
 * المندوب بيعدّي على نفس العربية تاني أو الإجماع اتأخّر — بتطلع صف جديد.
 *
 * ⇒ **لوحتين متطابقتين حرف بحرف في نفس الجلسة = نفس العربية.** مستحيل
 *   عربيتين مختلفتين بنفس اللوحة، فالنافذة هنا تبقى أوسع بكتير.
 *   والتوأم المسخّم بيفضل على ١٢ث زي ما هو (الحد ده مقيس على ورقة المالك).
 */
describe("اللوحة المتطابقة حرف بحرف", () => {
  const A = { plate: "رره6232", atMs: 10_000 };

  it("🔴 نفس اللوحة بعد ٣٠ ثانية = نفس العربية", () => {
    expect(sameCarTwin(A, { plate: "رره6232", atMs: 40_000 }, 12_000)).toBe(true);
  });

  it("ونفس اللوحة بعد دقيقة كمان", () => {
    expect(sameCarTwin(A, { plate: "رره6232", atMs: 10_000 + EXACT_REPEAT_MS - 1 }, 12_000)).toBe(true);
  });

  it("بس مش بعد المدة كلها — جلسة طويلة ممكن تعدّي على نفس العربية تاني", () => {
    expect(sameCarTwin(A, { plate: "رره6232", atMs: 10_000 + EXACT_REPEAT_MS + 1 }, 12_000)).toBe(false);
  });

  it("🔒 التوأم **المسخّم** لسه على ١٢ث — الحد المقيس ماتغيّرش", () => {
    expect(sameCarTwin(A, { plate: "رره6212", atMs: 21_000 }, 12_000)).toBe(true);
    expect(sameCarTwin(A, { plate: "رره6212", atMs: 40_000 }, 12_000)).toBe(false);
  });

  it("🔒 ولوحتين حقيقيتين مختلفتين مابيتلمّوش مهما قرّبوا", () => {
    // من ورقة المالك: فرق ٣ أرقام = عربيتين
    expect(sameCarTwin({ plate: "رقب7499", atMs: 0 }, { plate: "رقب7218", atMs: 500 }, 12_000)).toBe(false);
  });
});
