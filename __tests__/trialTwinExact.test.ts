import { describe, it, expect } from "vitest";
import { sameCarTwin, sameUtterance, SAME_UTTERANCE_MS } from "@/lib/trialTwin";

/**
 * 🔴 **بلاغ المالك (٢٣ سبتمبر ٢٠٢٦): «بيكتب اللوحة مرتين».**
 * `رره6232` ٣ صفوف · `ردق8637` ٣ · `رطص9784` ٣ — كلها نفس اللوحة بالحرف.
 *
 * أول إصلاح كان **حد زمني** (المتطابقة تتلمّ خلال دقيقتين).
 *
 * ⚠️ **والحد ده اتكذّب في نفس اليوم**: في جلسة الـ٥٠ لوحة المالك قال
 * `دمس5284` **مرتين بينهم ٤ لوحات تانية** — وطلعت **مرة واحدة**. يعني
 * الحد الزمني كان بيلمّ إعادات مقصودة.
 *
 * ⇒ القرار اتنقل لقاعدة **الفاصل**: المتطابقة تتلمّ بس لو هي **آخر صف**
 *   (`isExactRepeatOfLatest`، في `exactRepeatGap.test.ts`). والدالة دي
 *   بقى دورها التوائم **المسخّمة** بس + حارس زمني صغير للمتطابقة.
 */
describe("لمّ التوائم", () => {
  const A = { plate: "رره6232", atMs: 10_000 };

  it("نفس اللوحة في نفس النطقة (نافذتين متتاليتين) بتتلمّ", () => {
    expect(sameCarTwin(A, { plate: "رره6232", atMs: 11_500 }, 12_000)).toBe(true);
  });

  it("🔴 ونفس اللوحة بعد وقت طويل **مابتتلمّش هنا** — القرار عند الفاصل", () => {
    expect(sameCarTwin(A, { plate: "رره6232", atMs: 40_000 }, 12_000)).toBe(false);
  });

  it("🔒 التوأم المسخّم على ١٢ث — الحد المقيس ماتغيّرش", () => {
    expect(sameCarTwin(A, { plate: "رره6212", atMs: 21_000 }, 12_000)).toBe(true);
    expect(sameCarTwin(A, { plate: "رره6212", atMs: 40_000 }, 12_000)).toBe(false);
  });

  it("🔒 ولوحتين حقيقيتين مختلفتين مابيتلمّوش مهما قرّبوا", () => {
    expect(sameCarTwin({ plate: "رقب7499", atMs: 0 }, { plate: "رقب7218", atMs: 500 }, 12_000)).toBe(false);
  });
});

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🔴 القراية المتأخّرة (بعد وقعة الشبكة) مابتطلعش صف مكرّر
 * ══════════════════════════════════════════════════════════════════════
 *  إعادة إرسال النوافذ الفايتة (`lib/voicexReplay.ts`) بتجيب قرايات **متأخّرة
 *  بـ٢٠+ ثانية** بس بزمن صوتها الأصلي. ولو اللوحة كانت ظهرت خلاص من نافذة
 *  نجحت وقت الوقعة، قاعدة `isExactRepeatNearby` بتبص على **أول ٣ صفوف بالمكان**
 *  — واللوحة دي بقت تحت ⇒ كانت هتتحسب «إعادة مقصودة» ⇒ **صف مكرّر**.
 *
 *  ⇒ نفس اللوحة بالحرف **وزمن صوتها قريب** (≤٥ث) = **نفس النطقة**، مهما كان
 *    مكانها في الجدول.
 *
 *  ⚠️ **وليه ده مايبلعش الإعادة المقصودة**: نطقتين منفصلتين لنفس اللوحة
 *     مستحيل يتداخلوا في الصوت. الإعادة اللي المالك قالها (`دمس5284`) كان
 *     بينها ٤ لوحات ⇒ ١٠+ ثواني.
 */
describe("sameUtterance — نفس النطقة بزمن الصوت", () => {
  it("🔴 نفس اللوحة + زمن صوت قريب ⇒ نفس النطقة (القراية المتأخّرة)", () => {
    expect(sameUtterance({ plate: "بهح8083", atMs: 48_500 }, { plate: "بهح8083", atMs: 50_000 })).toBe(true);
  });

  it("⚠️ الإعادة المقصودة (بينها ٤ لوحات ≈ ١٠ث+) ⇒ **مش** نفس النطقة", () => {
    expect(sameUtterance({ plate: "دمس5284", atMs: 10_000 }, { plate: "دمس5284", atMs: 21_000 })).toBe(false);
  });

  it("على الحد بالظبط ⇒ نفس النطقة", () => {
    expect(sameUtterance({ plate: "بهح8083", atMs: 0 }, { plate: "بهح8083", atMs: SAME_UTTERANCE_MS })).toBe(true);
  });

  it("لوحة تانية ⇒ لأ (دي شغلة `sameCarTwin`)", () => {
    expect(sameUtterance({ plate: "بهح8083", atMs: 0 }, { plate: "بهح8084", atMs: 100 })).toBe(false);
  });
});
