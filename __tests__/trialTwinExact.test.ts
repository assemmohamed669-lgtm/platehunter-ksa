import { describe, it, expect } from "vitest";
import { sameCarTwin } from "@/lib/trialTwin";

/**
 * 🔴 **بلاغ المالك (٢٣ سبتمبر ٢٠٢٦): «بيكتب اللوحة مرتين».**
 * `رره6232` ٣ صفوف · `ردق8637` ٣ · `رطص9784` ٣ — كلها نفس اللوحة بالحرف.
 *
 * أول إصلاح كان **حد زمني** (المتطابقة تتلمّ خلال دقيقتين).
 *
 * ⚠️ **والحد ده اتكذّب في نفس اليوم**: في جلسة الـ٥٠ لوحة المالك قال
 * `دمس5284` **مرتين بينهم ٤ لوحات تانية** — وطلعت **مرة واحدة**. يعني
 * الحد الزمني كان بيلمّ إعادات مقصودة.
 *
 * ⇒ القرار اتنقل لقاعدة **الفاصل**: المتطابقة تتلمّ بس لو هي **آخر صف**
 *   (`isExactRepeatOfLatest`، في `exactRepeatGap.test.ts`). والدالة دي
 *   بقى دورها التوائم **المسخّمة** بس + حارس زمني صغير للمتطابقة.
 */
describe("لمّ التوائم", () => {
  const A = { plate: "رره6232", atMs: 10_000 };

  it("نفس اللوحة في نفس النطقة (نافذتين متتاليتين) بتتلمّ", () => {
    expect(sameCarTwin(A, { plate: "رره6232", atMs: 11_500 }, 12_000)).toBe(true);
  });

  it("🔴 ونفس اللوحة بعد وقت طويل **مابتتلمّش هنا** — القرار عند الفاصل", () => {
    expect(sameCarTwin(A, { plate: "رره6232", atMs: 40_000 }, 12_000)).toBe(false);
  });

  it("🔒 التوأم المسخّم على ١٢ث — الحد المقيس ماتغيّرش", () => {
    expect(sameCarTwin(A, { plate: "رره6212", atMs: 21_000 }, 12_000)).toBe(true);
    expect(sameCarTwin(A, { plate: "رره6212", atMs: 40_000 }, 12_000)).toBe(false);
  });

  it("🔒 ولوحتين حقيقيتين مختلفتين مابيتلمّوش مهما قرّبوا", () => {
    expect(sameCarTwin({ plate: "رقب7499", atMs: 0 }, { plate: "رقب7218", atMs: 500 }, 12_000)).toBe(false);
  });
});
