import { describe, it, expect } from "vitest";
import { parseSessionChunk, newSessionState } from "@/lib/sessionParser";

/**
 * Deepgram أحياناً بيقسّم اللوحة الواحدة على رسالتين **ويبعتها بالمقلوب**:
 * الأرقام في رسالة، والحروف في اللي بعدها. المندوب قال اللوحة صح (حروف ثم
 * أرقام) — المحرك هو اللي عكس. مرصود في جلسة المالك ٢٠٢٦/٠٨/٠٢:
 *   رسالة: "9999"  ·  رسالة: "قف نون نون"  ⇒ كان بيطلّع 9999 ناقصة والحروف تضيع.
 *
 * الإصلاح لازم يلمّ الرسالتين ويرتّبهم صح (حروف ثم أرقام) — **بشرط صارم**:
 * يرحّل الأرقام بس لو الرسالة مالهاش حروف خالص (نص لوحة مقطوع، مش لوحة كاملة).
 * أي التباس ⇒ مراجعة، مش تخمين. والأهم: **لوحتين متتاليتين ماينفعش يتلغبطوا**.
 */
function feed(chunks: Array<[string, boolean]>, reverseCarry = true): string[] {
  let st = newSessionState();
  const out: string[] = [];
  for (const [text, final] of chunks) {
    const r = parseSessionChunk(text, st, { final, reverseCarry });
    st = r.state;
    for (const rec of r.records) out.push(rec.plate);
  }
  return out;
}

describe("لوحة معكوسة من Deepgram (أرقام ثم حروف) تتلمّ صح", () => {
  it("«تسعة×٤» ثم «قاف نون نون» ⇒ قنن9999", () => {
    expect(feed([["تسعة تسعة تسعة تسعة", false], ["قاف نون نون", true]])).toEqual(["قنن9999"]);
  });
  it("«9999» رقمي ثم «قاف نون نون» ⇒ قنن9999", () => {
    expect(feed([["9999", false], ["قاف نون نون", true]])).toEqual(["قنن9999"]);
  });
  it("«اتنين اتنين تمانية تمانية» ثم «دال سين كاف» ⇒ دسك2288", () => {
    expect(feed([["اتنين اتنين تمانية تمانية", false], ["دال سين كاف", true]])).toEqual(["دسك2288"]);
  });
});

describe("🔴 حماية: لوحتين متتاليتين ماينفعش يتلغبطوا", () => {
  it("لوحتين كاملتين ورا بعض تفضلوا منفصلين", () => {
    // «دسك2288» كاملة ثم «قنن9999» كاملة — مفيش ترحيل، الاتنين صح.
    expect(feed([["دال سين كاف اتنين اتنين تمانية تمانية", false],
                 ["قاف نون نون تسعة تسعة تسعة تسعة", true]]))
      .toEqual(["دسك2288", "قنن9999"]);
  });
  it("لوحة كاملة (تنتهي بأرقام) ثم لوحة تبدأ بحروف — مفيش خلط", () => {
    // اللوحة الأولى كاملة، مالهاش دعوة بترحيل. التانية عادية.
    expect(feed([["دال سين كاف اتنين اتنين تمانية تمانية قاف نون نون", false],
                 ["تسعة تسعة تسعة تسعة", true]]))
      .toEqual(["دسك2288", "قنن9999"]);
  });
});

describe("ما اتكسرش حاجة — الحالة العادية زي ما هي", () => {
  it("حروف ثم أرقام (الترتيب الطبيعي) ⇒ قنن9999", () => {
    expect(feed([["قاف نون نون", false], ["تسعة تسعة تسعة تسعة", true]])).toEqual(["قنن9999"]);
  });
  it("لوحة كاملة في رسالة واحدة", () => {
    expect(feed([["قاف نون نون تسعة تسعة تسعة تسعة", true]])).toEqual(["قنن9999"]);
  });
  it("حروف مقسومة نص+نص ثم أرقام", () => {
    expect(feed([["قاف نون", false], ["نون تسعة تسعة تسعة تسعة", true]])).toEqual(["قنن9999"]);
  });
});

describe("🔒 عزل التشييك: بدون reverseCarry السلوك زيّه بالحرف", () => {
  it("المعكوس **مايتلمّش** لما الخيار مطفّي (زي التشييك دلوقتي)", () => {
    // بدون reverseCarry، الأرقام المعكوسة بتطلّع لوحة ناقصة زي السلوك القديم —
    // فالتشييك (المناديب) مايتأثرش بالتعديل خالص.
    const out = feed([["تسعة تسعة تسعة تسعة", false], ["قاف نون نون", true]], false);
    expect(out).not.toEqual(["قنن9999"]);   // مالمّهاش = التشييك زيّه
  });
  it("الحالة العادية شغّالة مع/بدون الخيار (مفيش فرق على الطبيعي)", () => {
    const on  = feed([["قاف نون نون", false], ["تسعة تسعة تسعة تسعة", true]], true);
    const off = feed([["قاف نون نون", false], ["تسعة تسعة تسعة تسعة", true]], false);
    expect(on).toEqual(["قنن9999"]);
    expect(off).toEqual(["قنن9999"]);
  });
});
