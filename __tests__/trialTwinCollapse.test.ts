import { describe, it, expect } from "vitest";
import { sameCarTwin } from "../lib/trialTwin";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  لمّ التوائم — لوحة واحدة اتقرت كذا طريقة
 * ══════════════════════════════════════════════════════════════════════
 *  من تقرير المالك التالت: لوحة `دطس2177` (قالها مرة واحدة) طلعت **أربع
 *  صفوف**:
 *      دطس2112 · دطس2121 · دطس2100 · دطس2177
 *  كلها نفس الحروف وفرقها رقمين، وعلى مدى ٩ ثواني — أبعد من نافذة الإجماع
 *  (٢ث) فاتفصلت لعناقيد مستقلة وكل واحدة عدّت لوحدها.
 *
 *  🔴 والحد لازم يفضل **ضيّق**: في نفس الورقة فيه `رقب7499` و`رقب7218` —
 *  **لوحتين حقيقيتين** بنفس الحروف وفرقهم **٣ أرقام**. لو وسّعنا الحد
 *  لتلاتة هنلمّهم غلط ونضيّع لوحة.
 *
 *  ⇒ القاعدة: نفس الحروف + فرق **رقمين على الأكثر** + خلال **١٢ ثانية**.
 *
 *  (١٢ث لأن قراءات `دطس` امتدّت ٩ ثواني فعلاً. والتوسيع آمن على ورقة
 *   المالك: مفحوص إن مافيش فيها أي لوحتين حقيقيتين بنفس الحروف وفرق
 *   ≤ رقمين — أقرب زوج `رقب7499`/`رقب7218` فرقهم ٣.)
 */

describe("sameCarTwin — نفس العربية ولا لوحتين؟", () => {
  const W = 12000;

  it("🔴 قراءات `دطس2177` الأربعة كلها نفس العربية", () => {
    for (const p of ["دطس2112", "دطس2121", "دطس2100"]) {
      expect(sameCarTwin({ plate: p, atMs: 61000 }, { plate: "دطس2177", atMs: 69500 }, W)).toBe(true);
    }
  });

  it("🔴 `رقب7499` و`رقب7218` **لوحتين مختلفتين** — فرقهم ٣ أرقام", () => {
    expect(sameCarTwin({ plate: "رقب7499", atMs: 26000 }, { plate: "رقب7218", atMs: 41000 }, W)).toBe(false);
    // وحتى لو جم في نفس اللحظة
    expect(sameCarTwin({ plate: "رقب7499", atMs: 26000 }, { plate: "رقب7218", atMs: 26500 }, W)).toBe(false);
  });

  it("حرفين مختلفين أو أكتر = عربيتين مهما كانت الأرقام", () => {
    // (حرف واحد مختلف + نفس الأرقام بالظبط = نفس العربية — تحت في describe التاني)
    expect(sameCarTwin({ plate: "دطس2177", atMs: 1000 }, { plate: "بعس2177", atMs: 1500 }, W)).toBe(false);
    expect(sameCarTwin({ plate: "دطس2177", atMs: 1000 }, { plate: "بعق2177", atMs: 1500 }, W)).toBe(false);
  });

  it("نفس اللوحة بالحرف = نفس العربية", () => {
    expect(sameCarTwin({ plate: "دطس2177", atMs: 1000 }, { plate: "دطس2177", atMs: 5000 }, W)).toBe(true);
  });

  it("بعيدة في الزمن = عربيتين حتى لو الأرقام قريبة", () => {
    expect(sameCarTwin({ plate: "دطس2112", atMs: 1000 }, { plate: "دطس2177", atMs: 30000 }, W)).toBe(false);
  });

  it("شكل بايظ مايلمّش حاجة", () => {
    expect(sameCarTwin({ plate: "", atMs: 0 }, { plate: "دطس2177", atMs: 0 }, W)).toBe(false);
    expect(sameCarTwin({ plate: "دطس21", atMs: 0 }, { plate: "دطس2177", atMs: 0 }, W)).toBe(false);
  });
});

describe("sameCarTwin — نفس الأرقام وحرف مختلف", () => {
  const W = 12000;

  it("🔴 `دطس2177` و`بطس2177` نفس العربية (من تقرير المالك الرابع)", () => {
    expect(sameCarTwin({ plate: "دطس2177", atMs: 62000 }, { plate: "بطس2177", atMs: 63500 }, W)).toBe(true);
  });

  it("حرفين مختلفين = عربيتين حتى لو الأرقام واحدة", () => {
    expect(sameCarTwin({ plate: "دطس2177", atMs: 1000 }, { plate: "بعس2177", atMs: 2000 }, W)).toBe(false);
  });

  it("🔴 حرف مختلف **ورقم** مختلف = عربيتين — الحد مشدود عن قصد", () => {
    expect(sameCarTwin({ plate: "دطس2177", atMs: 1000 }, { plate: "بطس2178", atMs: 2000 }, W)).toBe(false);
  });
});
