/**
 * محرك الصوت — العنقود الحيّ.
 *
 * **الباج:** لوحتين بنفس التلات حروف اتنطقوا بسرعة بيتحطّوا في عنقود واحد.
 * التقسيم بيحصل بس لو **كل** مجموعة أرقام ظهرت مرتين+. فلو التانية اتقرت في
 * نافذة واحدة بس، العنقود بيطلّع **لوحة واحدة** والتانية **تضيع خالص** —
 * ولو كانت مطلوبة، المندوب مايعرفش عنها حاجة أصلاً (لا صف ولا صفّارة).
 *
 * الاختبارات دي بتثبّت السلوك الموجود الأول (عشان مانكسرش حماية الأسطول
 * المقيسة)، وبعدين بتغطّي الفجوة.
 */
import { describe, it, expect } from "vitest";
import { LiveConsensus, type PlateRead } from "@/lib/liveConsensus";

const r = (plate: string, tMs: number, conf: number, minLp?: number): PlateRead =>
  ({ plate, tMs, conf, ...(minLp === undefined ? {} : { minLp }) });

/** يغذّي القراءات ويرجّع اللي اتعمد بعد الإغلاق. */
function run(reads: PlateRead[], opts = {}): string[] {
  const c = new LiveConsensus(opts);
  for (const x of reads) c.add(x);
  return c.flush().map((p) => p.plate);
}

describe("السلوك المقيس الموجود — مايتكسرش", () => {
  it("نفس اللوحة في ٣ نوافذ = لوحة واحدة", () => {
    expect(run([r("ابح1234", 0, 0.9), r("ابح1234", 1500, 0.95), r("ابح1234", 3000, 0.9)]))
      .toEqual(["ابح1234"]);
  });

  it("ضجيج نافذة (فرق خانة واحدة) بيتدمج مع الأصل — مايتقسمش", () => {
    const out = run([r("ابح1234", 0, 0.99), r("ابح1235", 1500, 0.7)]);
    expect(out).toEqual(["ابح1234"]);
  });

  it("نفس الحروف بس بعيدين زمنياً = لوحتين (فصل بالتوقيت)", () => {
    expect(run([r("ابح1234", 0, 0.9), r("ابح5678", 9000, 0.9)]).sort())
      .toEqual(["ابح1234", "ابح5678"]);
  });

  it("مجموعتين أرقام كل واحدة ثابتة (٢+) = الاتنين بيطلعوا", () => {
    const out = run([
      r("ابح1234", 0, 0.9), r("ابح1234", 1000, 0.9),
      r("ابح5678", 1500, 0.9), r("ابح5678", 2500, 0.9),
    ]).sort();
    expect(out).toEqual(["ابح1234", "ابح5678"]);
  });

  it("قراءة مفردة بثقة واطية = اختراع، بتتحجب", () => {
    expect(run([r("ردس8211", 0, 0.35)])).toEqual([]);
  });

  it("قراءة مفردة بأضعف توكن واطي = تلفيق، بتتحجب", () => {
    expect(run([r("ردس8211", 0, 0.9, -0.9)])).toEqual([]);
  });
});

describe("الفجوة: اللوحة التانية اتقرت مرة واحدة بس", () => {
  it("**اللوحة التانية مابتضيعش** — بتطلع مع الأولى", () => {
    // المندوب قال لوحتين بنفس الحروف ورا بعض؛ التانية لحقتها نافذة واحدة.
    const out = run([
      r("دوا7299", 0, 0.95, -0.2), r("دوا7299", 1200, 0.93, -0.2),
      r("دوا7116", 2200, 0.92, -0.2),
    ]).sort();
    expect(out).toEqual(["دوا7116", "دوا7299"]);
  });

  it("اللي اتقرت مرة واحدة بتترجّع «للمراجعة» مش مؤكّدة", () => {
    const c = new LiveConsensus();
    c.add(r("دوا7299", 0, 0.95, -0.2));
    c.add(r("دوا7299", 1200, 0.93, -0.2));
    c.add(r("دوا7116", 2200, 0.92, -0.2));
    const byPlate = Object.fromEntries(c.flush().map((p) => [p.plate, p.tier]));
    expect(byPlate["دوا7299"]).toBe("green");
    expect(byPlate["دوا7116"]).toBe("yellow");
  });

  it("الاسترجاع بيعدّي على **نفس** حواجز الاختراع — ثقة واطية = تتحجب", () => {
    const out = run([
      r("دوا7299", 0, 0.95, -0.2), r("دوا7299", 1200, 0.93, -0.2),
      r("دوا7116", 2200, 0.35, -0.2),      // اختراع وقفة
    ]);
    expect(out).toEqual(["دوا7299"]);
  });

  it("وعلى حاجز أضعف توكن كمان", () => {
    const out = run([
      r("دوا7299", 0, 0.95, -0.2), r("دوا7299", 1200, 0.93, -0.2),
      r("دوا7116", 2200, 0.92, -0.9),      // تلفيق
    ]);
    expect(out).toEqual(["دوا7299"]);
  });

  it("ضجيج الخانة الواحدة لسه مابيترجّعش (مش لوحة تانية)", () => {
    const out = run([
      r("ابح1234", 0, 0.99, -0.2), r("ابح1234", 1200, 0.98, -0.2),
      r("ابح1235", 2200, 0.97, -0.2),      // فرق خانة = نفس النطق
    ]);
    expect(out).toEqual(["ابح1234"]);
  });

  it("تلات لوحات بنفس الحروف ورا بعض — ولا واحدة تضيع", () => {
    const out = run([
      r("دوا7299", 0, 0.95, -0.2), r("دوا7299", 1200, 0.93, -0.2),
      r("دوا7116", 2200, 0.92, -0.2),
      r("دوا7450", 3400, 0.91, -0.2),
    ]).sort();
    expect(out).toEqual(["دوا7116", "دوا7299", "دوا7450"]);
  });
});
