import { describe, it, expect } from "vitest";
import { LiveConsensus } from "@/lib/liveConsensus";

/**
 * 🔴 **بلاغ المالك (٢٢ سبتمبر ٢٠٢٦ · جلسة ٢٨ لوحة):** صف ٢٢ طلع
 * `دعع1670` والصح `دعع1676`. والقراءات الخام:
 *
 *     107.0   دعع1670   ١٠٠٪   ← غلط، ظهر **أول**
 *     108.5   دعع1676   ١٠٠٪   ← صح
 *     110.0   دعع1676   ١٠٠٪   ← صح تاني
 *
 * الصح كسب **نافذتين** والغلط **واحدة** — وبرضه الغلط اتعرض.
 *
 * السبب: اختيار الإملاء بأعلى **ثقة مفردة** (قاعدة مقيسة ورفعت الدقة
 * ٣٣→٨٥٪ — ماتتلمسش). لكن لما الثقتين **متساويتين** الترتيب بيتحسم
 * باستقرار `sort` يعني **ترتيب الوصول** — ومافيش أي قياس بيقول إن الأسبق
 * أصح. الاتفاق في نوافذ أكتر دليل أقوى من الصدفة.
 *
 * ⇒ التعادل بس هو اللي بيتغيّر. أي فرق حقيقي في الثقة لسه بيحكم زي ما كان.
 */
describe("تعادل الثقة — الأكتر نوافذ يكسب مش الأسبق", () => {
  const mk = () => new LiveConsensus({ windowMs: 2000, stableMs: 0, greenMinMult: 2 });

  it("🔴 حالة المالك: دعع1670 مرة و دعع1676 مرتين بنفس الثقة", () => {
    const c = mk();
    c.add({ plate: "دعع1670", tMs: 107_000, conf: 1 });
    c.add({ plate: "دعع1676", tMs: 108_500, conf: 1 });
    c.add({ plate: "دعع1676", tMs: 110_000, conf: 1 });
    const out = c.drain(200_000);
    expect(out.map((o) => o.plate)).toEqual(["دعع1676"]);
  });

  it("الأسبق يكسب لو هو كمان الأكتر", () => {
    const c = mk();
    c.add({ plate: "دعع1670", tMs: 107_000, conf: 1 });
    c.add({ plate: "دعع1670", tMs: 108_500, conf: 1 });
    c.add({ plate: "دعع1676", tMs: 110_000, conf: 1 });
    expect(c.drain(200_000).map((o) => o.plate)).toEqual(["دعع1670"]);
  });

  it("🔒 فرق الثقة الحقيقي لسه بيحكم — القاعدة المقيسة ماتغيّرتش", () => {
    const c = mk();
    // الأقل ثقة اتكرر أكتر، والأعلى ثقة مرة واحدة ⇒ الأعلى ثقة يكسب
    c.add({ plate: "دعع1670", tMs: 107_000, conf: 0.90 });
    c.add({ plate: "دعع1670", tMs: 108_500, conf: 0.90 });
    c.add({ plate: "دعع1676", tMs: 110_000, conf: 0.99 });
    expect(c.drain(200_000).map((o) => o.plate)).toEqual(["دعع1676"]);
  });
});
