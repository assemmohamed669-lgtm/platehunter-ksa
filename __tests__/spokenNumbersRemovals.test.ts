import { describe, it, expect } from "vitest";
import { parsePlateFromTranscript, extractMultiplePlates, normalizePlate } from "../lib/plateParser";

// ─── مرحلة «شيل اللي بيأثّر، سيب اللي بيفيد» ────────────────────────────────
//
// قاعدة المالك بالحرف: «الأهم التست — لو لقيت حاجة ليها تأثير، بعد التست
// نشيلها ونسيب الباقي؛ واللي تلاقيه كويس نسيبه.»
//
// الملف ده بيثبّت **نتيجة** المرحلة دي: كل حاجة اتشالت لازم تفضل مشالة،
// وكل حاجة اتضيّقت لازم تفضل مضيّقة. القياس اللي بنى القرار:
//   · الآلاف بإملاء المالك (X الاف · X تلاف · Xتلاف): **صفر ورود** في ٧٢ ألف
//     حرف تفريغ ميداني حقيقي، و٦٣ إصلاح على داتا **مولَّدة** بس، مقابل ٢٨
//     حالة «ملاحظة فلوس قبل اللوحة» بتضيّع لوحة كانت صح.
//   · «اربع ستات»: صفر ورود حقيقي (اللي في الصوت هو «تلات/ثلاث ستات» بس)،
//     و١٠ إصلاحات مولَّدة، مقابل ٦٦٦٦ كاملة بتطلع من كلام عادي.
//   · «ثنان»: صفر ورود حقيقي، إصلاح واحد مولَّد، وبتتصادم مع اسم سعودي شائع
//     («ثنيان») لو التفريغ غلط بحرف.
// و«صفرين» و«ستات» و«خمسات» فضلوا — دول ليهم ورود **حقيقي** في الصوت وكلها
// إملاء لوحة، مش كلام عادي.

const plate = (t: string) => parsePlateFromTranscript(t).plate;
const norm = (t: string) => normalizePlate(parsePlateFromTranscript(t).plate);
const multi = (t: string) => extractMultiplePlates(t).map((r) => r.normalized);

// ─── ١) ملاحظة فلوس قبل اللوحة ما تاكلش اللوحة ──────────────────────────────
// دي كانت الخسارة الحقيقية الوحيدة: مسار `parsePlateFromTranscript` (اللي
// بيشتغل على محركات الجهاز في /instant-check) كان بيرجّع «8000» بدل اللوحة.
describe("إزالة الآلاف — ملاحظة الفلوس ما تاكلش اللوحة", () => {
  const cases: [string, string][] = [
    ["المطلوب عليه تمن الاف ريال حاء باء كاف تسعة ستة ستة ستة", "حبك9666"],
    ["دفعت خمستلاف حاء باء كاف واحد تسعة تسعة تسعة", "حبك1999"],
    ["الورشه اخدت تمنتلاف دال سين كاف اتنين اتنين تمانية تمانية", "دسك2288"],
    ["الرقم اللي معايا ستلاف بس الف لام به واحد خمسة صفر صفر", "الب1500"],
    ["الاستاذ ثنان مسؤول الفرع حاء باء كاف واحد اتنين تلاتة وواحد", "حبك1231"],
  ];
  for (const [text, expected] of cases) {
    it(`«${text}» ⇒ ${expected}`, () => {
      expect(norm(text)).toBe(normalizePlate(expected));
    });
  }
});

// ─── ٢) كلام فلوس عادي ما يطلّعش لوحة من العدم ──────────────────────────────
describe("إزالة الآلاف — كلام الفلوس ما يولّدش لوحة", () => {
  const money = [
    "الحساب طلع تمن الاف ريال",
    "دفعت خمستلاف",
    "المبلغ ستلاف ريال",
    "الونش بياخد خمستلاف",
    "قالي ثمن الاف وخلاص",
  ];
  for (const text of money) {
    it(`«${text}» ⇒ ولا لوحة`, () => {
      expect(plate(text)).toBe("");
      expect(multi(text)).toEqual([]);
    });
  }

  // «X الاف» جوّه إملاء لوحة كمان ما بقتش رقم — ده تمن الإزالة، ومقبول:
  // مافيش ولا ورود ليها في التفريغ الحقيقي.
  it("«حاء باء كاف ستلاف» ما بقاش حبك6000", () => {
    expect(plate("حاء باء كاف ستلاف")).not.toBe("حبك6000");
  });

  // الصيغة الفصحى الموجودة من الأصل **ما اتلمستش**.
  it("الآلاف الفصحى القديمة زي ما هي: «خمسة الاف» = 5000", () => {
    expect(norm("حاء باء كاف خمسة الاف")).toBe(normalizePlate("حبك5000"));
    expect(norm("حاء باء كاف ستة الاف")).toBe(normalizePlate("حبك6000"));
    expect(norm("حاء باء كاف ألفين")).toBe(normalizePlate("حبك2000"));
  });

  // والطريق التاني لنفس الرقم لسه شغّال (§١.١ من الوثيقة).
  it("5000 لسه ليها طريق: «خمسة تلات تصفار»", () => {
    expect(norm("حاء باء كاف خمسة تلات تصفار")).toBe(normalizePlate("حبك5000"));
  });
});

// ─── ٣) «اربع ستات» اتشالت · «تلات ستات» فضلت (قرار المالك) ─────────────────
describe("«ستات» — اللي فضل واللي اتشال", () => {
  it("«شفت اربع ستات قدام العماره» ما يطلّعش ٦٦٦٦", () => {
    expect(norm("شفت اربع ستات قدام العماره")).not.toContain("6666");
    expect(multi("طلعوا اربع ستات من السياره")).not.toContain("طلع6666");
  });

  // مثال المالك بالحرف — ده اللي وافق عليه وده اللي في الصوت الحقيقي
  // (٧ ورودات، كلها إملاء لوحة: «ره ب كاف ثلاث ستات سبعة»).
  it("«تسعة تلات ستات» ⇒ حبك9666 — مثال المالك محفوظ", () => {
    expect(norm("حاء باء كاف تسعة تلات ستات")).toBe(normalizePlate("حبك9666"));
  });

  it("«ثلاث ستات» جوّه إملاء لوحة لسه = ٦٦٦", () => {
    expect(norm("راء حاء عين ثلاث ستات سبعة")).toBe(normalizePlate("رحع6667"));
  });

  // «اربع خمسات» فضلت: «خمسات» ليها ٥ ورودات حقيقية وكلها إملاء لوحة.
  it("«اربع خمسات» لسه = ٥٥٥٥", () => {
    expect(norm("حاء باء كاف اربع خمسات")).toBe(normalizePlate("حبك5555"));
  });
});

// ─── ٤) «ثنان» اتشالت ───────────────────────────────────────────────────────
describe("إزالة «ثنان»", () => {
  it("«ثنان» لوحدها ما بقتش ٢", () => {
    expect(plate("حاء باء كاف ثنان تسعة تسعة تسعة")).not.toBe("حبك2999");
  });

  // «اثنان» الفصحى (الموجودة من الأصل) ما اتلمستش.
  it("«اثنان وعشرون تمانية وثمانين» لسه دسك2288", () => {
    expect(norm("دال سين كاف اثنان وعشرون تمانية وثمانين")).toBe(normalizePlate("دسك2288"));
  });
});

// ─── ٥) تضييق قاعدة الضم: نزول المرتبة من مرتبة **صحيحة** بس ────────────────
// الشكل (٢) من قاعدة الواو كان «و + رقم أصغر من مجموعة ≥١٠». مع مداخل التكرار
// («تلات تسعات» = 999) بقى «واحد» بعدها بيتجمع 999+1=1000 بدل ما يتلزق 9991.
// التضييق: النزول يتقبل بس لو المجموعة على مرتبة صحيحة (min % 10 === 0).
// «تلات ستات واحد» موجودة **بالحرف** في تفريغ ميداني حقيقي.
describe("تضييق الضم — عيلة «تكرار + واحد»", () => {
  const cases: [string, string][] = [
    ["حاء باء كاف تلات تسعات واحد", "حبك9991"],
    ["حاء باء كاف تلات وحايد واحد", "حبك1111"],
    ["حاء باء كاف تلات اتنينات واحد", "حبك2221"],
    ["حاء باء كاف تلات تلاتات واحد", "حبك3331"],
    ["حاء باء كاف تلات اربعات واحد", "حبك4441"],
    ["حاء باء كاف تلات خمسات واحد", "حبك5551"],
    ["حاء باء كاف تلات ستات واحد", "حبك6661"],
    ["حاء باء كاف تلات سبعات واحد", "حبك7771"],
    ["حاء باء كاف تلات تمنيات واحد", "حبك8881"],
    ["حاء باء كاف تلات تسعات وحده", "حبك9991"],
    ["دال حه به تلات تسعات واحد", "دحب9991"],
  ];
  for (const [text, expected] of cases) {
    it(`«${text}» ⇒ ${expected}`, () => {
      expect(norm(text)).toBe(normalizePlate(expected));
    });
  }

  // حراسة: التضييق ما يكسرش ولا مركّب واو حقيقي.
  const guards: [string, string][] = [
    ["حاء باء كاف تسعة تسعة تسعة وواحد", "حبك9991"],
    ["حاء باء كاف تسعة تسعة تسعة ووحده", "حبك9991"],
    ["حاء باء كاف مية وخمسة وعشرين", "حبك0125"],
    ["حاء باء كاف الف وخمسمية وستة", "حبك1506"],
    ["حاء باء كاف مية وواحد وعشرين", "حبك0121"],
    ["حاء باء كاف الف ومية وواحد", "حبك1101"],
    ["حاء باء كاف تسعة الاف وتسعمية وتسعة وتسعين", "حبك9999"],
    ["دال سين كاف اتنين وعشرين تمانية وثمانين", "دسك2288"],
    ["حاء باء كاف واحد خمسمية", "حبك1500"],
    ["راء ميم هاء ستة تسعمية", "رمه6900"],
    ["حاء باء كاف واحد اتنين تلاتة وواحد", "حبك1231"],
  ];
  for (const [text, expected] of guards) {
    it(`حراسة «${text}» ⇒ ${expected}`, () => {
      expect(norm(text)).toBe(normalizePlate(expected));
    });
  }
});
