import { describe, it, expect } from "vitest";
import { isExactRepeatOfLatest } from "@/lib/trialTwin";

/**
 * 🔴 **لوحة مكرّرة ضاعت** (جلسة المالك ٢٣ سبتمبر · ٥٠ لوحة).
 *
 * قال `دمس5284` **مرتين** (الثانية ٦.٥ والثانية ٢٠)، وطلعت **مرة واحدة**.
 *
 * السبب إصلاح «بيكتب اللوحة مرتين» اللي قبله: خلّيت المتطابقة تتلمّ خلال
 * **دقيقتين**. والحد ده واسع زيادة — بيلمّ إعادات مقصودة.
 *
 * ⇒ القاعدة الصح: المتطابقة تتلمّ **بس لو مافيش لوحة تانية بينهم**.
 *   إنت بتقول نفس اللوحة مرتين ورا بعض = نفس العربية (نفس النطقة اتقرت
 *   في نافذتين). وبتقولها تاني **بعد لوحات تانية** = إعادة مقصودة.
 *
 * ده بيصلّح الاتنين: الصفوف المكرّرة اللي اشتكى منها كانت **ورا بعض**
 * (`رره6232` ×٣ متتالية)، والإعادة المقصودة بينها لوحات.
 */
describe("اللوحة المتطابقة — الفاصل هو اللي يحكم", () => {
  it("🔴 نفس اللوحة وهي آخر صف ⇒ تتلمّ", () => {
    expect(isExactRepeatOfLatest("رره6232", ["رره6232", "دطس2177"])).toBe(true);
  });

  it("🔴 نفس اللوحة وبينهم لوحات تانية ⇒ **صف جديد**", () => {
    expect(isExactRepeatOfLatest("دمس5284",
      ["رمل3116", "ربل9914", "بحن2873", "اقص4063", "دمس5284"])).toBe(false);
  });

  it("أول لوحة في الجلسة ⇒ صف جديد", () => {
    expect(isExactRepeatOfLatest("بود3135", [])).toBe(false);
  });

  it("لوحة مختلفة ⇒ صف جديد", () => {
    expect(isExactRepeatOfLatest("سدر7771", ["بود3135"])).toBe(false);
  });

  it("تلاتة ورا بعض ⇒ كلهم يتلمّوا", () => {
    expect(isExactRepeatOfLatest("رره6232", ["رره6232"])).toBe(true);
    expect(isExactRepeatOfLatest("رره6232", ["رره6232", "رره6232"])).toBe(true);
  });
});
