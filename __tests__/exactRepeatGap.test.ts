import { describe, it, expect } from "vitest";
import { isExactRepeatNearby, EXACT_REPEAT_MAX_ROWS } from "@/lib/trialTwin";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🔁 نفس اللوحة: نطقة واحدة اتقرت مرتين؟ ولا إعادة مقصودة؟
 * ══════════════════════════════════════════════════════════════════════
 *
 * 🔴 **محاولتان قبل كده، الاتنين اتكذّبوا بجلسة حقيقية:**
 *
 * ① **حد زمني دقيقتين** — ضيّع إعادة مقصودة: المالك قال `دمس5284` مرتين
 *    بينهم ٤ لوحات (فرق ١٣.٥ث) وطلعت مرة واحدة.
 *
 * ② **«لازم تكون آخر صف»** — كسّر اللمّ لما المندوب يقول **لوحتين
 *    بالتبادل**: `ساك2121` · `دهس6877` · `ساك2121`… آخر صف بيبقى اللوحة
 *    التانية، فالشرط بيفشل **كل مرة** وكل نطقة بتطلع ٣ صفوف (مبدئي
 *    ومؤكّد جنب بعض). ده بالظبط اللي المالك بعت صورته.
 *
 * ⇒ **الصح: قريبة في الصفوف (≤٣) *و* قريبة في الوقت (نافذة التوأم).**
 *   · النطقة الواحدة بتتقري في نوافذ متداخلة ⇒ صفوفها متلاصقة وثوانيها
 *     قليلة — حتى لو فيه لوحة تانية في نفس النافذة.
 *   · الإعادة المقصودة بينها لوحات **وثواني أكتر**.
 *
 * الشرطين مع بعض بيفصلوا الحالتين اللي المالك عاشهم فعلاً.
 */
describe("اللوحة المتطابقة — قُرب في الصفوف", () => {
  it("🔴 لوحتين بالتبادل: نفس اللوحة بعد صف واحد ⇒ قريبة", () => {
    expect(isExactRepeatNearby("ساك2121", ["دهس6877", "ساك2121"])).toBe(true);
  });

  it("وورا بعض على طول ⇒ قريبة", () => {
    expect(isExactRepeatNearby("رره6232", ["رره6232", "دطس2177"])).toBe(true);
  });

  it("وتلات لوحات بالتبادل لسه جوّه المدى", () => {
    expect(isExactRepeatNearby("ساك2121", ["دهس6877", "رقع9709", "ساك2121"])).toBe(true);
  });

  it("🔴 إعادة مقصودة بعد ٤ لوحات ⇒ **مش** قريبة", () => {
    expect(isExactRepeatNearby("دمس5284",
      ["رمل3116", "ربل9914", "بحن2873", "اقص4063", "دمس5284"])).toBe(false);
  });

  it("أول لوحة في الجلسة ⇒ مش قريبة", () => {
    expect(isExactRepeatNearby("بود3135", [])).toBe(false);
  });

  it("لوحة مختلفة خالص ⇒ مش قريبة", () => {
    expect(isExactRepeatNearby("سدر7771", ["بود3135", "رمل3116"])).toBe(false);
  });

  it("المدى المعلَن هو اللي بيتطبّق", () => {
    const far = ["a", "b", "c"].slice(0, EXACT_REPEAT_MAX_ROWS);
    expect(isExactRepeatNearby("x", [...far, "x"])).toBe(false);
  });
});
