import { describe, it, expect } from "vitest";
import { defaultDataCols } from "@/lib/resultColumns";

/**
 * بطلب المندوب: عمود «نوع السيارة» بتاع الداتا (ونيت/فان/دباب...) يظهر تلقائي في
 * الفرز من غير ما يدوس يحدده — حتى لو اسم العمود مش معروف. defaultDataCols بيضيف
 * أي عمود أغلب قيَمه أنواع مركبات، فوق المفضّلة بالاسم.
 */
describe("defaultDataCols — نوع السيارة يظهر تلقائي بالمحتوى", () => {
  it("عمود باسم غير معروف بس قيَمه أنواع مركبات → يتحدد تلقائي", () => {
    const headers = ["رقم اللوحة", "الوصف", "اللون"];
    const rows = [
      { "رقم اللوحة": "دسك1234", "الوصف": "ونيت", "اللون": "أبيض" },
      { "رقم اللوحة": "قنن5678", "الوصف": "فان", "اللون": "أسود" },
      { "رقم اللوحة": "بحم9012", "الوصف": "دباب", "اللون": "أحمر" },
      { "رقم اللوحة": "الم3344", "الوصف": "صالون", "اللون": "أزرق" },
    ];
    expect(defaultDataCols(headers, rows, "رقم اللوحة")).toContain("الوصف");
  });

  it("عمود «نوع السيارة» بالاسم يفضل متحدد (المفضّلة)", () => {
    const headers = ["رقم اللوحة", "نوع السيارة"];
    const rows = [{ "رقم اللوحة": "دسك1234", "نوع السيارة": "ونيت" }];
    expect(defaultDataCols(headers, rows, "رقم اللوحة")).toContain("نوع السيارة");
  });

  it("عمود قيَمه مش أنواع مركبات (أسماء) مايتحددش بالمحتوى", () => {
    // فيه عمود مفضّل («اللون») فـguessDefaultColumns مايرجّعش الكل fallback —
    // فلو «المالك» ظهر يبقى من الكشف بالمحتوى (وهو مايفترضش يظهر).
    const headers = ["رقم اللوحة", "اللون", "المالك"];
    const rows = [
      { "رقم اللوحة": "دسك1234", "اللون": "أبيض", "المالك": "محمد أحمد" },
      { "رقم اللوحة": "قنن5678", "اللون": "أسود", "المالك": "علي حسن" },
      { "رقم اللوحة": "بحم9012", "اللون": "أحمر", "المالك": "سعد فهد" },
    ];
    const cols = defaultDataCols(headers, rows, "رقم اللوحة");
    expect(cols).toContain("اللون");
    expect(cols).not.toContain("المالك");
  });

  it("عمود اللوحة نفسه مايتحددش", () => {
    const headers = ["رقم اللوحة", "نوع"];
    const rows = [{ "رقم اللوحة": "دسك1234", "نوع": "ونيت" }];
    expect(defaultDataCols(headers, rows, "رقم اللوحة")).not.toContain("رقم اللوحة");
  });
});
