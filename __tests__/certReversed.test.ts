import { describe, it, expect } from "vitest";
import { normalizeReversedLabels, looksReversed, splitReversedLabelLine } from "@/lib/certReversed";
import { parseCertText } from "@/lib/certParse";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🔄 شهايد «توثيق» اللي ترتيب كلماتها مقلوب
 * ══════════════════════════════════════════════════════════════════════
 *  المالك (١٤ أكتوبر ٢٠٢٦) بعت ٥ شهايد «توثيق» عربيها **سليم ومقروء**، ومع ذلك
 *  البرنامج طلّع المصنع والنوع واللون والسنة والمؤجر **فاضيين** — نفس الأعمدة
 *  الفاضية في شيت الشهايد.
 *
 *  السبب مختلف تماماً عن شهايد «السجل»: مافيش رموز هنا، الكلام سليم بس
 *  **ترتيب الكلمات مقلوب** («الراجحي مصرف :االسم» بدل «االسم: مصرف الراجحي»)،
 *  فالبرنامج مش لاقي العنوان.
 *
 *  السطور تحت بنفس شكل الشهايد الحقيقية (بأسماء وهمية).
 */
const REVERSED = [
  "947956 :السند رقم",
  "الراجحي مصرف :االسم",
  "الرياض :المدينة",
  "متعثر :العقد حالة",
  "2025 :الصنع سنة",
  "اسوزو :المصنع",
  "ابيض :األصل لون",
  "JAMKP34T7S7P32222 :الهيكل رقم",
].join("\n");

describe("🔄 السطر المقلوب", () => {
  it("🔴 بيترجع «العنوان: القيمة»", () => {
    expect(splitReversedLabelLine("الراجحي مصرف :االسم")).toEqual({ label: "االسم", value: "مصرف الراجحي" });
    expect(splitReversedLabelLine("ابيض :األصل لون")).toEqual({ label: "لون األصل", value: "ابيض" });
  });

  it("السطر اللي مش «قيمة :عنوان» مايتلمسش", () => {
    expect(splitReversedLabelLine("تم اصدار هذه الوثيقة من قبل شركة توثيق")).toBeNull();
    expect(splitReversedLabelLine("")).toBeNull();
    // عنوان مش معروف ⇒ سيبه (مانخمّنش)
    expect(splitReversedLabelLine("حاجة :كلام غريب")).toBeNull();
  });

  it("🔴 الملف المقلوب بيتعرف، والسليم لأ", () => {
    expect(looksReversed(REVERSED)).toBe(true);
    expect(looksReversed("االسم: مصرف الراجحي\nالمصنع: اسوزو\nسنة الصنع: 2025")).toBe(false);
  });

  it("🔒 الملف السليم بيرجع زي ما هو بالحرف", () => {
    const ok = "االسم: مصرف الراجحي\nالمصنع: اسوزو\nلون األصل: ابيض";
    expect(normalizeReversedLabels(ok)).toBe(ok);
  });
});

describe("🔴 القراية بعد التطبيع — ده اللي كان فاضي عند المالك", () => {
  const f = parseCertText(REVERSED + "\nتوثيق\n1234 ح ب ا :اللوحة رقم", "2865.pdf");

  it("المصنع واللون والسنة والمؤجر وحالة العقد بقوا بيطلعوا", () => {
    expect(f).toMatchObject({
      make: "اسوزو", color: "ابيض", year: "2025", bank: "مصرف الراجحي", status: "متعثر",
    });
  });

  it("الشاص بيفضل صح", () => {
    expect(f.vin).toBe("JAMKP34T7S7P32222");
  });
});
