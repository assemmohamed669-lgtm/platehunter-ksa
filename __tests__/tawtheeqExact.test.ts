import { describe, it, expect } from "vitest";
import { runsFromOps, ligatureWordFixes, applyWordFixes, type PdfOp } from "@/lib/pdfRuns";
import { parseCertText } from "@/lib/certParse";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  📄 «توثيق» — الكلمات زي الشهادة بالظبط
 * ══════════════════════════════════════════════════════════════════════
 *  المالك (١٩ نوفمبر ٢٠٢٦): «صلح كل حاجه عايز كل البيانات صح 100%» — وبعت `9439.pdf` و`5172.pdf` و`3110.pdf`.
 *
 *  ١) الرباطات («لا» «لأ» «لى») في خط «توثيق» شكل واحد بحرفين. قارئ الكلام العادي بيقلب الكلمة **حرف حرف**
 *     فبيقلب الحرفين جوّه الرباط: «توكيلات» ⇒ «توكيالت»، «على» ⇒ «عىل»، «الاولى» ⇒ «االوىل»، «للأعمال» ⇒
 *     «لألعمال». من أوامر الرسم بنعرف كل شكل لوحده ⇒ الكلمة الصح، وبنبدّلها في النص (الكلمات دي بس).
 *  ٢) «المصنع: جا سي بي» كانت بتتقص لأول كلمتين («جا سي»).
 */

const g = (unicode: string) => ({ unicode, width: 500 });
/** أمر رسم بأشكال (كل عنصر شكل واحد — ممكن يبقى حرفين زي «لا») بالترتيب المرئي (شمال ⇒ يمين). */
const draw = (x: number, y: number, glyphs: string[]): PdfOp[] => [
  { fn: "beginText", args: null }, { fn: "setFont", args: ["f", 8] }, { fn: "moveText", args: [x, y] },
  { fn: "showText", args: [glyphs.map(g)] }, { fn: "endText", args: null },
];
/** كلمة عربي ⇒ أشكالها بالترتيب المرئي (معكوسة)؛ «لا/لأ/لى…» شكل واحد. */
const visual = (logical: string) => (logical.match(/ل[اأإآى]|./g) ?? []).reverse();

describe("١) الرباطات من أوامر الرسم", () => {
  const runs = runsFromOps([
    ...draw(100, 500, [...visual("شركة توكيلات للتمويل")]),
    ...draw(300, 500, [...visual("الاسم:")]),
    ...draw(100, 480, [...visual("تمويل الاولى")]),
    ...draw(100, 460, [...visual("بناء على طلب المؤجر")]),
    ...draw(100, 440, [...visual("شركة حسام الدين للأعمال")]),
    ...draw(100, 420, [...visual("حالة العقد: نشط")]),
  ]);
  const fixes = ligatureWordFixes(runs);

  it("🔴 كل كلمة فيها رباط ⇒ شكلها اللي القارئ العادي بيطلّعه ⇒ الصح", () => {
    expect(Object.fromEntries(fixes)).toEqual({
      "توكيالت": "توكيلات", "االسم": "الاسم", "االوىل": "الاولى", "عىل": "على", "لألعمال": "للأعمال",
    });
  });

  it("🔴 بيتبدّل في النص الكلمات دي بس — حتى لو لازقة في «:»", () => {
    const plain = "للتمويل توكيالت شركة :االسم\nاالوىل تمويل :االسم\nالمؤجر طلب عىل بناء\nلألعمال الدين حسام شركة :االسم\nنشط :العقد حالة";
    expect(applyWordFixes(plain, fixes)).toBe(
      "للتمويل توكيلات شركة :الاسم\nالاولى تمويل :الاسم\nالمؤجر طلب على بناء\nللأعمال الدين حسام شركة :الاسم\nنشط :العقد حالة",
    );
  });

  it("كلمة من غير رباط مابتتلمسش (ولا جزء من كلمة)", () => {
    expect(applyWordFixes("عىلي العىل عىل", new Map([["عىل", "على"]]))).toBe("عىلي العىل على");
  });
});

// «توثيق» بالشكل المقلوب اللي القارئ العادي بيطلّعه (من `5172.pdf`/`9439.pdf` — من غير بيانات شخصية)
const TAW = (lines: string[]) => ["شركة توثيق لتسجيل عقود االيجار التمويلي", ...lines, "www.TawtheeqCo.com.sa"].join("\n");

describe("٢) خانات الأصل كاملة", () => {
  it("🔴 «جا سي بي» مش «جا سي»", () => {
    const f = parseCertText(TAW([
      "بي سي جا :المصنع", "صغير شيول :األصل نوع", "5172 ع أ أ :اللوحة رقم", "اصفر :األصل لون", "2024 :الصنع سنة", "نشط :العقد حالة",
    ]), "أ أ ع 5172.pdf");
    expect([f.make, f.model, f.color, f.year, f.status]).toEqual(["جا سي بي", "شيول صغير", "اصفر", "2024", "نشط"]);
  });

  it("🔴 لون بكلمتين بيتاخد كامل", () => {
    const f = parseCertText(TAW(["كيا :المصنع", "سيراتو :األصل نوع", "لؤلؤي ابيض :األصل لون", "نشط :العقد حالة"]), "x.pdf");
    expect([f.make, f.color]).toEqual(["كيا", "ابيض لؤلؤي"]);
  });

  it("🔴 تاريخ الشهادة = تاريخ اصدار السند — مش تاريخ انتهاء الهوية (أبعد تاريخ في الشهادة)", () => {
    const f = parseCertText(TAW([
      "12/07/2023 :الأصل تسجيل تاريخ", "30/03/1979 :الميلاد تاريخ", "14/06/2028 :الهوية انتهاء تاريخ", "01/07/2026 :العقد انتهاء تاريخ",
      "كيا :المصنع", "فضي :األصل لون", "نشط :العقد حالة",
      "12/11/2026 15:39:35 :الشهادة طباعة تاريخ 12/11/2026 15:39:35 :السند اصدار تاريخ",
    ]), "د ي ب 9439.pdf");
    expect(f.certDate).toBe("12/11/2026");
  });

  it("🔴 خانتين في نفس السطر ⇒ كل واحدة لوحدها (مابتبلعش اسم الخانة اللي بعدها)", () => {
    const f = parseCertText("شركة توثيق\nالمصنع: كيا لون الأصل: فضي\nنوع الأصل: سيراتو رقم اللوحة: د ي ب 9439\n", "x.pdf");
    expect([f.make, f.color, f.model, f.plate]).toEqual(["كيا", "فضي", "سيراتو", "ديب9439"]);
  });
});
