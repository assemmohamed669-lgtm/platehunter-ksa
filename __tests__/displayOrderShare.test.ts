import { describe, it, expect } from "vitest";
import { buildDisplayRows } from "@/lib/exportColumns";

/**
 * في وضع **التخصيص** المشاركة لازم تطلع بترتيب المندوب بالظبط — زي الشاشة.
 *
 * قبل كده المشاركة كانت بتعدّي على الترتيب الثابت (#215)، فالمندوب يرتّب
 * أعمدته على التليفون وياخد إكسيل/صورة بترتيب تاني خالص. صفوف المشاركة
 * بتتبني أصلاً بترتيب العرض، فترتيب مفاتيح الصف **هو** ترتيب المندوب.
 */
describe("buildDisplayRows — المشاركة بترتيب المندوب", () => {
  it("بيحافظ على ترتيب الأعمدة زي ما هو", () => {
    const { columns } = buildDisplayRows([
      { "رقم اللوحة": "أ", "الحي": "النسيم", "نوع السيارة": "كامري", "اللون": "ابيض" },
    ]);
    // «ملاحظة» بتتضاف في الآخر — النوع والملاحظات دايماً ظاهرين (طلب المالك ١ أكتوبر ٢٠٢٦)
    expect(columns).toEqual(["رقم اللوحة", "الحي", "نوع السيارة", "اللون", "ملاحظة"]);
  });

  it("مابيعيدش الترتيب حسب الترتيب الثابت", () => {
    // «نوع السيارة» في الترتيب الثابت بييجي قبل «الحي» — هنا المندوب عكسها.
    const { columns } = buildDisplayRows([
      { "رقم اللوحة": "أ", "الحي": "النسيم", "نوع السيارة": "كامري" },
    ]);
    expect(columns.indexOf("الحي")).toBeLessThan(columns.indexOf("نوع السيارة"));
  });

  it("العمود الفاضي في كل الصفوف بيتشال — ماعدا النوع والملاحظات (طلب المالك ١ أكتوبر ٢٠٢٦)", () => {
    const { columns } = buildDisplayRows([
      { "رقم اللوحة": "أ", "البنك": "", "ملاحظة": "", "اللون": "ابيض" },
      { "رقم اللوحة": "ب", "البنك": "", "ملاحظة": "", "اللون": "اسود" },
    ]);
    expect(columns).toEqual(["رقم اللوحة", "نوع السيارة", "ملاحظة", "اللون"]);
  });

  it("«الحالة» مايظهرش — نفس قاعدة التصدير", () => {
    const { columns } = buildDisplayRows([
      { "رقم اللوحة": "أ", "الحالة": "مطلوبة", "اللون": "ابيض" },
    ]);
    expect(columns).not.toContain("الحالة");
  });

  it("أعمدة مصدر تاني (السجلات) بتتلحق بعد أعمدة الأول", () => {
    const { columns } = buildDisplayRows([
      { "رقم اللوحة": "أ", "اللون": "ابيض" },
      { "رقم اللوحة": "ب", "المندوب": "سلام", "التاريخ": "2026-09-16" },
    ]);
    expect(columns).toEqual(["رقم اللوحة", "نوع السيارة", "اللون", "المندوب", "التاريخ", "ملاحظة"]);
  });

  it("كل صف بياخد كل الأعمدة — الناقص يبقى فاضي", () => {
    const { rows } = buildDisplayRows([
      { "رقم اللوحة": "أ", "اللون": "ابيض" },
      { "رقم اللوحة": "ب", "المندوب": "سلام" },
    ]);
    expect(rows[0]["المندوب"]).toBe("");
    expect(rows[1]["اللون"]).toBe("");
  });
});
