import { describe, it, expect } from "vitest";
import { LiveConsensus } from "@/lib/liveConsensus";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🗣️ ٣ لوحات مخترعة من كلام ناس جنبه — والمالك مقالش ولا كلمة
 * ══════════════════════════════════════════════════════════════════════
 *
 * جلسة المالك (٢٢ سبتمبر ٢٠٢٦، ١١:٠٦م): ساب الميك شغّال وحد بيتكلم جنبه.
 * **٣٥ قراءة، كلها اتحجبت كاختراع** — ومع ذلك **٣ لوحات طلعت**:
 *
 *     حير2121 (٦٠٪ · ٣ نوافذ) · حسص3216 (٤٦٪ · ٢) · رقع8295 (٦٨٪ · ٢)
 *
 * ── ليه الحارس مامسكهمش ───────────────────────────────────────────────
 * حاجز الاختراع كان مشروط بـ`mult < greenMinMult` — يعني **القراءة المفردة
 * بس**. والمنطق كان «الاتفاق في نافذتين دليل».
 *
 * 🔴 **والمنطق ده غلط على النوافذ المتداخلة.** النافذة ٥ث والخطوة ١.٥ث،
 * يعني نافذتين ورا بعض بيتشاركوا **٧٠٪ من نفس الصوت**. فالهلوسة على نفس
 * المقطع بتتكرّر — ودي مش شهادة تانية، دي **نفس الشهادة مرتين**.
 *
 * ── 🔴 والتكرار لوحده مش الفيصل كمان ─────────────────────────────────
 * أول محاولة كانت «العنقود لازم فيه قراءة نضيفة واحدة على الأقل» —
 * و`inventionGuardSolo` كذّبها فوراً: في جلسة الـ٢٩ لوحة فيه لوحات **صح**
 * كل قراءاتها اتحجبت (`حطو6826` ٩١/٩٣٪ · `اسط4324` ٨٨٪)، والقاعدة دي كانت
 * هترجّع ضياعهم.
 *
 * ⇒ الفيصل هو **الثقة** لما كل القراءات تتحجب:
 *       صح ومحجوبة كلها : ٩٣ · ٩١ · ٨٨
 *       مخترعة من ضجيج  : ٦٨ · ٦٠ · ٤٦
 *   والحد `ALL_FLAGGED_MIN_CONF = 0.8` في وسط الفجوة.
 *
 * ⚠️ **مفصّل على ٧ حالات مقيسة — مش قانون.** أي تعديل يتقاس على نفس الجلسات.
 */
describe("اختراع على كلام عادي — الاتفاق بين قراءات محجوبة مش دليل", () => {
  const mk = () => new LiveConsensus({ windowMs: 2000, stableMs: 0, greenMinMult: 2 });

  it("🔴 جلسة الضجيج: نافذتين **الاتنين محجوبين** ⇒ مايطلعش", () => {
    const c = mk();
    // رقع8295 — ٤٥.٥ث بثقة ٠.٦٣ و٤٧.٠ث بثقة ٠.٦٨، الاتنين أضعف توكن < ‎-0.5‎
    c.add({ plate: "رقع8295", tMs: 45_500, conf: 0.63, minLp: -1.2 });
    c.add({ plate: "رقع8295", tMs: 47_000, conf: 0.68, minLp: -0.9 });
    expect(c.drain(200_000)).toEqual([]);
  });

  it("🔴 وحتى بتلات نوافذ محجوبة", () => {
    const c = mk();
    c.add({ plate: "حير2121", tMs: 35_000, conf: 0.60, minLp: -1.1 });
    c.add({ plate: "حير3541", tMs: 36_300, conf: 0.49, minLp: -1.4 });
    c.add({ plate: "حير3541", tMs: 38_000, conf: 0.47, minLp: -1.5 });
    expect(c.drain(200_000)).toEqual([]);
  });

  it("✅ قراءة نضيفة واحدة كفاية — اللوحة الحقيقية ماتتأثرش", () => {
    const c = mk();
    // رحه8917 من جلسة ٤٣ لوحة: ٦٠.٥ث نضيفة، و٦٢.٠ث اتحجبت
    c.add({ plate: "رحه8917", tMs: 60_500, conf: 1, minLp: -0.1 });
    c.add({ plate: "رحه8917", tMs: 62_000, conf: 0.91, minLp: -0.8 });
    expect(c.drain(200_000).map((o) => o.plate)).toEqual(["رحه8917"]);
  });

  it("✅ والقراءة المفردة النضيفة عالية الثقة زي ما هي", () => {
    const c = mk();
    c.add({ plate: "رقم2043", tMs: 38_000, conf: 1, minLp: -0.05 });
    expect(c.drain(200_000).map((o) => o.plate)).toEqual(["رقم2043"]);
  });

  it("🔒 المسار القديم (بلا minLp) مايتأثرش", () => {
    const c = mk();
    c.add({ plate: "دطس2177", tMs: 10_000, conf: 0.99 });
    c.add({ plate: "دطس2177", tMs: 11_500, conf: 0.99 });
    expect(c.drain(200_000).map((o) => o.plate)).toEqual(["دطس2177"]);
  });
});
