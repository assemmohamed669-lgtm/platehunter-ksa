import { describe, it, expect } from "vitest";
import { MissedWindows, canReplay, isStalled, REPLAY_MAX_AGE_SEC, MISSED_CAP, STALL_MS } from "../lib/voicexReplay";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🔴 «٧ لوحات ضاعوا في وقعة شبكة» — إعادة إرسال النوافذ الفايتة
 * ══════════════════════════════════════════════════════════════════════
 *  التجربة الأخيرة قبل الفتح للمناديب (٢٣ سبتمبر ٢٠٢٦ · ٩٢/١٠٠): ٧ من
 *  الـ٨ الضايعين ضاعوا في **فجوة ٢٢ ثانية** (ث٣٥ → ث٥٧). السيرفر كان سليم
 *  (كل طلب وصل اتعالج في ~١٧٧ms، صفر أخطاء، صفر رست) — الوقت ضاع **بين
 *  موبايل المالك وCloudflare**: رحلة واحدة ٧.٦ث، و٣ طلبات timeout، و١٢
 *  نافذة اتخطّت «مشغول».
 *
 *  🔴 **والصوت كان لسه على الموبايل** — الذاكرة الدوّارة بتشيل ٩٠ث. بس
 *  المحرّك **مابيعيدش المحاولة**: الطلب يفشل ⇒ لوحاته ضاعت للأبد.
 *  (العميل بيعيد مرة بس على فشل اتصال فوري، مش على timeout.)
 *
 *  ⇒ النوافذ الفايتة بتتسجّل، وأول ما الشبكة ترجع بتتبعت تاني من الذاكرة.
 */
describe("MissedWindows — سجل النوافذ الفايتة", () => {
  it("اللي اتسجّل بيرجع بالترتيب — الأقدم الأول", () => {
    const m = new MissedWindows();
    m.record(10, 15, 20);
    m.record(11.5, 16.5, 20);
    expect(m.take(20)).toEqual({ from: 10, to: 15 });
    expect(m.take(20)).toEqual({ from: 11.5, to: 16.5 });
    expect(m.take(20)).toBeNull();
  });

  it("نفس النافذة مرتين ⇒ مرة واحدة (اتخطّت ثم فشلت)", () => {
    const m = new MissedWindows();
    m.record(10, 15, 20);
    m.record(10, 15, 20);
    expect(m.size).toBe(1);
  });

  it("🔴 أقدم من الذاكرة الدوّارة ⇒ **بتتشال** (الصوت مابقاش موجود)", () => {
    const m = new MissedWindows();
    m.record(10, 15, 20);
    const now = 10 + REPLAY_MAX_AGE_SEC + 1;
    expect(m.take(now)).toBeNull();
    expect(m.size).toBe(0);
  });

  it("⚠️ في وقعة طويلة السجل مابيكبرش للأبد — الأقدم بيتشال", () => {
    const m = new MissedWindows();
    for (let i = 0; i < MISSED_CAP + 10; i++) m.record(i, i + 5, i + 5);
    expect(m.size).toBe(MISSED_CAP);
    // الأقدم اتشال، الأحدث فاضل
    expect(m.take(MISSED_CAP + 15)?.from).toBe(10);
  });

  it("`take` بيشيل اللي رجّعه — مابيتبعتش مرتين", () => {
    const m = new MissedWindows();
    m.record(10, 15, 20);
    m.take(20);
    expect(m.size).toBe(0);
  });
});

describe("canReplay — 🔴 الإعادة مابتأخّرش اللوحات الحيّة", () => {
  /**
   * بعد وقعة ٢٢ث فيه ~١٥ نافذة فايتة. لو اتبعتوا مرة واحدة كانوا هيسدّوا
   * السلوتين ⇒ اللوحات **الحيّة** تتأخر. فالإعادة بتاخد **سلوت واحد بس
   * ساعة الفراغ**، والحيّة ليها الأولوية.
   */
  it("فاضي خالص ⇒ يعيد", () => {
    expect(canReplay(0, 2, 0)).toBe(true);
  });

  it("🔴 سلوت مشغول من اتنين ⇒ **لأ** — السلوت التاني للحيّة", () => {
    expect(canReplay(1, 2, 0)).toBe(false);
  });

  it("فيه نطق مستني ⇒ لأ — النطق أهم", () => {
    expect(canReplay(0, 2, 1)).toBe(false);
  });

  it("سقف أكبر ⇒ يسيب سلوت واحد فاضي للحيّة", () => {
    expect(canReplay(2, 4, 0)).toBe(true);
    expect(canReplay(3, 4, 0)).toBe(false);
  });

  it("سقف ١ ⇒ يعيد لما يكون فاضي بس", () => {
    expect(canReplay(0, 1, 0)).toBe(true);
    expect(canReplay(1, 1, 0)).toBe(false);
  });
});

/**
 * ══════════════════════════════════════════════════════════════════════
 *  isStalled — 🔴 «مشغول» بيتسجّل **بس وقت الوقعة**
 * ══════════════════════════════════════════════════════════════════════
 *  النافذة الزاحفة بتتخطّى «مشغول» **في التشغيل العادي كمان** (١٢ في آخر
 *  جلسة، كتير منهم برّه الوقعة) — والنوافذ المتداخلة بتغطّيها. لو اتسجّلوا
 *  كلهم كنا هنعيد إرسال نوافذ **كل جلسة** بلا مشكلة شبكة = حمل زيادة وتغيير
 *  سلوك محدش طلبه.
 *
 *  ⇒ بتتسجّل بس لو فيه وقعة فعلاً: آخر طلب فشل، أو فيه طلب معلّق.
 *
 *  ⚠️ **٣ ثواني**: رحلات الجلسة العادية ٠.٥–٠.٩ث وأعلى واحدة عادية ٢.٧ث،
 *     والوقعة بدأت من ٣.٧ث (٣.٧ · ٥.٢ · ٧.٦ث).
 */
describe("isStalled — الوقعة بس", () => {
  it("كله تمام ⇒ مش واقعة (النافذة المتخطّية مابتتسجّلش)", () => {
    expect(isStalled(true, [], 10_000)).toBe(false);
  });

  it("🔴 آخر طلب فشل ⇒ واقعة", () => {
    expect(isStalled(false, [], 10_000)).toBe(true);
  });

  it("🔴 طلب معلّق أكتر من ٣ث ⇒ واقعة (قبل ما يوصل timeout)", () => {
    expect(isStalled(true, [10_000 - STALL_MS - 1], 10_000)).toBe(true);
  });

  it("طلبات عادية سريعة ⇒ مش واقعة", () => {
    expect(isStalled(true, [9_500, 9_800], 10_000)).toBe(false);
  });

  it("⚠️ أعلى رحلة عادية اتقاست (٢.٧ث) ⇒ **مش** واقعة", () => {
    expect(isStalled(true, [10_000 - 2_700], 10_000)).toBe(false);
  });
});
