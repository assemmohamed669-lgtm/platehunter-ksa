import { describe, it, expect } from "vitest";
import {
  extractMultiplePlates,
  parsePlateFromTranscript,
  normalizePlate,
} from "../lib/plateParser";
import { newSessionState, parseSessionChunk } from "../lib/sessionParser";

// ─── قاعدة الواو في المسار المتعدد / مسار الجلسة ────────────────────────────
//
// ده **مسار الإنتاج**: شاشة التسجيل بتنادي parseSessionChunk، مش
// parsePlateFromTranscript. قاعدة المالك كانت متطبّقة في المسار المفرد بس:
//
//   «و» + كلمة عشرات (عشرين تلاتين اربعين خمسين ستين سبعين تمانين تسعين
//        + صيغة الـ ـون الفصحى)      ⇒ جمع    «تمانية وثمانين» = 88
//   «و» + أي حاجة تانية               ⇒ وصل    «تلاتة وواحد»    = 31
//
// اللي كان بيحصل: «وثمانين» توكن واحد في القاموس بيتحوّل للنص "80"، فبيوصل
// لـplateAtoms كذرّتين رقم عاديتين، وplateAtoms **بتلزق**:
//   2 · 20 · 8 · 80 → "2"+"20"+"8"+"80" = 2208… (بعد القص) بدل 2288.
//
// ⚠️ مصيدة: «واحد»/«وحده» بيبدأوا بواو لكنهم **مش** عشرات ⇒ وصل زي ما هما،
// وإلا «تسعة تسعة تسعة وواحد» تبقى 999+1=1000 بدل 9991.
//
// ⚠️ خطوة ٢.٥ (واو العطف الواقفة لوحدها بين رقمين) حاجة **تانية خالص** وشغّالة
// صح — مغطّاة في plateParser.test.ts ومحروسة هنا كمان.

const multi = (t: string) => extractMultiplePlates(t).map((p) => p.plate);
const session = (t: string) =>
  parseSessionChunk(t, newSessionState(), { final: true }).records.map((r) => r.plate);
const single = (t: string) => parsePlateFromTranscript(t).plate;

describe("مركّب الواو — مثال المالك على المسارات التلاتة", () => {
  const text = "دال سين كاف اتنين وعشرين تمانية وثمانين";

  it(`multi: «${text}» ⇒ [دسك2288] (كان دسك2208)`, () => {
    expect(multi(text)).toEqual(["دسك2288"]);
  });

  it(`session: «${text}» ⇒ [دسك2288] (كان دسك2208)`, () => {
    expect(session(text)).toEqual(["دسك2288"]);
  });

  it("المسار المفرد كان صح من الأول ولازم يفضل ⇒ دسك2288", () => {
    expect(single(text)).toBe("دسك2288");
  });

  it("مركّب واحد لوحده ⇒ دسك0088 على التلاتة", () => {
    const t = "دال سين كاف تمانية وثمانين";
    expect(multi(t)).toEqual(["دسك0088"]);
    expect(session(t)).toEqual(["دسك0088"]);
    expect(single(t)).toBe("دسك0088");
  });
});

