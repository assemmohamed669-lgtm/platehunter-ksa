import { describe, it, expect } from "vitest";
import { windowTailSec, shouldSlideWindow } from "@/lib/voicexEngine";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🎯 آخر لوحة في النطقة كانت بتاخد نافذة واحدة بس
 * ══════════════════════════════════════════════════════════════════════
 *
 * بلاغ المالك (٢٣ سبتمبر ٢٠٢٦): «المندوب بيقول ٥ أو ١٠ لوحات، وآخر
 * واحدة مش بتطلع — وبعدها بيسكت لحد ما يوصل لأقرب عربيات، والتسجيل
 * مفتوح عادي. وأوقات تطلع عادي».
 *
 * ── السبب ─────────────────────────────────────────────────────────────
 * النافذة الزاحفة بتبصّ **لورا** ٥ث وبتتحرك كل ١.٥ث. فأي لوحة بتتغطّى
 * بالنوافذ اللي بتنتهي في [T, T+5] ⇒ **٣-٤ نوافذ**.
 *
 * لكن الحلقة كانت بتقف بعد **١.٥ث** من آخر كلام:
 *     `if (!speaking && elapsed - lastSpokeSec > 1.5) return;`
 * فاللوحة الأخيرة بتتغطّى بالنوافذ اللي بتنتهي في [T, T+1.5] ⇒ **نافذة
 * واحدة بس**.
 *
 * ونافذة واحدة = قراءة مفردة، والمفردة بتواجه حاجز الاختراع
 * (`minSoloConf` و`soloMinLp`) — فبتعدّي لو ثقتها عالية و**تتحجب** لو لأ.
 * ده بالظبط «أوقات تطلع وأوقات لأ».
 *
 * ⇒ الذيل بقى **٥ث** (طول النافذة) عشان آخر لوحة تاخد نفس عدد النوافذ
 *   زي أي لوحة تانية. مش رقم مخترع — هو بالظبط اللي بيلغي الفرق.
 */
describe("ذيل النافذة بعد ما الكلام يقف", () => {
  it("🔴 الذيل = طول النافذة، مش أقل", () => {
    expect(windowTailSec(5)).toBe(5);
  });

  it("أثناء الكلام بتزحف دايماً", () => {
    expect(shouldSlideWindow(true, 100, 100, 5)).toBe(true);
    expect(shouldSlideWindow(true, 100, 20, 5)).toBe(true);
  });

  it("🔴 بعد آخر كلام بـ٣ث لسه بتزحف — هنا آخر لوحة بتتقري", () => {
    expect(shouldSlideWindow(false, 103, 100, 5)).toBe(true);
  });

  it("وبعد ٤.٩ث كمان", () => {
    expect(shouldSlideWindow(false, 104.9, 100, 5)).toBe(true);
  });

  it("وبتقف بعد ما تعدّي النافذة — مانفضلش نقرا سكوت", () => {
    expect(shouldSlideWindow(false, 105.1, 100, 5)).toBe(false);
    expect(shouldSlideWindow(false, 130, 100, 5)).toBe(false);
  });

  it("🔒 السلوك القديم كان بيقف بعد ١.٥ث — ده اللي كان بيضيّع الأخيرة", () => {
    // نفس اللحظة: القديم يقف، الجديد لسه شغّال
    expect(shouldSlideWindow(false, 102, 100, 5)).toBe(true);
    expect(102 - 100 > 1.5).toBe(true);
  });
});
