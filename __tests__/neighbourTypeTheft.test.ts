import { describe, it, expect } from "vitest";
import { scanTypeAndNote } from "@/lib/vehicleTypeScan";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🔴 اللوحة بتاخد نوع جارتها لما أرقام الجار تتمسخ
 * ══════════════════════════════════════════════════════════════════════
 *  القصّ بيربط **بداية** النافذة عند أرقام اللوحة، وبيوقف عند أرقام
 *  اللوحة اللي بعدها. بس لو الشاهد مسخ أرقام الجار مابيلاقيش وقفة
 *  وبيلفّ لآخر النص.
 *
 *  ⚠️ الحالة دي **منسوخة حرفياً** من جلسة ١٠٠ لوحة (٢٠ سبتمبر ٢٠٢٦):
 *  «متحركة» كانت لـ`يكق2192` ونزلت على `صسل2350` اللي قبلها، لأن
 *  «اتنين واحد ساعتين» مابتديش 2192.
 */

const REAL = "صاد سي اللام اتنين تلاته خمسين ي كاف قاف اتنين واحد ساعتين متحرك";

describe("🔴 سرقة نوع الجار", () => {
  it("اللوحة الأولى ماتاخدش نوع اللي بعدها", () => {
    const r = scanTypeAndNote(REAL, { afterPlate: "صسل2350" });
    expect(r.note, "«متحركة» بتاعة يكق2192 مش صسل2350").toBeNull();
    expect(r.type).toBeNull();
  });

  /**
   * 🛡️ والوقفة ماتاكلش النوع الشرعي: لو النوع بيتقال **قبل** حروف
   * اللوحة الجاية، لازم يفضل. الحالة دي من نفس الجلسة كذلك.
   */
  it("🛡️ النوع اللي قبل اللوحة الجاية بيفضل", () => {
    const r = scanTypeAndNote(
      "ص م ب خمسة تلاتة اربعة اتنين مبنشر ط هي زيرو واحد ستة سبعة",
      { afterPlate: "صمب5342" }
    );
    expect(r.note).toBe("مبنشره");
  });

  it("🛡️ عبارة فيها كلمات قصيرة ماتتقطعش", () => {
    const r = scanTypeAndNote(
      "د ك ن 81 65 جراش يمين ا ه ل 345 جراش يمين",
      { afterPlate: "دكن8165" }
    );
    expect(r.note).toBe("جراج يمين");
  });
});
