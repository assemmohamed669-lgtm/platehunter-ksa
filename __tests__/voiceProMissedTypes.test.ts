/**
 * 🏷️ الأنواع اللي فضلت تضيع بعد النوافذ اللي بعد اللوحة (٢٣ أكتوبر ٢٠٢٦ — قبل الفتح للكل). المالك: «اتأكد انها
 * شغاله كويس وبتطلع كل حاجه قدام لوحتها ومش بتفوت حاجه … ولو فيه اي تعديل عدلو».
 *
 * من ٢٩ ضايعة على ٢٤٠ لوحة بنوع (صوت المجمّع الحقيقي) — النصوص هنا **منقولة حرفياً** من كوهير:
 *  · «ونيل» (٣) و«توانيت» (٢) = ونيت · «ودباب» (الواو لازقة) · «ثلاث تمنيات أربعة» = 8884 · «ملاك» = ملاكي · «باث» = باص
 * ⛔ ماتضافش (اتقاست قبل كده وطلّعت أنواع غلط — شوف `vehicleTypeScan.ts`): «ونين» · «و ن» المقطوعة في آخر الكلام.
 * ⛔ وماتضافش لأنها كلمات عادية: «عمارة» (≠ غمارة) · «بان» (≠ فان) · «فهمت».
 */
import { describe, expect, it } from "vitest";
import { scanTypeAndNote } from "@/lib/vehicleTypeScan";

const scan = (t: string, p: string) => scanTypeAndNote(t, { afterPlate: p });

describe("النصوص الحقيقية اللي كانت بتضيع", () => {
  it("«ونيل» = ونيت", () => {
    expect(scan("باء تاس ميم واحد ستة واحد صفر ونيل", "بكم1610").type).toBe("ونيت");
    expect(scan("ا ب د س ستين خمسة اثنين ونيل.", "ادس6052").type).toBe("ونيت");
  });
  it("«توانيت» = ونيت", () => {
    expect(scan("صاديه ١٢٠٢٠٦ ونيت بـ6٪٤٣٤ ا ص ي واحد اتنين اتنين ستة توانيت", "اصي1226").type).toBe("ونيت");
  });
  it("«ودباب» (الواو لازقة) = دباب", () => {
    expect(scan("به به نون 8061 ودباب راحة حجال 67861", "ببن8061").type).toBe("دباب");
  });
  it("«ثلاث تمنيات أربعة» = 8884 ⇒ غمارة", () => {
    expect(scan("به صوت لام ثلاث تمنيات اربعة غمارة", "بصل8884").type).toBe("غمارة");
    expect(scan("بيه صوت ليهم ثلاث ثمانيات أربعة غمارة؟", "بصل8884").type).toBe("غمارة");
  });
  it("«ملاك» = ملاكي", () => {
    expect(scan("ب ا س اربعة اربعة اربعة تسعة ملاك يبارحة يمين", "باس4449").type).toBe("ملاكي");
  });
  it("«باث» = باص", () => {
    expect(scan("ب ص ب خمسة ستة اتنين ستة باث", "بصب5626").type).toBe("باص");
  });
});

describe("🛡️ ومايطلعش نوع غلط", () => {
  it("«ونين» لسه مش نوع (أرقام ممسوخة — دال0521)", () => {
    expect(scan("د ا ل صفر خمسة اتنين واحد ونين", "دال0521").type).toBeNull();
  });
  it("الواو اللي في أول كلمة مش نوع مابتتشالش", () => {
    expect(scan("ا ب ح واحد اتنين تلاتة اربعة وبعدين", "ابح1234").type).toBeNull();
    expect(scan("ا ب ح واحد اتنين تلاتة اربعة والشارع", "ابح1234").type).toBeNull();
  });
  it("«ونيت» نفسها لسه ونيت (مابتتقطعش «و» + «نيت»)", () => {
    expect(scan("ا ب ح واحد اتنين تلاتة اربعة ونيت", "ابح1234").type).toBe("ونيت");
  });
  it("«تمنيات» من غير عدّاد قبلها مش رقم", () => {
    expect(scan("ا ب ح واحد اتنين تلاتة اربعة تمنيات", "ابح1234").type).toBeNull();
  });
  it("كلمات عادية: «عمارة» / «بان» / «فهمت» مش أنواع", () => {
    expect(scan("ب ص ح واحد تسعة واحد تمانية عمارة", "بصح1918").type).toBeNull();
    expect(scan("ا ن ل اتنين صفر تلاتة تمانية بان", "انل2038").type).toBeNull();
  });
});
