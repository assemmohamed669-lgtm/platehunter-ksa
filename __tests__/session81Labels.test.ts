import { describe, it } from "vitest";
import { scanTypeAndNote } from "@/lib/vehicleTypeScan";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  جلسة الـ٨١ صف (٢٠ سبتمبر ٢٠٢٦) — اللي ضاع: قاموس ولا سمع؟
 * ══════════════════════════════════════════════════════════════════════
 *  ١٥ صف مطلعش نوعه/ملاحظته في الجلسة الحيّة. الاختبار ده بيمرّر
 *  **النص المكتوب صح** على الماسح. لو طلع ⇒ القاموس سليم والضياع من
 *  الموديل (ماسمعش الكلمة). لو مطلعش ⇒ القاموس هو العيب.
 */

const LOST: Array<[string, string]> = [
  ["حهق 4079 ملاكي", "ملاكي"],
  ["راح 7729 ونيت", "ونيت"],
  ["ررق 7075 نقل", "نقل"],
  ["ربل 3525 فان", "فان"],
  ["دحس 6215 تاكسي", "تاكسي"],
  ["رلل 4472 دينه", "دينه"],
  ["رال 3767 ديانا", "ديانا"],
  ["ددق 7622 نقليات", "نقليات"],
  ["رسا 9598 بي ام", "بي ام"],
  ["ددم 7151 متربه", "متربه"],
  ["ررق 9655 جراج يمين", "جراج يمين"],
  ["رسر 8658 جراج يسار", "جراج يسار"],
  ["راس 1892 برحه اخر الشارع يمين", "برحه اخر الشارع يمين"],
  ["ردن 2101 جراج اتنين يمين", "جراج اتنين يمين"],
  ["حطك 9966 جراج اتنين يسار", "جراج اتنين يسار"],
];

describe("جلسة الـ٨١ — اللي ضاع", () => {
  it("القاموس بيطلّعهم من النص السليم؟", () => {
    const ok: string[] = [];
    const bad: string[] = [];
    for (const [text, want] of LOST) {
      const r = scanTypeAndNote(text);
      const hits = [r.type, r.note].filter(Boolean) as string[];
      (hits.includes(want) ? ok : bad).push(
        `${want.padEnd(22)} ⇒ ${hits.join(" · ") || "لا شيء"}`
      );
    }
    // eslint-disable-next-line no-console
    console.log(
      `\n╔═══ القاموس على النص السليم · ${ok.length}/${LOST.length} ═══\n` +
        ok.map((s) => "║ ✅ " + s).join("\n") +
        (bad.length ? "\n" + bad.map((s) => "║ ❌ " + s).join("\n") : "") +
        `\n╚════════════════════════════════════\n`
    );
  });
});
