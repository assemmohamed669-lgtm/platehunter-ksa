import { describe, it, expect } from "vitest";
import { scanTypeAndNote } from "@/lib/vehicleTypeScan";

/**
 * 🔴 **الشاهد بيكتب عدّاد الجراج رقم مش كلمة.**
 *
 * من جلسة شيت الأنواع التانية (١٦ سبتمبر ٢٠٢٦) — نصوص حقيقية من السجل:
 *
 *     «ع ألف قاف 0674 جرش **2** يسار»     ⇒ لازم «جراج اتنين يسار»
 *     «ق ف ا هى 4 8 6 5 جراج **3** يسار»  ⇒ لازم «جراج تلاته يسار»
 *
 * والقائمة مكتوبة بالكلام («جراج اتنين يسار») فالعبارة كانت بتتقصّ
 * لـ«جراج يسار» — **مكان غلط بيتكتب في داتا المالك في صمت**.
 */
const note = (t: string, p: string) => scanTypeAndNote(t, { afterPlate: p }).note;

describe("عدّاد الجراج رقم", () => {
  it("الرقم يساوي كلمته", () => {
    expect(note("ع ألف قاف 0674 جرش 2 يسار", "عاق0674")).toBe("جراج اتنين يسار");
    expect(note("ق ف ا هى 4 8 6 5 جراج 3 يسار رهوة", "قاه4865")).toBe("جراج تلاته يسار");
    expect(note("م ك ط 8 9 2 9 جراش 3 يمين", "مكط8929")).toBe("جراج تلاته يمين");
    expect(note("م مراهقة في 4 2 7 2 جراش 1 يمين", "مرق4272")).toBe("جراج واحد يمين");
  });

  it("🛡️ الكلمة المكتوبة لسه شغّالة", () => {
    expect(note("ح 6 3 7 4 جراش واحد يسار", "حبح6374")).toBe("جراج واحد يسار");
    expect(note("تسعة اتنين تسعة جراش تلاتة يمين", "مكط8929")).toBe("جراج تلاته يمين");
    expect(note("حي ب 6075 جراج", "حيب6075")).toBe("جراج");
    expect(note("5 جراش لميا هي 3 2 4 1 جراش يمين", "ليه3241")).toBe("جراج يمين");
  });
});
