import { describe, it, expect } from "vitest";
import {
  orderedLabels, optionalAvailable, toggleColumn,
  LEADING_DEFAULT_LABELS, migrateColumnOrder,
} from "@/lib/columnOrder";

const AVAIL = ["نوع السيارة", "الماركة", "ملاحظة", "العنوان", "الحي", "GPS", "اللون", "سنة الصنع"];

describe("columnOrder", () => {
  it("الوضع المخصّص بلا اختيار → الافتراضي (نوع السيارة ثم الماركة)", () => {
    expect(orderedLabels(AVAIL, [])).toEqual(["نوع السيارة", "الماركة"]);
  });

  it("🔓 النوع والماركة بقوا زي أي عمود: المندوب يحطّهم في أي مكان", () => {
    expect(orderedLabels(AVAIL, ["اللون", "الماركة", "الحي", "نوع السيارة"])).toEqual(
      ["اللون", "الماركة", "الحي", "نوع السيارة"],
    );
  });

  it("🔓 الماركة تقدر تيجي قبل النوع", () => {
    expect(orderedLabels(AVAIL, ["الماركة", "نوع السيارة"])).toEqual(["الماركة", "نوع السيارة"]);
  });

  it("🔓 اللي ماختارهمش مايظهروش (مش متفروضين عليه)", () => {
    expect(orderedLabels(AVAIL, ["اللون", "الحي"])).toEqual(["اللون", "الحي"]);
  });

  it("مايكررش عمود اتحدّد مرتين", () => {
    expect(orderedLabels(AVAIL, ["الماركة", "اللون", "الماركة"])).toEqual(["الماركة", "اللون"]);
  });

  it("بيتجاهل أعمدة مش متاحة في الملف ده", () => {
    expect(orderedLabels(AVAIL, ["اسم المسجل", "اللون"])).toEqual(["اللون"]);
  });

  it("الافتراضي بيتقصّ على المتاح في الملف", () => {
    expect(orderedLabels(["الماركة", "اللون"], [])).toEqual(["الماركة"]);
  });

  it("optionalAvailable = كل المتاح ناقص رقم اللوحة بس — النوع والماركة جوّاها", () => {
    expect(optionalAvailable(["رقم اللوحة", ...AVAIL])).toEqual(AVAIL);
  });

  it("toggleColumn: يضيف آخر القائمة ويشيل", () => {
    expect(toggleColumn([], "اللون")).toEqual(["اللون"]);
    expect(toggleColumn(["اللون"], "الحي")).toEqual(["اللون", "الحي"]);
    expect(toggleColumn(["اللون", "الحي"], "اللون")).toEqual(["الحي"]);
  });

  it("الافتراضيان متعرّفان صح", () => {
    expect(LEADING_DEFAULT_LABELS).toEqual(["نوع السيارة", "الماركة"]);
  });
});

/**
 * قبل الفك كان النوع والماركة **مفروضين** في أول كل ترتيب. مندوب مرتّب أعمدته
 * خلاص (مثلاً ["اللون","الحي"]) كان بيشوف: النوع · الماركة · اللون · الحي.
 * لو فكّينا القفل من غير ترحيل، العمودين كانوا هيختفوا من عنده فجأة — ده كسر
 * لحاجة شغّالة. الترحيل بيحطّهم في أول ترتيبه **مرة واحدة**، وبعد كده هو حر.
 */
describe("migrateColumnOrder — اللي مرتّب خلاص مايفقدش عمودين فجأة", () => {
  it("بيحط النوع والماركة في أول ترتيب موجود", () => {
    expect(migrateColumnOrder(["اللون", "الحي"])).toEqual(
      ["نوع السيارة", "الماركة", "اللون", "الحي"],
    );
  });

  it("مايكررش اللي المندوب مختاره أصلاً", () => {
    expect(migrateColumnOrder(["الماركة", "اللون"])).toEqual(
      ["نوع السيارة", "الماركة", "اللون"],
    );
  });

  it("الترتيب الفاضي بيفضل فاضي (الافتراضي بيتكفّل بيه)", () => {
    expect(migrateColumnOrder([])).toEqual([]);
  });
});
