  "0339": "ك", "033a": "ل", "033b": "م", "033c": "ن", "033d": "ه", "033e": "ه", "033f": "ه", "0340": "ي", "0341": "ي",
  "0342": "ة", "0343": "ى", "0344": "،", "0345": "ئ", "0346": "لا", "0347": "لا", "034b": "لأ", "034c": "لأ", "034d": "لآ",
  "034e": "ئ", "0350": "لآ", "0353": "ء", "0354": "آ", "0355": "أ", "0356": "ؤ", "0357": "إ", "0359": "ا", "035a": "ب",
  "035b": "ة", "035c": "ت", "035d": "ث", "035f": "ح", "0361": "د", "0362": "ذ", "0363": "ر", "0365": "س", "0366": "ش",
