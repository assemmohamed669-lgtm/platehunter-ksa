import { describe, it, expect } from "vitest";
import { buildExportRows, toExportRow } from "@/lib/exportColumns";

/**
 * ملف التصدير كان بيطلع فيه «الماركة» مرتين و«العنوان» مرتين وأعمدة فاضية،
 * لأن الأعمدة كانت اتحاد مفاتيح صفوف الداتا + صفوف السجلات.
 */
const dataRow = {
  "رقم اللوحة": "رسع6876",
  "طراز المركبة": "توسان",
  "العنوان": "عزيز بعد تالت تقاطع 127",
  "GPS": "https://maps.google.com/?q=21.5,39.2",
  "صانع المركبة": "هونداي",
  "لون المركبة الأساسي": "ابيض",
  "سنة الصنع": "2023",
  "الحالة": "مطلوبة",
  "رقم الهيكل": "XYZ123",
};

const recordRow = {
  "رقم اللوحة": "ريي3706",
  "النوع": "يارس",
  "الحي-الشارع": "الصفاء - الصفاء",
  "GPS": "https://maps.google.com/?q=21.58,39.19",
  "ملاحظات": "",
  "التاريخ": "05-09-2026 04:15",
  "المندوب": "محمد عفيفي",
  "الحالة": "متشيكة بالصوت",
};

describe("أعمدة التصدير الموحّدة", () => {
  it("الترتيب زي ما المالك طلبه", () => {
    const { columns } = buildExportRows([dataRow, recordRow]);
    expect(columns.slice(0, 9)).toEqual([
      "رقم اللوحة", "نوع السيارة", "الحي-الشارع", "GPS", "الماركة",
      "اللون", "سنة الصنع", "تاريخ التسجيل", "المندوب",
    ]);
  });

  it("أعمدة المعنى الواحد بتتلمّ في عمود واحد — مافيش تكرار", () => {
    const { rows } = buildExportRows([dataRow, recordRow]);
    expect(rows[0]["نوع السيارة"]).toBe("توسان");      // «طراز المركبة»
    expect(rows[1]["نوع السيارة"]).toBe("يارس");       // «النوع»
    expect(rows[0]["الحي-الشارع"]).toBe("عزيز بعد تالت تقاطع 127"); // «العنوان»
    expect(rows[1]["الحي-الشارع"]).toBe("الصفاء - الصفاء");
    expect(rows[0]["الماركة"]).toBe("هونداي");
    expect(rows[0]["اللون"]).toBe("ابيض");
  });

  it("العمود الفاضي في كل الصفوف بيتشال", () => {
    const { columns } = buildExportRows([dataRow, recordRow]);
    expect(columns).not.toContain("ملاحظة");   // فاضية في الاتنين
  });

  it("العمود اللي مالوش مكان في الترتيب مابيضيعش", () => {
    const { columns, rows } = buildExportRows([dataRow]);
    expect(columns).toContain("رقم الهيكل");
    expect(rows[0]["رقم الهيكل"]).toBe("XYZ123");
  });

  it("الخانة الفاضية مابتاكلش مكان خانة فيها قيمة", () => {
    const r = toExportRow({ "النوع": "", "طراز المركبة": "كامري" });
    expect(r["نوع السيارة"]).toBe("كامري");
  });
});

/**
 * عمود «نوع السيارة (المحفظة)» — نوع السيارة اللي جاي من شيت الإحالة.
 *
 * الباج: `toExportRow` كانت بتعتبر العمودين (نوع الداتا ونوع المحفظة) **مرشحين
 * لخانة واحدة** و«أول قيمة تكسب». النتيجة على صفوف حقيقية:
 *   • الصف اللي نوعه موجود في الداتا  → نوع المحفظة بيتزقّ **آخر الجدول بعد «الحالة»**
 *   • الصف اللي نوعه فاضي في الداتا   → نوع المحفظة بياخد مكان عمود الداتا
 * فالعمود بقى معناه بيتغيّر من صف لصف، ولو المحفظة فاضية في كل الصفوف اللي
 * الداتا فيها نوع، العمود بيتشال خالص ⇒ «نوع السيارة من المحفظة مش بيطلع».
 *
 * القاعدة: أي عمود متسمّي بمصدره — «... (المحفظة)» أو «... (الداتا)» — بيفضل
 * **عمود مستقل** جنب أخوه، مايسرقش خانته ولا يتزقّ آخر الملف.
 */
describe("عمود المصدر المتسمّي (المحفظة/الداتا)", () => {
  const rows = [
    { "رقم اللوحة": "أ", "نوع السيارة": "ونيت", "نوع السيارة (المحفظة)": "كامري", "الحالة": "مطلوبة" },
    { "رقم اللوحة": "ب", "نوع السيارة": "",     "نوع السيارة (المحفظة)": "النترا", "الحالة": "مطلوبة" },
    { "رقم اللوحة": "ج", "نوع السيارة": "دباب", "نوع السيارة (المحفظة)": "",       "الحالة": "مطلوبة" },
  ];

  it("عمود المحفظة مايسرقش خانة عمود الداتا لما الداتا تكون فاضية", () => {
    const { rows: out } = buildExportRows(rows);
    expect(out[1]["نوع السيارة"]).toBe("");
    expect(out[1]["نوع السيارة (المحفظة)"]).toBe("النترا");
  });

  it("كل عمود بيفضل على قيمته هو في كل الصفوف", () => {
    const { rows: out } = buildExportRows(rows);
    expect(out.map((r) => r["نوع السيارة"])).toEqual(["ونيت", "", "دباب"]);
    expect(out.map((r) => r["نوع السيارة (المحفظة)"])).toEqual(["كامري", "النترا", ""]);
  });

  it("بيقف جنب أخوه مش مرمي آخر الملف", () => {
    // عمود غريب في الآخر — الأعمدة الغريبة بتتلحق آخر الملف، وعمود المحفظة
    // المفروض يقف جنب أخوه **قبلها**، مش يتحط معاها.
    const { columns } = buildExportRows(rows.map((r) => ({ ...r, "عمود غريب": "قيمة" })));
    const i = columns.indexOf("نوع السيارة");
    expect(columns[i + 1]).toBe("نوع السيارة (المحفظة)");
    expect(columns.indexOf("نوع السيارة (المحفظة)")).toBeLessThan(columns.indexOf("عمود غريب"));
  });

  it("لو عمود المحفظة فاضي في كل الصفوف بيتشال زي أي عمود فاضي", () => {
    const { columns } = buildExportRows([
      { "رقم اللوحة": "أ", "نوع السيارة": "ونيت", "نوع السيارة (المحفظة)": "", "الحالة": "مطلوبة" },
    ]);
    expect(columns).not.toContain("نوع السيارة (المحفظة)");
    expect(columns).toContain("نوع السيارة");
  });

  it("الأعمدة الغريبة اللي مالهاش مكان لسه بتتلحق آخر الملف", () => {
    const { columns } = buildExportRows([
      { "رقم اللوحة": "أ", "نوع السيارة": "ونيت", "حاجة غريبة": "قيمة", "الحالة": "مطلوبة" },
    ]);
    expect(columns[columns.length - 1]).toBe("حاجة غريبة");
  });
});

/**
 * عمود «الحالة» اتشال من نتيجة الفرز بالكامل (بطلب المالك).
 *
 * كان البرنامج بيحطّه بنفسه بقيمة **«مطلوبة» في كل صف** — يعني معلومة صفر،
 * بياخد عرض من الجدول والصورة بلا أي فايدة. والشيل لازم يكون **صريح**: مجرد
 * إني أشيله من الترتيب مش كفاية، لأن أي عمود مش في الترتيب بيتلحق آخر الملف.
 */
describe("عمود «الحالة» مايظهرش في نتيجة الفرز", () => {
  it("بيتشال حتى لو الصف جايبه معاه", () => {
    const { columns, rows } = buildExportRows([
      { "رقم اللوحة": "رري3706", "نوع السيارة": "ونيت", "الحالة": "مطلوبة" },
    ]);
    expect(columns).not.toContain("الحالة");
    expect(rows[0]).not.toHaveProperty("الحالة");
  });

  it("مايتلحقش آخر الملف مع الأعمدة الغريبة", () => {
    const { columns } = buildExportRows([
      { "رقم اللوحة": "رري3706", "الحالة": "مطلوبة", "حاجة غريبة": "قيمة" },
    ]);
    expect(columns).toEqual(["رقم اللوحة", "حاجة غريبة"]);
  });

  it("مايشيلش عمود اسمه قريب زي «الحالة الفنية» — المطابقة كاملة", () => {
    const { columns } = buildExportRows([
      { "رقم اللوحة": "رري3706", "الحالة الفنية": "ممتازة" },
    ]);
    expect(columns).toContain("الحالة الفنية");
  });
});

/**
 * الأعمدة اللي بتتلمّ تحت نفس الخانة لازم تقف **جنب بعض**.
 *
 * «العنوان» و«الحي» الاتنين بيطابقوا خانة «الحي-الشارع». واحد بس كان بيكسب
 * الخانة، والتاني بيتزقّ **آخر الملف** — فالمندوب اللي مختار «الحي» رقم ٤
 * كان بيلاقيه آخر عمود في الإكسيل والصورة مهما عمل.
 *
 * نفس اللي حصل مع «نوع السيارة (المحفظة)» في #222 — بس ده كان الحل فيه مقصور
 * على الأعمدة المتسمّية بمصدرها. القاعدة دلوقتي عامة: أي عمود بيطابق خانة
 * متاخدة بيقف **بعدها على طول**، مش آخر الملف.
 */
describe("الأعمدة الشقيقة بتقف جنب بعض", () => {
  it("«الحي» بيقف بعد «الحي-الشارع» مش آخر الملف", () => {
    const { columns } = buildExportRows([{
      "رقم اللوحة": "رري3706", "نوع السيارة": "كامري",
      "العنوان": "شارع 208", "الحي": "النسيم الغربي",
      "GPS": "https://maps.example/x",
    }]);
    expect(columns).toEqual(["رقم اللوحة", "نوع السيارة", "الحي-الشارع", "الحي", "GPS"]);
  });

  it("عمود المحفظة لسه جنب أخيه (ماكسرناش #222)", () => {
    const { columns } = buildExportRows([{
      "رقم اللوحة": "أ", "نوع السيارة": "ونيت", "نوع السيارة (المحفظة)": "كامري", "اللون": "ابيض",
    }]);
    const i = columns.indexOf("نوع السيارة");
    expect(columns[i + 1]).toBe("نوع السيارة (المحفظة)");
  });

  it("العمود اللي مالوش أي خانة لسه بيتلحق آخر الملف", () => {
    const { columns } = buildExportRows([{
      "رقم اللوحة": "أ", "الحي": "النسيم", "حاجة غريبة": "قيمة",
    }]);
    expect(columns[columns.length - 1]).toBe("حاجة غريبة");
  });

  it("تلات إخوة بيقفوا ورا بعض بترتيب ظهورهم", () => {
    const { columns } = buildExportRows([{
      "رقم اللوحة": "أ", "العنوان": "ش 1", "الشارع": "ش 2", "الحي": "النسيم",
    }]);
    expect(columns).toEqual(["رقم اللوحة", "الحي-الشارع", "الشارع", "الحي"]);
  });
});
