import { describe, it, expect } from "vitest";
import { parsePlateFromTranscript, normalizePlate } from "../lib/plateParser";

// ─── مداخل قاموس الأرقام المنطوقة ──────────────────────────────────────────
//
// المصدر: `docs/spoken-numbers-dictionary.md` — «★ القائمة النهائية المعروضة
// للموافقة» (٢٠٢٦/٠٨/٠١). المستويات ١ و٢ و٣ بس. المستوى ٤ (المثنى ما عدا
// «صفرين» · «امية» · «خمس مية» · «دبل») **مرفوض بقياس** ومش هنا.
//
// المداخل دي **إضافية**: كل صيغة شغّالة النهاردة لازم تفضل شغّالة بالحرف —
// عشان كده في آخر الملف قسم حراسة بيثبّت الصيغ المنطوقة اللي المندوب
// بيستعملها فعلاً دلوقتي.
//
// ⚠️ التكلفة المقبولة (قرار المالك): «ستات» كلمة عربية عادية (نساء)، فجملة
// زي «شفت تلات ستات» هتطلّع ٦٦٦. المالك قبلها صراحةً — المندوب بيملي لوحة
// مش بيتكلم كلام عادي، والمكسب (أكتر صيغة تكرار في صوتنا) أكبر.

const plate = (t: string) => parsePlateFromTranscript(t).plate;
const norm = (t: string) => normalizePlate(parsePlateFromTranscript(t).plate);

// ─── مستوى ١: «صفرين» = 00 ──────────────────────────────────────────────────
describe("قاموس — «صفرين» = 00", () => {
  it("«صفرين صفرين» = لوحة كلها أصفار", () => {
    expect(plate("حاء باء كاف صفرين صفرين")).toBe("حبك0000");
  });

  it("«واحد اتنين صفرين» = 1200", () => {
    expect(plate("حاء باء كاف واحد اتنين صفرين")).toBe("حبك1200");
  });

  it("«صفرين تسعة تسعة» = 0099 — الصفرين في الأول", () => {
    expect(plate("حاء باء كاف صفرين تسعة تسعة")).toBe("حبك0099");
  });
});

// ─── مستوى ١: «أربع × رقم» = اللوحة كاملة (٤ خانات) ─────────────────────────
describe("قاموس — «أربع × رقم» = ٤ خانات", () => {
  const cases: [string, string][] = [
    ["اربع اصفار", "حبك0000"],
    ["اربع تصفار", "حبك0000"],
    ["اربع وحايد", "حبك1111"],
    ["اربع اتنينات", "حبك2222"],
    ["اربع تلاتات", "حبك3333"],
    ["اربع ثلاثات", "حبك3333"],
    ["اربع اربعات", "حبك4444"],
    ["اربع خمسات", "حبك5555"],
    ["اربع سبعات", "حبك7777"],
    ["اربع تمنيات", "حبك8888"],
    ["اربع تمانيات", "حبك8888"],
    ["اربع ثمانيات", "حبك8888"],
    ["اربع تسعات", "حبك9999"],
  ];
  for (const [spoken, expected] of cases) {
    it(`«${spoken}» ⇒ ${expected}`, () => {
      expect(plate(`حاء باء كاف ${spoken}`)).toBe(expected);
    });
  }

  // الأنبوب بيحوّل أإآ→ا قبل القاموس في كل المسارات، فمدخل الألف العادية
  // بيمسك النطق المهموز كمان. الاختبار ده هو اللي بيثبت إننا مش محتاجين
  // مدخل مكرر بالهمزة لكل عبارة.
  it("النطق بالهمزة «أربع أصفار» بيمسكه مدخل الألف العادية", () => {
    expect(plate("حاء باء كاف أربع أصفار")).toBe("حبك0000");
  });

  it("النطق بالهمزة «أربع أربعات» بيمسكه مدخل الألف العادية", () => {
    expect(plate("حاء باء كاف أربع أربعات")).toBe("حبك4444");
  });
});

// ─── مستوى ٣ (قرار المالك): «ستات» ──────────────────────────────────────────
// «تلات/ثلاث ستات» فضلت — دي اللي المالك وافق عليها ودي اللي في الصوت الحقيقي
// (٧ ورودات، كلها إملاء لوحة). «اربع ستات» **اتشالت** بعد القياس: صفر ورود
// حقيقي، و«شفت اربع ستات» كانت بتطلّع ٦٦٦٦ كاملة — لوحة قابلة للمطابقة، غير
// الـ٠٦٦٦ اللي المالك اتعرضت عليه ووافق. التفاصيل في spokenNumbersRemovals.
describe("قاموس — «ستات» (قرار المالك)", () => {
  // مثال المالك بالحرف — كان بيطلّع حبك0093 قبل المدخل ده.
  it("«تسعة تلات ستات» ⇒ حبك9666 — مثال المالك", () => {
    expect(plate("حاء باء كاف تسعة تلات ستات")).toBe("حبك9666");
  });

  it("«ثلاث ستات» جوّه إملاء لوحة = ٦٦٦", () => {
    expect(norm("راء حاء عين ثلاث ستات سبعة")).toBe(normalizePlate("رحع6667"));
  });
});

// ─── مستوى ٢: «تلات × رقم» = ٣ خانات + خانة قبلها ───────────────────────────
describe("قاموس — «تلات × رقم» = ٣ خانات", () => {
  const cases: [string, string][] = [
    ["واحد تلات تصفار", "حبك1000"],
    ["اتنين تلاتصفار", "حبك2000"],
    ["واحد تلات وحايد", "حبك1111"],
    ["اتنين تلات اتنينات", "حبك2222"],
    ["تلاتة تلات تلاتات", "حبك3333"],
    ["اربعة تلات اربعات", "حبك4444"],
    ["ستة تلات سبعات", "حبك6777"],
    ["تمانية تلات تمنيات", "حبك8888"],
    ["تمانية تلات ثمانيات", "حبك8888"],
    ["تمانية تلات تمانيات", "حبك8888"],
  ];
  for (const [spoken, expected] of cases) {
    it(`«${spoken}» ⇒ ${expected}`, () => {
      expect(plate(`حاء باء كاف ${spoken}`)).toBe(expected);
    });
  }

  // مثال المالك بالحرف — كان بيطلّع حبك0013 قبل المدخل ده.
  it("«حه به كاف واحد تلات تسعات» ⇒ حبك1999 — مثال المالك", () => {
    expect(plate("حه به كاف واحد تلات تسعات")).toBe("حبك1999");
  });

  // نفس الرقم بكل إملاءات كلمة «تلاتة» اللي المالك والتفريغ بيستعملوها.
  const heads = ["تلات", "ثلاث", "تلاته", "تالت"];
  for (const head of heads) {
    it(`«واحد ${head} تسعات» ⇒ حبك1999`, () => {
      expect(plate(`حاء باء كاف واحد ${head} تسعات`)).toBe("حبك1999");
    });
  }

  it("«تالت تلتات» = 333 — إملاء المالك لجمع التلاتة", () => {
    expect(plate("حاء باء كاف تلاتة تالت تلتات")).toBe("حبك3333");
  });
});

// ─── مستوى ٢: الآلاف بإملاء المالك — **اتشالت كلها بعد القياس** ─────────────
// كانت ٢٦ مدخل (ستلاف · «X تلاف» · «X الاف»). القياس: صفر ورود لأي واحدة منهم
// في ٧٢ ألف حرف تفريغ ميداني حقيقي، ومكسبها (٦٣ إصلاح) كله على داتا مولَّدة من
// نفس قائمة الإملاء. مقابل ده كانت ملاحظة فلوس قبل اللوحة بتاكل اللوحة، و«تمن»
// في المصري = السعر. الحراسة الكاملة في `spokenNumbersRemovals.test.ts`.
describe("قاموس — الآلاف: الفصحى فضلت والعامّية اتشالت", () => {
  // الصيغة الفصحى بالتاء المربوطة موجودة من قبل المهمة و**ما اتلمستش**.
  const kept: [string, string][] = [
    ["خمسة الاف", "حبك5000"],
    ["ستة الاف", "حبك6000"],
    ["تسعة الاف", "حبك9000"],
    ["ألفين", "حبك2000"],
  ];
  for (const [spoken, expected] of kept) {
    it(`الفصحى «${spoken}» ⇒ ${expected}`, () => {
      expect(norm(`حاء باء كاف ${spoken}`)).toBe(normalizePlate(expected));
    });
  }

  // 5000 لسه ليها طريق — الصيغة اللي المندوب بيستعملها فعلاً في الصوت.
  it("5000 عبر «خمسة تلات تصفار» (الصيغة اللي في الصوت الحقيقي)", () => {
    expect(plate("حاء باء كاف خمسة تلات تصفار")).toBe("حبك5000");
  });
});

// ─── مستوى ٢: المئات المدغمة بواو ───────────────────────────────────────────
describe("قاموس — المئات المدغمة «خومسمية» و«ستومية»", () => {
  it("«واحد خومسمية» ⇒ حبك1500", () => {
    expect(plate("حاء باء كاف واحد خومسمية")).toBe("حبك1500");
  });

  it("«واحد خومسميه» ⇒ حبك1500", () => {
    expect(plate("حاء باء كاف واحد خومسميه")).toBe("حبك1500");
  });

  it("«ستة ستومية» ⇒ حبك6600", () => {
    expect(plate("حاء باء كاف ستة ستومية")).toBe("حبك6600");
  });

  it("«ستة ستوميه» ⇒ حبك6600", () => {
    expect(plate("حاء باء كاف ستة ستوميه")).toBe("حبك6600");
  });
});

// ─── مستوى ٢: الصيغة الفصحى/السعودية (ـون) بواو ─────────────────────────────
// «اثنان وعشرون» كان بيتكسر: الكود بيمسك 2 ويفشل في «وعشرون» لأن جدول الواو
// فيه صيغ الـ ـين بس. والمركّب لازم يتجمع (قاعدة الواو + عشرات صحيحة).
describe("قاموس — العشرات الفصحى بواو (ـون)", () => {
  const cases: [string, string][] = [
    ["اثنان وعشرون تمانية وثمانين", "حبك2288"],
    ["اثنان وعشرون تسعة وتسعون", "حبك2299"],
    ["خمسة وخمسون ستة وستون", "حبك5566"],
    ["تلاتة وثلاثون أربعة وأربعون", "حبك3344"],
    ["سبعة وسبعون تمانية وثمانون", "حبك7788"],
  ];
  for (const [spoken, expected] of cases) {
    it(`«${spoken}» ⇒ ${expected}`, () => {
      expect(plate(`حاء باء كاف ${spoken}`)).toBe(expected);
    });
  }

  // «ثنان» المختصرة **اتشالت** — الحراسة في spokenNumbersRemovals. اللي بيهم
  // المكسب هنا هو الـ٨ كلمات ـون نفسها (١٦٠٧ إصلاح)، ومالهاش دعوة بـ«ثنان».
});

// ─── حراسة: كل صيغة شغّالة النهاردة لازم تفضل زي ما هي ──────────────────────
describe("قاموس — حراسة عدم الانحدار", () => {
  const guards: [string, string][] = [
    // الصيغ المفكوكة اللي المندوب بيستعملها فعلاً دلوقتي
    ["حه به كاف واحد تسعه تسعه تسعه", "حبك1999"],
    ["حاء باء كاف واحد تسعة تسعة تسعة", "حبك1999"],
    ["حاء باء كاف تسعة ستة ستة ستة", "حبك9666"],
    ["الف لام به واحد خمسة صفر صفر", "الب1500"],
    ["دال سين كاف اتنين اتنين تمانية تمانية", "دسك2288"],
    ["حاء باء كاف واحد اتنين تلاتة وواحد", "حبك1231"],
    // بنية «رقم + تلات اصفار» — كانت شغّالة قبل أي إضافة
    ["حاء باء كاف واحد تلات اصفار", "حبك1000"],
    ["حاء باء كاف خمسة تلات اصفار", "حبك5000"],
    ["حاء باء كاف تلاتة تلات اصفار", "حبك3000"],
    ["حاء باء كاف خمسة تلات خمسات", "حبك5555"],
    // الكلمات المفردة لازم تفضل أرقام مفردة — العبارة الأطول ما تاكلهاش
    ["حاء باء كاف اربع تسعة تسعة تسعة", "حبك4999"],
    ["حاء باء كاف تلات تسعة تسعة تسعة", "حبك3999"],
    ["حاء باء كاف ست تسعة تسعة تسعة", "حبك6999"],
    ["حاء باء كاف خمس تسعة تسعة تسعة", "حبك5999"],
    ["حاء باء كاف تسع تسعة تسعة تسعة", "حبك9999"],
    // مركّبات الواو العامّية (صيغة ـين) زي ما هي
    ["دال سين كاف اتنين وعشرين تمانية وثمانين", "دسك2288"],
    ["حاء باء كاف ستة وستين تسعة وتسعين", "حبك6699"],
    // الآلاف الفصحى الموجودة أصلاً
    ["حاء باء كاف خمسة الاف", "حبك5000"],
    ["حاء باء كاف ستة الاف", "حبك6000"],
    ["حاء باء كاف ألفين", "حبك2000"],
  ];
  for (const [spoken, expected] of guards) {
    it(`«${spoken}» ⇒ ${expected}`, () => {
      expect(norm(spoken)).toBe(normalizePlate(expected));
    });
  }
});
