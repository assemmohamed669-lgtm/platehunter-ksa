import { describe, it, expect } from "vitest";
import { areaOf, AREA_COLUMN } from "@/lib/fieldCheckView";
import { AREA_KEY } from "@/lib/trialRecords";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🏘️ «الحي والشارع بيظهروا وقت التشييك وبيضيعوا بعد التصدير»
 * ══════════════════════════════════════════════════════════════════════
 *  بلاغ المالك (٣٠ سبتمبر ٢٠٢٦): المندوب شايف «اسم الحي - الشارع» قدام كل
 *  لوحة وهو بيشيّك في صفحة «الجديد»، وأول ما يصدّر للسجلات بيختفي — ولا في
 *  الجدول ولا في ملف الإكسيل اللي بيشاركه.
 *
 *  السبب: **اسمين مختلفين لنفس الحاجة**.
 *    • صفحة «الجديد» (Voice PRO) بتكتبه تحت  «اسم الحي - الشارع»
 *    • صفحة التشييك والسجلات والتصدير بيقروا «الحي-الشارع»
 *  فالقيمة موجودة في السجل بس محدش بيدوّر عليها بالاسم الصح ⇒ خانة فاضية.
 *
 *  الحل: قراية واحدة بتفهم الاسمين — فالسجلات القديمة (١٠٬٨١٦ لوحة) بتبان
 *  من غير أي تعديل على الداتا ولا ترحيل.
 */
describe("قراية «الحي - الشارع» بتفهم الاسمين", () => {
  it("الاسم اللي صفحة التشييك بتكتبه", () => {
    expect(areaOf({ [AREA_COLUMN]: "الشولة - حي السعادة" })).toBe("الشولة - حي السعادة");
  });

  it("🔴 الاسم اللي صفحة «الجديد» بتكتبه — ده اللي كان ضايع", () => {
    expect(areaOf({ [AREA_KEY]: "الشواطئ - حي السعادة" })).toBe("الشواطئ - حي السعادة");
  });

  it("الاتنين موجودين ⇒ الاسم الأساسي يكسب", () => {
    expect(areaOf({ [AREA_COLUMN]: "أ", [AREA_KEY]: "ب" })).toBe("أ");
  });

  it("الأساسي فاضي والتاني فيه قيمة ⇒ ياخد اللي فيه قيمة", () => {
    expect(areaOf({ [AREA_COLUMN]: "   ", [AREA_KEY]: "الشولة - حي السعادة" }))
      .toBe("الشولة - حي السعادة");
  });

  it("مفيش ولا واحد ⇒ نص فاضي (مش undefined ولا «غير متاح»)", () => {
    expect(areaOf({})).toBe("");
    expect(areaOf(undefined)).toBe("");
    expect(areaOf({ "رقم اللوحة": "ابح1234" })).toBe("");
  });

  it("بيشيل الفراغات الزيادة", () => {
    expect(areaOf({ [AREA_KEY]: "  الشولة - حي السعادة  " })).toBe("الشولة - حي السعادة");
  });

  it("الاسمين مختلفين فعلاً — لو اتوحّدوا يوم، الاختبار ده بيقول", () => {
    expect(AREA_COLUMN).not.toBe(AREA_KEY);
  });
});
