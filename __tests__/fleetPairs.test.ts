import { describe, it, expect } from "vitest";
import { isFleetPair, FleetMemory, FLEET_MAX_STEP, FLEET_GAP_MS, FLEET_GAP_MAX_STEP } from "@/lib/fleetPairs";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  🚚 أسطول الأرقام المتسلسلة — «حبل1234 حبل1235 حبل1236»
 * ══════════════════════════════════════════════════════════════════════
 *  المالك (٢٤ سبتمبر ٢٠٢٦): «لما بيبقى فيه أسطول سيارات لشركة أرقامها متسلسلة
 *  حبل1234 حبل1235 حبل1236… لما بيقول السيارات بالتسلسل ده مش بيظهروا، بيعدّل
 *  على السيارة اللي قالها ومش بيكتب التسلسل».
 *
 *  الدليل (٧٦ تسجيل مناديب · ٤٬٠٤٥ لوحة · موديل ٧٥٠٠): لوحتين بنفس الحروف
 *  **في نافذة واحدة**:
 *    · أسطول حقيقي  : دعن6156/6157 · داط5801/5803 · رعو2472/2473 — فرق ١–٢
 *    · غلط سمع      : بمم8788/6789 · الن6337/6077 · ارع5333/5773 … — فرق ٢٦٠+
 *  ⇒ مفيش ولا غلط واحد فرقه ≤ ١٠.
 */
describe("isFleetPair — «ده أسطول مش غلط سمع»", () => {
  it("🔴 متسلسلة بنفس الحروف ⇒ عربيتين", () => {
    expect(isFleetPair("حبل1234", "حبل1235")).toBe(true);
    expect(isFleetPair("حبل1236", "حبل1234")).toBe(true);
    expect(isFleetPair("داط5801", "داط5803")).toBe(true);
  });
  it("🔴 عبور العشرة (1239 ⇐ 1240) — خانتين مختلفين بس متتاليين", () => {
    expect(isFleetPair("حبل1239", "حبل1240")).toBe(true);
    expect(isFleetPair("حبل1299", "حبل1300")).toBe(true);
  });
  it(`الحد ${FLEET_MAX_STEP} بالظبط`, () => {
    expect(isFleetPair("حبل1230", "حبل1240")).toBe(true);
    expect(isFleetPair("حبل1230", "حبل1241")).toBe(false);
  });
  it("🔴 أغلاط السمع المقيسة في نفس النافذة ⇒ لأ (كلها بعيدة)", () => {
    expect(isFleetPair("بمم8788", "بمم6789")).toBe(false);
    expect(isFleetPair("الن6337", "الن6077")).toBe(false);
    expect(isFleetPair("ارع5333", "ارع5773")).toBe(false);
    expect(isFleetPair("رلع6055", "رلع6022")).toBe(false);
  });
  it("حروف مختلفة · نفس اللوحة · شكل مش لوحة ⇒ لأ", () => {
    expect(isFleetPair("حبل1234", "حبك1235")).toBe(false);
    expect(isFleetPair("حبل1234", "حبل1234")).toBe(false);
    expect(isFleetPair("حبل123", "حبل124")).toBe(false);
    expect(isFleetPair("", "حبل1234")).toBe(false);
  });
});

/**
 * ══════════════════════════════════════════════════════════════════════
 *  FleetMemory — الدليل: كل عربية اتقرت في نافذتين+ وقراياتهم مش متداخلة
 * ══════════════════════════════════════════════════════════════════════
 *  تجربة المالك (٢٤ سبتمبر): «قلت دبر2102 و2103 و2104، ماكتبش غير 2104 —
 *  كان بيعدّل على آخر لوحة». قالهم **بسكتة بين كل عربية** ⇒ مفيش نافذة سمعت
 *  اتنين مع بعض ⇒ الدليل القديم (نافذة مشتركة بس) ماشتغلش.
 *
 *  الأسطول الحقيقي: كل عربية بتتقري في نوافذها **ورا بعض** — ٢١٠٢ ٢١٠٢ ثم
 *  ٢١٠٣ ٢١٠٣. وغلطتين السمع المقيستين من الشارع شكلهم مختلف:
 *    · سطل6789 ٦٧٨٩ ← ٦٧٨٧ ٦٧٨٧ ← ٦٧٨٩ ٦٧٨٩  (الغلط **وسط** قرايات الصح)
 *    · حنل7220 ٧٢٢٩ ٧٢٢٩ ← ٧٢٢٠              (الصح اتقرا **مرة** بس)
 */
const at = (m: FleetMemory, t: number, ...plates: string[]) => m.note(plates, t * 1000);

describe("FleetMemory — أسطول بسكتة بين كل عربية (تجربة المالك)", () => {
  it("🔴 كل عربية في نوافذها لوحدها ورا بعض ⇒ عربيتين", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102");
    at(m, 7.5, "دبر2103"); at(m, 9, "دبر2103");
    expect(m.distinct("دبر2102", "دبر2103")).toBe(true);
    expect(m.distinct("دبر2103", "دبر2102")).toBe(true);
  });
  it("🔴 التسلسل كله من غير ولا نافذة مشتركة ⇒ كل الأزواج", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102");
    at(m, 7.5, "دبر2103"); at(m, 9, "دبر2103");
    at(m, 13.5, "دبر2104"); at(m, 15, "دبر2104");
    expect(m.distinct("دبر2102", "دبر2104")).toBe(true);
    expect(m.distinct("دبر2103", "دبر2104")).toBe(true);
  });
  it(`سكتة قصيرة (نافذة واحدة بينهم مسمعتش ولا واحدة) ⇒ عربيتين — الحد ${FLEET_GAP_MS}م`, () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102");
    at(m, 6, "دبر2103"); at(m, 7.5, "دبر2103");
    expect(m.distinct("دبر2102", "دبر2103")).toBe(true);
  });
});

describe("FleetMemory — أغلاط السمع المقيسة مابتعدّيش", () => {
  it("🔴 سطل6789: الغلط وسط قرايات الصح (متداخل) ⇒ نفس العربية", () => {
    const m = new FleetMemory();
    at(m, 68, "دسي4600", "يرو1111", "سطل6789");
    at(m, 69.5, "سطل6787"); at(m, 71, "سطل6787");
    at(m, 72.5, "سطل6789"); at(m, 74, "سطل6789", "اين2099");
    expect(m.distinct("سطل6789", "سطل6787")).toBe(false);
  });
  it("🔴 سطل6789 بقراية موديل تاني: ٦٧٨٧ ٦٧٨٧ ثم ٦٧٨٩ ٦٧٨٩ **ورا بعض من غير فاصل** ⇒ نفس النطقة", () => {
    // نطقة واحدة بتتقري في ~٤ نوافذ متلاصقة؛ الأولانيين غلط والتانيين صح
    const m = new FleetMemory();
    at(m, 68, "دسي4600", "يرو1111", "سطل6711");
    at(m, 69.5, "سطل6787"); at(m, 71, "سطل6787");
    at(m, 72.5, "سطل6789"); at(m, 74, "سطل6789", "اين2099");
    expect(m.distinct("سطل6789", "سطل6787")).toBe(false);
  });
  it("🔴 إيقاع المالك العادي: ورا بعض متلاصقين من غير نافذة مشتركة، **الفرق ١** ⇒ عربيتين", () => {
    // ٤٤٪ من اللوحات المتتالية في جلسات المالك شكلها كده (سكتة ١.٥–٢.٥ث)
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102");
    at(m, 4.5, "دبر2103"); at(m, 6, "دبر2103");
    expect(m.distinct("دبر2102", "دبر2103")).toBe(true);
  });
  it("⚠️ متلاصقين من غير نافذة مشتركة، **الفرق ٢** ⇒ مش دليل (نفس شكل سطل6787/6789)", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102");
    at(m, 4.5, "دبر2104"); at(m, 6, "دبر2104");
    expect(m.distinct("دبر2102", "دبر2104")).toBe(false);
  });
  it(`🔴 سكتة بس (من غير نافذة مشتركة) والفرق أكبر من ${FLEET_GAP_MAX_STEP} ⇒ مش دليل (المندوب بيعيد عربية اتقرت غلط)`, () => {
    // ميس3706 اتقرت ميس3705… بس رطه8654 اتقرت رطه8645 (فرق ٩) — والمندوب قالها تاني بعد سكتة
    const m = new FleetMemory();
    at(m, 198.5, "رطه8645"); at(m, 200, "رطه8645"); at(m, 201.5, "رطه8645");
    at(m, 206, "رطه8654"); at(m, 207.5, "رطه8654");
    expect(m.distinct("رطه8645", "رطه8654")).toBe(false);
  });
  it("🔴 حنل7220: الصح اتقرا مرة واحدة ⇒ مش دليل", () => {
    const m = new FleetMemory();
    at(m, 161, "حبم7596", "حنل7229"); at(m, 162.5, "حنل7229", "ركو1219");
    at(m, 164, "حنل7220", "ركو1219", "ررد8257");
    expect(m.distinct("حنل7229", "حنل7220")).toBe(false);
  });
  it("🔴 لوحة مقطوعة على حرف النافذة (اتقرت مرة) جنب عربية ⇒ مش عربية زيادة", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102"); at(m, 4.5, "دبر2102", "دبر2108");
    at(m, 7.5, "دبر2103"); at(m, 9, "دبر2103");
    expect(m.distinct("دبر2102", "دبر2108")).toBe(false);
    expect(m.distinct("دبر2108", "دبر2103")).toBe(false);
    expect(m.distinct("دبر2102", "دبر2103")).toBe(true);
  });
  it("غلط سمع بعيد (مش متسلسل) ⇒ لأ مهما اتكرر", () => {
    const m = new FleetMemory();
    at(m, 1, "بمم8788"); at(m, 2.5, "بمم8788");
    at(m, 6, "بمم6789"); at(m, 7.5, "بمم6789");
    expect(m.distinct("بمم8788", "بمم6789")).toBe(false);
  });
  it("🔴 نفس النافذة لو اتبعتت تاني (استرجاع بعد وقعة الشبكة) ⇒ مش نافذة تانية", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102");
    at(m, 7.5, "دبر2103"); at(m, 7.5, "دبر2103");
    expect(m.count("دبر2103")).toBe(1);
    expect(m.distinct("دبر2102", "دبر2103")).toBe(false);
  });
});

describe("FleetMemory — مراجعة الخصم (٢٤ سبتمبر)", () => {
  it("🔴 ٣ عربيات بإيقاع عادي: ٢١٠٢ و٢١٠٤ عمرهم مااتسمعوا مع بعض ⇒ برضه عربيتين (العضوية مش الأزواج)", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102", "دبر2103");
    at(m, 4.5, "دبر2103", "دبر2104"); at(m, 6, "دبر2104");
    expect(m.distinct("دبر2102", "دبر2104")).toBe(true);
  });
  it("🔴 اتثبتت مرة ⇒ تفضل ثابتة: المندوب رجع قال ٢١٠٢ تاني (أ ب أ)", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102");
    at(m, 7.5, "دبر2103"); at(m, 9, "دبر2103");
    at(m, 13.5, "دبر2102"); at(m, 15, "دبر2102");
    expect(m.distinct("دبر2102", "دبر2103")).toBe(true);
  });
  it("🔴 عدّى على نفس الأسطول تاني بعد ٥ دقايق ⇒ الدليل بيتحسب على المرور ده لوحده", () => {
    const m = new FleetMemory();
    // المرور الأول: الفرق ٢ ومتلاصقين ⇒ مااتثبتش
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102"); at(m, 4.5, "دبر2104"); at(m, 6, "دبر2104");
    expect(m.distinct("دبر2102", "دبر2104")).toBe(false);
    // المرور التاني بعد ٥ دقايق بسكتة ⇒ يتثبت (المرور الأول مايبوّظهوش)
    at(m, 301.5, "دبر2104"); at(m, 303, "دبر2104"); at(m, 307.5, "دبر2102"); at(m, 309, "دبر2102");
    expect(m.distinct("دبر2102", "دبر2104")).toBe(true);
  });
  it("isMember", () => {
    const m = new FleetMemory();
    at(m, 1.5, "دبر2102"); at(m, 3, "دبر2102"); at(m, 7.5, "دبر2103"); at(m, 9, "دبر2103");
    expect(m.isMember("دبر2102")).toBe(true);
    expect(m.isMember("دبر2104")).toBe(false);
  });
});

describe("FleetMemory — أسطول بإيقاع عادي (نوافذ مشتركة)", () => {
  it("مشتركة في النص وكل واحدة لوحدها على الطرف ⇒ عربيتين", () => {
    const m = new FleetMemory();
    at(m, 1.5, "حبل1234"); at(m, 3, "حبل1234", "حبل1235"); at(m, 4.5, "حبل1235");
    expect(m.distinct("حبل1234", "حبل1235")).toBe(true);
  });
  it("اتسمعوا مع بعض في نافذتين بس ⇒ عربيتين", () => {
    const m = new FleetMemory();
    at(m, 1.5, "حبل1234", "حبل1235"); at(m, 3, "حبل1234", "حبل1235");
    expect(m.distinct("حبل1234", "حبل1235")).toBe(true);
  });
  it("🔴 نافذة النطق (توقيتها مش على شبكة الـ١.٥ث) سمعت الاتنين — والباقي متلاصق ⇒ عربيتين", () => {
    // النافذة المشتركة لوحدها دليل؛ مش لازم فاصل
    const m = new FleetMemory();
    at(m, 1.5, "حبل1234"); at(m, 3, "حبل1234"); at(m, 3.7, "حبل1234", "حبل1235"); at(m, 4.5, "حبل1235");
    expect(m.distinct("حبل1234", "حبل1235")).toBe(true);
  });
  it("الأسطول الحقيقي من الشارع (دعن6156/6157)", () => {
    const m = new FleetMemory();
    at(m, 26, "دعن6156"); at(m, 27.5, "دعن6156", "دعن6157");
    at(m, 29, "دعن6156", "دعن6157"); at(m, 30.5, "دعن6157");
    expect(m.distinct("دعن6156", "دعن6157")).toBe(true);
  });
  it("حروف مختلفة ⇒ مش شغلتنا", () => {
    const m = new FleetMemory();
    at(m, 1, "حبل1234"); at(m, 2.5, "حبل1234"); at(m, 6, "سار1235"); at(m, 7.5, "سار1235");
    expect(m.distinct("حبل1234", "سار1235")).toBe(false);
  });
  it("count + reset", () => {
    const m = new FleetMemory();
    at(m, 1, "حبل1234"); at(m, 2.5, "حبل1234");
    expect(m.count("حبل1234")).toBe(2);
    m.reset();
    expect(m.count("حبل1234")).toBe(0);
  });
});
