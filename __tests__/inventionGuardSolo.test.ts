import { describe, it, expect } from "vitest";
import { LiveConsensus } from "../lib/liveConsensus";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  حاجز الاختراع — على **القراءة المفردة** بس
 * ══════════════════════════════════════════════════════════════════════
 *  من تقرير المالك (٢٢ سبتمبر · ٢٩ لوحة): **١٦ قراءة اتحجبت**، ومنها
 *  لوحات **صح** ضاعت بالكامل:
 *
 *      63.5  حطو6826          اختراع-محجوب  91%
 *      65.0  حطو6826 اسط4324  اختراع-محجوب  93%
 *      66.5  اسط4324          اختراع-محجوب  88%
 *
 *  التلاتة دول قراءات **صحيحة** (اللوحتين في ورقة المالك)، واتحجبوا، فاللوحتين
 *  ماظهروش خالص. بينما `بنس1919` الحقيقية اتقريت غلط تلات مرات بقيم **مختلفة**
 *  (`بنس7787` · `بنس9999` · `بنس9919`) — ودي المفروض تتحجب فعلاً.
 *
 *  🔴 **الفرق بينهم هو التكرار، مش الثقة.** وده مكتوب في `liveConsensus.ts`
 *  من زمان: «الحاجز على الكل بيرمي **نص** اللوحات الحقيقية؛ عليها مفردة بس آمن».
 *
 *  بس `voicexEngine` كان بيطبّق الحاجز **مسطّحاً قبل الإجماع** فبيمنع القاعدة
 *  دي من الشغل أصلاً. الاختبار ده بيثبّت العقد اللي المحرّك هيعتمد عليه.
 */

const OPTS = { windowMs: 2000, stableMs: 0, greenMinMult: 2 };
const LOW = -0.9;   // أضعف من soloMinLp (-0.5)

describe("حاجز الاختراع بيفرّق بالتكرار مش بالثقة", () => {
  it("🔴 لوحة اتقرت **مرتين** بـminLp واطي — **تعدّي** (الاتفاق دليل)", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "حطو6826", tMs: 63500, conf: 0.91, minLp: LOW });
    c.add({ plate: "حطو6826", tMs: 65000, conf: 0.93, minLp: LOW });
    const out = c.flush();
    expect(out.map((o) => o.plate)).toContain("حطو6826");
  });

  it("🔴 نفس اللوحة **مرة واحدة** بنفس الـminLp — **تتحجب**", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "حطو6826", tMs: 63500, conf: 0.91, minLp: LOW });
    expect(c.flush().map((o) => o.plate)).not.toContain("حطو6826");
  });

  it("اختراعات مفردة بحروف مختلفة — كلها تتحجب", () => {
    const c = new LiveConsensus(OPTS);
    // من سجل المالك: اختراعات نافذة-واحدة بحروف مختلفة عن بعضها
    c.add({ plate: "بطع7295", tMs: 800, conf: 0.58, minLp: LOW });
    c.add({ plate: "ااح3278", tMs: 59000, conf: 0.52, minLp: LOW });
    c.add({ plate: "حسس4121", tMs: 53000, conf: 0.86, minLp: LOW });
    const got = c.flush().map((o) => o.plate);
    for (const bad of ["بطع7295", "ااح3278", "حسس4121"]) expect(got).not.toContain(bad);
  });

  /**
   * ⚠️ **حدّ القاعدة — مسجّل بصراحة.** الإجماع بيجمّع بالحروف، فقراءات نفس
   * الحروف بأرقام مختلفة (`بنس7787` · `بنس9999` · `بنس9919`) بتتلمّ في عنقود
   * واحد بـ`mult = 3` **وتعدّي**، وأعلاها ثقة بتكسب.
   *
   * يعني شيل الحاجز المسطّح **بيكسّب** اللوحات المتكررة الصح (حطو6826 ·
   * اسط4324) و**بيخسّر** إن لوحة صعبة تطلع بأرقام غلط بدل ما تختفي.
   * المقايضة دي مقصودة: **الظهور غلط أحسن من الاختفاء** في أداة ميدانية —
   * المندوب بيشوفها ويصحّحها، أما اللي بيختفي محدش بياخد باله.
   */
  it("نفس الحروف بأرقام مختلفة بتتلمّ في عنقود واحد وأعلاها ثقة تكسب", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "بنس7787", tMs: 38000, conf: 0.58, minLp: LOW });
    c.add({ plate: "بنس9999", tMs: 39500, conf: 0.88, minLp: LOW });
    c.add({ plate: "بنس9919", tMs: 41000, conf: 0.87, minLp: LOW });
    const got = c.flush();
    expect(got).toHaveLength(1);
    expect(got[0].plate.startsWith("بنس")).toBe(true);
    expect(got[0].mult).toBe(3);
  });

  it("minLp سليم + قراءة واحدة بثقة عالية — تعدّي زي ما هي", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "بطد8766", tMs: 1500, conf: 0.99, minLp: -0.02 });
    expect(c.flush().map((o) => o.plate)).toContain("بطد8766");
  });
});
