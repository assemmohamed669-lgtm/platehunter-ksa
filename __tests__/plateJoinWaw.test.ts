import { describe, it, expect } from "vitest";
import { parsePlateFromTranscript, normalizePlate } from "../lib/plateParser";

// ─── قاعدة الواو في ضمّ أرقام اللوحة ────────────────────────────────────────
//
// قاعدة المالك (وثيقة docs/spoken-numbers-dictionary.md §٨):
//   «الـ«و» بتعمل مركّب بس لما اللي بعدها كلمة عشرات. أي حاجة تانية = وصل.»
//
//   ستة وستين      → عشرات بعد الواو  → مركّب → جمع  → 66
//   تلاتة وواحد    → آحاد بعد الواو   → وصل   → لزق  → 31
//   واحد خمسمية    → مافيش واو أصلاً   → وصل   → لزق  → 1500
//
// اللي كان بيحصل قبل الإصلاح: أي رقم ≥ ١٠ في الجملة كان بيحوّل **كل** الأرقام
// لجمع، فـ«واحد خمسمية» بقت 1+500=501 بدل 1500.
//
// ⚠️ مصيدة: «واحد» و«وحده» بيبدأوا بواو لكنهم **مش** مركّب — من غير استثناء
// صريح «تسعة تسعة تسعة وواحد» تبقى 999+1=1000 بدل 9991.
//
// القاعدة دي **إضافية**: كل صيغة شغّالة النهاردة لازم تفضل شغّالة بالحرف.

const plate = (t: string) => parsePlateFromTranscript(t).plate;

describe("ضمّ الأرقام — الصيغ المكسورة قبل الإصلاح", () => {
  it("«واحد خمسمية» بلا واو = لزق ⇒ الب1500 (كان الب0501)", () => {
    expect(plate("الف لام باء واحد خمسمية")).toBe("الب1500");
  });

  it("«ستة تسعمية» بلا واو = لزق ⇒ رمه6900 (كان رمه0906)", () => {
    expect(normalizePlate(plate("راء ميم هاء ستة تسعمية"))).toBe("رمه6900");
  });

  // مثال المالك «دال سين كاف اتنين تمانية وثمانين» ⇒ دسك2288 ناقص «وعشرين»:
  // النص ده فيه معلومة رقمين بس (٢ و٨٨) فمستحيل يطلّع أربعة. الصيغة الكاملة
  // اللي المالك بيقصدها هي دي، والقاعدة بتمسكها صح: مركّبين متلزقين.
  it("«اتنين وعشرين تمانية وثمانين» = مركّبين متلزقين ⇒ دسك2288", () => {
    expect(plate("دال سين كاف اتنين وعشرين تمانية وثمانين")).toBe("دسك2288");
  });

  it("«تمانية وثمانين» لوحدها = مركّب واحد ⇒ 0088", () => {
    expect(plate("دال سين كاف تمانية وثمانين")).toBe("دسك0088");
  });
});

describe("ضمّ الأرقام — الصيغ المفكوكة الشغّالة (ممنوع تتكسر)", () => {
  const works: [string, string][] = [
    ["حه به كاف واحد تسعه تسعه تسعه", "حبك1999"],
    ["حاء باء كاف واحد تسعة تسعة تسعة", "حبك1999"],
    ["حاء باء كاف تسعة ستة ستة ستة", "حبك9666"],
    ["الف لام به واحد خمسة صفر صفر", "الب1500"],
    ["دال سين كاف اتنين اتنين تمانية تمانية", "دسك2288"],
  ];
  for (const [text, expected] of works) {
    it(`${text} ⇒ ${expected}`, () => {
      expect(plate(text)).toBe(expected);
    });
  }
});

describe("ضمّ الأرقام — «و» + آحاد = وصل مش جمع", () => {
  it("«تلاتة وواحد» = 31 (قاعدة المالك) ⇒ حبك1231", () => {
    expect(plate("حاء باء كاف واحد اتنين تلاتة وواحد")).toBe("حبك1231");
  });

  it("مصيدة «وواحد»: تسعة تسعة تسعة وواحد = 9991 مش 1000", () => {
    expect(plate("حاء باء كاف تسعة تسعة تسعة وواحد")).toBe("حبك9991");
  });

  it("مصيدة «ووحده»: تسعة تسعة تسعة ووحده = 9991 مش 1000", () => {
    expect(plate("حاء باء كاف تسعة تسعة تسعة ووحده")).toBe("حبك9991");
  });

  it("«ستة وستة» وصل ⇒ 0066", () => {
    expect(plate("حاء باء كاف ستة وستة")).toBe("حبك0066");
  });

  it("«ستة وستين» مركّب ⇒ 0066 (نفس النتيجة، طريق مختلف)", () => {
    expect(plate("حاء باء كاف ستة وستين")).toBe("حبك0066");
  });

  it("«صفر وخمسة» وصل ⇒ 0005", () => {
    expect(plate("حاء باء كاف صفر وخمسة")).toBe("حبك0005");
  });
});

