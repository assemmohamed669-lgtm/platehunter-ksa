import { describe, it, expect } from "vitest";
import { speechEndLatencyMs, HALF_WINDOW_MS } from "../lib/trialLatency";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  «ظهرت بعد» — من آخر كلام المندوب، مش من نص النافذة
 * ══════════════════════════════════════════════════════════════════════
 *  المالك (٢٣ سبتمبر ٢٠٢٦): «ظهرت بعد مكتوب فيها ٣ ثواني ونص و٢ ونص و٣،
 *  ده كتير جداً».
 *
 *  🔴 **الرقم كان بيكدب**: كان بيتحسب من `tMs` = **نص النافذة** (٥ث)، يعني
 *  من ٢.٥ث قبل آخرها. فلو السيرفر رد في صفر ثانية الرقم كان هيقول ٢.٥ث.
 *  من تقرير المالك: الرحلة ٠.٥٧ث ⇒ 2.5 + 0.57 = **3.07ث** — بالظبط اللي شافه.
 *
 *  ⇒ اللي المندوب بيحسّه = **من ما سكت لحد ما ظهرت**.
 *
 *  ⚠️ **والحد العلوي نهاية النافذة**: لو المندوب كمّل كلام (قال اللوحة
 *  اللي بعدها)، آخر صوت بيبقى **بعد** اللوحة دي — فمن غير الحد الرقم كان
 *  هيطلع صغير غلط أو سالب. واللوحة أكيد خلصت قبل نهاية نافذتها.
 */
describe("speechEndLatencyMs", () => {
  it("🔴 قال اللوحة وسكت ⇒ من لحظة السكوت", () => {
    // النافذة مركزها ١٠ث ⇒ آخرها ١٢.٥ث. سكت عند ١٢ث، ظهرت عند ١٣.٣ث.
    expect(speechEndLatencyMs({ nowMs: 13_300, tMs: 10_000, lastVoiceEndMs: 12_000 })).toBe(1300);
  });

  it("⚠️ كمّل كلام بعدها ⇒ الحد نهاية النافذة (مش آخر صوت)", () => {
    // آخر صوت ١٥ث (بيقول اللوحة التانية) — أكيد مش نهاية اللوحة دي.
    const got = speechEndLatencyMs({ nowMs: 13_300, tMs: 10_000, lastVoiceEndMs: 15_000 });
    expect(got).toBe(13_300 - (10_000 + HALF_WINDOW_MS));
  });

  it("مافيش معلومة عن الصوت ⇒ نهاية النافذة", () => {
    expect(speechEndLatencyMs({ nowMs: 13_300, tMs: 10_000, lastVoiceEndMs: null }))
      .toBe(13_300 - (10_000 + HALF_WINDOW_MS));
  });

  it("مابيطلعش سالب أبداً", () => {
    expect(speechEndLatencyMs({ nowMs: 5_000, tMs: 10_000, lastVoiceEndMs: 12_000 })).toBe(0);
  });

  it("🔴 الفرق عن الحساب القديم = الـ٢.٥ث اللي كانت هندسة مش تأخير", () => {
    const now = 13_070, tMs = 10_000;                 // رحلة ٠.٥٧ث بعد آخر النافذة
    const old = now - tMs;                             // ← القديم: 3070
    const neu = speechEndLatencyMs({ nowMs: now, tMs, lastVoiceEndMs: 12_500 });
    expect(old).toBe(3070);
    expect(neu).toBe(570);
  });
});
