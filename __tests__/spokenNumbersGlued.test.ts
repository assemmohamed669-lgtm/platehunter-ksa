import { describe, it, expect } from "vitest";
import { extractMultiplePlates } from "@/lib/plateParser";

/**
 * إملاءات Deepgram الحقيقية لصيغ التكرار — من جلسة ميدانية للمالك (٢٠٢٦/٠٨/٠٢).
 *
 * القاموس اتضاف بإملاء واحد لكل صيغة («اربع سبعات»)، والميدان طلّع تلات أشكال
 * تانية مامتغطّياش:
 *   ١. بالتاء المربوطة  — «اربعة وحايد» (الأنبوب بيحوّل أ→ا بس، ة مابتتحولش)
 *   ٢. ملزوقة بلا مسافة — «اربعسبعات»
 *   ٣. رقم مكرر ملزوق   — «تسعتسع» = تسعة تسعة
 *
 * كلها اتقاست على كلام حقيقي: ٣ من ٦ غلطات الجلسة كانت من النقص ده وحده.
 * (التلاتة الباقيين Deepgram سمعهم غلط — «أربعة ساعات» بدل «أربع تسعات» — ومش
 * في إيد المحلّل.)
 */
const plate = (t: string) => (extractMultiplePlates(t) || []).map((p) => p.plate).join(",");

describe("إملاءات التكرار الملزوقة وبالتاء المربوطة — من الميدان", () => {
  it("«اربعة وحايد» بالتاء المربوطة = ١١١١", () => {
    expect(plate("طا صاد ص أربعة وحايد")).toBe("طصص1111");
  });

  it("«أربعسبعات» ملزوقة = ٧٧٧٧", () => {
    expect(plate("ألف سين كاف أربعسبعات")).toBe("اسك7777");
  });

  it("«تسعتسع» رقم مكرر ملزوق = ٩٩", () => {
    expect(plate("أ واو باء اثنين ثلاثه تسعتسع")).toBe("اوب2399");
  });
});

describe("باقي عيلة التاء المربوطة", () => {
  const cases: [string, string][] = [
    ["اربعة اصفار", "0000"], ["اربعة تصفار", "0000"], ["اربعة اتنينات", "2222"],
    ["اربعة تلاتات", "3333"], ["اربعة اربعات", "4444"], ["اربعة خمسات", "5555"],
    ["اربعة سبعات", "7777"], ["اربعة تمنيات", "8888"], ["اربعة تسعات", "9999"],
  ];
  it.each(cases)("«حاء باء كاف %s» → %s", (form, digits) => {
    expect(plate(`حاء باء كاف ${form}`)).toBe(`حبك${digits}`);
  });
});

describe("باقي العيلة الملزوقة", () => {
  const cases: [string, string][] = [
    ["اربعاصفار", "0000"], ["اربعوحايد", "1111"], ["اربعاتنينات", "2222"],
    ["اربعتلاتات", "3333"], ["اربعاربعات", "4444"], ["اربعخمسات", "5555"],
    ["اربعتمنيات", "8888"], ["اربعتسعات", "9999"],
  ];
  it.each(cases)("«حاء باء كاف %s» → %s", (form, digits) => {
    expect(plate(`حاء باء كاف ${form}`)).toBe(`حبك${digits}`);
  });
});

describe("ما اتكسرش حاجة", () => {
  it("الصيغة المفصولة الأصلية لسه شغّالة", () => {
    expect(plate("حاء باء كاف اربع تسعات")).toBe("حبك9999");
    expect(plate("حاء باء كاف اربع وحايد")).toBe("حبك1111");
  });

  it("رقم-رقم العادي زي ما هو", () => {
    expect(plate("حه به كاف واحد تسعه تسعه تسعه")).toBe("حبك1999");
  });

  it("«تلات ×» المفصولة لسه شغّالة", () => {
    expect(plate("ره دال حاء ثلاث أصفار تسعة")).toBe("ردح0009");
  });

  it("الحالات اللي اتصلّحت امبارح ثابتة", () => {
    expect(plate("ألف لام ب واحد خمسمئة")).toBe("الب1500");
    expect(plate("ره م ه ستة تسعمية")).toBe("رمه6900");
    expect(plate("دال سين كاف اتنين وعشرين تمانية وثمانين")).toBe("دسك2288");
  });
});
