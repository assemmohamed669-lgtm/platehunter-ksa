import { describe, it, expect } from "vitest";
import { scanTypeAndNote } from "@/lib/vehicleTypeScan";

/**
 * 🔴 غلطتان من فحص أداة النوع مع `checkpoint-7500` (١٨ سبتمبر ٢٠٢٦) —
 * نصوص حقيقية من شريط المالك.
 */
const t = (txt: string, p: string) => {
  const s = scanTypeAndNote(txt, { afterPlate: p });
  return [s.type, s.note].filter(Boolean).join(" · ");
};

describe("تصليحات الموديل الجديد", () => {
  /**
   * «س ه ره 6 4 2 8 **جراش 2 يمين**» ⇒ «جراج اتنين يمين»
   * العدّاد بالرقم موجود في المفاتيح، بس «جراش» بالشين مع الرقم
   * مكانتش بتوصل للتقريب.
   */
  it("جراش ٢ يمين = جراج اتنين يمين", () => {
    expect(t("س ه ره 6 4 2 8 جراش 2 يمين بطحات ساعة 23 يمين", "سهر6428"))
      .toBe("جراج اتنين يمين");
  });

  /**
   * «ألف يا ألف 7168 **bm** هايم قاف 1196 ليكزس» ⇒ «بي ام»
   * كوهير كتبها لاتيني `bm`. والماسح أخد «هاي اس» من كلمة «هايم»
   * اللي هي أصلاً حرف اللوحة الجارة.
   */
  it("bm لاتيني = بي ام · ومياخدش نوع الجار", () => {
    const got = t("ألف يا ألف 7168 bm هايم قاف 1196 ليكزس", "ايا7168");
    expect(got).not.toBe("هاي اس");     // 🔴 الأهم: مايطلعش نوع غلط
    expect(["بي ام", ""]).toContain(got);
  });

  it("🛡️ اللي كان شغّال يفضل شغّال", () => {
    expect(t("ع ألف قاف 0674 جرش 2 يسار", "عاق0674")).toBe("جراج اتنين يسار");
    expect(t("ح 6 3 7 4 جراش واحد يسار", "حبح6374")).toBe("جراج واحد يسار");
    expect(t("واو ا هي 2528 ليكزس حيرة 8437", "واه2528")).toBe("لكزس");
    expect(t("حي ب 6075 جراج", "حيب6075")).toBe("جراج");
  });
});
