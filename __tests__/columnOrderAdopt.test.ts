import { describe, it, expect } from "vitest";
import { adoptNewColumns } from "@/lib/columnOrder";

/**
 * التخصيص كان **أعمى للأعمدة الجديدة**: الترتيب المحفوظ فيه اللي المندوب
 * اختاره بس، فأي عمود يظهر بعد كده (محفظة بأعمدة مختلفة، داتا بأعمدة مختلفة،
 * أو عمود جديد زوّدناه زي «نوع السيارة (المحفظة)») مايظهرش عنده **أبداً** —
 * ولا في الجدول ولا في المشاركة — ومافيش حاجة تقوله ليه.
 *
 * الفخ: العمود اللي المندوب **أخفاه بإيده** والعمود **الجديد** شكلهم واحد في
 * التخزين (الاتنين مش في الترتيب). فلازم نسجّل «الأعمدة اللي اتعرضت عليه قبل
 * كده» عشان نفرّق: مش معروف = جديد ⇒ يتعرض؛ معروف ومش مختار = مخفي بإرادته.
 */
describe("adoptNewColumns", () => {
  it("أول مرة: مايضيفش حاجة — بيسجّل المعروف بس", () => {
    // `known = null` يعني الجهاز ده لسه ماسجّلش. لو ضفنا هنا كنا هنرجّع كل
    // الأعمدة لأي مندوب مرتّب أعمدته خلاص — كسر لحاجة شغّالة.
    const r = adoptNewColumns(["نوع السيارة"], null, ["نوع السيارة", "الماركة", "اللون"]);
    expect(r.order).toEqual(["نوع السيارة"]);
    expect(r.added).toEqual([]);
    expect(r.known).toContain("الماركة");
  });

  it("العمود الجديد بيتضاف آخر ترتيب المندوب", () => {
    const r = adoptNewColumns(
      ["نوع السيارة", "الماركة"],
      ["نوع السيارة", "الماركة", "اللون"],
      ["نوع السيارة", "الماركة", "اللون", "نوع السيارة (المحفظة)"],
    );
    expect(r.order).toEqual(["نوع السيارة", "الماركة", "نوع السيارة (المحفظة)"]);
    expect(r.added).toEqual(["نوع السيارة (المحفظة)"]);
  });

  it("العمود اللي أخفاه بإيده يفضل مخفي", () => {
    // «اللون» معروف ومش مختار ⇒ إخفاء بإرادته، مايرجعش.
    const r = adoptNewColumns(
      ["نوع السيارة"],
      ["نوع السيارة", "الماركة", "اللون"],
      ["نوع السيارة", "الماركة", "اللون"],
    );
    expect(r.order).toEqual(["نوع السيارة"]);
    expect(r.added).toEqual([]);
  });

  it("الترتيب الفاضي مايتلمسش — الافتراضي يفضل شغّال", () => {
    const r = adoptNewColumns([], ["نوع السيارة"], ["نوع السيارة", "اللون"]);
    expect(r.order).toEqual([]);
    expect(r.added).toEqual([]);
    expect(r.known).toContain("اللون");   // بس بنفضل نتعلّم
  });

  it("«رقم اللوحة» عمره ما يتضاف — بيتعرض منفصل", () => {
    const r = adoptNewColumns(["نوع السيارة"], ["نوع السيارة"], ["رقم اللوحة", "نوع السيارة", "اللون"]);
    expect(r.order).toEqual(["نوع السيارة", "اللون"]);
    expect(r.order).not.toContain("رقم اللوحة");
  });

  it("مافيش تكرار لو العمود موجود في الترتيب أصلاً", () => {
    const r = adoptNewColumns(["اللون"], [], ["اللون"]);
    expect(r.order).toEqual(["اللون"]);
  });

  it("كذا عمود جديد بيتضافوا بترتيب ظهورهم", () => {
    const r = adoptNewColumns(
      ["نوع السيارة"],
      ["نوع السيارة"],
      ["نوع السيارة", "البنك", "سنة الصنع"],
    );
    expect(r.order).toEqual(["نوع السيارة", "البنك", "سنة الصنع"]);
    expect(r.added).toEqual(["البنك", "سنة الصنع"]);
  });
});
