import { describe, it, expect } from "vitest";
import { extractMultiplePlates, parsePlateFromTranscript, normalizePlate } from "../lib/plateParser";

// ─── مصيدة «ألف» على المسار المفرد ──────────────────────────────────────────
//
// «ألف» كلمة واحدة بمعنيين: اسم الحرف «ا» **و** الرقم ١٠٠٠. المسار المتعدد
// (plateAtoms) بيحلّها صح من زمان — بيبني الحروف الأول فـ«ألف» عنده دايماً حرف.
// المسار المفرد (parsePlateFromTranscript) كان بيحلّها بخطوة نصّية قبل ما يعرف
// أي شكل: أي «ألف» جاي بعدها كلمة **بتبدأ بواو** تتحوّل ١٠٠٠. و«واحد» بتبدأ
// بواو! يعني «… ألف واحد …» — أشيع إملاء ممكن — كانت بتاكل الحرف ا وتحطّ ١٠٠٠
// مكانه، وبعدين قاعدة الضم بتجمع ١٠٠٠+١ = ١٠٠١.
//
// قاعدة المالك (اللوحة السعودية حروفها الأول دايماً، بلا استثناء):
//   قبل ما نجمع ٣ حروف ⇒ «ألف» هي الحرف ا
//   بعد ما نجمع ٣ حروف ⇒ «ألف» هي الرقم ١٠٠٠
// المالك نفسه أكّدها لما كتب «الف لام به واحد خمسمية» ⇒ الب1500 (الألف حرف).
//
// الحل بنفس حيلة «واو» الموجودة أصلاً في plateAtoms: علامة لاتينية بتتحط
// بدري (قبل ما جدول أسماء الحروف ياكل الكلمة) وتتحل بعدين لمّا الشكل يبان.

const single = (t: string) => parsePlateFromTranscript(t).plate;
const multi = (t: string) => extractMultiplePlates(t).map((p) => p.plate);

describe("«ألف» حرف قبل اكتمال الحروف التلاتة", () => {
  // الحالة اللي اتقاست: ٣٦ من ٥٥٦ فشل «حرف حرف» على المسار المفرد، كلها
  // لوحات حرفها التالت ا — لأن أول رقم بعده هو «واحد» (بتبدأ بواو).
  const cases: [string, string][] = [
    // ألف = الحرف التالت (الحالة اللي كانت بتكسر)
    ["باء واو ألف واحد ستة واحد واحد", "بوا1611"],
    ["باء حاء ألف واحد اتنين تلاتة اربعة", "بحا1234"],
    ["دال سين ألف واحد واحد واحد واحد", "دسا1111"],
    // ألف = الحرف التاني — كانت شغّالة وبتفضل
    ["باء ألف حاء واحد اتنين تلاتة اربعة", "باح1234"],
    ["دال ألف واو واحد اتنين تلاتة اربعة", "داو1234"],
    // ألف = الحرف الأول — كانت شغّالة وبتفضل
    ["ألف باء حاء واحد اتنين تلاتة اربعة", "ابح1234"],
    ["ألف لام باء واحد خمسمية", "الب1500"],
    ["الف هاء باء واحد اثنين ثلاثة اربعة", "اهب1234"],
  ];
  for (const [text, expected] of cases) {
    it(`«${text}» ⇒ ${expected}`, () => {
      expect(normalizePlate(single(text))).toBe(normalizePlate(expected));
    });
  }

  it("المسار المفرد بقى يتفق مع المسار المتعدد على نفس النص", () => {
    const t = "باء واو ألف واحد ستة واحد واحد";
    expect(multi(t)).toEqual(["بوا1611"]);
    expect(normalizePlate(single(t))).toBe(normalizePlate(multi(t)[0]));
  });
});

describe("«ألف» رقم ١٠٠٠ بعد اكتمال الحروف التلاتة", () => {
  const cases: [string, string][] = [
    // ٣ حروف ملزوقة في توكن واحد — الاختبارات القديمة، لازم تفضل
    ["حمن ألف وخمسمية", "حمن1500"],
    ["درق ألف وخمسمية وأربعة وعشرين", "درق1524"],
    // ٣ حروف منطوقة بأسمائها — نفس القاعدة
    ["حاء ميم نون ألف وخمسمية", "حمن1500"],
    // ألفين = ٢٠٠٠ كلمة مستقلة، العلامة ما بتلمسهاش
    ["حاء باء كاف ألفين", "حبك2000"],
    ["حمن ألفين", "حمن2000"],
  ];
  for (const [text, expected] of cases) {
    it(`«${text}» ⇒ ${expected}`, () => {
      expect(normalizePlate(single(text))).toBe(normalizePlate(expected));
    });
  }

  /**
   * ⚠️ **الاختبار ده اتغيّر — قبل: «ألف باء حاء ألف» ⇒ ابح1000 · بعد: مافيش لوحة.**
   *
   * كان بيتوثّق الفرع اللي بيقرا «ألف» **آخر توكن** كرقم ١٠٠٠. الفرع ده اتشال
   * بعد القياس: `plateLetterCount` بتعدّ أي كلمة عربية من ٣ حروف كلها من حروف
   * اللوحة، و«معه»/«كان»/«منه»/«قال»/«مال»/«سدد»/«قسط» كلها كده — فجملة تحصيل
   * عادية زي «صاحبها قال الف» كانت بتطلّع «قال1000»، لوحة كاملة الشكل
   * و`uncertain=false` (١٦ جملة من ١٨). وكمان كان بيخترع الخانة الناقصة في
   * لوحة مقطوعة: «… تسعة تمانية سبعة ألف» ⇒ حبك9871 بدل حبك0987.
   *
   * التمن المدفوع موثَّق هنا: لوحة نمرتها ١٠٠٠ بالظبط ومملياة كده مابقتش
   * تتقرا (٣ مدخلات مولَّدة في كل الكوربَس، صفر في التفريغ الميداني الحقيقي).
   * المندوب لسه يقدر يمليها «واحد تلات اصفار» — الاختبار اللي تحت.
   * التفاصيل في `__tests__/plateAlefNoPlate.test.ts`.
   */
  it("«ألف باء حاء ألف» ⇒ مافيش لوحة (تمن شيل فرع «آخر توكن»)", () => {
    expect(single("ألف باء حاء ألف")).toBe("");
  });

  it("البديل اللي لسه شغّال: «ألف باء حاء واحد تلات اصفار» ⇒ ابح1000", () => {
    expect(normalizePlate(single("ألف باء حاء واحد تلات اصفار")))
      .toBe(normalizePlate("ابح1000"));
  });
});

// عدّ الحروف لوحده ما يكفيش: توكن ملزوق من ٣ حروف ممكن يكون لوحة كاملة
// («حمن») أو اسم حرف واحد اتغلط في تفريغه («دار» بدل «دال»). الفرق بينهم مش
// في التوكن نفسه — في اللي بعده. المصدر تفريغ حقيقي من التقييم الذهبي.
describe("«ألف» — منطقة الحروف لسه مفتوحة طالما لسه جاي حرف بعدها", () => {
  const cases: [string, string][] = [
    // whisper-large سمع «دال» غلط «دار» ⇒ التوكن شكله ٣ حروف، لكن «نون» بعده
    // معناها إن الحروف لسه بتتقال ⇒ الألف حرف مش ١٠٠٠.
    ["دار ألف نون واحد تمانية زيرو تمانية", "دان1808"],
    // نفس النص متفرّغ صح — كانت شغّالة ولازم تفضل
    ["دال ألف نون واحد تمانية زيرو تمانية", "دان1808"],
    // وبالعكس: مافيش حرف بعد الألف ⇒ رقم، حتى لو الحروف جت ملزوقة
    ["حمن ألف وخمسمية", "حمن1500"],
  ];
  for (const [text, expected] of cases) {
    it(`«${text}» ⇒ ${expected}`, () => {
      expect(normalizePlate(single(text))).toBe(normalizePlate(expected));
    });
  }

  it("كلام بعد اللوحة ما يرجّعش الألف حرف — الحرف اللي بعد أول رقم مالوش دعوة", () => {
    expect(normalizePlate(single("حمن ألف وخمسمية لا مش هي"))).toBe(normalizePlate("حمن1500"));
  });
});

// العربي بيركّب الآلاف بواو: «ألف وخمسمية». «ألف» ورا ٣ حروف وبعدها رقم منطوق
// **بلا واو** مش مركّب — والقراءة كرقم بتدمّر: ١٠٠٠ لوحدها ٤ خانات، فبتاكل كل
// الأرقام اللي بعدها وتطلّع لوحة نمرتها 1000. التلات أمثلة دي تفريغ حقيقي من
// التقييم الذهبي، كلها توكن ملزوق شكله ٣ حروف (حطه · بيه · اله) بيغش العدّاد.
describe("«ألف» رقم بس لو فاتحة مركّب واو (أو هي الرقم كله)", () => {
  const keepsSpokenDigits: [string, string][] = [
    ["حطه ألف تسعة من اثنين تمانية", "حطا"],
    ["بيه بيه ألف تماني أسد رتس أسد", "بيا"],
  ];
  for (const [text, letters] of keepsSpokenDigits) {
    it(`«${text}» — الألف حرف، والأرقام المنطوقة ما تتاكلش`, () => {
      const p = single(text);
      expect(p.slice(0, 3)).toBe(letters);
      expect(p).not.toContain("1000");
    });
  }

  it("«اله الف الف ثلاثة تمانية نن سبعة» — الألفين الاتنين حروف", () => {
    expect(single("اله الف الف ثلاثة تمانية نن سبعة")).not.toContain("1000");
  });

  it("وبالعكس — «ألف» فاتحة مركّب واو تفضل ١٠٠٠", () => {
    expect(normalizePlate(single("حمن ألف وخمسمية"))).toBe(normalizePlate("حمن1500"));
  });
});

describe("«ألف» — حراسة عدم الانحدار على الجيران", () => {
  const guards: [string, string][] = [
    // «رقم + تلات اصفار» — عيلة تانية خالص، ما تتلمسش
    ["حاء باء كاف خمسة تلات اصفار", "حبك5000"],
    ["حاء باء كاف واحد تلات اصفار", "حبك1000"],
    ["حاء باء كاف تلاتة تلات اصفار", "حبك3000"],
    // آلاف فصحى موجودة في القاموس
    ["حاء باء كاف خمسة الاف", "حبك5000"],
    ["حمن سبعة آلاف", "حمن7000"],
    ["حمن سبعة آلاف ومئة وواحد وسبعين", "حمن7171"],
    // إملاء المالك — الألف حرف والرقم ١٥٠٠ لزق
    ["الف لام به واحد خمسة صفر صفر", "الب1500"],
    ["الف لام باء واحد خمسمية", "الب1500"],
    // «الالف» و«الفا» أسماء حرف لا لبس فيها
    ["الالف نون راء واحد اتنين تلاتة اربعة", "انر1234"],
    // أرقام عربية-هندية مع ألف كحرف تاني
    ["حاء الف باء ٥٨١٩", "حاب5819"],
  ];
  for (const [text, expected] of guards) {
    it(`«${text}» ⇒ ${expected}`, () => {
      expect(normalizePlate(single(text))).toBe(normalizePlate(expected));
    });
  }
});
