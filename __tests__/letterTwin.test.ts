import { describe, it, expect } from "vitest";
import { isLetterTwin, resolveLetterTwin, LETTER_TWIN_MS, type LetterTwinRow } from "../lib/letterTwin";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  «نفس الأرقام + حرفين مختلفين» خلال ثواني = نفس العربية — **والأقدم صح**
 * ══════════════════════════════════════════════════════════════════════
 *  جلسة المالك (٢٣ سبتمبر ٢٠٢٦ · ١٠٠ لوحة): زيادتين — `ردد5899` جنب
 *  `بصد5899` و`بنق6617` جنب `دمق6617`.
 *
 *  📏 **اتقاس على ٦ جلسات بحقيقة المالك (٣٣٢ لوحة)** — مش مفترض:
 *
 *      القاعدة                 صح   زيادة  ضايعة
 *      الحالي                  324   11      8
 *      الأقوى يكسب · ٥ث         323    9      9    🔴 لوحة حقيقية ضاعت
 *      **الأقدم يكسب · ٥-١٢ث**   324    8      8    ✅ ٣ اتشالوا · صفر خسارة
 *
 *  🔴 **ليه الأقدم مش الأقوى**: في الـ٣ أزواج (٣/٣) **الأرقام صح والحروف
 *  غلط، والغلط هو المتأخّر**. الحروف في **أول** اللوحة، والنافذة اللي
 *  بتيجي بعدها زاحفت لقدّام فبتقصّ بداية الكلام ⇒ الحروف تضيع والأرقام
 *  تفضل. و`بنط9093` الغلط كان عنده نوافذ **أكتر** (٣ مقابل ١) — فـ«الأقوى
 *  يكسب» كان بيشيل **الصح**.
 *
 *  ⚠️ **وليه ٨ث**: أقصى فرق بين قرايتين لنفس العربية = **٥ث**، وأقل فرق
 *  بين عربيتين **حقيقيتين** بنفس الأرقام في حقيقة المالك = **٣٨ث**
 *  (`ححه7518`/`حرب7518`). ٨ فوق الـ٥ بهامش وتحت الـ٣٨ بكتير.
 *  ⚠️ العيّنة ٣ أزواج — الآلية منطقية بس مش قانون. تتقاس تاني مع جلسات أكتر.
 */
const r = (plate: string, atMs: number, over: Partial<LetterTwinRow> = {}): LetterTwinRow => ({
  id: plate + atMs, plate, atMs, provisional: false, mult: 2, match: null, ...over,
});

describe("isLetterTwin", () => {
  it("🔴 نفس الأرقام + حرفين مختلفين + قريبين ⇒ توأم", () => {
    expect(isLetterTwin(r("بصد5899", 0), r("ردد5899", 5000))).toBe(true);
    expect(isLetterTwin(r("دمق6617", 0), r("بنق6617", 1000))).toBe(true);
  });

  it("⚠️ عربيتين حقيقيتين بنفس الأرقام بعيد عن بعض ⇒ **مش** توأم", () => {
    // من حقيقة المالك: ٣٨ث بينهم
    expect(isLetterTwin(r("ححه7518", 0), r("حرب7518", 38_000))).toBe(false);
  });

  it("فوق المهلة بشوية ⇒ مش توأم", () => {
    expect(isLetterTwin(r("بصد5899", 0), r("ردد5899", LETTER_TWIN_MS + 1))).toBe(false);
  });

  it("حرف واحد بس ⇒ مش شغلته (دي بتاعة `sameCarTwin`)", () => {
    expect(isLetterTwin(r("بصد5899", 0), r("بصس5899", 1000))).toBe(false);
  });

  it("٣ حروف ⇒ مش توأم (عربية تانية غالباً)", () => {
    expect(isLetterTwin(r("رنا6948", 0), r("حور6948", 1000))).toBe(false);
  });

  it("رقم مختلف ⇒ مش توأم", () => {
    expect(isLetterTwin(r("بصد5899", 0), r("ردد5898", 1000))).toBe(false);
  });

  it("نفس اللوحة بالحرف ⇒ مش شغلته", () => {
    expect(isLetterTwin(r("بصد5899", 0), r("بصد5899", 1000))).toBe(false);
  });
});

describe("resolveLetterTwin — 🔴 الأقدم يكسب", () => {
  it("الجديد هو المتأخّر ⇒ اللوحة الأقدم تفضل", () => {
    const out = resolveLetterTwin(r("بصد5899", 0, { id: "A" }), r("ردد5899", 5000, { id: "B" }));
    expect(out.plate).toBe("بصد5899");
  });

  it("🔴 الغلط عنده نوافذ **أكتر** ⇒ برضه الأقدم يكسب (`بنط9093`)", () => {
    const out = resolveLetterTwin(r("بلد9093", 0, { mult: 1 }), r("بنط9093", 5000, { mult: 3 }));
    expect(out.plate).toBe("بلد9093");
  });

  it("وصلت متأخّرة بس **اتقالت الأول** ⇒ هي اللي تكسب (بالزمن مش بالوصول)", () => {
    const out = resolveLetterTwin(r("ردد5899", 5000, { id: "A" }), r("بصد5899", 0, { id: "B" }));
    expect(out.plate).toBe("بصد5899");
  });

  it("الـid بتاع الصف الموجود يفضل (نفس قاعدة `mergeTwinRow`)", () => {
    const out = resolveLetterTwin(r("ردد5899", 5000, { id: "A" }), r("بصد5899", 0, { id: "B" }));
    expect(out.id).toBe("A");
  });

  it("🔴 الأقدم مبدئي والمتأخّر مؤكّد ⇒ **الصف يتأكّد** (وإلا الكنس يمسحه)", () => {
    // المتأخّر دليل إن العربية اتقالت — حروفه غلط بس وجوده صح.
    const out = resolveLetterTwin(r("بصد5899", 0, { provisional: true, mult: 1 }),
                                  r("ردد5899", 5000, { provisional: false, mult: 2 }));
    expect(out.provisional).toBe(false);
    expect(out.mult).toBe(2);
  });

  it("المطابقة مع الشيت ماشية مع اللوحة اللي كسبت", () => {
    const hit = { "اللوحة": "بصد5899" };
    const out = resolveLetterTwin(r("بصد5899", 0, { match: hit }), r("ردد5899", 5000, { match: null }));
    expect(out.match).toBe(hit);
  });

  it("✋ المندوب صحّح اللوحة بإيده ⇒ تصحيحه يغلب", () => {
    const out = resolveLetterTwin(
      r("ردد5899", 5000, { edited: { plate: true } }),
      r("بصد5899", 0));
    expect(out.plate).toBe("ردد5899");
  });
});
