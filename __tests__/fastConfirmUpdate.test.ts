import { describe, it, expect } from "vitest";
import { LiveConsensus } from "@/lib/liveConsensus";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  ⚡ تأكيد أسرع **بلا** خسارة — المتأخّر بيحدّث بدل ما يعمل صف جديد
 * ══════════════════════════════════════════════════════════════════════
 *
 * المالك (٢٣ سبتمبر ٢٠٢٦): «ليه لازم يكون فيه تمن؟ ليه متدوّرش على حل
 * كويس، لا نخسر آخر لوحة ولا نأخّر ظهورها؟»
 *
 * ── ليه كان فيه تمن ────────────────────────────────────────────────────
 * العنقود كان بيستنى **سكوت**: أي قراءة — حتى المتطابقة — بتجدّد
 * الانتظار. `درط3533` اتقرت ٤ مرات متطابقة فالتأكيد استنى ٣ ثواني زيادة
 * **بلا أي معلومة جديدة**.
 *
 * وأول محاولة للتسريع (تأكيد عند الاستقرار) **كسرت حاجة تانية**: العنقود
 * بيتقفل قبل ما آخر قراءة تلحقه، فبتعمل **صف جديد** — رجوع التكرار.
 *
 * ── الحل بلا تمن ──────────────────────────────────────────────────────
 * ① التأكيد بيستنى **الاستقرار** (إملاء جديد) مش السكوت ⇒ أسرع.
 * ② والقراءة اللي توصل **بعد** التأكيد مابتعملش عنقود جديد — بتنضمّ
 *    للعنقود المؤكَّد ويترجّع **تحديث** لنفس اللوحة. الصفحة بتلمّه على
 *    نفس الصف (نفس اللوحة · متلاصقة · جوّه النافذة) فالمندوب بيشوف صف
 *    واحد بيتحدّث، مش صفّين.
 *
 * ⇒ ظهور أسرع · ولا لوحة بتضيع · ولا تكرار.
 */
const OPTS = { windowMs: 2000, stableMs: 2500, greenMinMult: 2 };

describe("تأكيد أسرع مع تحديث المتأخّر", () => {
  it("⚡ التكرار المتطابق مابيأخّرش — التأكيد من أول قراءة + المهلة", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "درط3533", tMs: 114_500, conf: 1 });
    c.add({ plate: "درط3533", tMs: 116_000, conf: 1 });
    expect(c.drain(117_000).map((o) => o.plate)).toEqual(["درط3533"]);
  });

  it("🔴 والقراءة المتأخّرة بترجّع **تحديث** لنفس اللوحة مش صف جديد", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "درط3533", tMs: 114_500, conf: 1 });
    c.add({ plate: "درط3533", tMs: 116_000, conf: 1 });
    const first = c.drain(117_000);
    expect(first).toHaveLength(1);
    expect(first[0].mult).toBe(2);

    // قراءة تالتة وصلت بعد التأكيد
    c.add({ plate: "درط3533", tMs: 117_500, conf: 1 });
    const upd = c.drain(120_500);
    expect(upd).toHaveLength(1);
    expect(upd[0].plate).toBe("درط3533");
    expect(upd[0].mult).toBe(3);          // نفس اللوحة بتأكيد أقوى
  });

  it("🔒 التصحيح المتأخّر بيوصل كمان", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "دسك8200", tMs: 15_600, conf: 0.90 });
    const a = c.drain(18_200);
    expect(a.map((o) => o.plate)).toEqual(["دسك8200"]);
    // التصحيح وصل بعد التأكيد
    c.add({ plate: "دسك2206", tMs: 17_000, conf: 0.93 });
    const b = c.drain(21_000);
    expect(b.map((o) => o.plate)).toEqual(["دسك2206"]);
  });

  it("🔒 مافيش تحديث من غير قراءة جديدة", () => {
    const c = new LiveConsensus(OPTS);
    c.add({ plate: "بود3135", tMs: 1_000, conf: 1 });
    expect(c.drain(3_600)).toHaveLength(1);
    expect(c.drain(9_000)).toEqual([]);
    expect(c.drain(99_000)).toEqual([]);
  });
});
