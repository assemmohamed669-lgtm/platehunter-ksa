import { describe, it, expect } from "vitest";
import { parsePlateFromTranscript, normalizePlate } from "@/lib/plateParser";
import { newSessionState, parseSessionChunk } from "@/lib/sessionParser";

/**
 * «ألف» في آخر الجملة **مش** رقم ١٠٠٠.
 *
 * قاعدة المالك («بعد ٣ حروف تُقرا ١٠٠٠») بتتحقق بالغلط في كلام عادي خالص:
 * `plateLetterCount` بتعدّ أي كلمة عربية من ٣ حروف كلها من حروف اللوحة —
 * و«معه»، «كان»، «هنا»، «منه»، «قال»، «مال»، «سدد»، «قسط» كلها كده. فجملة
 * تحصيل عادية زي «صاحبها قال الف» كانت بتطلّع لوحة **كاملة الشكل وواثقة**
 * (`uncertain === false`) والمندوب يشيّك عليها.
 *
 * ده تطبيق قاعدة المالك نفسها: «لو حاجة ليها أثر، نشيلها ونسيب الباقي».
 * الفرع اللي بيقرا «ألف» آخر توكن كرقم اتشال. مكسبه كان ٣ مدخلات مولَّدة بس
 * («حاء باء كاف ألف» ⇒ حبك1000)، وتمنه ١٦ جملة من ١٨ بتطلّع لوحة مفبركة.
 */

const single = (t: string) => parsePlateFromTranscript(t);
const sessionPlates = (t: string) =>
  parseSessionChunk(t, newSessionState(), { final: true }).records.map((x) => x.plate);

describe("كلام تحصيل فيه «ألف» ومافيهوش لوحة ⇒ مافيش لوحة", () => {
  const noise = [
    "معه ألف", "منه الف", "هنا الف", "كان الف", "لها الف",
    "قال لك الف", "صاحبها قال الف", "الحساب كان الف", "دفع منه الف",
    "السواق قال معه ألف", "مالك السيارة معه ألف", "مال ألف",
    "سدد ألف", "قسط ألف", "مطلوب منه ألف", "رقم ألف",
  ];

  for (const t of noise) {
    it(`«${t}» ⇒ مافيش لوحة (المسار المفرد)`, () => {
      expect(single(t).plate).toBe("");
    });
    it(`«${t}» ⇒ مافيش سجل (مسار الجلسة)`, () => {
      expect(sessionPlates(t)).toEqual([]);
    });
  }
});

describe("«ألف» في آخر لوحة ناقصة خانة ما تخترعش الخانة الناقصة", () => {
  // ١٠٠٠ أربع خانات، فقراءتها رقم بتحشر «١» في آخر لوحة ناقصة وتخلّيها
  // شكلها سليم تماماً — أخطر من الحشو بصفر لأنها بتعدّي على المندوب.
  const cases: [string, string][] = [
    ["حاء باء كاف تسعة تمانية سبعة ألف", "حبك0987"],
    ["دال سين كاف تسعة تمانية سبعة معه الف", "دسك0987"],
    ["حاء باء كاف تسعة تمانية الف", "حبك0098"],
    ["حاء باء كاف تسعة ألف", "حبك0009"],
    ["حاء باء كاف تسعة تمانية سبعة آلف", "حبك0987"],
  ];
  for (const [t, expected] of cases) {
    it(`«${t}» ⇒ ${expected}`, () => {
      expect(normalizePlate(single(t).plate)).toBe(normalizePlate(expected));
    });
  }

  it("لوحة كاملة ٤ خانات + «ألف» بعدها ⇒ الأرقام ما تتلمسش", () => {
    expect(normalizePlate(single("حاء باء كاف تسعة تمانية سبعة ستة ألف").plate))
      .toBe(normalizePlate("حبك9876"));
  });
});

describe("اللي بيتشال ما بيمسّش الشغّال", () => {
  const keep: [string, string][] = [
    // «ألف» = الحرف ا قبل اكتمال التلات حروف — ده مكسب المهمة الأصلي، لازم يفضل
    ["باء ألف واحد اتنين تلاتة اربعة", "با1234"],
    ["باء واو ألف واحد ستة واحد واحد", "بوا1611"],
    ["دار ألف نون واحد تمانية زيرو تمانية", "دان1808"],
    ["الف لام باء واحد خمسمية", "الب1500"],
    ["الف لام به واحد خمسة صفر صفر", "الب1500"],
    // مركّب الواو بعد اكتمال الحروف لسه ١٠٠٠ — الفرع ده ما اتلمسش
    ["حمن ألف وخمسمية", "حمن1500"],
    ["حاء ميم نون ألف وخمسمية", "حمن1500"],
    ["درق ألف وخمسمية وأربعة وعشرين", "درق1524"],
    // مداخل الآلاف المستقلة في القاموس
    ["حاء باء كاف ألفين", "حبك2000"],
    ["حاء باء كاف سبعة آلاف", "حبك7000"],
    ["حاء باء كاف خمسة تلات اصفار", "حبك5000"],
  ];
  for (const [t, expected] of keep) {
    it(`«${t}» ⇒ ${expected}`, () => {
      expect(normalizePlate(single(t).plate)).toBe(normalizePlate(expected));
    });
  }
});
