import { describe, it, expect } from "vitest";
import { resolveDataPlateCol } from "@/lib/dataSources";

/**
 * ملف الداتا الإضافي كان بيتطابق على **عمود غلط في صمت**.
 *
 * السبب: `detectPlateColumn` عمره ما بيرجّع `null` — آخر احتياطي عنده
 * `headers[0]`. فلو الكشف بالمحتوى مالقاش دليل (شيت بأسماء أعمدة غريبة أو
 * صفوف أوّلها مش لوحات)، الملف الإضافي بيتفرز على **أول عمود** فمايطلّعش ولا
 * نتيجة. والمربع الأساسي فيه اختيار يدوي للعمود — الإضافي مافيهوش، فمافيش
 * طريقة يصلّحها المندوب ولا حتى يعرف إنها حصلت.
 *
 * القاعدة: الإضافي بياخد **عمود الملف الأساسي** (اللي ممكن يكون المندوب اختاره
 * بإيده) قبل ما يقع على `headers[0]` — الملفات الإضافية مفترض نفس الأعمدة.
 */
describe("resolveDataPlateCol", () => {
  it("بيلاقي عمود اللوحة العربي زي ما هو", () => {
    const rows = [{ "رقم اللوحة": "رري3706" }, { "رقم اللوحة": "اسر2244" }];
    expect(resolveDataPlateCol(["رقم اللوحة", "الحي"], rows, null)).toBe("رقم اللوحة");
  });

  it("الكشف بالمحتوى بيكسب على احتياطي الأساسي", () => {
    const rows = [{ "أ": "الربوة", "ب": "رري3706" }, { "أ": "النزهة", "ب": "اسر2244" }];
    expect(resolveDataPlateCol(["أ", "ب"], rows, "أ")).toBe("ب");
  });

  it("لما مفيش دليل بيستخدم عمود الأساسي مش أول عمود — ده الباج", () => {
    const rows = [{ "أ": "كلام", "ب": "كلام تاني" }, { "أ": "حاجة", "ب": "حاجة تانية" }];
    expect(resolveDataPlateCol(["أ", "ب"], rows, "ب")).toBe("ب");
  });

  it("لو عمود الأساسي مش موجود في الملف بيرجع للسلوك القديم بدل ما يقع", () => {
    const rows = [{ "أ": "كلام" }, { "أ": "حاجة" }];
    expect(resolveDataPlateCol(["أ"], rows, "مش موجود")).toBe("أ");
  });

  it("عمره ما يرجّع عمود مش في رؤوس الملف", () => {
    const rows = [{ "أ": "كلام" }];
    const got = resolveDataPlateCol(["أ"], rows, "عمود تاني خالص");
    expect(got === null || ["أ"].includes(got)).toBe(true);
  });

  it("ملف بلا رؤوس بيرجّع null بدل ما يخترع عمود", () => {
    expect(resolveDataPlateCol([], [], "رقم اللوحة")).toBeNull();
  });
});
