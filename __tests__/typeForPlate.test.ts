import { describe, it, expect } from "vitest";
import {
  pickTypeForPlate,
  pruneTypeQueue,
  TYPE_NEAR_MS,
  TYPE_QUEUE_KEEP_MS,
} from "@/lib/typeForPlate";

/**
 * 🔴 **بلاغ المالك (٢٢ سبتمبر ٢٠٢٦):** «أقول لوحة `حبك1234` — يحطّ
 * قدامها ونيت وأنا مقولتهاش».
 *
 * النافذة ٥ ثواني، فبتشيل اللوحة اللي قبلها ونوعها كمان. الصفحة كانت
 * بتاخد النوع **بالتوقيت وحده** فنوع الجارة كان بيترحّل. الحارس هنا:
 * النوع لازم ييجي **بعد أرقام اللوحة نفسها** في نصّ كوهير.
 */
describe("نوع اللوحة — من نصّ النافذة بقصّ عند أرقامها", () => {
  // نافذة واحدة فيها لوحتين: الأولى بنوع، والتانية (بتاعة المالك) بلا نوع
  const نص = "ا م ن تسعة واحد صفر سبعة ونيت ح ب ك واحد اتنين تلاتة اربعة";
  const طابور = [{ text: نص, tMs: 10_000 }];

  it("اللوحة اللي اتقال لها نوع بتاخده", () => {
    expect(pickTypeForPlate(طابور, "امن9107", 10_000)).toEqual({
      type: "ونيت",
      note: null,
    });
  });

  it("🔴 اللوحة اللي مقالش لها نوع **متاخدش** نوع الجارة", () => {
    expect(pickTypeForPlate(طابور, "حبك1234", 10_500)).toBeNull();
  });

  it("لوحة مش في النص خالص ⇒ فاضية، مش أول نوع في النافذة", () => {
    expect(pickTypeForPlate(طابور, "دطس2177", 10_000)).toBeNull();
  });

  it("نافذة بعيدة عن اللوحة مابتتسألش", () => {
    const بعيد = [{ text: نص, tMs: 10_000 }];
    expect(pickTypeForPlate(بعيد, "امن9107", 10_000 + TYPE_NEAR_MS + 1)).toBeNull();
  });

  it("أقرب نافذة **بتدّي نتيجة** هي اللي تكسب — مش أقرب نافذة وخلاص", () => {
    const طابور2 = [
      // أقرب زمنياً بس أرقامنا مش فيها ⇒ تتخطّى
      { text: "د ط س اتنين واحد سبعة سبعة مصدومه", tMs: 10_000 },
      { text: نص, tMs: 12_000 },
    ];
    expect(pickTypeForPlate(طابور2, "امن9107", 10_200)).toEqual({
      type: "ونيت",
      note: null,
    });
  });

  it("نافذة واحدة بتخدم **لوحتين** — مافيش استهلاك", () => {
    const نص2 = "ا م ن تسعة واحد صفر سبعة ونيت ب ر د تسعة ستة تمانية صفر دباب";
    const q = [{ text: نص2, tMs: 10_000 }];
    expect(pickTypeForPlate(q, "امن9107", 10_000)?.type).toBe("ونيت");
    expect(pickTypeForPlate(q, "برد9680", 10_000)?.type).toBe("دباب");
  });

  it("التنضيف بيسيب اللي جوّه المدة بس", () => {
    const q = [
      { text: "أ", tMs: 0 },
      { text: "ب", tMs: 1_000 },
    ];
    // الحد **شامل**: اللي بالظبط عند `now - KEEP` بيفضل.
    expect(pruneTypeQueue(q, TYPE_QUEUE_KEEP_MS + 1_000)).toEqual([q[1]]);
    expect(pruneTypeQueue(q, TYPE_QUEUE_KEEP_MS)).toEqual(q);
  });
});
