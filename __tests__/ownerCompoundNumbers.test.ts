import { describe, it } from "vitest";
import { digitStreamsOf } from "@/lib/vehicleTypeScan";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  الصيغ المركّبة اللي المالك بيقولها فعلاً — قايمته حرفياً
 * ══════════════════════════════════════════════════════════════════════
 *  المالك (٢٠ سبتمبر ٢٠٢٦): «انا عايز يطلع اي ارقام مركبه... وكتير إلى
 *  آخره، كل المركب اللي كده في كل الأربع أرقام».
 *
 *  فالقايمة دي **مواصفة** مش عيّنة. كل سطر جاي من نطقه هو.
 *
 *  العائلات اللي فيها:
 *   · عدّ التكرار      «تلات تسعات» ⇒ 999 · «اربع سبعات» ⇒ 7777
 *   · المثنى           «تمنيتين» ⇒ 88 · «صفرين» ⇒ 00
 *   · العقود بالعطف    «سته وستين» ⇒ 66 · «سبعه وسبعين» ⇒ 77
 *   · العشرات          «تسعتاشر» ⇒ 19 · «ستاشر» ⇒ 16
 *   · المئات           «تسعميه» ⇒ 900 · «روبعميه» ⇒ 400
 *   · العقود المفردة   «سبعين» ⇒ 70 · «تمانين» ⇒ 80
 */

const CASES: Array<[string, string]> = [
  ["تلات تسعات", "999"],
  ["اربع سبعات", "7777"],
  ["تمنيتين سته سبعه", "8867"],
  ["ستين سته وستين", "6066"],
  ["تسعتاشر تمانين", "1980"],
  ["تسعميه واحد", "9001"],
  ["سبعه وسبعين عشرين", "7720"],
  ["سته تلات اتنينات", "6222"],
  ["سبعه تلات تسعات", "7999"],
  ["تلات وحايد تمانيه", "1118"],
  ["صفرين سبعين", "0070"],
  ["صفرين ستاشر", "0016"],
  ["تلات تصفار سبعه", "0007"],
  ["تلات تصفار خمسه", "0005"],
  ["تمانيه تلات اربعات", "8444"],
  ["صفر خمسين واحد", "0501"],
  ["صفر خمسميه", "0500"],
  ["تسعه اربعميه", "9400"],
  ["سته تلاتين واحد", "6301"],
  ["خمسه اتنين وعشرين خمسه", "5225"],
];

describe("الصيغ المركّبة — قايمة المالك", () => {
  it("كام صيغة بتطلع صح", () => {
    const ok: string[] = [];
    const bad: string[] = [];
    for (const [text, want] of CASES) {
      const streams = digitStreamsOf(`ببد ${text}`).join(" ");
      (streams.includes(want) ? ok : bad).push(
        `${want.padEnd(5)} ← "${text}"${streams.includes(want) ? "" : `   ⇒ ${streams || "لا شيء"}`}`
      );
    }
    // eslint-disable-next-line no-console
    console.log(
      `\n╔═══ صيغ المالك المركّبة · ${ok.length}/${CASES.length} ═══\n` +
        ok.map((s) => "║ ✅ " + s).join("\n") +
        (bad.length ? "\n" + bad.map((s) => "║ ❌ " + s).join("\n") : "") +
        `\n╚═══════════════════════════════════════\n`
    );
  });
});
