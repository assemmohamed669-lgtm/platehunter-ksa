import { describe, it, expect } from "vitest";
import {
  noGpsWarning, autoExportPrompt, autoExportStopPrompt, trialExcelRows,
} from "../lib/trialToggles";

/**
 * ══════════════════════════════════════════════════════════════════════
 *  ⑩ الزرّين + ⑨ مشاركة الإكسيل
 * ══════════════════════════════════════════════════════════════════════
 *  المالك (٢٣ سبتمبر ٢٠٢٦):
 *   · «زرّ يقفل أخد موقع للوحات، ولما المندوب يدوس عليه يجيبله رسالة
 *     تحذير: اللوحات اللي هتاخدها بعد كده هتاخدها بدون موقع»
 *   · «زرّ التصدير التلقائي… يسأل المندوب: سيتم تفعيل التصدير التلقائي
 *     هل تريد هذا؟»
 *   · «بعد ما المندوب يقفل التسجيل تيجيله رسالة سيتم تصدير عدد كذا ويظهر
 *     اللوحات اللي متصدرتش عددها، هل تريد التصدير للسجلات؟»
 *
 *  🔴 الرسايل نصّ **بيتقرا وقت قرار** — المندوب واقف في الشارع وبيدوس بسرعة.
 *  فالعدد لازم يكون **في الرسالة نفسها** مش «تمام؟» مجرّدة، وإلا بيدوس نعم
 *  بلا ما يعرف هيضيّع إيه. نفس مبدأ `unexportedDeleteWarning` الموجود.
 */
describe("⑩ رسايل الزرّين", () => {
  it("قفل الموقع: التحذير بيقول اللي جاي بس", () => {
    const w = noGpsWarning();
    expect(w).toContain("بدون موقع");
    expect(w).toContain("بعد كده");
  });

  it("التصدير التلقائي: السؤال واضح", () => {
    expect(autoExportPrompt()).toContain("التصدير التلقائي");
  });

  it("🔴 رسالة نهاية التسجيل بتقول **العدد**", () => {
    const m = autoExportStopPrompt(7);
    expect(m).toContain("7");
    // بكلام المالك بالحرف: «هل تريد التصدير للسجلات»
    expect(m).toContain("للسجلات");
  });

  it("مافيش لوحات ⇒ مافيش رسالة أصلاً", () => {
    expect(autoExportStopPrompt(0)).toBeNull();
  });
});

/**
 * ══════════════════════════════════════════════════════════════════════
 *  ⑨ مشاركة إكسيل — الأعمدة اللي المندوب شايفها بالظبط
 * ══════════════════════════════════════════════════════════════════════
 *  🔴 **الفاضي مابيتحطّش عمود**: نفس قاعدة السجلات. ولو حطّينا عمود فاضي
 *  للكل، الملف بيتملّى أعمدة بيضا والمالك بيدوّر في نص فاضي.
 */
describe("⑨ صفوف الإكسيل", () => {
  const row = (over: Record<string, unknown> = {}) => ({
    plate: "أبح1234", type: null, note: null, match: null,
    lat: 25.3, lng: 55.37, shownAt: 1_700_000_000_000, ...over,
  });

  it("العمود الأساسي: اللوحة", () => {
    const out = trialExcelRows([row()], {});
    expect(out[0]["رقم اللوحة"]).toBe("أبح1234");
  });

  it("المطلوبة بتتعلّم", () => {
    const out = trialExcelRows([row({ match: { a: "b" } })], {});
    expect(out[0]["مطلوبة"]).toBe("نعم");
  });

  it("🔴 النوع والملاحظة الفاضيين مابيطلعوش أعمدة", () => {
    const out = trialExcelRows([row()], {});
    expect("النوع" in out[0]).toBe(false);
    expect("الملاحظة" in out[0]).toBe(false);
  });

  it("حقول الجلسة بتتكرّر على كل صف", () => {
    const out = trialExcelRows([row(), row()], { area: "النسيم", recorder: "أحمد" });
    expect(out[0]["اسم الحي - الشارع"]).toBe("النسيم");
    expect(out[1]["اسم المسجّل"]).toBe("أحمد");
  });

  it("الموقع بيطلع رابط خريطة", () => {
    const out = trialExcelRows([row()], {});
    expect(String(out[0]["الموقع"])).toContain("25.3");
  });

  it("مافيش موقع ⇒ مافيش عمود موقع للصف ده", () => {
    const out = trialExcelRows([row({ lat: null, lng: null })], {});
    expect("الموقع" in out[0]).toBe(false);
  });

  it("الأحدث الأول — زي ما المندوب شايفهم", () => {
    const out = trialExcelRows(
      [row({ plate: "أأأ1111", shownAt: 1 }), row({ plate: "ببب2222", shownAt: 2 })], {});
    expect(out[0]["رقم اللوحة"]).toBe("ببب2222");
  });
});
