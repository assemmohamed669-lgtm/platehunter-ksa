/** خريطة مبنيّة مرة واحدة: مفتاح مطبّع → الحرف */
const NAME_TO_LETTER = new Map<string, string>();
for (const [letter, names] of Object.entries(LETTER_NAMES)) {
  for (const name of names) {
    const key = lookupKey(name);
    if (key && !NAME_TO_LETTER.has(key)) NAME_TO_LETTER.set(key, letter);
  }
}

/**
 * الحرف من اسمه (أو من نفسه).
 * «كاف» → «ك» ، «هـــا» → «ه» ، «سيارة» → null
 */
export function letterFromName(word: string): string | null {
  const key = lookupKey(word);
  if (!key) return null;
  return NAME_TO_LETTER.get(key) ?? null;
}

/** هل الحرف ده موجود فعلاً على اللوحات السعودية؟ */
export function isPlateLetter(ch: string): boolean {
  return PLATE_LETTER_SET.has(ch);
}

/* ==========================================================================
 *  التصحيح الصوتي — من حرف مستحيل لأقرب حرف معتمد
 * ==========================================================================
 *  الترتيب في المصفوفة = ترتيب الأولوية. الأول هو الترشيح الرئيسي
 *  والباقي بدائل تظهر للمندوب لو حبّ يبدّل بضغطة.
 *
 *  الأساس في الاختيار: القرابة الصوتية (اللي محرك الصوت بيغلط فيها)
 *  مش القرابة الشكلية.
 */
const LETTER_SNAP: Record<string, string[]> = {
  ت: ["ط"], // نفس المخرج، والمعتمد على اللوحة هو الطاء
  ث: ["س", "ط"], // ث تُنطق س في كثير من اللهجات
  ج: ["ح"], // جيم/حاء أقرب زوج التباس في أسماء الحروف
  خ: ["ح", "ق"],
  ذ: ["د"], // ذال/دال
  ز: ["س", "ر"], // ز و س زوج مهموس/مجهور
  ش: ["س"],
  ض: ["ص", "د"], // ضاد/صاد زوج مفخّم
  ظ: ["ط", "ص"],
  غ: ["ع"], // نفس الرسم، نقطة واحدة
  ف: ["ق", "و"],
  ة: ["ه"],
  ى: ["ي"],
  ئ: ["ي"],
  ؤ: ["و"],
  أ: ["ا"],
  إ: ["ا"],
  آ: ["ا"],
  ء: ["ا"],
  پ: ["ب"],
  چ: ["ح"],
  ژ: ["س"],
  گ: ["ك"],
  ڤ: ["ق"],
};

export interface SnapResult {
  letter: string;
  changed: boolean;
  alternatives: string[];
}

/**
 * يصحّح الحرف لو مش موجود على اللوحة السعودية.
 * «ض» → «ص» (وبديل «د») ، «ب» → «ب» بلا تغيير
 */
export function snapToPlateLetter(ch: string): SnapResult {
  if (isPlateLetter(ch)) {
    return { letter: ch, changed: false, alternatives: [] };
  }
  const candidates = (LETTER_SNAP[ch] ?? []).filter(isPlateLetter);
  if (candidates.length === 0) {
    // حرف مش معروف خالص — نسيبه زي ما هو ونعلّمه للمراجعة
    return { letter: ch, changed: false, alternatives: [] };
  }
  return {
    letter: candidates[0],
    changed: true,
    alternatives: candidates.slice(1),
  };
}

/** شكل العرض: الهاء على اللوحة بتترسم «هـ» */
export function displayLetter(ch: string): string {
  return ch === "ه" ? "هـ" : ch;
}

/** يرسم مصفوفة حروف بشكل اللوحة: «أ ب حـ» */
export function displayLetters(letters: string[]): string {
  return letters.map(displayLetter).join(" ");
}

/* ==========================================================================
 *  تعزيز المفردات (Keyword Boosting)
 * ==========================================================================
 *  Deepgram و Whisper بيقبلوا قائمة مفردات متوقعة، وده بيرفع الدقة كتير
 *  لأنه بيقول للمحرك «الكلام المتوقع هو أسماء حروف وأرقام، مش كلام عادي».
 */
export function letterBoostTerms(): string[] {
  const terms = new Set<string>();

  // أسماء الحروف المعتمدة على اللوحة فقط — مش عايزين نعزّز حروف مستحيلة
  for (const letter of KSA_PLATE_LETTERS) {
    for (const name of LETTER_NAMES[letter] ?? []) {
      if (name.length >= 2) terms.add(name);
    }
  }

  // أسماء الأرقام من صفر لتسعة — دي أهم من الحروف في اللوحة
  for (const n of [
    "صفر",
    "واحد",
    "اتنين",
    "اثنين",
    "تلاتة",
    "ثلاثة",
    "أربعة",
    "خمسة",
    "ستة",
    "سبعة",
    "تمانية",
    "ثمانية",
    "تسعة",
  ]) {
    terms.add(n);
  }

  return [...terms];
}

