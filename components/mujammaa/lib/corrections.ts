/** لوحة سعودية: ٣ حروف عربية + ٤ أرقام */
const WELL = /^[\u0621-\u064a]{3}\d{4}$/;

export interface CorrectionInput {
  /** معرّف الصف في الجلسة */
  id: string;
  /** قراءة الموديل — الأصلية، قبل أي تعديل */
  heard: string;
  /** اللي المندوب كتبه */
  corrected: string;
  /** لحظة نطق اللوحة في التسجيل (ملي ثانية) — بيها نقصّ الصوت */
  tMs: number;
  /** ارفض التصحيح لو لحظة النطق مش معروفة (tMs = 0) */
  requireTime?: boolean;
}

export interface Correction {
  id: string;
  /** قراءة الموديل الأصلية — **مابتتغيّرش** مهما اتعدّل الصف بعد كده */
  heard: string;
  corrected: string;
  tMs: number;
  at: number;
}

export class CorrectionLog {
  private rows = new Map<string, Correction>();
  /** أول قراءة شفناها لكل صف — الأصل اللي بنقارن بيه */
  private origin = new Map<string, string>();

  record(input: CorrectionInput): void {
    const { id, heard, corrected, tMs, requireTime } = input;

    // الأصل بيتسجّل **مرة واحدة**. بعد أول تعديل، الصف بيرجّع القراءة المعدّلة
    // في `heard` — لو مشينا وراها هنقارن التصحيح بنفسه ونخسر الأصل.
    if (!this.origin.has(id)) this.origin.set(id, heard);
    const original = this.origin.get(id)!;

    if (requireTime && !tMs) return;          // مافيش صوت نقصّه ⇒ بلا فايدة للتدريب
    if (!WELL.test(corrected)) return;        // كتابة وسط ⇒ نتجاهل بلا ما نمسح القديم

    if (corrected === original) {
      // رجّعها لأصلها ⇒ مافيش تصحيح. مانسجّلوش كأنه تأكيد إن الموديل صح —
      // ممكن يكون بيجرّب بس، والتأكيد الصامت مش دليل.
      this.rows.delete(id);
      return;
    }
    this.rows.set(id, { id, heard: original, corrected, tMs, at: Date.now() });
  }

  /** التصحيحات الحقيقية بس */
  list(): Correction[] {
    return [...this.rows.values()];
  }

  get size(): number {
    return this.rows.size;
  }

  clear(): void {
    this.rows.clear();
    this.origin.clear();
  }

  toJSON(): Correction[] {
    return this.list();
  }

  static fromJSON(rows: Correction[]): CorrectionLog {
    const c = new CorrectionLog();
    for (const r of rows ?? []) {
      c.origin.set(r.id, r.heard);
      c.rows.set(r.id, r);
    }
    return c;
  }
}
