/**
 * ==========================================================================
 *  أسماء محركات «التفريغ المجمع» في التقرير
 * ==========================================================================
 *
 *  🔴 **ليه ملف لوحده وليه فيه اختبار.**
 *
 *  تقرير المالك (١٠ سبتمبر) قال «المحرك: Whisper» والشغّال كان «المقاطع».
 *  الاسم كان جوّه سلسلة `? :` في الصفحة بتغطّي ٣ محركات وبعدين
 *  `: "Whisper"` — فأي محرك جديد (وإحنا ضفنا `seg` وبعدين `chunks`)
 *  بيقع تلقائياً على اسم محرك **مااشتغلش**.
 *
 *  الغلطة دي مكلّفة مش شكلية: التقرير هو الحاجة الوحيدة اللي بتوصلني من
 *  الميدان، فلو سمّى المحرك غلط، القياس والتشخيص كله بيمشي على محرك تاني.
 *
 *  ⇒ الاسم بقى دالة نقية على `switch` **شامل**: أي محرك جديد يتضاف
 *    للنوع لازم ياخد حالة، وإلا `tsc` بيرفض عند `never` تحت.
 */

/** محركات صفحة المجمع — نفس مفاتيح `engine` في `BatchPage`. */
export type BatchEngine =
  | "chunks"
  | "seg"
  | "scan"
  | "vad"
  | "fused"
  | "openai";

/** القائمة بترتيب العرض على الشاشة — الاختبار بيلف عليها كلها. */
export const BATCH_ENGINES: readonly BatchEngine[] = [
  "chunks",
  "seg",
  "scan",
  "vad",
  "fused",
  "openai",
] as const;

/**
 * `— اسم` لو الاسم موجود، وإلا فاضي — عشان مافيش شرطة معلّقة.
 *
 * 🔴 وبيرفض **علامات النيابة** كمان. تقرير المالك (١٠ سبتمبر) طلع فيه
 * «كامل ⚡ (نداء واحد **— ؟** · النوع من كوهير)»: اسم الموديل بيوصل «؟»
 * لما حالة السيرفر لسه مااستقرّتش. «— ؟» في تقرير مابيقولش حاجة، وبيبان
 * كأنه بق. مافيش اسم ⇒ مافيش شرطة.
 */
const PLACEHOLDERS = new Set(["?", "؟", "—", "-", "…", "..", "...", "n/a", "null", "undefined"]);

function dash(model: string): string {
  const m = String(model || "").trim();
  if (!m || PLACEHOLDERS.has(m.toLowerCase())) return "";
  return ` — ${m}`;
}

/**
 * اسم المحرك زي ما بيظهر في «تقرير التفريغ (ابعته زي ما هو)».
 *
 * `model` = اسم موديل اللوحات الفعلي اللي السيرفر رجّعه (`seg-v3-3000`...)
 * — بيتحطّ في المحركات اللي بتستخدمه عشان التقرير يقول **بأي موديل**
 * اتقاست النتيجة، مش «موديلنا» المبهمة.
 */
export function batchEngineLabel(engine: BatchEngine, model: string): string {
  switch (engine) {
    case "chunks":
      return `كامل ⚡ (نداء واحد${dash(model)} · النوع من كوهير)`;
    case "seg":
      return `المقاطع (نوافذ متداخلة + إجماع${dash(model)} · بلا Deepgram)`;
    case "scan":
      return `المسح (موديلنا${dash(model)} + Deepgram شاهد)`;
    case "vad":
      return `VAD + الدمج (موديلنا${dash(model)} لوحده · بلا Deepgram)`;
    case "fused":
      return "المدمج (Deepgram + موديلنا)";
    case "openai":
      return "Whisper (OpenAI)";
    default: {
      /**
       * حارس الشمول: لو انضاف محرك للنوع بلا حالة هنا، `tsc` بيفشل عند
       * السطر ده — بدل إنه يقع بالسكوت على اسم محرك تاني زي الأول.
       */
      const never: never = engine;
      return String(never);
    }
  }
}
