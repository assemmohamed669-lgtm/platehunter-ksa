/**
 * ==========================================================================
 *  فصل النوع عن الملاحظة — عمودين بدل عمود
 * ==========================================================================
 *
 * 🔴 **البق اللي بيتصلّح (مقيس ٩ سبتمبر ٢٠٢٦):** الماسح كان بيرجّع **قيمة
 * واحدة** («الأخير يكسب»)، فلو المالك قال نوع **و**حالة، النوع **بيضيع**:
 *
 *     «ونيت مصدومه»      → مصدومه      (ونيت ضاع)
 *     «فان جراج يمين»    → جراج يمين   (فان ضاع)
 *     «اتش١ متربه»       → متربه       (اتش١ ضاع)
 *
 * طلب المالك: نوع العربية يفضل في **عمود النوع**، والحالة والمكان يروحوا
 * **عمود الملاحظات**. الحقلين موجودين أصلاً في `PlateEntry`
 * (`vehicleType` و `note`) وبيتصدّروا، فمافيش عمود جديد ولا هجرة.
 *
 * 🔴 **تلات تصنيفات مش اتنين** — عشان مانضيّعش حماية «الأخير يكسب»:
 * نافذة النوع بتبدأ ثانيتين **قبل** مركز اللوحة، فأولها ذيل اللوحة اللي
 * قبلها ومعاه نوعها/حالتها. لو لمّينا **كل** المطابقات في الملاحظة، حالة
 * اللوحة السابقة هتتسرّب. فكل تصنيف (نوع · حالة · مكان) بياخد **قيمة
 * واحدة، الأخيرة تكسب** — بالظبط زي ما اتقاس في ٨ سبتمبر.
 *
 * 🔴 **«لوحه صفرا» نوع مش مكان (تصحيح المالك، ٩ سبتمبر):** اللوحة الصفرا
 * في السعودية معناها **ملاكي تبع شركة** — فهي وصف نوع زي «ونيت»، ومنها
 * بنعرف إن العربية ملاكي شركة. كانت مصنّفة «مكان» غلط.
 */
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * 🧮 قناص: `type_server.py` (كوهير) مش في الريبو ده — بيشتغل على إيطاليا من نسخة
 * المعمل (`plate-voice-lab/serving`، متحقّق بالـmd5 ١٦ أكتوبر). اختبارَي «المرايا» بيقروه
 * من ريبو المعمل لو موجود جنبنا (`PLATE_LAB_DIR`)، ولو مش موجود بيتخطّوا بدل ما يفشلوا.
 */
const TYPE_SERVER_PY = resolve(
  process.env.PLATE_LAB_DIR || "C:/Users/assem/OneDrive/Dokumente/GitHub/plate-voice-lab",
  "serving/type_server.py"
);
const HAVE_TYPE_SERVER = existsSync(TYPE_SERVER_PY);
import {
  VEHICLE_CONDITION_KINDS,
  VEHICLE_NOTE_KINDS,
  VEHICLE_PLACE_KINDS,
  VEHICLE_TYPES,
  VEHICLE_TYPE_KINDS,
} from "../plateEntry";
import { scanTypeAndNote } from "../ph/vehicleTypeScan";

const say = (s: string) => `ا ب س تنين تسعة تمانية خمسة ${s}`;

describe("فصل النوع عن الملاحظة", () => {
  it("🔴 نوع + حالة ⇒ الاتنين يتحفظوا (النوع كان بيضيع)", () => {
    expect(scanTypeAndNote(say("ونيت مصدومه"))).toEqual({
      type: "ونيت",
      note: "مصدومه",
    });
  });

  it("🔴 نوع + مكان ⇒ الاتنين يتحفظوا", () => {
    expect(scanTypeAndNote(say("فان جراج يمين"))).toEqual({
      type: "فان",
      note: "جراج يمين",
    });
  });

  it("🔴 حالة + مكان ⇒ الاتنين في الملاحظة", () => {
    expect(scanTypeAndNote(say("مركونه برحه يمين"))).toEqual({
      type: null,
      note: "مركونه · برحه يمين",
    });
  });

  it("نوع + حالة + مكان ⇒ كل واحد في مكانه", () => {
    expect(scanTypeAndNote(say("ونيت متربه جراج يسار"))).toEqual({
      type: "ونيت",
      note: "متربه · جراج يسار",
    });
  });

  /**
   * الحماية اللي **ماينفعش** تضيع: ذيل اللوحة اللي قبلها في أول النافذة.
   * لو لمّينا كل المطابقات، «مصدومه» بتاعت اللوحة السابقة هتتلزق على دي.
   */
  it("🔴 حالتين في نافذة واحدة ⇒ الأخيرة تكسب (ذيل اللوحة السابقة ما يتسربش)", () => {
    expect(scanTypeAndNote(say("مصدومه رابع سين ستة ربعة تسعة سبعة متربه"))).toEqual(
      { type: null, note: "متربه" }
    );
  });

  it("مافيش نوع ولا ملاحظة ⇒ الاتنين فاضيين (ميهلوسش)", () => {
    expect(scanTypeAndNote(say("كلام عادي مالوش علاقة"))).toEqual({
      type: null,
      note: null,
    });
  });

  describe("«لوحه صفرا» = ملاكي شركة ⇒ نوع مش مكان", () => {
    it("بتروح لعمود النوع", () => {
      expect(scanTypeAndNote(say("لوحه صفرا"))).toEqual({
        type: "لوحه صفرا",
        note: null,
      });
    });

    it("🔴 كل إملاءاتها مقبولة — «صفرة» و«صفراء» كانوا بيفشلوا", () => {
      for (const s of [
        "لوحه صفرا",
        "لوحه صفرة",
        "لوحة صفرا",
        "لوحة صفرة",
        "لوحه صفراء",
        "لوحة صفراء",
      ]) {
        expect(scanTypeAndNote(say(s)).type, s).toBe("لوحه صفرا");
      }
    });

    it("مع حالة ⇒ النوع في عموده والحالة في الملاحظة", () => {
      expect(scanTypeAndNote(say("لوحه صفرا مصدومه"))).toEqual({
        type: "لوحه صفرا",
        note: "مصدومه",
      });
    });
  });

  /**
   * ==========================================================================
   * 🔴 **النوع كان مزحلق لوحة — كل لوحة تاخد نوع اللي قبلها.**
   * ==========================================================================
   * من جلسة المالك (٩ سبتمبر ٢٠٢٦، بعد فصل العمودين):
   *
   *     درر9200: قال «اتش١» وطلع «ونيت»   ← نوع بسل8763 اللي قبلها
   *     حهه6816: قال «شاص» وطلع «اتش١»    ← نوع درر9200 اللي قبلها
   *
   * سببين متضافرين:
   * ١. نافذة النوع بتبدأ **ثانيتين قبل** مركز اللوحة، فبتلقط نوع اللي قبلها.
   *    ولوجه بيوريها: `[النوع ✓ ونيت] ونيد دار رهرة 9200 H4` — «ونيد» بتاعة
   *    بسل، ونوع درر الحقيقي اتسمع «H4» (مش في القائمة) فمطابقش.
   * ٢. وبعدين حارس «املا لو فاضي بس» **يقفل الغلط**: لحهه جِت نافذة تانية
   *    `[النوع ✓ شاص] ه ه ه 6 8 1 6 شاص` — **صح** — بس اترفضت.
   *
   * 🔴 **الحل: نقص النص عند أرقام اللوحة نفسها، وناخد أول مطابقة بعدها.**
   * «الأخير يكسب» كانت موجودة عشان ماناخدش نوع اللوحة **السابقة** — والقيد
   * الجديد بيمنع ده **بنيوياً**، فبقى الأصح ناخد **الأول** بعد الأرقام لأن
   * النوع بيتقال ورا اللوحة فوراً. وده اللي بيحل الحالة الرابعة كمان:
   * «ح ب ك 5270 فان ب سيلم 8763 ونيد» ⇒ حبك تاخد «فان» مش «ونيت».
   *
   * ولو أرقام اللوحة **مش موجودة** في النص (منطوقة كلمات) بنرجع للسلوك
   * القديم بالكامل — فالتغيير **مايخسّرش** حاجة.
   */
  describe("النوع بيتقص عند أرقام اللوحة (منع الزحلقة)", () => {
    it("🔴 نوع اللوحة السابقة مايتحسبش", () => {
      // درر9200 — «ونيد» بتاعة بسل قبل الأرقام، و«H4» بعدها مش في القائمة
      expect(
        scanTypeAndNote("ونيد دار رهرة 9200 H4", { afterPlate: "درر9200" })
      ).toEqual({ type: null, note: null });
      // ومن غير القيد بتاخد نوع السابقة — ده السلوك اللي كان غلّط
      expect(scanTypeAndNote("ونيد دار رهرة 9200 H4").type).toBe("ونيت");
    });

    it("🔴 النوع اللي بعد الأرقام بيتحسب", () => {
      expect(
        scanTypeAndNote("ه ه ه 6 8 1 6 شاص", { afterPlate: "حهه6816" })
      ).toEqual({ type: "شاص", note: null });
    });

    it("🔴 نافذة فيها لوحتين ⇒ كل لوحة تاخد نوعها هي", () => {
      const w = "ح ب ك 5270 فان ب سيلم 8763 ونيد";
      expect(scanTypeAndNote(w, { afterPlate: "حبك5270" }).type).toBe("فان");
      expect(scanTypeAndNote(w, { afterPlate: "بسل8763" }).type).toBe("ونيت");
    });

    it("الأرقام مش في النص ⇒ السلوك القديم (كل النص، الأخير يكسب)", () => {
      // «دسر5210» اتقالت كلمات فالأرقام مش موجودة كأرقام
      expect(
        scanTypeAndNote("درسين راف 5 اتنين 10 مركونه", { afterPlate: "دسر5210" })
      ).toEqual({ type: null, note: "مركونه" });
    });

    /**
     * 🔴 **القيد كان معطّل لما الأرقام تتنطق كلمات (جلسة ١٠ سبتمبر ٢٠٢٦).**
     * المالك اتهجّى اللوحات («د ر خ سته خمسه خمسه اربع») فمافيش أرقام في
     * النص، فالقصّ مااشتغلش والزحلقة رجعت: `درق6554` خدت «اتش١» بتاعة
     * `حمس2635` اللي قبلها. الحل: نحوّل كلمات الأرقام لأرقام
     * (`arabicNumbers.numberTokenValue`) قبل الدوران.
     */
    it("🔴 الأرقام منطوقة كلمات ⇒ القيد يشتغل برضه", () => {
      const w = "تلاته خمسه اتش ون د ر خ سته خمسه خمسه اربع شاقص";
      /**
       * 🔴 **التوقّع اتصحّح (١٤ سبتمبر ٢٠٢٦).** كان `toBeNull()` — وده كان
       * بيوثّق **حدّ** مش قاعدة: «شاقص» وقتها ماكانتش بتطابق «شاص» لأن
       * التقريب كان مقفول على الكلمات ذات التلات حروف.
       *
       * و«شاقص» **بعد** أرقام اللوحة ⇒ هي نوع اللوحة دي فعلاً، وورقة أخو
       * المالك بتقول `شاص | درق6554` بالحرف. فالصح إنها تطلع «شاص».
       *
       * والحارس نفسه ما اتغيّرش: المهم إنها **مش** بتاخد «اتش١» بتاعة
       * اللوحة اللي قبلها — وده اللي السطر التاني بيثبته.
       */
      expect(scanTypeAndNote(w, { afterPlate: "درق6554" }).type).toBe("شاص");
      /**
       * ⚠️ **السطر ده بطّل يصلح كمثال على التسريب.** كان بيقول «من غير
       * القيد بتاخد نوع اللوحة السابقة (اتش١)» — ودلوقتي «شاقص» بقت
       * تتطابق، وهي **آخر** مطابقة في النص، فبدون القصّ بترجّع «شاص».
       *
       * الحراسة ضد التسريب نفسها **مغطّاة في اختبارين تانيين**:
       *   · «ولازم يوقف عند أرقام اللوحة اللي بعدها» (تحت مباشرة)
       *   · «كل لوحة تاخد النوع اللي بعدها هي» في `vehicleTypeScanFull`
       * فماحصلش ضعف في التغطية — النص ده بس اتغيّر معناه.
       */
      expect(scanTypeAndNote(w).type).toBe("شاص");
    });

    /**
     * 🔴 **ولازم يوقف عند أرقام اللوحة اللي بعدها (نفس الجلسة).**
     * `حهد4197` خدت ملاحظة «مصدومه» وهي بتاعة `ربس6497`:
     *     «ديال 4197 لوحة صفراء بسيم 6497 مصدوم»
     * القصّ من بعد ٤١٩٧ لوحده مش كفاية — «مصدوم» بعد ٦٤٩٧، يعني بتاعة
     * اللوحة اللي بعدها. فبنوقف عند أول تسلسل ٣ أرقام+ تاني.
     */
    it("🔴 يوقف عند أرقام اللوحة اللي بعدها", () => {
      const w = "اه اه ديال 4197 لوحة صفراء بسيم 6497 مصدوم";
      expect(scanTypeAndNote(w, { afterPlate: "حهد4197" })).toEqual({
        type: "لوحه صفرا",
        note: null,
      });
      expect(scanTypeAndNote(w, { afterPlate: "ربس6497" })).toEqual({
        type: null,
        note: "مصدومه",
      });
    });

    it("أرقام مفرّقة بشرط + لوحة بعدها ⇒ كل واحدة ملاحظتها", () => {
      const w = "5/2/10 مركون راس 8/1/4 مطرب";
      expect(scanTypeAndNote(w, { afterPlate: "دسر5210" }).note).toBe("مركونه");
    });

    it("الأرقام موجودة والحالة بعدها ⇒ تتحفظ", () => {
      expect(
        scanTypeAndNote("ره ب س 6497 مصدومة", { afterPlate: "ربس6497" })
      ).toEqual({ type: null, note: "مصدومه" });
    });
  });

  describe("سلامة التصنيفات", () => {
    it("النوع + الملاحظة = القائمة الكاملة، بلا تكرار ولا نقصان", () => {
      const union = [...VEHICLE_TYPE_KINDS, ...VEHICLE_NOTE_KINDS];
      expect(new Set(union).size).toBe(union.length); // بلا تكرار
      expect(new Set(union)).toEqual(
        new Set(VEHICLE_TYPES.filter((t) => t !== "أخرى"))
      );
    });

    it("«لوحه صفرا» في النوع، و«جراج» في الملاحظة", () => {
      expect(VEHICLE_TYPE_KINDS).toContain("لوحه صفرا");
      expect(VEHICLE_NOTE_KINDS).toContain("جراج");
      expect(VEHICLE_NOTE_KINDS).not.toContain("لوحه صفرا");
    });
  });

  /**
   * 🔴 **حارس التفكّك — ده البق اللي لقيناه فعلاً.**
   *
   * العميل كان فيه نطقات «لوحةصفرا» و«لوحهصفراء» والسيرفر **مافيهوش ولا
   * واحدة** — والسيرفر هو المسار الأساسي (شاهد كوهير). فالمالك يقول إملاء
   * صحيح والخانة تفضل فاضية بلا أي سبب ظاهر.
   *
   * القايمتين **لازم يبقوا مرايا**، والاختبار ده بيقرا ملف بايثون فعلاً
   * ويقارن — فأي تفكيك جديد بيفشل هنا بدل ما يوصل للميدان.
   */
  it.skipIf(!HAVE_TYPE_SERVER)("🔴 قائمة السيرفر (type_server.py) مطابقة لقائمة العميل", () => {
    const py = readFileSync(
      TYPE_SERVER_PY,
      "utf8"
    );
    const grab = (name: string) => {
      const m = py.match(new RegExp(`^${name}\\s*=\\s*\\[([\\s\\S]*?)^\\]`, "m"));
      if (!m) throw new Error(`مالقيتش ${name} في type_server.py`);
      return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
    };
    expect(new Set(grab("VEHICLE_TYPE_KINDS"))).toEqual(new Set(VEHICLE_TYPE_KINDS));
    expect(new Set(grab("VEHICLE_CONDITION_KINDS"))).toEqual(
      new Set(VEHICLE_CONDITION_KINDS)
    );
    expect(new Set(grab("VEHICLE_PLACE_KINDS"))).toEqual(new Set(VEHICLE_PLACE_KINDS));
    // `VEHICLE_NOTE_KINDS` على السيرفر **مشتقّة** (جمع الحالة + المكان) مش
    // قائمة حرفية، والتحقّق من التلاتة فوق بيغطّيها بالبناء.
    expect(new Set([...VEHICLE_CONDITION_KINDS, ...VEHICLE_PLACE_KINDS])).toEqual(
      new Set(VEHICLE_NOTE_KINDS)
    );
  });

  /**
   * 🔴 **وحارس النطقات — ده اللي البق الحقيقي كان فيه.**
   * العميل كان فيه نطقات للوحة الصفرا والسيرفر **مافيهوش ولا واحدة**،
   * فالمالك يقول «لوحة صفراء» والخانة تفضل فاضية. بنقارن الخريطتين
   * بعد تطبيع موحّد (شيل الفراغات · أ/إ/آ→ا · ة→ه · تصغير).
   */
  it.skipIf(!HAVE_TYPE_SERVER)("🔴 نطقات السيرفر مطابقة لنطقات العميل", () => {
    const flat = (s: string) =>
      s
        .replace(/[أإآ]/g, "ا")
        .replace(/ة/g, "ه")
        .replace(/ـ/g, "")
        .replace(/\s+/g, "")
        .toLowerCase();

    const pairs = (src: string, block: string) => {
      const m = src.match(new RegExp(`${block}[\\s\\S]*?\\{([\\s\\S]*?)^\\}`, "m"));
      if (!m) throw new Error(`مالقيتش ${block}`);
      const out = new Map<string, string>();
      // مفتاح مجرّد أو بين علامتين ⇒ "قيمة"
      for (const [, k1, k2, v] of m[1].matchAll(
        /(?:"([^"]+)"|([^\s:,{}"]+))\s*:\s*"([^"]+)"/g
      )) {
        out.set(flat(k1 ?? k2), flat(v));
      }
      return out;
    };

    const here = readFileSync(resolve(__dirname, "../ph/vehicleTypeScan.ts"), "utf8");
    const there = readFileSync(
      TYPE_SERVER_PY,
      "utf8"
    );
    const a = pairs(here, "const VARIANTS");
    const b = pairs(there, "^VARIANTS");
    expect(a.size).toBeGreaterThan(20); // اطمن إن التحليل نجح
    expect(Object.fromEntries([...b].sort())).toEqual(
      Object.fromEntries([...a].sort())
    );
  });
});
