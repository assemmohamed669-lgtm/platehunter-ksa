/**
 * ==========================================================================
 *  🔴 «تلاتة اربعين ستة» = ٣٤٠٦ مش ٤٩ — العشرات كانت بتتجمع بدل ما تتلزق
 * ==========================================================================
 *  المندوب بينطق خانات اللوحة بأي تشكيلة، ومنها **خانة عشرات**:
 *
 *      «حا طا قاف تلاتة اربعين ستة»  ⇒  حطق3406   (٣ · ٤٠ · ٦)
 *      «صاد واو ستين تلاتة ستة»      ⇒  رصو6036   (٦٠ · ٣ · ٦)
 *      «ياء ميم أربعة أربعة عشرة»    ⇒  ديم4410   (٤ · ٤ · ١٠)
 *
 *  المحرك كان بيشوف كلمة قيمتها ≥١٠ فيدخل «الوضع المركّب» ويجمع:
 *  ٣+٤٠+٦ = **٤٩**. فاللوحة تطلع خانتين وتترمي على إنها ناقصة.
 *  وده كان بياكل تلات لوحات من السبعة الضايعين في جلسة الـ٩٠ لوحة.
 *
 *  ── القاعدة اللي بتفرّق ──────────────────────────────────────────────
 *      **«و» بتوصّل، والفراغ بيفصل.**
 *          «خمسة وعشرين»          ⇒ عدد واحد = ٢٥
 *          «سبعة وسبعين ستة سبعة» ⇒ ٧٧ · ٦ · ٧ = "٧٧٦٧"
 *          «ألفين وسبعمية»        ⇒ عدد واحد = ٢٧٠٠
 *  والصيغة الملزوقة «وستين» و«واربعين» — Deepgram بيكتبها كلمة واحدة —
 *  كانت **مش متعرَّف عليها خالص** فبتتشال بالسكوت.
 *
 *  ── القياس على ٩٧٨ رسالة من ٢٦ جلسة (الأرقام في الكوميت) ─────────────
 */
import { describe, it, expect } from "vitest";
import { parseNumberGroup } from "../arabicNumbers";

const digits = (s: string) => parseNumberGroup(s.split(/\s+/)).digits;

describe("العشرات جوّه خانات اللوحة", () => {
  it("🔴 الفراغ بيفصل ⇒ الخانات تتلزق", () => {
    expect(digits("تلاتة اربعين ستة")).toBe("3406");
    expect(digits("ستين تلاتة ستة")).toBe("6036");
    expect(digits("أربعة أربعة عشرة")).toBe("4410");
    expect(digits("صفر اربعين تسعة")).toBe("0409");
    expect(digits("تسعين ثمانية ثمانية")).toBe("9088");
    expect(digits("عشرة تلاتين")).toBe("1030");
    expect(digits("واحد خمسة احداشر")).toBe("1511");
  });

  it("🔴 «و» بتوصّل ⇒ عدد واحد", () => {
    expect(digits("خمسة وعشرين")).toBe("25");
    expect(digits("ألفين و سبعمية")).toBe("2700");
  });

  it("🔴 الصيغة الملزوقة «وسبعين» توصّل زي «و سبعين»", () => {
    expect(digits("سبعة وسبعين ستة سبعة")).toBe("7767");
    expect(digits("تلاتة وستين")).toBe("63");
  });

  /**
   * الاتنين قيمتهم ١٠ ودورهم مختلف — والداتا الحقيقية هي اللي حسمت:
   *     ديم4410 و ريع1030 لوحتين مؤكّدتين من قائمة المالك، ومحتاجين
   *     «عشرة» تبقى خانة. و«خمسة عشر» = ١٥ في أي عربي.
   */
  it("🔴 «عشر» بتكمّل العدد · «عشرة» خانة لوحدها", () => {
    expect(digits("خمسة عشر")).toBe("15");
    expect(digits("أربعة أربعة عشرة")).toBe("4410");
  });

  it("الأرقام المفردة زي ما هي", () => {
    expect(digits("واحد اتنين تلاتة أربعة")).toBe("1234");
    expect(digits("صفر ستة سبعة ثمانية")).toBe("0678");
  });

  it("الأرقام المكتوبة رقمياً زي ما هي", () => {
    expect(digits("12 34")).toBe("1234");
    expect(digits("83 64")).toBe("8364");
  });
});
