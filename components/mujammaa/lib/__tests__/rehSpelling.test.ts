/**
 * ==========================================================================
 *  🔴 «ره» — الراء اللي كانت بتضيع من أول كل لوحة
 * ==========================================================================
 *  Deepgram بيكتب الراء «ره» أو «راه» في معظم الأحيان، والقاموس كان فيه
 *  «راء / را / ريه / ر» بس. النتيجة إن الحرف الأول كان **بيتشال بالسكوت**:
 *
 *      «ره سين قاف ٤٩٢٢»   ⇒  سق4922   [حروف أقل من ٣]
 *      «ره صاد واو ٦٠٣٦»   ⇒  صو6036   [حروف أقل من ٣]
 *      «حا ره ب ٦٩٨٦»      ⇒  (مافيش لوحة خالص)
 *
 *  ودي مش حالة نادرة — دي **أكتر سبب واحد للوحات الناقصة** في السجل.
 *
 *  ── القياس على ٩٧٨ رسالة من ٢٦ جلسة حقيقية ─────────────────────────────
 *      ناقصة الشكل  ⇒ سليمة        : **٩٠**
 *      مافيش لوحة   ⇒ لوحة سليمة   : **١٩**
 *      🔴 سليمة     ⇒ بقت غلط      : **صفر**
 *
 *  ⚠️ توسيع قاموس النطق **اتـرفض قبل كده بالقياس** — صيغ مضافة على
 *  التخمين زوّدت الغلط. الفرق هنا إن الإضافة دي اتقاست على الجلسات نفسها
 *  قبل ما تتحط: ١٠٩ مكسب وصفر خسارة. أي صيغة جديدة تعدّي نفس القياس.
 */
import { describe, it, expect } from "vitest";
import { parseSaudiPlates } from "../parseSaudiPlates";

const plateOf = (text: string) =>
  (parseSaudiPlates(text) as Array<{ plate: string; flags: string[] }>).map(
    (p) => `${p.plate}${p.flags.length ? `[${p.flags.join(",")}]` : ""}`
  );

describe("«ره» و«راه» = راء", () => {
  it("🔴 الراء في أول اللوحة ماتضيعش", () => {
    expect(plateOf("ره سين قاف أربعة تسعة اتنين اتنين")).toEqual(["رسق4922"]);
    expect(plateOf("ره صاد واو ستة زيرو تلاتة ستة")).toEqual(["رصو6036"]);
  });

  it("🔴 لوحة كانت ضايعة خالص بقت تطلع", () => {
    expect(plateOf("حا ره ب ستة تسعة ثمانية ستة")).toEqual(["حرب6986"]);
    expect(plateOf("دال ره ب سبعة خمسة اتنين واحد")).toEqual(["درب7521"]);
  });

  it("الراء في النص أو في الآخر برضه", () => {
    expect(plateOf("ب ره واو خمسة زيرو تسعة واحد")).toEqual(["برو5091"]);
    expect(plateOf("حاء ميم ره ثمانية زيرو أربعة ستة")).toEqual(["حمر8046"]);
  });

  it("«راه» زي «ره»", () => {
    expect(plateOf("دال راه دال ثمانية ستة واحد اتنين")).toEqual(["درد8612"]);
  });

  it("راءين ورا بعض ماتتلغبطش", () => {
    expect(plateOf("ره ره ميم سبعة ستة ستة تلاتة")).toEqual(["ررم7663"]);
  });

  /** الصيغ القديمة لازم تفضل شغّالة — الإضافة بتزوّد مابتستبدلش */
  it("الصيغ القديمة زي ما هي", () => {
    expect(plateOf("راء سين قاف أربعة تسعة اتنين اتنين")).toEqual(["رسق4922"]);
    expect(plateOf("ر س ق أربعة تسعة اتنين اتنين")).toEqual(["رسق4922"]);
  });
});
