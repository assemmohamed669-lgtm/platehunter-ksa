/**
 * القائمة الكاملة اللي أملاها المالك (٨ سبتمبر ٢٠٢٦) — فيها **أماكن**
 * من ٤ و٥ كلمات، والماسح القديم كان بيجرّب كلمتين بس فمستحيل كان يمسكها.
 */
import { describe, it, expect } from "vitest";
import { scanVehicleType, scanTypeAndNote } from "../ph/vehicleTypeScan";
import { VEHICLE_TYPE_KINDS } from "../plateEntry";

describe("ماسح النوع — القائمة الكاملة", () => {
  it("بيمسك كل نوع قاله المالك", () => {
    const cases: Array<[string, string]> = [
      ["ابح1234 ونيت", "ونيت"],
      ["ابح1234 نقل", "نقل"],
      ["ابح1234 فان", "فان"],
      ["ابح1234 تاكس", "تاكسي"],
      ["ابح1234 دينه", "دينه"],
      ["ابح1234 دباب", "دباب"],
      ["ابح1234 باص", "باص"],
      ["ابح1234 ملاكي", "ملاكي"],
      ["ابح1234 موتوسيكل", "موتوسيكل"],
      ["ابح1234 شاص", "شاص"],
      ["ابح1234 مصدومه", "مصدومه"],
      ["ابح1234 متربه", "متربه"],
      ["ابح1234 مركونه", "مركونه"],
      ["ابح1234 اتش١", "اتش١"],
      ["ابح1234 لوحه صفرا", "لوحه صفرا"],
      ["ابح1234 فندق", "فندق"],
      ["ابح1234 امام فندق", "امام فندق"],
    ];
    for (const [text, want] of cases) {
      expect(scanVehicleType(text), text).toBe(want);
    }
  });

  /**
   * الدفعة التانية اللي أملاها المالك في نفس اليوم:
   * «غمارتين غمارة هاي اس جينيسيس حادث شاحنه صالون دفع رباعي نقليات».
   * تمانية منهم كانوا موجودين أصلاً — الفرق كان في **الإملا**:
   * أنا كاتب «جينسيس» وهو بيقول «جينيسيس»، وأنا «شاحنة» وهو «شاحنه».
   * الإملا بتاعته هي اللي بتتكتب في الخانة، فهي اللي بقت الرسمية.
   */
  it("بيمسك الدفعة التانية بإملا المالك", () => {
    const cases: Array<[string, string]> = [
      ["ابح1234 غمارتين", "غمارتين"],
      ["ابح1234 غمارة", "غمارة"],
      ["ابح1234 غمره", "غمارة"],
      ["ابح1234 هاي اس", "هاي اس"],
      ["ابح1234 هايس", "هاي اس"],
      ["ابح1234 جينيسيس", "جينيسيس"],
      ["ابح1234 جنسيس", "جينيسيس"],
      ["ابح1234 حادث", "حادث"],
      ["ابح1234 شاحنه", "شاحنه"],
      ["ابح1234 شاحنة", "شاحنه"],
      ["ابح1234 صالون", "صالون"],
      ["ابح1234 دفع رباعي", "دفع رباعي"],
      ["ابح1234 نقليات", "نقليات"],
    ];
    for (const [text, want] of cases) {
      expect(scanVehicleType(text), text).toBe(want);
    }
  });

  it("🔴 العبارة الأطول بتكسب الأقصر — مكان غلط أوحش من مكان فاضي", () => {
    expect(scanVehicleType("ابح1234 برحه يمين")).toBe("برحه يمين");
    expect(scanVehicleType("ابح1234 برحه اخر الشارع يمين")).toBe(
      "برحه اخر الشارع يمين"
    );
    expect(scanVehicleType("ابح1234 برحه اول الشارع يسار")).toBe(
      "برحه اول الشارع يسار"
    );
    expect(scanVehicleType("ابح1234 جراج يسار")).toBe("جراج يسار");
  });

  it("🔴 مابيخترعش من كلام عادي — «شايف أنا» كانت بتطلّع «فان»", () => {
    expect(scanVehicleType("أنا شايف أنا مش موجود")).toBeNull();
    expect(scanVehicleType("ازيك عامل ايه النهاردة")).toBeNull();
  });

  it("🔴 أسماء حروف اللوحة مابتطلّعش نوع", () => {
    expect(scanVehicleType("باء دال سين تلاتة")).toBeNull();
    expect(scanVehicleType("ألف لام ميم اتنين")).toBeNull();
  });

  /**
   * 🔴 **نوافذ حقيقية من جلسة المالك (٨ سبتمبر) — النوع كان بيتلخبط.**
   *
   * نافذة النوع في الفوري بتبدأ ثانيتين **قبل** مركز اللوحة، فأولها
   * بيبقى ذيل اللوحة اللي قبلها ومعاه نوعها. القاعدة القديمة («أطول
   * عبارة تكسب») خلّت «لوحه صفرا» بتاعة اللوحة اللي فاتت تكسب
   * «مصدومه» بتاعة اللوحة دي.
   */
  it("كل لوحة تاخد النوع اللي بعدها هي — مش نوع اللي قبلها", () => {
    const real: Array<[string, string | null]> = [
      ["سبعة لوحة صفرا رابع سين ستة ربعة تسعة سبعة مصدومة", "مصدومه"],
      ["ربعة صفر رعبة سين ستة اربعة تسعة سبعة مصدوم", "مصدومه"],
      ["من عشرة مركونة راه راسين تمانية واحد تسعة اربعة مطرب", "متربه"],
      ["حانون دال تسعه زيرو زيرو تلاته برحه يمين", "برحه يمين"],
      ["يعتبرها يمين، وها هي دي الـ 4/1/9/7 لوحة صفرا.", "لوحه صفرا"],
      ["بسيره خمسه اثنين عشره مركون", "مركونه"],
      ["تسين رقم ستنين عشرة مركون.", "مركونه"],
      // 🔴 «مدينة» كانت بتطلّع «دينه» — حرف زيادة في الأول
      ["9 مدينة 20 راح هي 6 8 1 6 شهر", null],
      ["الف بس يكون تسعة تمانية خمسة قروش", null],
      ["ها ها ها ستة تمانية واحد ستة شخص", null],
    ];
    for (const [text, want] of real) {
      expect(scanVehicleType(text), text).toBe(want);
    }
  });

  it("بياخد آخر نوع — النوع بيتقال بعد اللوحة", () => {
    expect(scanVehicleType("دباب ا ب ح واحد اتنين تلاتة اربعة ملاكي")).toBe(
      "ملاكي"
    );
  });

  /**
   * 🔴 **«جراج» لوحدها كانت ناقصة من القائمة (مكتشف ٩ سبتمبر ٢٠٢٦).**
   *
   * القائمة كان فيها «جراج يمين» و«جراج يسار» بس. والمالك في تسجيلاته
   * التلاتة قال «ابس٢٩٨٥ **جراج**» — كلمة واحدة — فالكلمة كانت **مستحيل
   * تطابق**، وخانة النوع فضلت فاضية في كل جريّة. مش عيب سمع، عيب قائمة.
   */
  it("🔴 «جراج» لوحدها بتتطابق — المالك بيقولها كده", () => {
    expect(scanVehicleType("ا ب س تنين تسعة تمانية خمسة جراج")).toBe("جراج");
  });

  it("«جراج يمين» تفضل تكسب «جراج» — الأطول أولاً", () => {
    expect(scanVehicleType("حهد اربعة واحد تسعة سبعة جراج يمين")).toBe("جراج يمين");
  });

  /**
   * 🔴 وإضافتها **ماتفتحش باب اختراع**: «جراج» ٤ حروف، فلو دخلت المطابقة
   * التقريبية (فرق حرف + نفس أول حرف) كانت **«جرار»** و**«جراح»** هيطلّعوا
   * «جراج» — و«جرار» كلمة ميدانية واردة. فهي **نص كامل بس**.
   */
  it("🔴 «جرار» و«جراح» ماينفعش يطلّعوا «جراج»", () => {
    expect(scanVehicleType("عندنا جرار")).toBeNull();
    expect(scanVehicleType("الدكتور جراح")).toBeNull();
  });
});

/**
 * 🔴 **نوع مخترع من أرقام ممسوخة — جلسة المالك ١٨ سبتمبر ٢٠٢٦.**
 *
 * البطاقة `دال0521` طلعت بنوع «ونيت» من نص مافيهوش نوع خالص: «ده الألف
 * لم خمسة اتنين واحد تسعة ونين» — «ونين» أرقام ممسوخة («وتسعين»).
 *
 * والحاجزين لازم مع بعض:
 *  · «ونيت» نفسها (٤ حروف) بحرف **مختلف** ⇒ نفس الطول ومفتاح <٥ ⇒ مرفوض
 *  · والبديل «وني» (٣ حروف) بحرف **زيادة** ⇒ بديل قصير ⇒ تمام بس
 */
describe("نوع مخترع من أرقام ممسوخة", () => {
  it("«ونين» ماتطلّعش «ونيت»", () => {
    expect(scanVehicleType("ونين")).toBeNull();
    expect(scanVehicleType("خمسة اتنين واحد تسعة ونين.")).toBeNull();
    expect(
      scanTypeAndNote("ده الألف لم خمسة اتنين واحد تسعة ونين.", { afterPlate: "دال0521" }).type
    ).toBeNull();
  });

  it("والأنواع الحقيقية لسه بتتمسك", () => {
    expect(scanVehicleType("ونيت")).toBe("ونيت");
    expect(scanVehicleType("ونيته")).toBe("ونيت");
    expect(scanVehicleType("وني")).toBe("ونيت");
    // الأنواع التلات حروف: التقريب عليها مقيس ومطلوب
    expect(scanVehicleType("شاقص")).toBe("شاص");
    expect(scanVehicleType("شاص")).toBe("شاص");
  });
});

/**
 * 🔴 **«ديانا» هي «دينه» — قرار المالك (٣ أكتوبر ٢٠٢٦).**
 * «ديانا» و«دينه» **نفس العربية**، والإملاء الصح «دينه». فأي سمعة —
 * «ديانا» · «ديانة» · «ديان» · «دينا» · «دينة» — بتتكتب «دينه»، و«ديانا»
 * **اتشالت** كعضو منفصل من القائمة المقفولة.
 *
 * اللي جاب القرار: جلسة المالك (٣ أكتوبر ٢٠٢٦) — `درس7305` حقيقتها
 * «دينه»، وكوهير كتب «ديانة»/«ديانا» في التلات نوافذ فالتقرير كتب «ديانا».
 *
 * التاريخ: قبل القرار كانوا عضوين، و«ديان» (مسافته **١** من «ديانا»
 * و**٢** من «دينه») كان بيروح «ديانا» غلط — مقيس على `حدص1077` (كوهير
 * «ديان» في التلات نوافذ) و`ربه8173` (جلسة ٨٦ بطاقة، ١٨ سبتمبر ٢٠٢٦)،
 * والاتنين حقيقتهم «دينه». وكنا بنفرّق «ديانة» = «ديانا» بالتاء المربوطة
 * (`هحر1654` · `راص7371`) — التفرقة دي **اتلغت بالقرار**.
 */
describe("ديانا = دينه (قرار المالك ٣ أكتوبر ٢٠٢٦)", () => {
  it("كل السمعات بتتكتب «دينه»", () => {
    expect(scanVehicleType("ديان")).toBe("دينه");
    expect(scanVehicleType("ديانة")).toBe("دينه");
    expect(scanVehicleType("ديانا")).toBe("دينه");
    expect(scanVehicleType("دينه")).toBe("دينه");
    expect(scanVehicleType("دينا")).toBe("دينه");
    expect(scanVehicleType("دينة")).toBe("دينه");
  });

  it("«ديانا» مش عضو منفصل في القائمة", () => {
    expect(VEHICLE_TYPE_KINDS).not.toContain("ديانا");
    expect(VEHICLE_TYPE_KINDS).toContain("دينه");
  });

  it("على النصوص الحقيقية من المقاعد", () => {
    const t = (plate: string, text: string) =>
      scanTypeAndNote(text, { afterPlate: plate }).type;
    expect(t("حدص1077", "حاد الصاد 10 77 ديان (أ طه سين 162 9 دباب)")).toBe("دينه");
    expect(t("ربه8173", "19.31 تاكسي ، آه ب 8173 ديان، ب د 8123 دباب")).toBe("دينه");
    expect(t("هحر1654", "(جينيسيس) (حارة 1654 ديانة) (B cup 4287 شحنة)")).toBe("دينه");
    expect(t("راص7371", "جينيسيس ، را أ ص 7371 ديانة ، أ طهارة 9154 شاحنة")).toBe("دينه");
    // جلسة المالك ٣ أكتوبر ٢٠٢٦ — نص كوهير الحقيقي لـ`درس7305` (نافذتين)
    expect(
      t("درس7305", "نقليات درا سين سبعة تلاتة زيرو خمسة ديانة دال ميم ياس خمسة ستة تلاتين شاحنة")
    ).toBe("دينه");
    expect(
      t("درس7305", "نقليات درا سين سبعة تلاتة زيرو خمسة ديانا دال ميم يس خمسة ستة تلاتين شاحنة")
    ).toBe("دينه");
  });
});
