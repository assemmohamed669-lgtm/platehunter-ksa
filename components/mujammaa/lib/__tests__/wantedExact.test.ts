/**
 * ==========================================================================
 *  «مطلوبة» = تطابق كامل بس — لا تقريبي ولا شدّ
 * ==========================================================================
 *
 *  قرار المالك (٢٠٢٦/٨/١٥) بعد تقارير أربع مناديب:
 *      «مش عايز أشوف كلمة مقاربة للوحة مطلوبة — المطلوبة تبقى مطابقة كاملة،
 *       لوحات وحروف.»
 *
 *  اللي كان بيحصل قبل القرار ده:
 *
 *  ١. **تطابق تقريبي (٨٦٪)** — ظهر ٦ مرات في جلسة واحدة (مندوب د). واللوحات
 *     كانت **صح ١٠٠٪** ومش في الشيت، والبرنامج بيعرض عليها تفاصيل عربية
 *     تانية بتفرق خانة واحدة (سورينتو · سيلفرادو · أمجراند). المندوب يقرا
 *     تفاصيل عربية مالهاش علاقة بالّي قدامه.
 *
 *  ٢. **الشدّ للشيت** — أخطر: عند مندوب أ اللوحة اتسمعت «ا0007» (حرف واحد!)
 *     فالبرنامج شدّها لأقرب لوحة في الشيت وعرضها **«لا0007 — مطلوبة»**.
 *     يعني لوحة مخترعة بعلامة يقين، والمندوب ممكن يتحرّك عليها.
 *
 *  ⚠️ التمن المعروف والمقبول: لو التفريغ غلط في خانة واحدة، اللوحة المطلوبة
 *  **مش هيرن عليها تنبيه** وهتعدّي. بدّلنا **إنذار كاذب** بـ**فرصة ضايعة**
 *  — وده اختيار المالك المتكرّر: «الأهم إنه ميطلعش غلط».
 */

import { describe, it, expect } from "vitest";
import { buildBankSheet, matchInBankSheet } from "../bankSheet";

const sheet = buildBankSheet(
  ["اللوحة", "البنك"],
  [
    { اللوحة: "دهس2110", البنك: "الراجحي" },
    { اللوحة: "بلن5947", البنك: "تاجير" },
  ],
  { fileName: "شيت.xlsx", sheetName: "تشييك" }
);

describe("«مطلوبة» = تطابق كامل بس", () => {
  it("التطابق الكامل بيرن زي ما هو", () => {
    const m = matchInBankSheet(sheet, "دهس2110");
    expect(m.kind).toBe("exact");
    expect(m.row?.البنك).toBe("الراجحي");
  });

  it("🔴 فرق خانة واحدة = **مش مطلوبة**", () => {
    expect(matchInBankSheet(sheet, "دهس2111").kind).toBe("none");
  });

  it("🔴 فرق حرف واحد = **مش مطلوبة**", () => {
    expect(matchInBankSheet(sheet, "دهش2110").kind).toBe("none");
  });

  it("🔴 اللوحة الناقصة عمرها ما تطابق — حتى لو قريبة", () => {
    // الحالة الحقيقية: «ا0007» اتشدّت لـ«لا0007» وظهرت مطلوبة
    expect(matchInBankSheet(sheet, "ا0007").kind).toBe("none");
    expect(matchInBankSheet(sheet, "لن5947").kind).toBe("none");
  });

  it("لوحة مش في الشيت خالص = مش مطلوبة", () => {
    expect(matchInBankSheet(sheet, "احح2854").kind).toBe("none");
  });
});
