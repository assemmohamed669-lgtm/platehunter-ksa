/**
 * ==========================================================================
 *  أنهي ورقة في ملف الشيت هي اللي فيها اللوحات؟
 * ==========================================================================
 *
 *  🔴 باج حقيقي في شغل المندوب اليومي (اتكشف ٢٠٢٦/٨/١٤ على ملف «تشييك
 *  العــربـــي» الحقيقي):
 *
 *  القاعدة القديمة: «فضّل الورقة اللي اسمها تشييك/إحالة». وفي الملف الحقيقي:
 *      ورقة «تشييك»  ← ٣٨٣٢ صف ·   **٣ لوحات صالحة**  (ورقة عمل يومية فاضية)
 *      ورقة «العربي» ← ٦٢١٤٢ صف · **٥١٤٣١ لوحة**      (الداتا الحقيقية)
 *
 *  فالبرنامج كان بياخد الورقة الفاضية ⇒ تنبيه «مطلوبة» عمره ما يرن، والمندوب
 *  يفوّت عربية مطلوبة وهو شايف إن البرنامج شغّال. أسوأ نوع فشل: صامت.
 *
 *  القاعدة الجديدة: **الورقة اللي فيها لوحات أكتر تكسب.** والاسم يبقى
 *  مرجّح عند التساوي بس — لأن الاسم رأي والعدد حقيقة.
 */

import { describe, it, expect } from "vitest";
import { pickPlateSheet } from "../bankSheet";

/** ورقة كأنها من ‎sheet_to_json‎ */
const rowsWith = (plates: string[]) =>
  plates.map((p) => ({ اللوحة: p, البنك: "بنك" }));

describe("اختيار ورقة اللوحات", () => {
  it("🔴 الورقة الأكبر تكسب حتى لو اسمها مش «تشييك»", () => {
    const picked = pickPlateSheet({
      تشييك: rowsWith(["بكب7322", "", ""]),
      العربي: rowsWith(["دقح6735", "دعو2429", "رحم3249", "ررا2791", "دنه8986"]),
    });
    expect(picked).toBe("العربي");
  });

  it("«تشييك» تكسب لما تكون هي اللي فيها الداتا", () => {
    const picked = pickPlateSheet({
      تشييك: rowsWith(["دقح6735", "دعو2429", "رحم3249"]),
      ملاحظات: rowsWith(["", "كلام", ""]),
    });
    expect(picked).toBe("تشييك");
  });

  it("عند التساوي الاسم المفضّل يكسب", () => {
    const same = ["دقح6735", "دعو2429"];
    expect(pickPlateSheet({ ورقة1: rowsWith(same), تشييك: rowsWith(same) })).toBe(
      "تشييك"
    );
  });

  it("ورقة واحدة = هي المختارة، ولو مافيهاش لوحات", () => {
    expect(pickPlateSheet({ أي: rowsWith(["", "كلام"]) })).toBe("أي");
  });

  it("مافيش ورقات = فاضي، مش استثناء", () => {
    expect(pickPlateSheet({})).toBe("");
  });
});
