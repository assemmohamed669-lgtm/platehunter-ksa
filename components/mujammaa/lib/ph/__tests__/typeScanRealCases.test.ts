/**
 * ══════════════════════════════════════════════════════════════════════
 *  🔴 إملاء الحروف **مايطلّعش نوع** — جلسة ٧٥ لوحة بلا أنواع
 * ══════════════════════════════════════════════════════════════════════
 *
 * المالك سجّل ٧٥ لوحة و**ماقالش ولا نوع واحد**، وطلعت ٦ أنواع من العدم.
 * والسبب إن إملاء حروف اللوحة اتقرا كنوع:
 *
 *   «ع راه راه … هاي س»  ← «هاي س» = حرف «س» متهجّى  ⇒ اتقرت «هاي اس»
 *   «ا ص … ب لام س»      ← حروف اللوحة اللي بعدها    ⇒ اتقرت «بي ام»
 *   «هنر را …»           ← «را» اسم حرف               ⇒ اتقرت «راس شاحنه»
 *
 * حارس `LETTER_NAMES` موجود من زمان — لكنه بيشتغل على **الكلمة الواحدة**
 * بس (`n === 1`). ولما وسّعنا التقريب للعبارات المركّبة، «هاي س» و«ب لام»
 * (كلمتين) عدّوا من تحته.
 *
 * ⚠️ ودي أخطر من نوع ناقص: المالك **ماقالش** نوع خالص، فأي نوع بيظهر
 *   هو اختراع صافي بيتكتب في داتاه.
 */
describe("إملاء الحروف مايطلّعش نوع", () => {
  const CASES: Array<[string, string]> = [
    ["ع راه راه زيرو سبعة اتنين خمسة هاي س خمسة سبعة", "عرر0725"],
    ["ا ص واحد سبعة زيرو ست ب لام س اربعة تسعة", "اصط1706"],
    ["هنر را تمانية تسعة اتنين تمانية، هنر را تمانية تسعة تلاتة واحد.", "حنر8928"],
    ["ح نور 8932 ح ر بي 6233", "حنر8932"],
    ["بـ ع نون 7128 حاطط را 6389 بـ س ه 8129", "بعن7128"],
  ];
  for (const [text, plate] of CASES) {
    it(`«${text.slice(0, 34)}…» ⇒ مافيش نوع`, () => {
      expect(scanTypeAndNote(text, { afterPlate: plate }).type).toBeNull();
    });
  }
});

/**
 * 🔴 **ثغرة تانية في حارس الإملاء — جلسة ٨١ لوحة بلا أنواع.**
 *
 * «راس بي لم 2927 بي لم أ 9238» ⇒ طلّعت «بي ام» للوحة `ربل2927`.
 * و«بي لم» هنا **إملاء حروف اللوحة اللي بعدها** (بلا)، مش نوع.
 *
 * الحارس بيعدّ الحروف **المفردة** (طول ١)، و«بي» و«لم» طولهم حرفين
 * فعدّوا من تحته. الحل: «لم» نطق لحرف «لام» ومافيش نوع بيبدأ بيها،
 * فدخولها قائمة أسماء الحروف آمن — بخلاف «بي» اللي أول كلمة في «بي ام».
 */
describe("ثغرة الإملاء بحرفين", () => {
  it("«بي لم» إملاء مش نوع", () => {
    expect(
      scanTypeAndNote("راس بي لم 2927 بي لم أ 9238", { afterPlate: "ربل2927" }).type
    ).toBeNull();
  });
  it("«بي ام» الحقيقي لسه شغّال", () => {
    expect(scanTypeAndNote("ابح1234 بي ام", { afterPlate: "ابح1234" }).type).toBe("بي ام");
  });
});
