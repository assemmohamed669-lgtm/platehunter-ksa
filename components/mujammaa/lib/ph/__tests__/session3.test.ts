import { describe, it, expect } from "vitest";
import { scanTypeAndNote, digitStreamOf, digitStreamsOf } from "../vehicleTypeScan";

/**
 * 🔴 نصوص حقيقية من جلسة ١٧ سبتمبر ٢٠٢٦ (٨٢ كارت على شيت ٨١ صف).
 * كل واحدة الموديل **سمع الكلمة صح** والماسح رماها.
 */
const t = (txt: string, p: string) => {
  const s = scanTypeAndNote(txt, { afterPlate: p });
  return [s.type, s.note].filter(Boolean).join(" · ");
};

describe("جلسة ١٧ سبتمبر — اللي اترمي غلط", () => {
  it("«نقلية» = نقليات", () => {
    expect(t("4 دفع رباعي، ح م مية، 4 1، 9 1، نقلية.", "حمي4191")).toBe("نقليات");
  });

  it("«تسعة وتسعين» = ٩٩ مش ٩٩٠", () => {
    // المندوب قال ٩ ٩ ٧ ٣ وكوهير كتبها مركّبة
    expect(digitStreamsOf("واو لام تسعة وتسعين سبعة تلاتة").some((x) => x.includes("9973"))).toBe(true);
    expect(t("واو لام تسعة وتسعين سبعة تلاتة جرش واحد يسار س هره ستة اربعة", "بول9973"))
      .toBe("جراج واحد يسار");
  });

  /**
   * ⚠️ الفكرة دي **اترفضت بالقياس ١٤ سبتمبر** (طلّعت «لوحه صفرا ← استار»
   * من نافذة جارة). السبب وقتها إن القصّ لما يفشل كان بيرجع يقرا النافذة
   * **كلها**؛ ودلوقتي بقى fail-closed فالسبب اتشال — وأعدت القياس على
   * المقعدين ومسطرة الشيت: **صفر ارتداد**.
   */
  it("«ستار» = استار", () => {
    expect(t("ب ح ن تسعة ستة أربعة ستة ستار أ ك", "بحن9646")).toBe("استار");
  });

  it("🛡️ والقراءة التانية لنفس الشكل لسه شغّالة", () => {
    // هنا «تسعة وستين» معناها ٩ وبعدها ٦٠ — واللوحة ٨٩٦٠
    expect(digitStreamOf("ع ه م تمانية تسعة وستين")).toContain("8960");
    expect(t("ع ه م تمانية تسعة وستين تحت تند ب يه واو سبعة وستين", "عهم8960")).toBe("تحت تنده");
  });
});
