-- =====================================================================
-- ملاحظة الأدمن على المندوب (القلم في قايمة المناديب).
--
-- المالك (٤ أكتوبر ٢٠٢٦): «علامه قلم علشان اكتب ملاحظه قدام المندوب دة انه مثلا
-- عليه 50 ريال دفع 100 حق الاشتراك … تظهر في المربع عند المندوب دة ك ملاحظه باللون
-- الاحمر و اقدر اشيل الملاحظه دي بعدين».
--
-- عمود على صف المندوب في `profiles` (زي agent_notice). الكتابة من
-- `/api/admin/manage-agent` (setAdminNote) بمفتاح الخدمة بس؛ والعرض في صفحة الأدمن.
--
-- يُشغَّل مرة واحدة على Supabase (SQL Editor). آمن للتشغيل المتكرر.
-- =====================================================================

alter table public.profiles
  add column if not exists admin_note text;

comment on column public.profiles.admin_note is
  'ملاحظة الأدمن على المندوب (مثلاً: عليه 50 ريال). NULL = مافيش ملاحظة.';
