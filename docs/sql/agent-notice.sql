-- =====================================================================
-- رسالة خاصة لمندوب واحد.
--
-- الأدمن بيكتبها من صفحة المندوب، وتظهر عنده **هو لوحده** بالأحمر في كل
-- صفحات البرنامج، وتفضل لحد ما الأدمن يشيلها.
--
-- الفرق عن `app_notice`: دي رسالة عامة بتروح لكل المناديب؛ الرسالة دي على
-- صفّ المندوب نفسه في `profiles`، فمحدش غيره بيقراها — سياسة RLS الموجودة
-- بتخلّي كل مندوب يقرا صفّه بس.
--
-- الكتابة بتتم من `/api/admin/manage-agent` بمفتاح الخدمة (نفس قاعدة كل
-- كتابات `profiles`) — فمافيش دالة setter هنا ولا صلاحية كتابة للعميل.
--
-- يُشغَّل مرة واحدة على Supabase (SQL Editor). آمن للتشغيل المتكرر.
-- =====================================================================

alter table public.profiles
  add column if not exists agent_notice    text,
  add column if not exists agent_notice_at timestamptz;

comment on column public.profiles.agent_notice is
  'رسالة خاصة بالمندوب ده — بتظهر عنده بالأحمر. NULL = مافيش رسالة.';
comment on column public.profiles.agent_notice_at is
  'وقت آخر كتابة للرسالة (للعرض عند المندوب).';
