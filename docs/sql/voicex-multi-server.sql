-- VoiceX — توزيع المناديب على أكتر من صندوق
-- يُشغَّل مرة واحدة على Supabase (SQL Editor). آمن للتشغيل المتكرر.
--
-- ليه (مقيس ٢٣ سبتمبر ٢٠٢٦):
--   · طاقة الصندوق  = ٣.٣ نافذة/ث  (قياس مفتوح الحلقة بصوت حقيقي)
--   · المندوب الحقيقي = ١٠.٦ نافذة/دقيقة  (٣٠ مندوب · ٣٣ ألف نافذة من
--     حصاد كوريا — الوسيط ١٠.٠ يعني بيتكلم ٢٥٪ من الوقت)
--   ⇒ ~١٥-١٨ مندوب للصندوق. والمتوقّع ٢٠-٢٥ ⇒ صندوقين.
--
-- 🔴 وقبل ده المؤشّر كان **عنوان واحد لكل المناديب**، فأي صندوق إضافي
--    مكانش هيشوف ولا مندوب مهما استأجرنا.
--
-- ⚠️ التشغيل ده **مايغيّرش أي سلوك لوحده**: العمود بيتولد فاضي (null)،
--    والكود ساعتها بيشتغل بالصندوق الأساسي بس — نفس النهاردة بالحرف.
--    التوزيع بيبدأ **بس** لما تحطّ صناديق في العمود.
-- =====================================================================

-- ─────────────────────────────────────────────────────────────────────
-- (١) عمود الصناديق الإضافية.
--     الشكل: [{"url": "https://...", "is_up": true}, ...]
--     الصندوق الأساسي يفضل في `url`/`is_up` زي ما هو (توافق كامل).
-- ─────────────────────────────────────────────────────────────────────
alter table public.voicex_pointer
  add column if not exists servers jsonb;

comment on column public.voicex_pointer.servers is
  'صناديق VoiceX الإضافية: [{"url","is_up"}]. الأساسي في url/is_up. '
  'فاضي = صندوق واحد = السلوك القديم. الكود بيوزّع المناديب عليهم بتجزئة '
  'ثابتة لمعرّف المندوب، والصندوق الواقع بيحوّل اللي عليه بس.';

-- ─────────────────────────────────────────────────────────────────────
-- (٢) القراءة: الصف مقروء أصلاً لأي مسجّل، والعمود الجديد بيرث نفس
--     السياسة تلقائياً. مافيش سياسة جديدة مطلوبة.
--     ⚠️ الكتابة تفضل للمالك بس (زي ما هي) — العنوان بيتكتب من أداة النفق.
-- ─────────────────────────────────────────────────────────────────────

-- =====================================================================
-- الاستعمال — لما تجيب صندوق تاني:
--
--   update public.voicex_pointer
--      set servers = '[{"url": "https://<الصندوق-التاني>", "is_up": true}]'::jsonb
--    where id = true;
--
-- ولإيقاف صندوق مؤقّتاً (صيانة) بلا ما تشيله:
--
--   update public.voicex_pointer
--      set servers = '[{"url": "https://<...>", "is_up": false}]'::jsonb
--    where id = true;
--
-- المناديب اللي عليه هيتحوّلوا لغيره **لحظياً** (realtime)، والباقي
