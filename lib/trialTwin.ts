/**
 * ══════════════════════════════════════════════════════════════════════
 *  لمّ التوائم — «لوحة واحدة اتقرت كذا طريقة» مقابل «لوحتين حقيقيتين»
 * ══════════════════════════════════════════════════════════════════════
 *
 * 🔴 **الباج** (تقرير المالك، ٢٢ سبتمبر · التجربة التالتة): لوحة `دطس2177`
 * اتقالت **مرة واحدة** وطلعت **أربع صفوف**:
 *
 *     60.5  دطس2112      62.0  دطس2112
 *     66.5  دطس2121      68.0  دطس2100      69.5  دطس2177 ×٢
 *
 * السبب: الإجماع بيجمّع بنافذة **٢ ثانية**، والقراءات دي على مدى **٩ ثواني**
 * فاتفصلت لأربع عناقيد مستقلة، وكل واحدة عدّت لوحدها (اتنين منهم بنافذتين
 * والباقي بثقة عالية).
 *
 * ⇒ الإجماع بيشتغل على مستوى **النافذة**؛ محتاجين طبقة تانية على مستوى
 *   **الصف** — دي هي.
 *
 * ── 🔴 ليه الحد رقمين مش تلاتة ────────────────────────────────────────
 * في **نفس ورقة المالك** فيه `رقب7499` و`رقب7218` — **لوحتين حقيقيتين**
 * بنفس الحروف وفرقهم **٣ أرقام**. لو وسّعنا الحد لتلاتة نلمّهم غلط ونضيّع
 * لوحة حقيقية. ورقمين بيغطّي كل قراءات `دطس` الأربعة (فرق كل واحدة عن الصح
 * رقمين بالظبط).
 *
 * ⚠️ الحد ده **مقيس على ورقة المالك**، مش مفترض. أي تغيير فيه لازم يتقاس
 *    على نفس الورقة تاني.
 */

/** ٣ حروف + ٤ أرقام — أي شكل تاني مالوش معنى نقارنه. */
const WELL = /^[ء-ي]{3}\d{4}$/;

/** أقصى فرق في الأرقام عشان نعتبرهم نفس العربية. */
export const TWIN_MAX_DIGIT_DIFF = 2;

/**
 * 🔴 **اللوحة المتطابقة حرف بحرف بتتلمّ لمدة أطول بكتير.**
 *
 * بلاغ المالك (٢٣ سبتمبر ٢٠٢٦): «بيكتب اللوحة مرتين» — `رره6232` طلعت
 * **٣ صفوف**، و`ردق8637` و`رطص9784` و`رحج2976` كمان.
 *
 * السبب إن النافذة كانت **١٢ث لكل الحالات**. والحد ده متحط للتوائم
 * **المسخّمة** (`دطس2112`/`دطس2177`) عشان مايلمّش لوحتين حقيقيتين
 * متشابهتين — وده لازم يفضل ضيّق.
 *
 * لكن **لوحتين متطابقتين حرف بحرف = نفس العربية**، مستحيل غير كده. فدي
 * نافذتها أوسع: دقيقتين. أطول من أي تأخير إجماع أو تكرار نطق، وأقصر من
 * إن المندوب يلفّ ويرجع لنفس العربية في جلسة طويلة.
 */
export const EXACT_REPEAT_MS = 120_000;

/**
 * 🔴 **نفس اللوحة: قُرب في الصفوف + قُرب في الوقت.**
 *
 * محاولتان قبل كده اتكذّبوا بجلسات حقيقية:
 *   ① **حد زمني دقيقتين** — ضيّع إعادة مقصودة (`دمس5284` مرتين بينهم
 *      ٤ لوحات، طلعت مرة واحدة).
 *   ② **«لازم تكون آخر صف»** — كسّر اللمّ لما المندوب يقول **لوحتين
 *      بالتبادل** (`ساك2121` · `دهس6877` · `ساك2121`…): آخر صف بيبقى
 *      اللوحة التانية فالشرط بيفشل كل مرة، وكل نطقة بتطلع ٣ صفوف.
 *
 * ⇒ النطقة الواحدة بتتقري في نوافذ متداخلة، فصفوفها **متلاصقة** وثوانيها
 *   **قليلة** — حتى لو فيه لوحة تانية في نفس النافذة. والإعادة المقصودة
 *   بينها لوحات **وثواني أكتر**. الشرطين مع بعض بيفصلوا الحالتين.
 */
export const EXACT_REPEAT_MAX_ROWS = 3;

/** نفس اللوحة موجودة في آخر `maxRows` صف؟ (القُرب في الصفوف) */
export function isExactRepeatNearby(
  plate: string,
  shownPlatesNewestFirst: readonly string[],
  maxRows: number = EXACT_REPEAT_MAX_ROWS,
): boolean {
  const p = String(plate ?? "").trim();
  if (!p) return false;
  return (shownPlatesNewestFirst ?? []).slice(0, maxRows).includes(p);
}


export interface TwinRow {
  plate: string;
  /** زمن النطق داخل الجلسة (مللي) */
  atMs: number;
}

function digitsDiff(a: string, b: string): number {
  let n = 0;
  for (let i = 0; i < 4; i++) if (a[i] !== b[i]) n += 1;
  return n;
}

/**
 * الاتنين دول نفس العربية؟ **نفس الحروف + فرق ≤ رقمين + خلال `windowMs`.**
 *
 * الزمن شرط لازم: نفس اللوحة بتتقري في نوافذ متتالية خلال ثواني؛ أما لوحتين
 * متشابهتين في جلسة طويلة فبينهم دقايق.
 */
export function sameCarTwin(a: TwinRow, b: TwinRow, windowMs: number): boolean {
  const pa = String(a?.plate ?? "");
  const pb = String(b?.plate ?? "");
  if (!WELL.test(pa) || !WELL.test(pb)) return false;
  const gap = Math.abs((a.atMs ?? 0) - (b.atMs ?? 0));
  /**
   * 🔴 **المتطابقة حرف بحرف بيحكمها الفاصل، مش الوقت.**
   *
   * الحد الزمني (دقيقتين) ضيّع إعادة مقصودة عند المالك: قال `دمس5284`
   * مرتين بينهم ٤ لوحات، وطلعت مرة واحدة. فالمقارنة الزمنية هنا بقت
   * **مساعدة بس** — القرار الحقيقي عند المنادي عبر
   * `isExactRepeatOfLatest` (تتلمّ لو هي **آخر صف** بس).
   *
   * وبنسيب حد زمني صغير كحارس أخير: نطقة واحدة بتتقري في نوافذ خلال
   * ثواني، مش دقايق.
   */
  if (pa === pb) return gap <= windowMs;
  if (gap > windowMs) return false;

  const la = pa.slice(0, 3), lb = pb.slice(0, 3);
  const da = pa.slice(3), db = pb.slice(3);

  // ① نفس الحروف + فرق ≤ رقمين  (دطس2112 / دطس2177)
  if (la === lb) return digitsDiff(da, db) <= TWIN_MAX_DIGIT_DIFF;

  /**
   * ② **نفس الأرقام بالظبط + حرف واحد مختلف** (`دطس2177` / `بطس2177` —
   * من تقرير المالك الرابع). أربع أرقام متطابقة في نفس الثواني احتمال
   * إنها عربيتين مختلفتين ضئيل جداً، والفرق حرف واحد = سمع مش عربية تانية.
   *
   * ⚠️ مشدود عن قصد: **الأرقام لازم تتطابق بالكامل**. لو سمحنا برقم مختلف
   * كمان كنا هنلمّ لوحات حقيقية.
   */
  if (da === db) {
    let diff = 0;
    for (let i = 0; i < 3; i++) if (la[i] !== lb[i]) diff += 1;
    return diff <= 1;
  }
  return false;
}

/**
 * ══════════════════════════════════════════════════════════════════════
 *  «لوحة اتسمعت وماظهرتش» — بحساب التوائم، مش بالتطابق الحرفي
 * ══════════════════════════════════════════════════════════════════════
 *
 * 🔴 **إنذار كاذب** (جلسة المالك ٢٢ سبتمبر ٢٠٢٦ · ٤٣ لوحة): التقرير قال
 * «لوحة اتسمعت وماظهرتش: 1 [حبل6899]» — و`حبل6899` **مش ضياع**، دي قراءة
 * مغلوطة لـ`حبل6819` اللي ظهرت فعلاً في الصف ٤٢. النافذة اللي بعدها
 * قرتها صح، ولمّ التوائم شالها زي ما المفروض.
 *
 * العدّاد كان بيقارن بـ`Set` من نص اللوحات المعروضة، فأي قراءة مسخّمة
 * بخانة واحدة كانت بتتعدّ ضياع.
 *
 * ⚠️ **وده أخطر من عيب تجميل**: المالك بيقرا الرقم ده عشان يحكم على
 *    الموديل، فالتقرير بيدّيه فقد مالوش وجود.
 *
 * ⇒ القراءة ماتتحسبش ضياع لو فيه صف معروض **توأمها** (`sameCarTwin`) —
 *   نفس الحكم اللي الصفحة بتلمّ بيه الصفوف أصلاً، فالاتنين مايختلفوش.
 */

/** ٣ حروف + ٤ أرقام — أي شكل تاني مش لوحة نحاسبها. */
const WELL_FORM = /^[ء-ي]{3}\d{4}$/;

export interface HeardRead {
  /** ممكن تكون أكتر من لوحة في نافذة واحدة، مفصولة بمسافات. */
  plate: string;
  tMs: number;
  accepted: boolean;
  blocked: boolean;
}

export interface ShownRow {
  plate: string;
  atMs: number;
}

/**
 * اللوحات اللي الموديل قراها وقبلناها ومع ذلك **ماوصلتش الجدول** —
 * بعد استبعاد القراءات المسخّمة للوحات ظهرت فعلاً.
 *
 * `windowMs` هي نفس نافذة لمّ التوائم في الصفحة (١٢ث افتراضياً) عشان
 * التقرير يحكم بنفس حكم العرض بالظبط.
 */
export function heardNotShown(
  reads: readonly HeardRead[],
  rows: readonly ShownRow[],
  windowMs = 12000
): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const r of reads ?? []) {
    if (!r?.accepted || r.blocked) continue;
    for (const p of String(r.plate ?? "").split(/\s+/)) {
      if (!WELL_FORM.test(p) || seen.has(p)) continue;
      const covered = (rows ?? []).some(
        (row) =>
          row.plate === p ||
          sameCarTwin({ plate: p, atMs: r.tMs }, { plate: row.plate, atMs: row.atMs }, windowMs)
      );
      if (covered) continue;
      seen.add(p);
      out.push(p);
    }
  }
  return out;
}
