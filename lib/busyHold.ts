/**
 * ══════════════════════════════════════════════════════════════════════
 *  «الميك مشغول» لحد **آخر خطوة** — مش لحظة ضغط «إيقاف»
 * ══════════════════════════════════════════════════════════════════════
 *
 * المالك (٢٣ سبتمبر ٢٠٢٦): «لما بنزّل تحديث بيتعمل تحديث تلقائي معايا وأنا
 * مشغّل المايك وبقول لوحات، فبيفصل مني التسجيل. خلّي التحديث يتعمل بعد ما
 * أقفل المسجّل».
 *
 * التحديث التلقائي (`UpdateBanner`) بيأجّل نفسه طول ما `isMicBusy()`. بس
 * «أقفل المسجّل» في «الجديد» مش لحظة واحدة: المحرك بيستنى آخر نوافذ من
 * السيرفر (آخر لوحات اتقالت)، وبعدين سؤال التصدير، وبعدين التصدير نفسه.
 * تحديث في النص = آخر لوحات ضايعة أو تصدير نصّه اتعمل.
 *
 * فكل خطوة **بتمسك** (`hold`) وبتسيب لما تخلص، و«مشغول» = فيه مسكة واحدة
 * على الأقل. السيب مرتين مابيفكّش مسكة حد تاني.
 */

export interface BusyHold {
  /** يمسك — بيرجّع دالة السيب (آمنة لو اتندهت أكتر من مرة). */
  hold(): () => void;
  /** الصفحة اتقفلت — كله يتساب، والمسكات القديمة مابتأثرش بعد كده. */
  reset(): void;
  readonly busy: boolean;
}

export function createBusyHold(set: (busy: boolean) => void): BusyHold {
  let count = 0;
  let epoch = 0;
  return {
    hold() {
      const mine = epoch;
      let released = false;
      count++;
      set(true);
      return () => {
        if (released || mine !== epoch) return;
        released = true;
        count = Math.max(0, count - 1);
        if (count === 0) set(false);
      };
    },
    reset() {
      epoch++;
      count = 0;
      set(false);
    },
    get busy() { return count > 0; },
  };
}
