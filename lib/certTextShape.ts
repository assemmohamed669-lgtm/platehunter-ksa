/**
 * 📄 شكل نص الشهادة من غير أي بيانات — عشان نعرف القارئ مش لاقي اللوحة ليه.
 *
 * المالك (٦ أكتوبر ٢٠٢٦): «فيه حد بيفرز مش بيطلع معاه نتيجه». شهايد ٤ و٥ أكتوبر أغلبها اتقرى منها
 * الشاص بس من غير لوحة. السطور بتطلع بعد ما كل حرف إنجليزي يبقى «L» وكل رقم «9» و**أي** حرف تاني
 * «ع» — ماعدا كلمات العناوين المعروفة (رقم/اللوحة/Plate…) — فبيبان مكان اللوحة وشكلها من غير اسم ولا رقم.
 */
const KEEP = new Set([
  "رقم", "اللوحة", "اللوحه", "لوحة", "لوحه", "المركبة", "المركبه", "الأصل", "األصل", "الاصل", "نوع", "لون", "سنة", "الصنع",
  "المصنع", "الهيكل", "الشاصي", "الشاسيه", "التسجيل", "حالة", "العقد", "الاسم", "االسم", "تاريخ", "الشهادة", "الوثيقة", "السند",
  "Plate", "PLATE", "plate", "No", "No.", "NO", "Number", "VIN", "Chassis", "CHASSIS", "Registration", "Vehicle", "VEHICLE",
  "المسجل", "المسجّل",
]);

/**
 * كلمة واحدة: إنجليزي ⇒ «L» · رقم ⇒ «9» · **أي** حرف تاني ⇒ «ع» — عربي ولا متلخبط من الخط (شهايد
 * «السجل» العربي جوّاها رموز من لغات تانية؛ لازم تستخبى هي كمان، مايتسابش ولا حرف). العلامات اللي
 * فوق/تحت الحروف بتتشال، والمسافات وعلامات الترقيم الإنجليزي بتفضل.
 */
function maskToken(tok: string): string {
  let out = "";
  for (const ch of tok) {
    if (/[A-Za-z]/.test(ch)) out += "L";
    else if (/[0-9٠-٩۰-۹]/.test(ch)) out += "9";
    else if (ch.charCodeAt(0) < 0x80) out += ch;
    else if (/\p{M}/u.test(ch)) continue;
    else out += "ع";
  }
  return out;
}

/** سطر واحد: كلمات العناوين زي ما هي، والباقي حروف/أرقام مستخبية. */
export function maskCertLine(line: string): string {
  return line.split(/(\s+)/).map((tok) => (KEEP.has(tok.replace(/[:：.,]+$/g, "")) ? tok : maskToken(tok))).join("");
}

/** أول `max` سطر من النص بعد الإخفاء. */
export function certTextShape(text: string, max = 60): string[] {
  return text.split("\n").map((l) => l.trim()).filter(Boolean).slice(0, max).map(maskCertLine);
}
