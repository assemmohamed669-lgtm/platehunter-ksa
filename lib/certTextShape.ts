/**
 * 📄 شكل نص الشهادة من غير أي بيانات — عشان نعرف القارئ مش لاقي اللوحة ليه.
 *
 * المالك (٦ أكتوبر ٢٠٢٦): «فيه حد بيفرز مش بيطلع معاه نتيجه». شهايد ٤ و٥ أكتوبر أغلبها اتقرى منها
 * الشاص بس من غير لوحة. السطور بتطلع بعد ما **كل** حرف عربي يبقى «ع» وكل حرف لاتيني «L» وكل رقم «9»
 * — ماعدا كلمات العناوين المعروفة (رقم/اللوحة/Plate…) — فبيبان مكان اللوحة وشكلها من غير اسم ولا رقم.
 */
const KEEP = new Set([
  "رقم", "اللوحة", "اللوحه", "لوحة", "لوحه", "المركبة", "المركبه", "الأصل", "األصل", "الاصل", "نوع", "لون", "سنة", "الصنع",
  "المصنع", "الهيكل", "الشاصي", "الشاسيه", "التسجيل", "حالة", "العقد", "الاسم", "االسم", "تاريخ", "الشهادة", "الوثيقة", "السند",
  "Plate", "PLATE", "plate", "No", "No.", "NO", "Number", "VIN", "Chassis", "CHASSIS", "Registration", "Vehicle", "VEHICLE",
]);

/** سطر واحد: كلمات العناوين زي ما هي، والباقي حروف/أرقام مستخبية. */
export function maskCertLine(line: string): string {
  return line
    .split(/(\s+)/)
    .map((tok) => (KEEP.has(tok.replace(/[:：.,]+$/g, "")) ? tok : tok
      .replace(/[ء-ي]/g, "ع")
      .replace(/[A-Za-z]/g, "L")
      .replace(/[0-9٠-٩]/g, "9")))
    .join("");
}

/** أول `max` سطر من النص بعد الإخفاء. */
export function certTextShape(text: string, max = 60): string[] {
  return text.split("\n").map((l) => l.trim()).filter(Boolean).slice(0, max).map(maskCertLine);
}
