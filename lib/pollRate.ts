/**
 * معدّلات التكرار اللي بتضرب الداتابيز — في مكان واحد ومقيسة باختبار.
 *
 * ليه الملف ده موجود: يوم ٢٠٢٦-٠٩-٠٦ الداتابيز وقعت (Unhealthy) من حلقة تكرار
 * كانت بتكتب كل ثانيتين لكل مندوب بيسوق. البق ده عاش شهور لأن اختباره كان بيقيس
 * **قرار واحد معزول** («المفروض يبعت دلوقتي؟») والمشكلة مكانتش بتبان إلا في
 * **المعدّل التراكمي** (كام طلب في اليوم). فأي تكرار جديد يتحط هنا وينقاس بحمله.
 */

/**
 * كل قد إيه بانر رسالة الأدمن وبانر الاستطلاع بيسألوا الداتابيز.
 *
 * كان **دقيقة** = ٢ بانر × ٦٠ × ٢٥ مندوب × ١٠ ساعات = ٣٠ ألف طلب/يوم، وده كان
 * تاني أكبر مصدر حمل بعد تحديث الموقع. بقى **٥ دقايق** = ٦ آلاف (-٨٠٪).
 *
 * ومحصلش تأخير حقيقي في وصول الرسايل: البانرين الاتنين بيسألوا الداتابيز **فوراً**
 * أول ما المندوب يرجع للتطبيق من الخلفية (`visibilitychange`). فالتأخير بيحصل بس
 * لو التطبيق مفتوح قدامه وسايبه — ووقتها هو شايف الشاشة أصلاً.
 */
export const BANNER_POLL_MS = 300_000;

/**
 * كام طلب في اليوم بتولّدهم حلقة تكرار واحدة عبر كل المناديب.
 * `pollsPerTick` = عدد الاستعلامات في النبضة الواحدة (بانرين = ٢).
 */
export function dailyPollRequests(
  pollMs: number,
  agents: number,
  hoursOpen: number,
  pollsPerTick = 1,
): number {
  if (pollMs <= 0 || agents <= 0 || hoursOpen <= 0 || pollsPerTick <= 0) return 0;
  const ticksPerHour = 3_600_000 / pollMs;
  return Math.round(ticksPerHour * hoursOpen * agents * pollsPerTick);
}
