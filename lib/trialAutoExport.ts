/**
 * التصدير التلقائي في صفحة Voice PRO — **مفتوح افتراضياً** وبيتحفظ.
 *
 * كان `useState(false)` وخلاص: مقفول افتراضياً و**مش متخزّن أصلاً**، يعني حتى
 * اللي فعّله بيلاقيه مقفول تاني أول ما يفتح الصفحة. فعملياً كان مقفول عند الكل.
 *
 * ونتيجته ظهرت يوم ١٢ أكتوبر ٢٠٢٦: مندوب قفل التسجيل من غير تصدير، راح لصفحة
 * الفرز ورجع، فملقاش لوحاته — وضاعت بالكامل (مفيش نسخة على الجهاز ولا على
 * السيرفر ولا في الصوت الخام، لأن سيرفر أكتوبر مش بيحفظ المقاطع).
 *
 * الافتراضي بقى **مفتوح**: المندوب اللي مش عارف الخاصية موجودة أصلاً يبقى
 * محمي، واللي مش عايزها يقفلها مرة واحدة وتفضل مقفولة.
 *
 * مفتاحه **منفصل** عن تصدير صفحة التشييك — الصفحتان مستقلتان وللمندوب الحق
 * يظبّط كل واحدة لوحدها.
 */
export const TRIAL_AUTO_EXPORT_KEY = "rv2:autoExport";

export function loadTrialAutoExport(): boolean {
  try {
    // "0" وحدها = المندوب قفلها بإيده. أي حاجة تانية (مافيش قيمة، أو قيمة
    // بايظة) = الافتراضي المفتوح — الحماية مابتتشالش بالصدفة.
    return localStorage.getItem(TRIAL_AUTO_EXPORT_KEY) !== "0";
  } catch { return true; }
}

export function saveTrialAutoExport(on: boolean): void {
  try { localStorage.setItem(TRIAL_AUTO_EXPORT_KEY, on ? "1" : "0"); } catch { /* التخزين مقفول */ }
}
