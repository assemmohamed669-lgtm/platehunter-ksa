/**
 * حدّ الاحتياطي: امتى ينفع نقرا ملف داتا **كامل في الذاكرة**.
 *
 * السياق: `importLargeDataFile` بيقرا الداتا على دفعات (آمن للذاكرة). لو
 * القراءة دي فشلت **قبل أول صف** (صيغة مش xlsx من جوّه، أو أول ورقة فاضية)،
 * فيه احتياطي بيقرا الملف كامل بـSheetJS عشان المندوب مايتوقفش.
 *
 * المشكلة: الاحتياطي ده على آيفون بملف كبير **بيقتل الصفحة** — المندوب بيشوف
 * «حدثت مشكلة بشكل متكرر» عند صفر بالمية. سفاري بيدّي التبويب سقف ذاكرة صارم،
 * والقراءة الكاملة لملف ٣٥ ميجا بتحجز مئات الميجابايتات دفعة واحدة.
 *
 * فبدل ما ننقذ المندوب، الاحتياطي بيبقى هو سبب العطل. فوق الحدّ ده بنرفض
 * برسالة واضحة بدل ما نجرّب ونقتل الصفحة.
 *
 * الرقم محافظ عن قصد: مندوب آيفون عدّى ملف ١٣ ميجا، بس **مانعرفش** لو عدّى من
 * التدفّق ولا من الاحتياطي — فمابنيناش الحدّ على رقم مش متأكدين منه.
 * لو اتأكد لاحقاً إن الاحتياطي نفسه بيعدّي أكبر من كده، ارفع الرقم.
 */
export const FULL_PARSE_FALLBACK_MAX_BYTES = 8 * 1024 * 1024; // ٨ ميجا

/** هل ينفع نجرّب القراءة الكاملة للملف ده؟ */
export function canFullParseFallback(fileSizeBytes: number): boolean {
  // حجم غير معروف (صفر/NaN) → نسمح: مانمنعش المندوب بناءً على معلومة ناقصة.
  if (!Number.isFinite(fileSizeBytes) || fileSizeBytes <= 0) return true;
  return fileSizeBytes <= FULL_PARSE_FALLBACK_MAX_BYTES;
}

/** رسالة للمندوب لما الملف كبير ومش قابل للقراءة على دفعات. */
export function largeFileFallbackMessage(fileSizeBytes: number): string {
  const mb = Math.round(fileSizeBytes / (1024 * 1024));
  return (
    `الملف (${mb} ميجا) مش بصيغة xlsx اللي البرنامج بيقراها على دفعات، ` +
    `وحجمه أكبر من إن يتقرا كامل على التليفون. ` +
    `افتحه على الكمبيوتر واحفظه باسم جديد بصيغة xlsx، وبعدين ارفعه.`
  );
}
