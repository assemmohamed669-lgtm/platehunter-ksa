/**
 * ══════════════════════════════════════════════════════════════════════
 *  «ظهرت بعد» — من آخر كلام المندوب، مش من نص النافذة
 * ══════════════════════════════════════════════════════════════════════
 *
 * المالك (٢٣ سبتمبر ٢٠٢٦): «ظهرت بعد مكتوب فيها ٣ ثواني ونص و٢ ونص و٣،
 * ده كتير جداً — مينفعش نخليها بعد ثانية؟»
 *
 * 🔴 **الرقم القديم كان بيكدب — بيزوّد ٢.٥ث مالهاش علاقة بالسرعة.**
 * كان `now - tMs`، و`tMs` = **نص النافذة** (`(from+to)/2` على نافذة ٥ث)،
 * يعني ٢.٥ث قبل آخرها. فلو السيرفر رد في صفر ثانية، الرقم = ٢.٥ث.
 * من تقرير المالك: الرحلة ٠.٥٧ث ⇒ 2.5 + 0.57 = **3.07ث** — بالظبط اللي شافه.
 *
 * وكمان كان بيقارن ساعتين مختلفتين: `Date.now() - startedAt` (من **الضغطة**)
 * ناقص `tMs` (من **فتح المايك**) ⇒ زمن فتح المايك كان بيتضاف عليه كمان.
 *
 * ⇒ الرقم الجديد = **من ما المندوب سكت لحد ما اللوحة ظهرت**، بساعة واحدة
 *   (ساعة الصوت نفسها). وده اللي المندوب بيحسّه فعلاً.
 */

/** نص نافذة الـ٥ث — `tMs` مركزها، فآخرها = `tMs + ٢٥٠٠`. */
export const HALF_WINDOW_MS = 2500;

export interface LatencyInput {
  /** ساعة الصوت دلوقتي (مللي من فتح المايك) — نفس ساعة `tMs`. */
  nowMs: number;
  /** مركز النافذة اللي طلّعت اللوحة. */
  tMs: number;
  /** آخر لحظة الكاشف سمع فيها صوت، أو `null`. */
  lastVoiceEndMs: number | null;
}

/**
 * التأخير من آخر كلام المندوب.
 *
 * ⚠️ **الحد العلوي = نهاية النافذة**: لو المندوب كمّل كلام (قال اللوحة اللي
 * بعدها)، آخر صوت بيبقى **بعد** اللوحة دي — فمن غير الحد الرقم كان هيطلع
 * صغير غلط. واللوحة أكيد خلصت قبل نهاية نافذتها (النافذة لازم تحتويها كلها).
 * في الحالة دي الرقم **حد أدنى** — بيقول الشبكة والموديل بس.
 */
export function speechEndLatencyMs(i: LatencyInput): number {
  const windowEnd = i.tMs + HALF_WINDOW_MS;
  const end = i.lastVoiceEndMs == null || !Number.isFinite(i.lastVoiceEndMs)
    ? windowEnd
    : Math.min(i.lastVoiceEndMs, windowEnd);
  return Math.max(0, Math.round(i.nowMs - end));
}
