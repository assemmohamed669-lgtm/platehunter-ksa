/**
 * ══════════════════════════════════════════════════════════════════════
 *  🔄 شهايد «توثيق» اللي ترتيب كلماتها مقلوب
 * ══════════════════════════════════════════════════════════════════════
 *
 * المالك (١٤ أكتوبر ٢٠٢٦) بعت ٥ شهايد «توثيق» عربيها **سليم ومقروء**، ومع ذلك
 * البرنامج طلّع المصنع والنوع واللون والسنة والمؤجر **فاضيين**.
 *
 * السبب: بعض شهايد «توثيق» بتطلع من الملف **بترتيب كلمات مقلوب**:
 *
 *     الراجحي مصرف :االسم        بدل        االسم: مصرف الراجحي
 *
 * فالبرنامج بيدوّر على «الخانة: القيمة» ومايلاقيش حاجة.
 *
 * هنا بنقلب السطر لشكله الصح **قبل** القراية. والشهايد اللي ترتيبها سليم أصلاً
 * مابتتلمسش — الشرط إن اللي **بعد** النقطتين يكون عنوان معروف.
 */

/** عناوين شهادة «توثيق» اللي بنعرفها (من غير مسافات — المقارنة بتتجاهلها). */
const LABELS = [
  "الاسم", "االسم", "رقمالتواصل", "رقمالهوية", "نوعالهوية", "الجنسية", "مصدرها",
  "المدينة", "العنوانالوطني", "رقمالترخيص", "رقمالسجلالتجاري", "الرقمالوطنيالموحد",
  "تاريخالميالد", "تاريخالميلاد", "تاريخانتهاءالهوية", "مكانالوفاء", "مكانالتحرير",
  "حالةالعقد", "رقمالعقد", "تاريخانتهاءالعقد", "سبب التنفيذ", "سببالتنفيذ",
  "الدفعاتالحالة", "المبلغالمستحق", "نوعمستنداثباتالملكية", "سنةالصنع", "المصنع",
  "نوعاألصل", "نوعالأصل", "رقماللوحة", "لوناألصل", "لونالأصل", "رقمالهيكل",
  "الرقمالتسلسلي", "بلدالمنشأ", "التامين", "التأمين", "رقمالسند", "رقمالعقدالمسجل",
  "تاريختسجيلاألصل", "تاريختسجيلالأصل", "رقماألصلالمسجل", "رقمالأصلالمسجل",
];
const LABEL_SET = new Set(LABELS);

const squeeze = (s: string) => s.replace(/\s+/g, "");

/**
 * السطر مقلوب؟ يعني شكله «القيمة :العنوان» — النقطتين في النص واللي بعدهم عنوان.
 * بنرجّع العنوان (بترتيب كلماته الصح) والقيمة، أو `null` لو السطر مش كده.
 */
export function splitReversedLabelLine(line: string): { label: string; value: string } | null {
  const at = line.lastIndexOf(":");
  if (at < 0) return null;
  const before = line.slice(0, at).trim();
  const after = line.slice(at + 1).trim();
  if (!before || !after) return null;
  // الجزء اللي بعد النقطتين هو العنوان — وكلماته مقلوبة هي كمان
  const label = after.split(/\s+/).reverse().join(" ");
  if (!LABEL_SET.has(squeeze(label))) return null;
  return { label, value: before.split(/\s+/).reverse().join(" ") };
}

/** فيه سطور مقلوبة كفاية عشان نعتبر الملف كله مقلوب؟ */
export function looksReversed(text: string): boolean {
  let hits = 0;
  for (const line of text.split("\n")) if (splitReversedLabelLine(line)) hits++;
  return hits >= 3;
}

/**
 * بيرجّع النص بشكل «العنوان: القيمة». لو الملف مش مقلوب بيرجّعه **زي ما هو**.
 *
 * السطور اللي مش «قيمة :عنوان» (الكلام الثابت، اللوحة…) بتفضل زي ما هي —
 * عشان مانخربش حاجة شغّالة (اللوحة بتتقرا صح من النص الأصلي).
 */
export function normalizeReversedLabels(text: string): string {
  if (!looksReversed(text)) return text;
  return text.split("\n").map((line) => {
    const p = splitReversedLabelLine(line);
    return p ? `${p.label}: ${p.value}` : line;
  }).join("\n");
}
