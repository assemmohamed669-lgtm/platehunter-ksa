/**
 * pendingWindow — نافذة الصوت اللي اتأجّلت لأن الخط كان مزنوق.
 *
 * **المشكلة:** المحرك بيبعت نافذة ٥ث كل ١.٥ث، وبحد أقصى نافذتين طايرين. لما
 * الاتنين مشغولين كانت النبضة بتعمل `return` وخلاص — بلا طابور ولا إعادة
 * محاولة. ولما الرد من السيرفر بياخد أكتر من ٣ ثواني (= نافذتين × ١.٥ث) الخط
 * بيفضل مزنوق والنبضات بتتلغي ورا بعض، فآخر لوحة في السلسلة ممكن ماتدخلش أي
 * نافذة اتبعتت أصلاً — لا صفّارة ولا صف ولا أي أثر.
 *
 * **ليه نافذة واحدة بس مستنية (الأحدث):** النوافذ متداخلة بشدة (٥ث كل ١.٥ث)،
 * فالقديمة تقريباً كلها جوّه الأحدث. وطابور طويل معناه نتيجة بتوصل بعد ما
 * المندوب مشي من عند العربية — ودي أسوأ من إنها ماتوصلش.
 *
 * ⚠️ **مافيش أي تغيير في الصوت** اللي بيوصل للموديل: نفس المدى، نفس الطول،
 * نفس المعدّل. بنخزّن **المدى** مش البايتات، والصوت محفوظ في الجلسة فقصّ نفس
 * المدى بعد ثانية بيجيب نفس البايتات بالظبط.
 */

export interface WindowRange {
  /** بداية المدى في تسجيل الجلسة (ثواني). */
  start: number;
  /** نهايته (ثواني). */
  end: number;
}

export class PendingWindow {
  private w: WindowRange | null = null;

  /** يحط نافذة مستنية — الأحدث بتغلب على اللي قبلها. */
  set(range: WindowRange): void {
    this.w = range;
  }

  /** ياخد النافذة المستنية ويفضّيها. `null` لو مافيش. */
  take(): WindowRange | null {
    const out = this.w;
    this.w = null;
    return out;
  }

  get has(): boolean {
    return this.w !== null;
  }

  clear(): void {
    this.w = null;
  }
}
