/**
 * ══════════════════════════════════════════════════════════════════════
 *  🚚 أسطول الأرقام المتسلسلة — «حبل1234 حبل1235 حبل1236»
 * ══════════════════════════════════════════════════════════════════════
 *
 * المالك (٢٤ سبتمبر ٢٠٢٦): «لما بيبقى فيه أسطول سيارات لشركة أرقامها متسلسلة…
 * لما بيقول السيارات بالتسلسل ده مش بيظهروا، بيعدّل على السيارة اللي قالها
 * ومش بيكتب التسلسل».
 *
 * السبب: طبقتين بيلمّوا «نفس الحروف + فرق خانة» على إنها **نفس العربية
 * اتقرت غلط** — الإجماع (`digitDist ≤ 1`) ولمّ الصفوف (`sameCarTwin`، ≤ خانتين
 * في ١٢ث). وده صح لأغلاط السمع (`دطس2112`/`دطس2177`)، بس الأسطول شكله نفس
 * الشكل بالظبط.
 *
 * ── إمتى لوحتين يتثبتوا عربيتين (`proves`) ─────────────────────────────
 * متسلسلين (نفس الحروف · فرق الرقم ≤ ١٠) + **كل واحدة اتقرت في نافذتين+ بنفس
 * الإملاء** + قراياتهم **مش متداخلة** (النوافذ اللي سمعت الاتنين بتتشال من
 * الحساب) + واحد من دول:
 *   · **نافذة سمعت الاتنين مع بعض** (أي فرق ≤ ١٠)
 *   · **الفرق ١** وقراياتهم ورا بعض — حتى متلاصقين (إيقاع المالك العادي:
 *     ٤٤٪ من لوحاته المتتالية بتيجي كده)
 *   · **الفرق ٢** وبينهم **فاصل** (نافذة ماقرتش ولا واحدة ⇒ ≥ `FLEET_GAP_MS`)
 * ويتحسب على **المرور الحالي بس** (القرايات اللي بينها أقل من ١٢ث) — عشان
 * مرور تاني على نفس الأسطول بعد دقايق مايتبوّظش بالأول.
 *
 *   الأسطول:   ٢١٠٢ ٢١٠٢ ‖ ٢١٠٣ ٢١٠٣ ‖ ٢١٠٤ ٢١٠٤   (ورا بعض)
 *   غلط سمع ①: ٦٧٨٩ ٦٧٨٧ ٦٧٨٧ ٦٧٨٩ ٦٧٨٩             (الغلط **وسط** الصح — سطل6789)
 *   غلط سمع ②: ٧٢٢٩ ٧٢٢٩ ٧٢٢٠                       (الصح اتقرا **مرة** — حنل7220)
 *   غلط سمع ③: لوحة مقطوعة على حرف النافذة            (اتقرت **مرة**)
 *   غلط سمع ④: ٦٧٨٧ ٦٧٨٧ ٦٧٨٩ ٦٧٨٩ **متلاصقين**      (نطقة واحدة في ٤ نوافذ، فرق ٢
 *              — نفس سطل6789 بقراية «سحر» ⇒ الفرق ٢ محتاج فاصل)
 *   غلط سمع ⑤: المندوب **بيعيد** عربية اتقرت غلط كلها (رطه8654 ⇐ رطه8645 فرق ٩)
 *              ⇒ السكتة لوحدها دليل للفرق ١–٢ بس
 *
 * ── عضوية مش أزواج، وثابتة ───────────────────────────────────────────
 * اللوحة اللي اتثبتت مع جارة **بقت عربية** (`members`)، وأي عربيتين بنفس
 * الحروف ومتسلسلين = مختلفين. من غير ده: في ٣ عربيات بإيقاع عادي ٢١٠٢ و٢١٠٤
 * عمرهم مابيتسمعوا مع بعض ⇒ ٢١٠٢ كانت بتتعدّل لـ٢١٠٤ (مراجعة الخصم، ٢٤ سبتمبر).
 * والعضوية **مابتتشالش**: المندوب لما يرجع يقول ٢١٠٢ تاني بعد ٢١٠٣ القرايات
 * بقت «متداخلة» — لو الدليل بيتحسب من الأول، الصف الصح كان بيتعدّل تاني.
 *
 * ── القياس ────────────────────────────────────────────────────────────
 * نفس خط الصفحة بالحرف (`__tests__/jadeedReplay.eval.test.ts`) على ٥ مجاري
 * قرايات حقيقية (٣ موديلات على ٧٦ تسجيل مناديب + ماليزيا + المالك). الأرقام
 * في وصف الـPR.
 *
 * ⚠️ اللي **مش متغطّي** عن قصد: عربية اتقرت في **نافذة واحدة** بس، وفرق ٢+
 * متلاصقين من غير نافذة مشتركة — شكلهم نفس غلط السمع بالظبط.
 * ⚠️ ومقبول عن علم (تمن الثبات): لو نافذة واحدة سمعت **نفس العربية مرتين**
 * برقم قريب، أو نافذة متأخّرة جت بعد ما اتثبتت، الإثبات مابيترجعش. صفر مرة
 * في ~١٩ ألف نافذة حقيقية (مراجعة الخصم، ٢٤ سبتمبر).
 *
 * ── التاريخ ─────────────────────────────────────────────────────────
 * #315: «نافذة واحدة سمعت الاتنين» بس. تجربة المالك كذّبتها (٢٤ سبتمبر): «قلت
 * دبر2102 و2103 و2104 ماكتبش غير 2104 — كان بيعدّل على آخر لوحة». قالهم بسكتة
 * بين كل عربية فمفيش نافذة سمعت اتنين.
 */

const WELL = /^[ء-ي]{3}\d{4}$/;

/** أقصى فرق في الرقم عشان نعتبرهم أسطول متسلسل (١٢٣٩ ⇐ ١٢٤٠ فرقها ١). */
export const FLEET_MAX_STEP = 10;

/** نفس الحروف + رقمين قريبين (≤ ١٠) + مش نفس اللوحة. */
export function isFleetPair(a: string, b: string): boolean {
  const pa = String(a ?? ""), pb = String(b ?? "");
  if (!WELL.test(pa) || !WELL.test(pb) || pa === pb) return false;
  if (pa.slice(0, 3) !== pb.slice(0, 3)) return false;
  return Math.abs(Number(pa.slice(3)) - Number(pb.slice(3))) <= FLEET_MAX_STEP;
}

/** نافذتين بنفس الإملاء على الأقل — القراية الواحدة ممكن تكون مقطوعة أو غلط. */
export const FLEET_MIN_WINDOWS = 2;

/**
 * الفرق ٢ من غير نافذة مشتركة ⇒ لازم **فاصل**: نافذة واحدة بينهم ماقرتش ولا
 * واحدة (٣ث على شبكة الـ١.٥ث). النطقة الواحدة قراياتها متلاصقة (١.٥ث).
 */
export const FLEET_GAP_MS = 2250;

/**
 * الفرق ١ من غير نافذة مشتركة ⇒ **متلاصقين كفاية** (نافذة ورا نافذة على شبكة
 * الـ١.٥ث، ناقص هامش لرعشة التوقيت). مقيس: صفر غلط سمع بفرق ١ في نافذتين+
 * جنب اللوحة الصح في ٥ مجاري قرايات.
 */
export const FLEET_ADJ_GAP_MS = 1400;

/** من غير نافذة مشتركة، أقصى فرق يتصدّق — أكبر من كده = غالباً المندوب بيعيد عربية اتقرت غلط. */
export const FLEET_GAP_MAX_STEP = 2;

/** قرايات بينها أكتر من كده = مرور تاني (نفس نافذة لمّ الصفوف). */
export const FLEET_PASS_GAP_MS = 12000;

/** نوافذ الإملاءين في **المرور الأخير** بس (القرايات اللي بينها ≤ ١٢ث). */
function lastPass(ta: number[], tb: number[]): [number[], number[]] {
  const all = [...ta, ...tb].sort((x, y) => x - y);
  let from = all[0];
  for (let i = 1; i < all.length; i++) if (all[i] - all[i - 1] > FLEET_PASS_GAP_MS) from = all[i];
  return [ta.filter((t) => t >= from), tb.filter((t) => t >= from)];
}

/**
 * نوافذ كل إملاء في الجلسة (بزمن النطق — `tMs` مركز النافذة) + **العربيات
 * اللي اتثبتت** (`members`). نفس النافذة لو اتبعتت تاني (استرجاع بعد وقعة
 * الشبكة) **مش** نافذة تانية: نفس الصوت.
 */
export class FleetMemory {
  private windows = new Map<string, number[]>();
  private members = new Set<string>();

  /** كل اللوحات اللي نافذة واحدة (زمنها `tMs`) سمعتها. */
  note(plates: readonly string[], tMs: number): void {
    if (!Number.isFinite(tMs)) return;
    const ps = [...new Set((plates ?? []).map((p) => String(p ?? "").replace(/\s+/g, "")).filter((p) => WELL.test(p)))];
    for (const p of ps) {
      const ws = this.windows.get(p) ?? [];
      if (!ws.includes(tMs)) ws.push(tMs);
      this.windows.set(p, ws);
    }
    // الدليل بيتغيّر بس للإملاءات اللي النافذة دي سمعتها
    for (const p of ps) {
      for (const q of this.windows.keys()) {
        if (q === p || (this.members.has(p) && this.members.has(q))) continue;
        if (this.proves(p, q)) {
          this.members.add(p);
          this.members.add(q);
        }
      }
    }
  }

  /** كام نافذة مختلفة سمعت الإملاء ده. */
  count(p: string): number {
    return this.windows.get(String(p ?? ""))?.length ?? 0;
  }

  /** اللوحة دي اتثبتت إنها عربية في أسطول؟ */
  isMember(p: string): boolean {
    return this.members.has(String(p ?? ""));
  }

  /** عربيتين مختلفتين أكيد؟ — متسلسلين والاتنين عربيات مثبتة. */
  distinct(a: string, b: string): boolean {
    const pa = String(a ?? ""), pb = String(b ?? "");
    return isFleetPair(pa, pb) && this.members.has(pa) && this.members.has(pb);
  }

  /** الشروط في أول الملف. */
  private proves(pa: string, pb: string): boolean {
    if (!isFleetPair(pa, pb)) return false;
    const [ta, tb] = lastPass(this.windows.get(pa) ?? [], this.windows.get(pb) ?? []);
    if (ta.length < FLEET_MIN_WINDOWS || tb.length < FLEET_MIN_WINDOWS) return false;
    const sa = ta.filter((t) => !tb.includes(t));
    const sb = tb.filter((t) => !ta.includes(t));
    // كل النوافذ مشتركة ⇒ اتسمعوا مع بعض بس ⇒ عربيتين
    if (!sa.length || !sb.length) return true;
    const aFirst = Math.max(...sa) < Math.min(...sb);
    const bFirst = Math.max(...sb) < Math.min(...sa);
    if (!aFirst && !bFirst) return false;          // متداخلين = نطقة واحدة
    if (sa.length < ta.length) return true;         // فيه نافذة سمعت الاتنين
    const step = Math.abs(Number(pa.slice(3)) - Number(pb.slice(3)));
    if (step > FLEET_GAP_MAX_STEP) return false;
    const gap = aFirst ? Math.min(...sb) - Math.max(...sa) : Math.min(...sa) - Math.max(...sb);
    return gap >= (step === 1 ? FLEET_ADJ_GAP_MS : FLEET_GAP_MS);
  }

  reset(): void {
    this.windows.clear();
    this.members.clear();
  }
}
