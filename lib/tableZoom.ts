/**
 * ══════════════════════════════════════════════════════════════════════
 *  ⑫ زوم جدول اللوحات — يكبّر من غير ما ياكل عمود
 * ══════════════════════════════════════════════════════════════════════
 *
 * المالك (٢٣ سبتمبر ٢٠٢٦): «ضيفله زوم إن وزوم آوت علشان لو المندوب حب
 * يكبّر المربّع. المهم ميأثرش على مساحة الشاشة، وكل اللي في المربّع حتى لو
 * المندوب عمل زوم يقدر يشوفه زي دلوقتي وميتاكلش منه حاجة».
 *
 * 🔴 **«ميتاكلش منه حاجة» هو الشرط الصعب.** التكبير بـ`transform: scale`
 * بيكبّر المحتوى **من غير** ما يكبّر المساحة اللي بيتمرّر فيها، فآخر عمود
 * بيتقص ومافيش تمرير يوصّله. فالعرض الأدنى للجدول لازم **يتكبّر بنفس
 * النسبة**، وساعتها التمرير الأفقي بيوصل لآخره.
 *
 * و«ميأثرش على مساحة الشاشة» = الزوم جوّه **المربّع** بس، مش زوم الصفحة.
 */

export const ZOOM_MIN = 0.7;
export const ZOOM_MAX = 2.5;
export const ZOOM_STEP = 0.15;

/** يقيّد الزوم في حدوده، وأي قيمة غلط بترجع ١ (الوضع الطبيعي). */
export function clampZoom(z: number): number {
  if (typeof z !== "number" || !Number.isFinite(z)) return 1;
  return Math.min(ZOOM_MAX, Math.max(ZOOM_MIN, z));
}

/** خطوة واحدة بالزرّين ➖ ➕. */
export function stepZoom(z: number, dir: 1 | -1): number {
  return clampZoom(clampZoom(z) + dir * ZOOM_STEP);
}

/**
 * العرض الأدنى للجدول بعد الزوم.
 *
 * ⚠️ **مابنقللش تحت الأصلي عند التصغير**: التصغير بيخلّي كله باين أصلاً،
 * وتقليل العرض كمان بيلزّق الأعمدة في بعض بلا فايدة.
 */
export function zoomedMinWidth(baseWidthPx: number, z: number): number {
  return Math.round(baseWidthPx * Math.max(1, clampZoom(z)));
}
