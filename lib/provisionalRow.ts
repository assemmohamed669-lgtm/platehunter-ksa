/**
 * ══════════════════════════════════════════════════════════════════════
 *  «تظهر فوراً وتتأكّد بعدين» — سرعة بلا خسارة دقة
 * ══════════════════════════════════════════════════════════════════════
 *
 * بعد ما الإجماع بقى شغّال فعلاً (ساعة التصريف اتصلّحت) التأخير طلع من
 * **٤.١ث لـ٦.٨ث** — لأن اللوحة بقت تستنى نافذة تانية تأكّدها. وده تمن الدقة:
 * الحد الأدنى النظري لتأكيد بنافذتين ≈ ٥ ثواني.
 *
 * المالك طلب السرعة **بلا** خسارة دقة (٢٢ سبتمبر). الحل مش تقليل الانتظار —
 * الحل إن الصف يظهر من **القراءة الأولى** بعلامة 🟡 مبدئية، والإجماع لما ييجي
 * يأكّده 🟢 أو **يصحّحه**. المندوب بيشوف اللوحة في ~٣ث زي الأول، والدقة
 * النهائية زي ما هي.
 *
 * ── 🔴 الخطر الواضح ──────────────────────────────────────────────────
 * القراءة الخام فيها **الاختراع** كمان. فالمبدئي:
 *   · يتعرض للقراءات **عالية الثقة** بس (نفس بوابة الظهور المنفرد ٠.٩)
 *   · والمحجوب كاختراع **ماينفعش** مهما كانت ثقته
 *   · وأي مبدئي ماحدش أكّده خلال المهلة **يتشال** — كان اختراع
 */

/**
 * أقل ثقة للظهور المبدئي. **٠.٩** — نفس الحد المقيس في `liveConsensus`:
 * «اللوحات الحقيقية النافذة-الواحدة ثقتها ≥٠.٩، وكل ما ظهر تحت ٠.٦ كان
 * اختراع». بنمشي على ٠.٩ عشان المبدئي بيتعرض **قبل** أي تأكيد.
 */
export const PROVISIONAL_MIN_CONF = 0.9;

/**
 * لو ماحدش أكّد المبدئي خلال المدة دي **يتشال**.
 *
 * دورة التأكيد الكاملة ≈ ٧ث (نص نافذة + شبكة + استقرار). ١٢ث بتدي هامش
 * لتذبذب الشبكة وماتسيبش اختراع معروض دقيقة.
 */
export const PROVISIONAL_TTL_MS = 12_000;

export interface ReadGate {
  accepted: boolean;
  /** اتحجبت بحاجز الاختراع (أضعف توكن واطي) */
  blocked: boolean;
  conf: number;
}

/** القراءة دي تستاهل تظهر **فوراً** كصف مبدئي؟ */
export function showProvisional(r: ReadGate): boolean {
  if (!r || !r.accepted || r.blocked) return false;
  return Number.isFinite(r.conf) && r.conf >= PROVISIONAL_MIN_CONF;
}

export interface RowRank {
  provisional: boolean;
  /** عدد النوافذ اللي أكّدت (١ للمبدئي) */
  mult: number;
  conf: number;
  atMs: number;
}

/**
 * `a` يغلب `b`؟ **المؤكّد بيغلب المبدئي دايماً** — حتى لو ثقة المبدئي أعلى،
 * لأن الإجماع شاف نوافذ أكتر. وبين اتنين من نفس النوع: الأكتر نوافذ ← الأعلى
 * ثقة ← الأحدث.
 */
export function confirmedWins(a: RowRank, b: RowRank): boolean {
  if (a.provisional !== b.provisional) return !a.provisional;
  if (a.mult !== b.mult) return a.mult > b.mult;
  if (a.conf !== b.conf) return a.conf > b.conf;
  return a.atMs > b.atMs;
}
