const SINGLE_KEYS: string[] = (() => {
  const set = new Set<string>();
  for (const t of VEHICLE_TYPES) {
    if (t === "أخرى") continue;
    if (NO_FUZZY.has(glue(t))) continue;
    if (norm(t).split(" ").length === 1) set.add(glue(t));
  }
  for (const [v, canon] of Object.entries(VARIANTS)) {
    if (!(VEHICLE_TYPES as readonly string[]).includes(canon)) continue;
    /**
     * 🔴 **الحارس لازم يشمل النطقات كذلك — بق مسكه الاختبار.**
     * كان الفحص على أعضاء القائمة بس، فإضافة «جراش» (نطق لـ«جراج») لـ
     * `NO_FUZZY` مكانش ليها أي أثر: النطق بيدخل الفرق-حرف-واحد من الباب
     * التاني، و«جرار»/«جراح» رجعوا يطابقوا «جراج» عن طريقه.
     * (السيرفر كان بيفحص الحلقتين؛ العميل كان الناقص — تفكّك صامت.)
     */
    if (NO_FUZZY.has(glue(v))) continue;
    if (norm(v).split(" ").length === 1) set.add(glue(v));
  }
  return [...set].sort((a, b) => b.length - a.length || (a < b ? -1 : 1));
})();

/**
 * 🔴 **مفاتيح التقريب لكل عدد كلمات — مش الكلمة الواحدة بس.**
 *
 * `SINGLE_KEYS` فيه الأعضاء ذات الكلمة الواحدة فقط، والتقريب كان شغّال
 * عند `n === 1` بس. فالنتيجة إن أي عبارة مركّبة لازم تطابق **تمام**،
 * ولو الموديل مسخ كلمة واحدة فيها العبارة كلها بتسقط ويقع على أقصر
 * جزء منها. مقيس على مقعد المالك (٨٣ لوحة):
 *
 *   «جراش باترون»        ← جراج        (والصح: جراج بدروم)
 *   «جراش واحد يمين»     ← جراج        (والصح: جراج واحد يمين)
 *   «برح اول الشارع»     ← اول الشارع  (والصح: برحه اول الشارع يمين)
 *
 * سبع ملاحظات من ١٤ غلط كانت من العيب ده لوحده.
 *
 * ⚠️ والمفاتيح **مرتّبة بالأطول** عشان الأطول تكسب لما الاتنين يطابقوا.
 */
/**
 * ⛔ **«الكلمة المقطوعة عند حرف النافذة» اتشالت — القياس رفضها مرتين.**
 *
 * الفكرة كانت: لو آخر كلمة في المدى بداية **فريدة** لنوع، نعتبرها النوع
 * («… اربعة ون» ⇒ ونيت). والقياس الأول طلّع مكسبها **صفر صافي**: كسبت
 * واحدة عند أخو المالك وخسرت واحدة عنده.
 *
 * 🔴 وبعدين جلسة ٧٥ لوحة **بلا أي نوع** أثبتت إنها بتضرّ: اتنين من ٦
 *   أنواع مخترعة كانوا منها —
 *     «ح ر بي»  ⇒ «بي» بداية «بي ام»   ⇒ طلّعت «بي ام»
 *     «هاي س»   ⇒ «هاي» بداية «هاي اس» ⇒ طلّعت «هاي اس»
 *   والكلمتين دول **إملاء حروف اللوحة**، مش نوع مقطوع.
 *
 * ⇒ مكسب صفر + ضرر مقيس = تتشال. والكلمة المقطوعة الحقيقية («ون» ⇒
 *   ونيت) بتتمسك من **النافذة الاحتياطية الطويلة** في الصفحة، وهي
 *   مقيسة بمكسب حقيقي (أخوه: نوع ٦٠ ← ٨٠٪).
 */

const MULTI_KEYS: string[] = (() => {
  const set = new Set<string>();
  const add = (phrase: string) => {
    if (phrase === "أخرى") return;
    if (NO_FUZZY.has(glue(phrase))) return;
    if (norm(phrase).split(" ").length < 2) return;  // الواحدة لها مسارها
    set.add(glue(phrase));
  };
  for (const t of VEHICLE_TYPES) add(t);
  for (const [v, canon] of Object.entries(VARIANTS)) {
    if ((VEHICLE_TYPES as readonly string[]).includes(canon)) add(v);
  }
  for (const [form] of COUNT_FORMS) add(form);
  // 🔴 **بلا تقسيم بعدد الكلمات.** أول نسخة قسّمت المفاتيح بعدد كلماتها،
  //   فـ«بر ح يمين» (٣ كلمات في النص) ماقابلتش «برحه يمين» (٢ في القائمة)
  //   وهما نفس العبارة. اللزق بيلغي حدود الكلمات فالتقسيم كان بيمنع
  //   مطابقات صحيحة بلا فايدة.
  return [...set].sort((a, b) => b.length - a.length || (a < b ? -1 : 1));
})();

/**
 * 🔴 أسماء حروف الهجاء **مايطلّعوش نوع أبداً**.
 * إملاء اللوحة كله أسماء حروف، وأي مطابقة تقريبية على «باء» أو «هاء»
 * هي إملاء لوحة اتقرا نوع — وبيتكرر مع **كل لوحة** مش مرة واحدة.
 * (اسم الحرف «باء» كان بيطابق «دباب» ١٣٦ مرة في ١٠ تسجيلات.)
 */
const LETTER_NAMES = new Set(
  [
    "ألف", "الف", "باء", "تاء", "ثاء", "جيم", "حاء", "خاء", "دال", "ذال",
    "راء", "زاي", "زين", "سين", "شين", "صاد", "ضاد", "طاء", "ظاء", "عين",
    "غين", "فاء", "قاف", "كاف", "لام", "ميم", "نون", "هاء", "واو", "ياء",
    "همزة",
    /**
     * ⬇️ **نطقات قصيرة للحروف — من جلسة ٧٥ لوحة بلا أنواع.**
     * الموديل بيكتب اسم الحرف مقصوص وقت الإملاء السريع، والمقصوص ده
     * كان بيعدّي من تحت الحارس ويطابق نوع:
     *   «هاي س»  ⇒ هاي اس   ·  «ب لام»   ⇒ بي ام
     *   «را»     ⇒ راس شاحنه ·  «حاطط را» ⇒ راس شاحنه
     *
     * ⚠️ **وممنوع تحط كلمة بتبدأ بيها نوع حقيقي**: «هاي» (هاي اس) ·
     *   «بي» (بي ام) · «في» (فان) — إضافتهم كسرت الأنواع دي، وحارس
     *   `vehicleTypeScanFull` مسكها. القاعدة النسبية تحت بتمسك الحالة
     *   من غيرهم: «هاي س» فيها حرف مفرد واحد من كلمتين = ٥٠٪ ⇒ إملاء،
     *   و«هاي اس» مافيهاش حرف مفرد ⇒ نوع.
     */
    "را", "ها", "دي", "مي", "لا", "ني", "يا",
    "نور", "صوت", "كيف", "ايه", "اي",
    /**
     * ⬇️ **جولة تانية — جلسة ٨١ لوحة بلا أنواع (١٦ سبتمبر).**
     * «راس بي لم 2927 بي لم أ 9238» طلّعت «بي ام» للوحة `ربل2927`،
     * و«بي لم» إملاء حروف اللوحة اللي بعدها (بلا). الحارس بيعدّ الحروف
     * **المفردة**، ودول حرفين فعدّوا من تحته.
     * ⚠️ «لم» آمنة لأن مافيش نوع بيبدأ بيها — بخلاف «بي» (بي ام).
     */
    "لم", "لام", "سي", "تي", "جي", "كي", "في",
  ].map(glue)
);

/**
 * 🔴 **عبارة إملاء = أي عبارة أغلبها أسماء حروف.**
 *
 * `LETTER_NAMES` كان بيتفحص على **الكلمة الواحدة** بس (`n === 1`). ولما
 * وسّعنا التقريب للعبارات المركّبة، «هاي س» و«ب لام» (كلمتين) عدّوا من
 * تحته وطلّعوا «هاي اس» و«بي ام».
 *
 * مقيس على جلسة المالك (٧٥ لوحة · **ماقالش ولا نوع**): ٦ أنواع ظهرت من
 * العدم، كلها من إملاء حروف اللوحة. وده أخطر من نوع ناقص — نوع مخترع
 * بيتكتب في داتاه وهو ماقالوش أصلاً.
 */
function isSpelling(words: string[]): boolean {
  if (!words.length) return false;
  let letters = 0;
  /**
   * ⚠️ **الحرف الواحد بس، مش أي كلمة قصيرة.** أول نسخة عدّت أي كلمة
   *   ≤٢ حروف كإملاء، فـ«بر ح يمين» (نطق «برحه يمين») اتحسبت إملاء
   *   واترفضت. «بر» جزء من كلمة، مش اسم حرف.
   */
  for (const w of words) if (LETTER_NAMES.has(w) || w.length === 1) letters++;
  return letters * 2 >= words.length;   // نصّها أو أكتر إملاء
}

/**
 * مسافة تحرير ≤ `max`. `lev1` بترجّع ≤١ بس، والعبارات الطويلة بتتمسخ
 * في أكتر من موضع: «دافع رباع» مقابل «دفع رباعي» مسافتها ٢ — والاتنين
 * نفس الكلمة عند المندوب.
 *
 * ⚠️ مسموحة **للعبارات الطويلة بس** (شوف موضع النداء) — مسافة ٢ على
 *   كلمة قصيرة بتخلط أنواع ببعض.
 */
function levAtMost(a: string, b: string, max: number): boolean {
  if (Math.abs(a.length - b.length) > max) return false;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    let best = i;
    for (let j = 1; j <= b.length; j++) {
      const v = Math.min(
        prev[j] + 1,
        cur[j - 1] + 1,
        prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)
      );
      cur.push(v);
      if (v < best) best = v;
    }
    if (best > max) return false;
    prev = cur;
  }
  return prev[b.length] <= max;
}

function lev1(a: string, b: string): boolean {
  if (a === b) return true;
  let la = a.length;
  let lb = b.length;
  if (Math.abs(la - lb) > 1) return false;
  if (la === lb) {
    let d = 0;
    for (let i = 0; i < la; i++) if (a[i] !== b[i]) d++;
    return d === 1;
  }
  if (la > lb) {
    [a, b] = [b, a];
    [la, lb] = [lb, la];
  }
  let i = 0;
  let j = 0;
  let d = 0;
  while (i < la && j < lb) {
    if (a[i] === b[j]) {
      i++;
      j++;
    } else {
      d++;
      j++;
      if (d > 1) return false;
    }
  }
  return true;
}

/**
 * يرجّع عضو من القائمة المقفولة، وإلا null.
 *
 * 🔴 **الترتيب: المكان الأول، والطول جوّه المكان.**
 *
 * القاعدة اللي طلبها المالك (٨ سبتمبر): «كل لوحة تاخد النوع اللي بيتقال
 * وراها بعد آخر حرف». اللي بيحسم هو **موقع** الكلمة، مش طولها.
 *
 * النسخة اللي قبل كده كانت بتاخد **أطول عبارة في النافذة كلها**، وده
 * غلّط نوع حقيقي في جلسة المالك:
 *
 *     «سبعة **لوحة صفرا** رابع سين ستة ربعة تسعة سبعة **مصدومة**»
 *
 * نافذة النوع بتبدأ ثانيتين قبل مركز اللوحة، فأولها ذيل اللوحة اللي
 * قبلها ومعاه نوعها. «لوحه صفرا» (كلمتين) كسبت «مصدومه» (كلمة) —
 * فـربس٦٤٩٧ خدت نوع العربية اللي قبلها.
 *
 * فدلوقتي: بنمشي من الشمال لليمين، عند كل بداية بناخد **أطول** عبارة
 * تطابق (عشان «برحه يمين» ماتكسبش «برحه اخر الشارع يمين»)، و**آخر**
 * مطابقة هي اللي تكسب — لأن نوع اللوحة دي بيتقال بعدها، ونوع اللي
 * قبلها بيبقى في أول النافذة.
 */
interface ScanResult {
  /** آخر مطابقة مهما كان تصنيفها — السلوك القديم */
  last: string | null;
  /** آخر مطابقة **لكل تصنيف** على حدة */
  byCat: { type: string | null; condition: string | null; place: string | null };
}

/** ٠-٩ العربية → ASCII، عشان ندوّر على أرقام اللوحة في نص الشاهد */
const AR_DIGITS: Record<string, string> = {
  "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
  "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
};

/**
 * أرقام الكلمة: أرقام حرفية (عربية أو لاتينية)، وإلا **كلمة رقم مفردة**
 * («صفر» «اتنين» «سته»…) عبر `numberTokenValue` المختبَر.
 *
 * 🔴 كلمات الأرقام **إجبارية**: المالك بيتهجّى («د ر خ سته خمسه خمسه اربع»)
 * فمافيش أرقام في النص، والقيد كان بيبقى **معطّل** والزحلقة ترجع
 * (`درق6554` خدت «اتش١» بتاعة `حمس2635`، جلسة ١٠ سبتمبر ٢٠٢٦).
 */
function digitsOfWord(w: string): string {
  let out = "";
  for (const ch of w) {
    const d = ch >= "0" && ch <= "9" ? ch : AR_DIGITS[ch];
    if (d) out += d;
  }
  if (out) return out;
  const dual = dualDigits(w);
  if (dual) return dual;
  const hund = hundredDigits(w);
  if (hund) return hund;
  const t = numberTokenValue(w);
  if (!t) {
    /**
     * 🔴 **«ده لتمانية» — كوهير بيلزق اللام برقم اللوحة.**
     *
     * من جلسة المالك (١٨ سبتمبر ٢٠٢٦): `درد8260` اتسمعت «ده الراد ده
     * **لتمانية** تنين ستين». «لتمانية» مش في القاموس فالـ٨ **اتشالت
     * بالسكوت**، والتيار طلع `0231260` بدل `02318260`.
     *
     * والنتيجة مكانتش خانة فاضية وخلاص: شاهد الأرقام شاف `1260` جنب
     * لوحتنا `8260` (فرق خانة) فنزّل عليها **علامة كذّابة** — على لوحة
     * صح. نفس مبدأ لام العطف «وستين» اللي اتصلّحت في `arabicNumbers`.
     *
     * ⚠️ **الجذر لازم يبقى ٤ حروف+** عشان «لسته» و«لتره» مايتحوّلوش
     * أرقام — «لتمانية» و«لواحد» و«لتلاته» و«لستين» بيعدّوا.
     */
    const stem = w.startsWith("ل") ? w.slice(1) : "";
    if (stem.length >= 4) {
      const lt = numberTokenValue(stem);
      if (lt && !lt.isScale) {
        if (lt.isUnit) return String(lt.value);
        if (lt.value >= 10 && lt.value <= 99) return String(lt.value);
      }
    }
    return "";
  }
  if (t.isUnit) return String(t.value);
  /**
   * 🔴 **العشرات خانتين، مش صفر خانات** (جلسة شيت الأنواع، ١٦ سبتمبر ٢٠٢٦).
   *
   * الشرط القديم كان `t.isUnit` بس — فـ«ستين» و«اربعين» و«حداشر» كانوا
   * **بيتشالوا بالسكوت** من تيار الأرقام. والمندوب بينطق الخانتين
   * الأخيرتين كده طول الوقت:
   *
   *     «تمانية اتنين **ستين**»   ⇒ درد8260
   *     «زيرو تمانية **حداشر**»  ⇒ عور0811
   *
   * فأرقام اللوحة مكانتش بتتلاقي في نص الشاهد، والقصّ يفشل، والخانة
   * ترجع فاضية (fail-closed) — **رغم إن الموديل سامع النوع صح**.
   * ده كان سبب ١٥ من ٢٤ فشل في جلسة الـ٨٦ لوحة.
   *
   * القيمة ١٠-٩٩ بس: الميّة والألف (`isScale`) مش خانات لوحة.
   */
  if (!t.isScale && t.value >= 10 && t.value <= 99) return String(t.value);
  return "";
}

/**
 * 🔴 **المثنى: «خمسيتين» = ٥٥ مش لا حاجة.**
 *
 * لما خانتين متتاليتين يبقوا نفس الرقم، المندوب بينطقهم مثنى —
 * «سبعتين» «تسعتين» «خمسيتين» «تمانيتين» — ومفيش أي واحدة منهم في
 * قاموس الأرقام، فكانوا بيتشالوا بالكامل.
 *
 * ⚠️ **و«اتنين» و«ستين» و«تلاتين» بينتهوا بـ«تين» كمان** — فالجذر لازم
 * يكون رقم آحاد بنفسه عشان نقبلها: «س» و«تلا» مش أرقام فبتعدّي للمنطق
 * العادي (٢ و٦٠ و٣٠ صح).
 */
/**
 * 🔴 **مثنى وجمع شاذّين — من قايمة المالك (٢٠ سبتمبر ٢٠٢٦).**
 *
 * القاعدة العامة تحت بتشتغل على «سبعتين»/«تمانيتين» لأن جذرها رقم. لكن:
 *   · «صفرين» بتنتهي بـ«رين» مش «تين»
 *   · «تصفار»/«أصفار» جمع شاذّ للصفر (مش على وزن «ـات»)
 *   · «وحايد» جمع شاذّ للواحد
 *   · «تمنيتين» جذرها «تمن» — وهي كلمة عربية عادية، فمانضفهاش للقاموس
 *     العام ونتعامل معاها هنا بالاسم.
 *
 * خرايط صريحة بدل توسيع قاموس الأرقام — عشان مانفتحش باب تطابقات كاذبة.
 */
const IRREGULAR_DUAL: Record<string, string> = {
  صفرين: "00",
  "صفرتين": "00",
  تمنيتين: "88",
  تمنتين: "88",
};

/** جمع شاذّ ⇒ الخانة المتكرّرة (العدّاد قبلها بيحدّد التكرار) */
const IRREGULAR_PLURAL: Record<string, string> = {
  تصفار: "0",
  اصفار: "0",
  أصفار: "0",
  وحايد: "1",
  واحدات: "1",
};

/**
 * 🔴 **المئات: «تسعميه» = ٩٠٠ — كلمة واحدة.**
 *
 * من قايمة المالك: «تسعميه واحد» ⇒ 9001 · «صفر خمسميه» ⇒ 0500 ·
 * «تسعه اربعميه» ⇒ 9400. الكلمة ملزوقة فالقاموس مابيشوفهاش خالص.
 */
const HUNDRED_SUFFIX = ["ميه", "مية", "مئة", "مائة", "ميّة"];
/**
 * منقولة **حرفياً** من `serving/cohere_fields.py` — مصدر واحد.
 * الصيغ الشاذّة («تلتميه» ٣٠٠ · «ربعميه» ٤٠٠ · «ميتين» ٢٠٠) جذرها مش
 * رقم آحاد، فقاعدة اللاحقة تحت مابتشوفهاش.
 */
const HUNDREDS: Record<string, string> = {
  ميه: "100",
  مية: "100",
  مئه: "100",
  ميت: "100",
  ميتين: "200",
  متين: "200",
  ميتان: "200",
  تلتميه: "300",
  تلطميه: "300",
  تلتمية: "300",
  ثلثمائه: "300",
  ربعميه: "400",
  اربعميه: "400",
  ربعمية: "400",
  خمسميه: "500",
  خمسمية: "500",
  ستميه: "600",
  ستمية: "600",
  سبعميه: "700",
  سبعمية: "700",
  تمنميه: "800",
  تمانميه: "800",
  تمنمية: "800",
  تسعميه: "900",
  تسعمية: "900",
  تسعمئه: "900",
};
function hundredDigits(w: string): string {
  const exact = HUNDREDS[w];
  if (exact) return exact;
  for (const suf of HUNDRED_SUFFIX) {
    if (!w.endsWith(suf) || w.length <= suf.length) continue;
    const stem = w.slice(0, w.length - suf.length);
    const t = numberTokenValue(stem);
    if (t && t.isUnit && t.value >= 1 && t.value <= 9) return `${t.value}00`;
  }
  return "";
}

function dualDigits(w: string): string {
  const irr = IRREGULAR_DUAL[w];
  if (irr) return irr;
  if (!w.endsWith("تين")) return "";
  for (const cut of [3, 4]) {
    const stem = w.slice(0, w.length - cut);
    if (stem.length < 2) continue;
    const t = numberTokenValue(stem);
    if (t && t.isUnit) return String(t.value).repeat(2);
  }
  return "";
}

/**
 * 🔴 **الجمع بعدّاد: «تلات سبعات» = ٧٧٧.**
 *
 * شكوى المالك القديمة «أربع تلاتات بتطلع 4333 بدل 3333» هي نفس الشكل:
 * الجمع مش في القاموس فالعدّاد بيتحسب خانة لوحدها.
 *
 * ⚠️ **العدّاد إجباري**: «ستات» و«مرات» و«ساعات» كلمات عادية، ومن غير
 * رقم قبلها مانقبلهاش خالص.
 */
function pluralDigit(w: string): string {
  const irr = IRREGULAR_PLURAL[w];
  if (irr) return irr;
  if (!w.endsWith("ات") || w.length < 5) return "";
  const t = numberTokenValue(w.slice(0, -2));
  return t && t.isUnit ? String(t.value) : "";
}

/**
 * 🔴 **«تسعة وتسعين» ملتبسة — والقراءتان الاتنين حصلوا في جلسة واحدة.**
 *
 * الشكل ده معناه في العربي رقم واحد مركّب (٩٩)، لكن المندوب بينطق
 * الخانات ورا بعض فكوهير بيلزقهم. الجلسة الواحدة فيها الاتنين:
 *
 *     «واو لام **تسعة وتسعين** سبعة تلاتة»  ⇒ بول**9973**  (مركّب = ٩٩)
 *     «ع ه م تمانية **تسعة وستين**»          ⇒ عهم**8960**  (منفصل = ٩ ثم ٦٠)
 *
 * فمافيش قراءة واحدة صح — لازم **الاتنين** يتجرّبوا. بنولّد تيارات
 * بديلة (سقف ٨) و`plateSpan` بيدوّر في كلها.
 */
function conjTens(words: string[], i: number): number | null {
  if (i + 1 >= words.length) return null;
  const u = numberTokenValue(words[i]);
  if (!u || !u.isUnit || u.value < 1 || u.value > 9) return null;
  /**
   * 🔴 **الواو ممكن تيجي كلمة لوحدها** — «واحد **و** تمانين».
   *
   * الكود كان بيتوقعها ملزوقة («وتمانين») بس. والنتيجة إن `دله6781`
   * **ضاعت** في جلسة المالك (٨٢ بطاقة، ١٨ سبتمبر ٢٠٢٦): الموديل قرا
   * `دله6718` (قلب رقمين)، وكوهير كتب «ستة سبعة واحد و تمانين» —
   * فقراءة ٨١ ما اتولّدتش والشاهد مالقاش ٦٧٨١ يصحّح بيها.
   */
  const sep = words[i + 1] === "و" && i + 2 < words.length;
  const w = sep ? words[i + 2] : words[i + 1];
  if (!sep && !w.startsWith("و")) return null;
  const t = numberTokenValue(w);
  if (!t || t.isScale || t.value < 20 || t.value > 90 || t.value % 10 !== 0) return null;
  return t.value + u.value;
}

/**
 * كام كلمة بيستهلكها الشكل المركّب — ٢ للملزوقة («واحد وتمانين») و**٣**
 * للمنفصلة («واحد و تمانين»). `digitSlots` لازم يتخطّاهم كلهم، وإلا
 * الواو تفضل كلمة زيادة وتبوّظ حدود الخانات.
 */
function conjTensLen(words: string[], i: number): number {
  return words[i + 1] === "و" ? 3 : 2;
}

/**
 * خانات النص + صاحب كل خانة (فهرس الكلمة) — **مصدر واحد** يستعمله
 * `digitStreamOf` و`plateSpan` مع بعض.
 *
 * `joinAt` = فهارس الكلمات اللي نقرا فيها الشكل الملتبس **مركّب**.
 */
function digitSlots(
  words: string[],
  joinAt: ReadonlySet<number> = new Set()
): { stream: string; owner: number[] } {
  let stream = "";
  const owner: number[] = [];
  for (let w = 0; w < words.length; w++) {
    if (joinAt.has(w)) {
      const v = conjTens(words, w);
      if (v !== null) {
        const len = conjTensLen(words, w);
        stream += String(v);
        owner.push(w + len - 1, w + len - 1);
        w += len - 1;
        continue;
      }
    }
    const plural = pluralDigit(words[w]);
    if (plural) {
      const prev = w > 0 ? numberTokenValue(words[w - 1]) : null;
      if (prev && prev.isUnit && prev.value >= 2 && prev.value <= 9) {
        // العدّاد نفسه مش خانة لوحة — نشيله ونكرّر الخانة بعدده
        while (owner.length && owner[owner.length - 1] === w - 1) {
          owner.pop();
          stream = stream.slice(0, -1);
        }
        for (let k = 0; k < prev.value; k++) {
          stream += plural;
          owner.push(w);
        }
        continue;
      }
    }
    for (const d of digitsOfWord(words[w])) {
      stream += d;
      owner.push(w);
    }
  }
  return { stream, owner };
}

/**
 * تيار أرقام النص — أرقام مكتوبة **وأرقام منطوقة كلمات**.
 *
 * 🔴 الصفحة بتستخدمه كحارس للنافذة الاحتياطية الطويلة: ماتقبلش نتيجتها
 * إلا لو أرقام اللوحة موجودة في نصّها، يعني القصّ عند اللوحة قدر يشتغل.
 * من غير الحارس ده الطويلة بتجيب نوع اللوحة **الجارة** (مقيس: الأغلاط
 * طلعت من ٤ لـ٦ على مقعد المالك).
 *
 * بيستعمل نفس `digitsOfWord` بتاع الماسح فمافيش نسخة تانية من المنطق.
 */
export function digitStreamOf(text: string | null | undefined): string {
  return digitSlots(norm(text ?? "").split(" ").filter(Boolean)).stream;
}

/** كل قراءات تيار الأرقام — الأساسية الأول وبعدين بدائل الشكل الملتبس */
function slotVariants(words: string[]): { stream: string; owner: number[] }[] {
  const spots: number[] = [];
  for (let i = 0; i < words.length; i++) if (conjTens(words, i) !== null) spots.push(i);
  const out = [digitSlots(words)];
  if (!spots.length) return out;
  const total = Math.min(1 << spots.length, 8);
  for (let mask = 1; mask < total; mask++) {
    const join = new Set<number>();
    for (let b = 0; b < spots.length; b++) if (mask & (1 << b)) join.add(spots[b]);
    out.push(digitSlots(words, join));
  }
  return out;
}

/**
 * كل قراءات تيار الأرقام لنص — الصفحة بتستعملها كحارس للنافذة الطويلة،
 * فلازم تقبل **أي** قراءة فيها أرقام لوحتنا.
 */
export function digitStreamsOf(text: string | null | undefined): string[] {
  return slotVariants(norm(text ?? "").split(" ").filter(Boolean)).map((v) => v.stream);
}

/**
 * نفس قراءات `digitStreamsOf` بس **بحدود الأرقام المنطوقة معاها**
 * (`owner[k]` = فهرس الكلمة اللي نطقت الخانة رقم `k`).
 *
 * 🔴 شاهد النوع (`typeWitness.ts`) محتاج الحدود دي: مطابقة بتقص رقم
 * منطوق من نصّه («حداشر تلاتة وأربعين» ⇒ `11340` وجوّاها `1134`) مش
 * قراءة حقيقية، وكانت بتسكّت غلط حقيقي بـ«اتفاق» مزيّف.
 *
 * ⚠️ `digitStreamsOf` سلوكها **ما اتغيّرش** — الصفحة والسيرفر بيعتمدوا
 * عليها كحارس متسامح، والتقييد بالحدود هنا للشاهد بس.
 */
/**
 * 🔴 **نصّ كوهير منهار — حلقة تكرار.**
 *
 * عطل معروف عنده، وظهر في جلسات المالك بكل أشكاله:
 *   «20, 20, 20, 20, 20…»   «س س س س س س…»   «5-8-4-8-…A-A-A-A-A…»
 *   «(1654 ) (1654 ) (1654 ))»   «&rlm;&rlm;&rlm;…»   «‫ ‫ ‫ ‫ ‫…»
 *
 * والمهم إنه **حساس للإزاحة**: نفس اللحظة بتنهار على نافذة وتعدّي على
 * نافذة تانية بإزاحة مختلفة بثانية واحدة (مقيس في
 * `training/probe_type_third_window.py`). فكشفه = نعرف إمتى نعيد
 * المحاولة بنافذة تالتة بدل ما نسيب الخانة فاضية.
 *
 * تلات أشكال:
 *  · جرية ٦+ لنفس الحرف
 *  · أقل من ٣ حروف/أرقام مفيدة في النص كله (علامات اتجاه بس)
 *  · **حلقة على مستوى الكلمة** — ٣ كلمات+ وتمايزها ≤ التلت. (ده اللي
 *    مسك «(1654) (1654) (1654)»، وكشّاف الحروف كان أعمى عنه.)
 */
export function looksCollapsed(text: string | null | undefined): boolean {
  const t = String(text ?? "");
  if (!t) return true;
  let run = 1;
  for (let i = 1; i < t.length; i++) {
    run = t[i] === t[i - 1] ? run + 1 : 1;
    if (run >= 6) return true;
  }
  const solid = t.replace(/[^ء-ي0-9]/g, "");
  if (solid.length < 3) return true;
  const toks = t.replace(/[^ء-ي0-9]/g, " ").split(/\s+/).filter(Boolean);
  return toks.length >= 3 && new Set(toks).size <= toks.length / 3;
}

export function digitSlotReadings(
  text: string | null | undefined
): { stream: string; owner: number[] }[] {
  return slotVariants(norm(text ?? "").split(" ").filter(Boolean));
}

/**
 * 🔴 **مدى نوع اللوحة دي في النص: من بعد أرقامها لحد أرقام اللوحة اللي بعدها.**
 *
 * القصّ من البداية بيمنع نوع اللوحة **السابقة**، والوقوف عند اللوحة
 * **اللاحقة** بيمنع نوعها هي. الاتنين لازم:
 *
 *     «ديال 4197 لوحة صفراء بسيم 6497 مصدوم»
 *      حهد4197 ⇒ «لوحة صفراء» ✔   ·   ربس6497 ⇒ «مصدوم» ✔
 *
 * من غير الوقوف، `حهد4197` كانت بتاخد «مصدومه» بتاعة `ربس6497`
 * (جلسة ١٠ سبتمبر ٢٠٢٦).
 *
 * «اللوحة اللي بعدها» = أول **٣ أرقام** متجاورة (جوّه ٤ كلمات) بعد أرقامنا.
 * تلاتة تكفي لأن اللوحة اللاحقة أوقات تتسمع ناقصة. وكلمات النوع مافيهاش
 * أرقام (و«اتش١» رقم واحد بس) فمابتشغّلش الحد.
 *
 * `null` = أرقام اللوحة مش في النص ⇒ نرجع للسلوك القديم بالكامل.
 */
function plateSpan(
  words: string[],
  plate: string
): { start: number; end: number } | null {
  const want = plate.replace(/[^0-9٠-٩]/g, "").replace(/[٠-٩]/g, (d) => AR_DIGITS[d]);
  if (want.length < 3) return null;

  let { stream, owner } = digitSlots(words);
  let at = stream.lastIndexOf(want);
  if (at < 0) {
    // الشكل الملتبس («تسعة وتسعين») — نجرّب القراءة التانية
    for (const v of slotVariants(words).slice(1)) {
      const k = v.stream.lastIndexOf(want);
      if (k >= 0) { stream = v.stream; owner = v.owner; at = k; break; }
    }
  }
  let hit = want;
  if (at < 0) {
    /**
     * 🔴 **الشاهد بيبلع خانة — نجرّب آخر ٣ خانات، بشرط إنها فريدة.**
     *
     * من جلسة شيت الأنواع (١٦ سبتمبر ٢٠٢٦): «١٧-٢-**دودج**» — كوهير
     * بلع صفر `حنح0172` فالقصّ فشل والنوع اترمي **رغم إن الكلمة مكتوبة
     * قدامنا**. نفس الشكل في «وأودي الحوار **98** اودي» (ودح1899).
     *
     * ⚠️ **الفرادة هي الحارس**: لو الـ٣ خانات اتكرّرت في النافذة مابنقصّش
     * خالص — لأن قصّة غلط معناها اللوحة تاخد نوع جارتها، وده بالظبط اللي
     * قاعدة fail-closed اتعملت عشانه. ونفس الشرط على الـ٤ خانات: لو
     * اتكرّرت، الـ٣ مش هتنفع كمان فبنرجع null.
     */
    const three = want.slice(-3);
    const a3 = stream.indexOf(three);
    if (a3 < 0 || stream.indexOf(three, a3 + 1) >= 0) return null;
    at = a3;
    hit = three;
  }

  const lastIdx = at + hit.length - 1;
  const start = owner[lastIdx] + 1;

  let end = words.length;
  for (let k = lastIdx + 1; k + 2 < owner.length; k++) {
    /**
     * 🔴 **الحدّ نزل من ٤ كلمات لـ٢** (١٨ سبتمبر ٢٠٢٦).
     *
     * أرقام اللوحة بتتنطق متلاصقة — إما كلمة واحدة («6428») أو كلمات
     * متتالية («ستة أربعة اتنين تمانية»). فتلات أرقام على بعد ٤ كلمات
     * **مش لوحة**، وده كان بيقطع العبارة بالغلط:
     *
     *   «س ه ره 6428 **جراش 2 يمين** بطحات ساعة **23** يمين»
     *
     * الـ«٢» بتاعة جراج والـ«٢٣» بعدها بأربع كلمات اتحسبوا لوحة جاية،
     * فالقصّ وقف قبل «يمين» ورجّع «جراج» ناقصة بدل «جراج اتنين يمين».
     *
     * ⚠️ والحالة اللي الحدّ ده اتعمل عشانها لسه مغطّاة: «ديال 4197 لوحة
     * صفراء بسيم **6497** مصدوم» — أرقام الجار كلمة واحدة فالفرق ٠.
     */
    if (owner[k + 2] - owner[k] <= 2) {
      end = owner[k];
      break;
    }
  }

  /**
   * 🔴 **نوقف كمان عند حروف اللوحة اللي بعدها — مش الأرقام بس.**
   *
   * الحلقة فوق بتدوّر على أرقام الجار. بس لو الشاهد مسخ أرقام الجار
   * مابتلاقيش حاجة وبتسيب القصّ ماشي لآخر النص — والنتيجة إن **اللوحة
   * بتاخد نوع جارتها**.
   *
   * مقيس في جلسة ١٠٠ لوحة (٢٠ سبتمبر ٢٠٢٦):
   *   «صاد سي اللام ٢٣٥٠ **ي كاف قاف** اتنين واحد ساعتين متحرك»
   * أرقام `يكق2192` طلعت «اتنين واحد ساعتين» — خانتين بس — فالحلقة
   * مالقتش جار، و`صسل2350` لفّت لآخر النص وخدت «متحرك» اللي كانت
   * لجارتها. النتيجة: `متحركة` نزلت على اللوحة الغلط، و`يكق2192` فضلت
   * فاضية.
   *
   * تلات كلمات إملاء ورا بعض = **اللوحة الجاية بتتهجّى**. والعبارات
   * بتاعتنا مافيهاش الشكل ده («هاي اس» و«بي ام» كلمتين من حرفين، مش
   * حروف مفردة)، فالحارس ضيّق.
   */
  let run = 0;
  for (let i = start; i < end; i++) {
    const w = words[i];
    if (LETTER_NAMES.has(w) || w.length === 1) {
      run += 1;
      if (run >= 3) {
        end = i - 2;
        break;
      }
    } else {
      run = 0;
    }
  }

  return { start, end: Math.max(start, end) };
}

interface ScanOpts {
  /** نبدأ المسح من الكلمة دي (الافتراضي ٠ = كل النص) */
  startWord?: number;
  /** نوقف **قبل** الكلمة دي (الافتراضي = آخر النص) */
  endWord?: number;
  /**
   * `last` = آخر مطابقة تكسب (الافتراضي، وهو اللي بيحمي من نوع اللوحة
   * السابقة لما مانعرفش نقص). `first` = **أول** مطابقة بعد نقطة البداية —
   * وهو الأصح لما بنبدأ من بعد أرقام اللوحة، لأن النوع بيتقال وراها فوراً
   * (وبيمنع نوع اللوحة **اللي بعدها** إنه يتسرّب).
   */
  pick?: "first" | "last";
}

function scanAll(text: string | null | undefined, opts: ScanOpts = {}): ScanResult {
  const byCat: ScanResult["byCat"] = { type: null, condition: null, place: null };
  const words = norm(String(text || "")).split(" ").filter(Boolean);
  if (!words.length) return { last: null, byCat };
  const first = opts.pick === "first";

  const stop = Math.max(0, Math.min(opts.endWord ?? words.length, words.length));

  let last: string | null = null;
  let i = Math.max(0, Math.min(opts.startWord ?? 0, words.length));
  while (i < stop) {
    let hit: string | null = null;
    let step = 1;
    for (let n = Math.min(MAX_WORDS, stop - i); n >= 1; n--) {
      const chunk = words.slice(i, i + n);
      const g = chunk.join("");
      if (n === 1 && LETTER_NAMES.has(g)) break;
      // 🔴 عبارة إملاء (أغلبها أسماء حروف) ماتطلّعش نوع — أي طول
      if (n > 1 && isSpelling(chunk)) continue;
      const exact = IDX.get(g);
      if (exact) {
        hit = exact;
        step = n;
        break;
      }
      /**
       * 🔴 **التقريب بقى لكل عدد كلمات، وحدّ الطول نزل من ٤ لـ٣.**
       *
       * كان `n === 1 && length >= 4`، وده كان بيستبعد حاجتين مقيستين:
       *   · العبارات المركّبة (جراج بدروم · برحه يمين) — شوف KEYS_BY_WORDS
       *   · الأنواع **ذات التلات حروف**: شاص · فان · باص. «شاقص» فشلت
       *     تطابق «شاص» تلات مرات في مقعد أخو المالك، مش لفرق الطول
       *     (`lev1` بيسمح بحرف زيادة) لكن لأن «شاص» نفسها أقصر من ٤.
       *
       * الحواجز كلها باقية زي ما هي: أسماء الحروف · `NO_FUZZY` ·
       * **ومطابقة أول حرف** (من غيرها «مدينة» بقت «دينه» عند المالك).
       */
      const MIN_FUZZY_LEN = 3;
      /**
       * 🔴 **الكلمة اللي بعدها حرف مفرد = إحنا وسط إملاء لوحة.**
       *
       * «هاي س» (المالك بيتهجّى حرف «س») كانت بتطابق تقريبياً «هايس»
       * — نطق «هاي اس» — بفرق حرف واحد، فطلّعت نوع من إملاء لوحة.
       * مقيس على جلسة ٧٥ لوحة **بلا أي نوع**: دي كانت واحدة من ٦ أنواع
       * مخترعة.
       *
       * والحلّ مش منع «هاي» نفسها — هي أول كلمة في النوع الحقيقي
       * «هاي اس»، ومنعها بيكسره (حارس `vehicleTypeScanFull` مسك ده).
       * الفرق بين الحالتين هو **اللي بعدها**: حرف مفرد ⇒ إملاء.
       *
       * ⚠️ **والقيد رفع حدّ الطول، مش منع كامل.** أول نسخة منعت التقريب
       *   تماماً لما يكون بعده حرف مفرد — والقياس كذّبها: في تسجيلات
       *   المالك النوع/الملاحظة **دايماً** بعدها إملاء اللوحة الجاية،
       *   فالملاحظة نزلت ٩٢.٩ ← ٦٤.٣٪ عند أخوه. الحدّ ٤ حروف بيفرّق:
       *   «هاي» (٣) تتمنع · «مطرب» (٤ ⇒ متربه) تعدّي.
       *
       * ⚠️ والقيد على **التقريب بس**. المطابقة التامة بتفضل شغّالة،
       *   فنوع صريح جنب إملاء لوحة («ونيت ب أ س») مايتأثرش.
       */
      const nextIsLetter =
        n === 1 && i + 1 < stop && (words[i + 1]?.length ?? 0) === 1;
      if (g.length >= (nextIsLetter ? 4 : MIN_FUZZY_LEN)) {
        const keys = n === 1 ? SINGLE_KEYS : MULTI_KEYS;
        for (const k of keys) {
          if (k.length < MIN_FUZZY_LEN || k[0] !== g[0]) continue;
          /**
           * 🔴 **الكلمة القصيرة (≤٤ حروف): حرف زيادة بس، مش حرف مختلف.**
           *
           * نزّلنا الحدّ من ٤ لـ٣ عشان «شاقص» تطابق «شاص» — وفتحنا الباب
           * لـ**«شخص» ← «شاص»** (كلمة عربية شائعة جداً بقت نوع). الحارس
           * `vehicleTypeScanFull` مسكها.
           *
           * والفرق بين الحالتين بنيوي: مسخ الموديل بيزوّد/ينقّص حرف
           * (شاص←شاقص · فان←فاان)، أما الكلمة التانية بيبقى **نفس الطول
           * وحرف مختلف** (شاص↔شخص · فان↔فاز). فبنقبل فرق الطول بس.
           *
           * ⚠️ **والحدّ ٥ مش ٤** — رفعناه بعد جلسة المالك (١٨ سبتمبر
           * ٢٠٢٦): «ونيت» (٤ حروف) وقعت على **«ونين»** بحرف مختلف
           * وطلّعت نوع على `دال0521` من نص مافيهوش نوع خالص («خمسة
           * اتنين واحد تسعة ونين» = أرقام ممسوخة). حرف مختلف في كلمة
           * ٤ حروف = ربع الكلمة، تسامح كبير أوي.
           *
           * **مقيس على مقعد الـ٨١ صف: بلا أي خسارة** — ٩٠.١٪ وصفر غلط
           * قبل وبعد، ونفس التوزيع بالظبط (نوع ٣٤/٣٨ · حالة ١٠/١١ ·
           * مكان ٢٩/٣٢).
           */
          if (k.length < 5 && g.length === k.length) continue;
          /**
           * 🔴 **البديل القصير مايتقرّبش عليه — مطابقة تامة بس.**
           *
           * «وني» بديل مسجّل لـ«ونيت» وطوله ٣ حروف، فالتقريب سمح له
           * يقع على **«ونين»** بحرف زيادة — وطلّع نوع «ونيت» على
           * `دال0521` في جلسة المالك (١٨ سبتمبر ٢٠٢٦) من نص مافيهوش
           * نوع أصلاً («خمسة اتنين واحد تسعة ونين» = أرقام ممسوخة).
           *
           * ⚠️ **والقاعدة اللي فوق لوحدها مامسكتهاش**: هي منعت «ونيت»
           * نفسها (٤ حروف، حرف مختلف)، فالدور فضي للبديل «وني» (٣
           * حروف، حرف زيادة) وطابق. الاتنين لازم مع بعض.
           *
           * والفرق بنيوي: **البديل نفسه تسامح إملائي**، فالتقريب فوقه
           * بيضاعف التسامح — «وني»+حرف بتغطي أي كلمة ٤ حروف تبدأ بواو
           * وفيها نون. أما «شاص/فان/باص» فأسماء **أصلية** (المفتاح
           * قيمته نفسه) والتقريب عليها مقيس ومطلوب («شاقص» ← «شاص»).
           */
          if (k.length <= 3 && IDX.get(k) !== k) continue;
          // مسافة ٢ للعبارات الطويلة بس — «دافع رباع» ← «دفع رباعي»
          const max = n > 1 && k.length >= 7 ? 2 : 1;
          /**
           * 🔴 **الرقم مايتسامحش فيه.** «جراش **3** يمين» كانت بتقع على
           * «جراج **1** يمين» (مسافة ٢: ش←ج و٣←١) لأن مفتاح الواحد أسبق
           * في القائمة. الحروف ممكن تتمسخ، لكن الرقم المنطوق واضح —
           * فلو الاتنين فيهم رقم لازم يكونوا نفس الرقم.
           */
          const dg = g.replace(/\D/g, "");
          const dk = k.replace(/\D/g, "");
          if (dg && dk && dg !== dk) continue;
          if (levAtMost(g, k, max)) {
            hit = IDX.get(k) ?? null;
            if (hit) {
              step = n;
              break;
            }
          }
        }
        if (hit) break;
      }
    }
    if (hit) {
      last = hit;
      // 🔴 **الأخيرة تكسب — لكل تصنيف على حدة.** ده اللي بيخلّي «ونيت
      // مصدومه» يحفظ الاتنين، وفي نفس الوقت لو النافذة فيها حالتين (ذيل
      // اللوحة اللي قبلها + حالة دي) الأخيرة تغلب فمافيش تسريب.
      const cat = CATEGORY.get(hit);
      // `first`: أول مطابقة لكل تصنيف تثبت · `last`: الأخيرة تكسب
      if (cat && !(first && byCat[cat] !== null)) byCat[cat] = hit;
      i += step;
    } else {
      i += 1;
    }
  }
  return { last, byCat };
}

/**
 * السلوك القديم — **آخر مطابقة مهما كان تصنيفها**.
 * سايبينها زي ما هي للنداءات والاختبارات القديمة.
 */
export function scanVehicleType(text: string | null | undefined): string | null {
  return scanAll(text).last;
}

/**
 * 🔴 **التوزيع على العمودين** (طلب المالك، ٩ سبتمبر ٢٠٢٦).
 *
 *   `type` → عمود «نوع السيارة»   ·   `note` → عمود «ملاحظة المندوب»
 *
 * الحالة والمكان بيتلمّوا **مع بعض** في الملاحظة (مفصولين بـ«·») لأنهم
 * حقيقتين مختلفتين: «مركونه · برحه يمين». وكل تصنيف بياخد قيمة واحدة
 * (الأخيرة تكسب) فذيل اللوحة اللي قبلها مايتسربش.
 *
 * قبل ده كانت قيمة **واحدة** بس، فـ«ونيت مصدومه» كان بيرجّع «مصدومه»
 * والنوع **يضيع**.
 */
export function scanTypeAndNote(
  text: string | null | undefined,
  opts?: {
    /**
     * 🔴 اللوحة اللي بندوّر على نوعها (٣ حروف + ٤ أرقام). لو أرقامها
     * موجودة في النص، بنقص عندها وناخد **أول** مطابقة بعدها — وده اللي
     * بيمنع اللوحة تاخد نوع اللي قبلها ولا نوع اللي بعدها.
     * ولو الأرقام مش موجودة (اتقالت كلمات) بنرجع للسلوك القديم بالكامل.
     */
    afterPlate?: string;
  }
): { type: string | null; note: string | null; cutFailed?: boolean } {
  let scanOpts: ScanOpts = {};
  if (opts?.afterPlate) {
    const words = norm(String(text || "")).split(" ").filter(Boolean);
    const span = plateSpan(words, opts.afterPlate);
    if (span) {
      scanOpts = { startWord: span.start, endWord: span.end, pick: "first" };
    } else {
      /**
       * 🔴 **القصّ فشل ⇒ مانقراش النافذة، نرجع فاضي.**
       *
       * كان بيرجع للسلوك القديم (يقرا النافذة **كلها**) — وده مصنع
       * الأنواع الغلط. مقيس على مقعدي المالك (١١١ حالة بحقيقة مكتوبة):
       *
       *   القصّ نجح : صح ٧٥ · غلط  ٤   ⇒ دقّة ٩٤.٩٪
       *   القصّ فشل : صح  ٦ · غلط  ٩   ⇒ دقّة ٤٠.٠٪
       *
       * **٩ من ١٣ غلط كلها من نوافذ القصّ فشل فيها.** والسبب إن أرقام
       * لوحتنا مش في النص (اتقالت ناقصة/ممسوخة) فالماسح بيقرا نوع
       * اللوحة **الجارة**: «حلك2654» أخدت «مركون» بتاعة «بلم2864» لأن
       * النص كان «2-8-6-4 مركون» — أرقام الجار مش أرقامنا.
       *
       * ⚠️ **والتمن مدفوع بوعي**: بنخسر ٦ صح عشان نشيل ٩ غلط. والسبب
       *   إن النوع الغلط بيتكتب في داتا المالك **في صمت**، والخانة
       *   الفاضية بتبان وتتملّى. ودي نفس القاعدة المكتوبة في المشروع
       *   من الأول: «لو مفيش نوع مؤكّد الخانة تفضل فاضية مش نوع غلط».
       *
       * جرّبنا بدائل أخفّ والقياس رفضها:
       *   · تخطّي أول ٣٠٪ من النافذة  ← بلا أي أثر (١٣ غلط زي ما هي)
       *   · تخطّي أول ٥٠٪            ← ١٢ غلط (مكسب ١)
       *   · نقفلها لو فيها ≥٤ أرقام  ← ٦ غلط مقابل ٤
       *
       * و`cutFailed` بيرجع عشان الصفحة **تسجّل السبب** — الخانة الفاضية
       * لازم يكون ليها تفسير، مش صمت تاني.
       */
      return { type: null, note: null, cutFailed: true };
    }
  }
  const { byCat } = scanAll(text, scanOpts);
  const parts = [byCat.condition, byCat.place].filter(Boolean) as string[];
  return { type: byCat.type, note: parts.length ? parts.join(" · ") : null };
}
