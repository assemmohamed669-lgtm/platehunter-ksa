function norm(s: string): string {
  return String(s || "")
    .replace(/[؟?!.,،:;"'“”«»()[\]{}…\-—_/\\|]/g, " ")
    .split(/\s+/)
    .join(" ")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    /**
     * 🔴 **ث ← ت: كوهير بيكتب فصحى والقائمة عاميّة.**
     *
     * من جلسة شيت الأنواع (١٦ سبتمبر ٢٠٢٦): الشاهد كتب «جراش **ثلاثة**
     * يمين» والقائمة فيها «جراج **تلاته** يمين» — مسافة ٣ حروف فالعبارة
     * اترفضت ورجعت «جراج» ناقصة. نفس الشكل في «ثمانية» و«اثنين».
     *
     * التطبيع بيتطبّق على **الاتنين** (القائمة والنص) فمفيش تصادم:
     * «حادث» هي العضو الوحيد اللي فيه ث وبيبقى «حادت» على الجهتين.
     */
    .replace(/ث/g, "ت")
    /**
     * 🔴 **الرقم العربي-الهندي يبقى غربي.**
     *
     * `COUNT_FORMS` فيها صيغ بالرقم («جراج 2 يسار») عشان كوهير بيكتب
     * الأرقام أرقام. لكنه بيكتبها **عربي-هندي** أوقات، والمطابقة كانت
     * بتفشل فنقع على أقصر عبارة: «جراش **٢** يسار» طلعت
     * «جراج **واحد** يسار» في جلسة المالك (٨٢ بطاقة، ١٨ سبتمبر ٢٠٢٦).
     *
     * التطبيع بيتطبّق على الجهتين (القائمة والنص) فمافيش تصادم.
     */
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
    .replace(/ـ/g, "")
    .trim()
    .toLowerCase();
}

/** الشكل الملزوق — بنقارن بيه عشان الفراغات مابتفرقش في النطق */
function glue(s: string): string {
  return norm(s).split(" ").join("");
}

