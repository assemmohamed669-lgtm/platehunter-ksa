/**
 * مفتاح حدّ الاستهلاك — استخراج المندوب منه.
 *
 * بلاغ المالك (٧ أكتوبر ٢٠٢٦): سطر «تعدّى حد الاستهلاك» في سجل الأمان كان
 * بيسجّل الـIP بس و«الفاعل: —»، فمفيش طريقة تعرف مين المندوب اللي اتوقف.
 *
 * كل المسارات بتستعمل مفتاح شكله `<الخدمة>:<رقم المندوب>`، فبناخد الرقم من
 * المفتاح نفسه بدل ما نغيّر ١٦ مكان نداء. صفحة الأمان بتحوّل الرقم لاسم.
 *
 * 🔒 مسار اللينك العام (`/c/[token]`) مفتاحه IP مش رقم مندوب — والتحقق من شكل
 *    الـUUID بيخلّيه يرجع `null` بدل ما نكتب IP في خانة المندوب.
 */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function agentIdFromKey(key: string): string | null {
  const at = key.indexOf(":");
  if (at < 0) return null;
  const rest = key.slice(at + 1);
  return UUID_RE.test(rest) ? rest : null;
}
