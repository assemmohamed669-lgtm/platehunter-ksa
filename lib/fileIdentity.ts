/**
 * بصمة ملف — «ده نفس الملف اللي حلّلناه قبل كده؟»
 *
 * ليه: تحليل ورقات ملف الإحالة (فك الملف وقراءة كل ورقة) كان بيتعاد **كل مرة**
 * صفحة الفرز تفتح، حتى والملف ماتغيّرش. ده شغل تقيل بيوقف الواجهة.
 *
 * ⚠️ **التاريخ مش داخل البصمة عن قصد**: الملف بيتعاد بناؤه من التخزين في كل
 * مرة (`new File([blob], name)`)، والتاريخ ساعتها بيبقى «دلوقتي» — فبصمة
 * بالتاريخ هتتغيّر كل مرة والكاش مايشتغلش أبداً.
 */
export function fileIdentity(file: File | null | undefined): string {
  if (!file) return "";
  return `${file.name}|${file.size}`;
}
