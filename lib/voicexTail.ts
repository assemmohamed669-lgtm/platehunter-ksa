/**
 * ذيل الإيقاف — «آخر لوحة قبل ما يقفل التسجيل».
 * =============================================================================
 * 🔴 **الباج (بلاغ مندوب، ٤ سبتمبر ٢٠٢٦):** آخر لوحة بيقولها المندوب قبل ما
 * يدوس «إيقاف» مش بتتكتب.
 *
 * **السبب:** الصوت بيوصل الموديل بطريقتين بس —
 *   أ) `onUtterance` من الـVAD: محتاج **٩٠٠ مللي سكوت** بعد الكلام.
 *   ب) مؤقّت دوري كل **١.٥ث**: أثناء الكلام بس.
 * ولما يدوس إيقاف، الاتنين بيتقفلوا فوراً والتصريف بيحصل **من غير ما يتبعت
 * آخر جزء صوت**. فلو قال اللوحة ودَس بسرعة، مافيش سكوت (أ ماحصلتش) والمؤقّت
 * ماجاش دوره (ب ماحصلتش) ⇒ **الصوت ده عمره ما وصل الموديل**.
 *
 * ⚠️ **إصلاح قديم اتشال:** كان بيعيد قراءة **آخر ٥ث** وقت الإيقاف، فكان بيقرا
 * لوحات ظهرت خلاص ⇒ صفوف مكررة، فاتشال. يعني اتبدّلت مشكلة بمشكلة.
 *
 * **الإصلاح ده بيبعت اللي ماتبعتش بس** — من آخر ثانية اتبعتت لآخر الصوت.
 * فآخر لوحة تتكتب، **ومن غير تكرار**، لأننا مابنعيدش قراءة صوت اتبعت خلاص.
 */

export interface TailInput {
  /** آخر ثانية من الصوت اتبعتت للموديل فعلاً */
  lastSentToSec: number;
  /** طول التسجيل لحد لحظة الإيقاف */
  elapsedSec: number;
  /** آخر ثانية اتسمع فيها كلام (نهاية آخر نطق اكتشفه الـVAD) */
  lastSpokeSec: number;
  /** كان بيتكلم لسه وقت الإيقاف؟ (الـVAD ما سجّلش نهاية نطق) */
  speaking?: boolean;
}

export interface TailWindow {
  fromSec: number;
  toSec: number;
}

/** أقصر ذيل يستاهل نبعته — أقصر من كده مش هيكون فيه لوحة كاملة. */
export const MIN_TAIL_SEC = 0.6;
/** أطول ذيل نبعته — نفس حد النافذة، مانبعتش مقطع ضخم للموديل. */
export const MAX_TAIL_SEC = 6;
/**
 * أقصى بُعد بين آخر كلام ونهاية التسجيل عشان نعتبر الذيل «فيه كلام».
 * أبعد من كده = المندوب سكت خلاص والباقي صمت، ومافيش داعي نبعته.
 */
export const TAIL_SPEECH_GAP_SEC = 2;

/**
 * الجزء اللي **ماتبعتش** وقت الإيقاف — أو `null` لو مافيش حاجة تستاهل.
 *
 * بيرجّع `null` في الحالات دي عن قصد:
 *  · كله اتبعت خلاص ⇒ إعادة بعته = **صف مكرر** (الباج القديم).
 *  · الذيل صمت (آخر كلام بعيد) ⇒ بعتة بلا فايدة، وممكن الموديل يخترع فيها.
 *  · الذيل أقصر من `MIN_TAIL_SEC` ⇒ مش هيكون فيه لوحة.
 *  · العدادات متضاربة (اتبعت أكتر من طول التسجيل) ⇒ الأمان الافتراضي.
 */
export function tailToSend(input: TailInput): TailWindow | null {
  const { lastSentToSec, elapsedSec, lastSpokeSec, speaking } = input;

  const to = elapsedSec;
  let from = lastSentToSec;
  if (!(to > from)) return null;                     // كله اتبعت، أو عدادات متضاربة
  if (to - from < MIN_TAIL_SEC) return null;         // أقصر من إن يكون فيه لوحة

  // الذيل لازم يكون فيه كلام. لو المندوب كان لسه بيتكلم وقت الإيقاف، الـVAD
  // ما سجّلش نهاية نطق فـ`lastSpokeSec` بيبقى قديم — وساعتها `speaking` هي
  // الدليل. من غير الشرط ده كنا هنبعت صمت والموديل ممكن يخترع فيه لوحة.
  const hasSpeech = speaking === true || (lastSpokeSec > 0 && to - lastSpokeSec <= TAIL_SPEECH_GAP_SEC);
  if (!hasSpeech) return null;

  // ذيل طويل ⇒ نقصّ من **الأول**: آخر الصوت هو اللي فيه اللوحة الأخيرة.
  if (to - from > MAX_TAIL_SEC) from = to - MAX_TAIL_SEC;

  return { fromSec: from, toSec: to };
}
