/**
 * ══════════════════════════════════════════════════════════════════════
 *  ⚠️ «الموقع مش جاهز» — تحذير أثناء التسجيل
 * ══════════════════════════════════════════════════════════════════════
 *
 * بلاغ المالك (١٥ أكتوبر ٢٠٢٦): مندوب سجّل **٩٦ لوحة كلها بلا موقع**، ومعرفش
 * غير لما جه يصدّر ولقى «التصدير بيستنى الموقع (96 مستنية)» — شغل ساعة راح.
 *
 * البرنامج كان بيرفض كل قراءة دقتها أوحش من الحد **وساكت**. دلوقتي بيقول وهو
 * بيسجّل، فالمندوب يستنى ثانيتين أو يطلع من المبنى بدل ما يكتشف في الآخر.
 *
 * 🔧 **الحد بقى ١٠٠ متر** (كان ٢٥) — قرار المالك: «أفضل من إنه مياخدش خالص».
 *    يعني موقع تقريبي بيتسجّل، والمندوب شايف دقته قدامه.
 */

/** أوحش دقة بنقبل نختم بيها لوحة. أوحش من كده ⇒ تحذير. */
export const GPS_STAMP_MAX_ACCURACY_M = 100;

/**
 * رسالة التحذير، أو `null` لو مافيش داعي.
 *
 * @param fix     آخر قراءة موقع (أو `null` لو لسه مافيش).
 * @param recording المندوب بيسجّل دلوقتي؟ — مانزعّجوش وهو واقف.
 */
export function gpsRecordWarning(
  fix: { accuracy?: number | null } | null | undefined,
  recording: boolean,
): string | null {
  if (!recording) return null;

  if (!fix) return "⚠️ الموقع لسه مش جاهز — اللوحات دي مش هتتصدّر. استنى ثانية أو اطلع لمكان مكشوف.";

  const acc = Number(fix.accuracy);
  if (!Number.isFinite(acc) || acc <= 0) {
    return "⚠️ الموقع لسه مش جاهز — اللوحات دي مش هتتصدّر. استنى ثانية أو اطلع لمكان مكشوف.";
  }
  if (acc > GPS_STAMP_MAX_ACCURACY_M) {
    return `⚠️ دقة الموقع ضعيفة (${Math.round(acc)} متر) — اللوحات دي مش هتتصدّر. اطلع لمكان مكشوف.`;
  }
  return null;
}
