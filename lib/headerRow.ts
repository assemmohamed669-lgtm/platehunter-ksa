/**
 * headerRow — اختيار صف العناوين في ملف إكسيل.
 *
 * **ليه موجود:** الاختيار كان «أكتر صف خاناته مليانة» في أول ٥٠ صف. ده بيقع
 * في فخ بسيط: لو صف العناوين فيه **خانة فاضية واحدة** — يعني عمود بلا اسم —
 * بيبقى أقل بواحد من كل صف بيانات، فصف البيانات الأول بيكسب ويتحسب عناوين.
 *
 * حصلت في محفظة «التيسير المؤتمن الاول»: عمود اللوحة مالوش عنوان، فأول عربية
 * (ب ط م 3191) اتاكلت كاسم عمود و**اختفت من الفرز** — سيارة مطلوبة بتضيع
 * في صمت من غير ما حد يعرف.
 *
 * القاعدة: أقرب صف ناقص **على الأكتر خانة أو عُشر الأعمدة** من أعلى كثافة.
 * يعني عمود أو اتنين بلا اسم مابيخسّروش صف العناوين، لكن صف العنوان/التعليمات
 * اللي فوق الجدول (خانة أو اتنين من عشرين) بيفضل بعيد فبيتخطّى زي الأول.
 *
 * (حساب صحيح مش نِسَب عشان ٩٠٪ من ٥ أعمدة = ٤.٥، والعناوين الناقصة خانة من
 *  خمسة — وهي حالة الحادثة بالظبط — كانت هتقع تحتها.)
 */

/** أقصى عدد خانات فاضية مسموح بيها في صف العناوين (أو عُشر الأعمدة، الأكبر). */
function allowance(max: number): number {
  return Math.max(1, Math.round(max * 0.1));
}

/**
 * رقم صف العناوين المرشّح (اختيار بالكثافة). بيرجّع `0` للقايمة الفاضية.
 * @param scan أقصى عدد صفوف نبص فيها — بيمنع جدول مدفون بعدين من خطف العناوين.
 */
export function pickDenseHeaderRow(rows: unknown[][], scan = 50): number {
  const n = Math.min(rows.length, scan);
  if (n === 0) return 0;

  const filled: number[] = [];
  let max = 0;
  for (let i = 0; i < n; i++) {
    const c = (rows[i] ?? []).filter((v) => String(v ?? "").trim()).length;
    filled.push(c);
    if (c > max) max = c;
  }
  if (max === 0) return 0;

  const need = max - allowance(max);
  for (let i = 0; i < n; i++) if (filled[i] >= need) return i;
  return 0;
}
