/**
 * قيمة كلمة رقم واحدة، أو null لو الكلمة مش رقم.
 * الأرقام المكتوبة رقمياً («1234») بترجّع قيمتها كذلك.
 */
export function numberTokenValue(word: string): NumberToken | null {
  const raw = toWesternDigits(String(word)).trim();

  /**
   * 🔴 **Deepgram بيحطّ نقطة عشرية جوّه أرقام اللوحة.**
   *
   * من جلسة المالك ١٨ أغسطس: «راح عين ع **٦.٨** اربعة» و«الف س ص**1.511**».
   * والشرط اللي تحت (‎/^\d+$/‎) بيرفض أي رقم فيه نقطة، فالخانات **بتتشال
   * بالسكوت** واللوحة تضيع. «رعع6584» ضاعت بالطريقة دي بالظبط.
   *
   * واللوحة مافيهاش كسور — فـ«١.٥» معناها خانتين (١ و٥) مش واحد وخمسة
   * من عشرة. فبنشيل النقطة ونكمّل بالمنطق العادي.
   *
   * ⚠️ والشرط ‎\d+(\.\d+)+‎ مقصود: النقطة لازم تكون **بين رقمين**، فكلمة
   * فيها نقطة بس («...» أو «حاء.سين») ماتتحسبش رقم.
   */
  /**
   * ⚙️ مفتاح قياس: ‎PH_NO_DECIMAL_FIX=1‎ يرجّع السلوك القديم (الرقم بنقطة
   * يتشال) — عشان نقدر نقيس قبل/بعد على نفس الشريط.
   */
  const skipFix =
    typeof process !== "undefined" && process.env?.PH_NO_DECIMAL_FIX === "1";
  const noDots =
    !skipFix && /^\d+(\.\d+)+$/.test(raw) ? raw.replace(/\./g, "") : raw;
  if (noDots !== raw) {
    return { value: Number(noDots), isScale: false, isUnit: noDots.length === 1 };
  }

  // أرقام مكتوبة رقمياً
  if (/^\d+$/.test(raw)) {
    return {
      value: Number(raw),
      isScale: false,
      isUnit: raw.length === 1,
    };
  }

  const key = lookupKey(word);
  if (!key) return null;
  const direct = NUMBER_MAP.get(key);
  if (direct) return direct;

  /**
   * 🔴 **«وستين» و«واربعين» — العطف ملزوق بالكلمة.**
   *
   * Deepgram بيكتب «سبعة وسبعين» كلمتين: «سبعة» و«وسبعين». والصيغة
   * الملزوقة مكانتش في القاموس خالص، فالكلمة كانت **بتتشال بالسكوت**
   * والخانة تضيع: «سبعة وسبعين ستة سبعة» طلعت "767" بدل "7767".
   *
   * بنقبلها بقيمتها، وبنعلّمها إنها **موصولة** عشان تتجمع مع اللي
   * قبلها («خمسة وعشرين» = ٢٥) بدل ما تبقى خانة لوحدها.
   */
  if (key.length > 1 && key.startsWith("و")) {
    const inner = NUMBER_MAP.get(key.slice(1));
    if (inner && !inner.isUnit) return { ...inner, attachedConnector: true };
  }
  return null;
}

/**
 * 🔴 **«عشر» بتكمّل العدد، «عشرة» خانة لوحدها.**
 *
 * الاتنين قيمتهم ١٠، بس دورهم مختلف — والداتا الحقيقية بتفرّق بينهم:
 *     «خمسة عشر»            = ١٥       (عدد واحد)
 *     «أربعة أربعة عشرة»    = ٤·٤·١٠   ⇒ ديم4410 — لوحة مؤكّدة من
 *                                        قائمة المالك
 *     «ره ياء عين عشرة تلاتين» = ١٠·٣٠  ⇒ ريع1030 — لوحة مؤكّدة كذلك
 *
 * فـ«عشر» (بدون تاء) بتتصرّف زي الرابط: بتلزق باللي قبلها. و«عشرة»
 * خانة مستقلة زي أي رقم تاني.
 */
function isTeenSuffix(word: string): boolean {
  return lookupKey(word) === lookupKey("عشر");
}

/** هل الكلمة دي رقم (بأي شكل)؟ */
export function isNumberWord(word: string): boolean {
  return numberTokenValue(word) !== null;
}

/** رابط العطف «و» اللي بيجي جوّه العدد المركّب: «خمسة وعشرين» */
export function isNumberConnector(word: string): boolean {
  const key = lookupKey(word);
  return key === "و";
}

export interface NumberGroupResult {
  /** الأرقام كنص — ده اللي بيدخل في اللوحة */
  digits: string;
  /** تسلسل = أرقام ملزوقة ، مركّب = عدد محسوب */
  mode: "sequence" | "compound";
  /** القيمة المحسوبة (للمركّب فقط) */
  value?: number;
}

/**
 * يحوّل مجموعة كلمات أرقام متتالية لسلسلة أرقام.
 *
 *   ["واحد","اتنين","تلاتة","أربعة"] → "1234"   (تسلسل)
 *   ["ألفين","و","سبعمية"]            → "2700"   (مركّب)
 *   ["12","34"]                        → "1234"   (تسلسل)
 */
export function parseNumberGroup(words: string[]): NumberGroupResult {
  /**
   * الرابط **مش** مجرد فاصل — هو اللي بيقول أنهي كلمتين عدد واحد.
   * («خمسة وعشرين» = ٢٥ · «خمسة عشرين» = خانتين "٥" و"٢٠".)
   */
  const tokens: Array<{ word: string; info: NumberToken; joined: boolean }> = [];
  let pendingJoin = false;
  for (const w of words) {
    if (isNumberConnector(w)) {
      pendingJoin = true;
      continue;
    }
    const info = numberTokenValue(w);
    if (!info) {
      pendingJoin = false;
      continue;
    }
    tokens.push({
      word: w,
      info,
      joined: pendingJoin || Boolean(info.attachedConnector) || isTeenSuffix(w),
    });
    pendingJoin = false;
  }

  if (tokens.length === 0) return { digits: "", mode: "sequence" };

  // أرقام مكتوبة رقمياً بأكتر من خانة → تسلسل حرفي دايماً
  const hasMultiDigitLiteral = tokens.some(
    (t) => /^\d{2,}$/.test(toWesternDigits(t.word).trim())
  );

  // القاعدة الفاصلة: فيه أي كلمة قيمتها ١٠ أو أكتر؟
  const hasScaleOrTens = tokens.some((t) => t.info.value >= 10 || t.info.isScale);

  if (hasMultiDigitLiteral || !hasScaleOrTens) {
    // ── تسلسل: نلزق كل رقم ورا التاني
    let digits = "";
    for (const t of tokens) {
      const literal = toWesternDigits(t.word).trim();
      digits += /^\d+$/.test(literal) ? literal : String(t.info.value);
    }
    return { digits, mode: "sequence" };
  }

  /**
   * ── مركّب ─────────────────────────────────────────────────────────────
   *
   * 🔴 **الخانات بتتلزق، والعدد الواحد بس هو اللي بيتحسب.**
   *
   * الكود القديم كان بيجمع المجموعة كلها كعدد واحد أول ما يشوف كلمة
   * قيمتها ≥١٠. فـ«تلاتة اربعين ستة» بقت ٣+٤٠+٦ = **٤٩**، واللوحة
   * تطلع خانتين وتترمي على إنها ناقصة. تلات لوحات من السبعة الضايعين
   * في جلسة الـ٩٠ لوحة ضاعوا بالسبب ده بالظبط:
   *     «أربعة أربعة عشرة»   ⇒ ١٨   بدل ٤٤١٠
   *     «ستين تلاتة ستة»     ⇒ ٦٩   بدل ٦٠٣٦
   *     «تلاتة اربعين ستة»   ⇒ ٤٩   بدل ٣٤٠٦
   *
   * والفاصل هو **الرابط**: «خمسة وعشرين» عدد واحد (٢٥) لأن فيه «و»،
   * لكن «خمسة عشرين» خانتين ("٥" و"٢٠") لأن مافيش. فبنقسّم على
   * الروابط وبنلزق حصيلة كل عدد ورا التاني.
   */
  const parts: string[] = [];
  let total = 0;
  let pending = 0;
  let started = false;

  const flush = () => {
    if (!started) return;
    parts.push(String(total + pending));
    total = 0;
    pending = 0;
    started = false;
  };

  for (const t of tokens) {
    const { value, isScale } = t.info;
    // المُضاعِف بيكمّل اللي قبله دايماً («أربعة آلاف»)، والموصول كذلك
    if (!isScale && !t.joined) flush();
    started = true;
    if (isScale) {
      // مُضاعِف: يضرب اللي قبله (ولو مافيش حاجة قبله يبقى ١)
      total += (pending === 0 ? 1 : pending) * value;
      pending = 0;
    } else {
      // العربي بيقول الوحدات قبل العشرات: «سبعة وعشرين» = ٧+٢٠
      pending += value;
    }
  }
  flush();

  const digits = parts.join("");
  return { digits, mode: "compound", value: Number(digits) };
}
