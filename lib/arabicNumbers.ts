const AMBIGUOUS_ALF = new Set(["الف"].map(lookupKey));

/** خريطة موحّدة مبنيّة مرة واحدة */
const NUMBER_MAP = new Map<string, NumberToken>();

function register(
  table: Record<string, number>,
  opts: { isScale?: boolean; isUnit?: boolean }
) {
  for (const [word, value] of Object.entries(table)) {
    const key = lookupKey(word);
    if (!key || NUMBER_MAP.has(key)) continue;
    NUMBER_MAP.set(key, {
      value,
      isScale: Boolean(opts.isScale),
      isUnit: Boolean(opts.isUnit),
    });
  }
}

