/**
 * ==========================================================================
 *  محرك الأرقام المنطوقة — كل اللهجات
 * ==========================================================================
 *
 *  المندوب بينطق أرقام اللوحة بطريقتين مختلفتين تماماً:
 *
 *   ١. رقم رقم:      «واحد اتنين تلاتة أربعة»  →  1234
 *   ٢. عدد كامل:     «ألفين وسبعمية»            →  2700
 *
 *  والاتنين لازم يشتغلوا. الفرق بينهم إن الأول **تسلسل** (نلزق الأرقام)
 *  والثاني **مركّب** (نحسب القيمة). القاعدة اللي بنفرّق بيها:
 *
 *     لو كل كلمات المجموعة وحدات (٠-٩) → تسلسل
 *     لو فيها أي عشرة/مية/ألف        → مركّب
 *
 *  ليه القاعدة دي؟ لأن «خمسة واتنين» في سياق لوحة معناها 52 مش 7،
 *  لكن «خمسة وعشرين» معناها 25 قطعاً — ووجود «عشرين» هو الدليل.
 */

import { lookupKey, toWesternDigits } from "./voiceTextNormalize";

export interface NumberToken {
  /** القيمة الرقمية */
  value: number;
  /**
   * كلمة مُضاعِف: «مية» و «ألف» و «آلاف».
   * بتتصرف كضرب مش جمع: «أربعة آلاف» = 4 × 1000
   */
  isScale: boolean;
  /** وحدة من ٠ لـ ٩ — دي اللي بنبني بيها التسلسل */
  isUnit: boolean;
  /**
   * الكلمة ملتبسة مع اسم حرف.
   * «ألف» = الرقم ١٠٠٠ وكذلك اسم حرف الألف!
   * المحرك بيحلّها بالموقع: في خانة الحروف = حرف، في خانة الأرقام = رقم.
   */
  ambiguousWithLetter?: string;
  /**
   * العطف ملزوق بالكلمة: «وسبعين» بدل «و سبعين».
   * معناها إنها **بتكمّل العدد اللي قبلها** مش بتبدأ خانة جديدة.
   */
  attachedConnector?: boolean;
}

