/**
 * ══════════════════════════════════════════════════════════════════════
 *  🏷️ نوع اللوحة وملاحظتها — **من نصّ النافذة، بقصّ عند أرقام اللوحة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * ── العلّة ────────────────────────────────────────────────────────────
 * بلاغ المالك (٢٢ سبتمبر ٢٠٢٦) على صفحة «التسجيل الجديد (تجربة)»:
 *
 *     «أقول لوحة `حبك1234` — يحطّ قدامها **ونيت** وأنا مقولتهاش»
 *
 * صفحة التجربة كانت بتاخد النوع **بالتوقيت وحده**: كوهير بيمسح النافذة
 * (٥ ثواني) كلها ويرجّع أي نوع فيها، والصفحة بتلزّقه على أقرب لوحة.
 * والنافذة بتبدأ ٢.٥ث **قبل** مركزها — يعني أولها ذيل اللوحة اللي
 * قبلها. فنوع الجارة بيترحّل للوحة اللي المالك مقالش لها نوع.
 *
 * ── الحارس ───────────────────────────────────────────────────────────
 * الحل مش توقيت أدقّ — الحل إن النوع يتقصّ عند **أرقام لوحتنا** في نصّ
 * كوهير وناخد أول مطابقة بعدها. ده الحارس المقيس في المعمل على ١١١
 * حالة بحقيقة مكتوبة بإيد المالك:
 *
 *     القصّ نجح : صح ٧٥ · غلط ٤  ⇒ ٩٤.٩٪
 *     القصّ فشل : صح  ٦ · غلط ٩  ⇒ ٤٠.٠٪   ← بترجع فاضية **بالقصد**
 *
 * ⚠️ التمن مدفوع بوعي: بنخسر ٦ صح عشان نشيل ٩ غلط. السبب إن النوع
 *   الغلط بيتكتب في داتا المالك **في صمت**، والخانة الفاضية بتبان
 *   وتتملّى. دي نفس قاعدة المشروع: «لو مفيش نوع مؤكّد الخانة تفضل
 *   فاضية، مش نوع غلط».
 *
 * القرار اتشال برّه الصفحة عشان يتغطّى باختبار — نفس أسلوب
 * `trialModelGate` و`provisionalRow` (الصفحة مكوّن React ومالهاش اختبار).
 */

import { scanTypeAndNote } from "./vehicleTypeScan";

/**
 * 🏷️ **بُعد اللوحة عن مركز النافذة عشان النافذة تتسأل عن نوعها.**
 *
 * النافذة ٥ ثواني ومركزها `tMs`، فأي لوحة **جوّه** النافذة بعدها عنه
 * ≤ ٢.٥ث. كان الحد ١.٢ث — أضيق من النافذة نفسها، فلوحات في أطرافها
 * كانت بتضيّع نوعها، **و**في نفس الوقت كان بيسمح لنوع الجارة يعدّي
 * لأنه مكانش فيه أي شرط على المحتوى.
 *
 * دلوقتي اللي بيحكم هو القصّ عند أرقام اللوحة، فالتوسيع لـ٣ث آمن:
 * النافذة البعيدة مش هتدّي حاجة أصلاً لو أرقامنا مش في نصّها.
 */
export const TYPE_NEAR_MS = 3000;

/** نوافذ أقدم من كده مالهاش لزوم في الطابور (> ٤× البُعد المسموح). */
export const TYPE_QUEUE_KEEP_MS = 15000;

/** نافذة صوت واحدة: نصّ كوهير الخام + مركزها الزمني داخل الجلسة. */
export interface TypeWindow {
  text: string;
  tMs: number;
}

export interface TypePick {
  type: string | null;
  note: string | null;
}

/**
 * النوع/الملاحظة بتوع `plate` من أقرب نافذة **بتدّي نتيجة** —
 * مش أقرب نافذة وخلاص.
 *
 * 🔴 الفرق مهم: نافذة قريبة جداً ممكن تكون بتاعة اللوحة اللي قبلها
 * خالص. لو قصّينا عند أرقامنا ومالقيناش، بنعدّيها ونكمّل — بدل ما
 * نرجع فاضي ونضيّع نوع موجود في نافذة أبعد شوية.
 *
 * ⇒ ومافيش «استهلاك»: نافذة ٥ث ممكن تشيل **لوحتين**، وكل واحدة بتقصّ
 *   عند أرقامها هي. اللي بيمنع الكتابة فوق بعضها هو إن الصف اللي عنده
 *   نوع بيتخطّى في الصفحة، مش علامة على النافذة.
 */
export function pickTypeForPlate(
  queue: readonly TypeWindow[],
  plate: string,
  atMs: number
): TypePick | null {
  let best = Infinity;
  let pick: TypePick | null = null;
  for (const w of queue ?? []) {
    const d = Math.abs(w.tMs - atMs);
    if (d > TYPE_NEAR_MS || d >= best) continue;
    const sc = scanTypeAndNote(w.text, { afterPlate: plate });
    if (!sc.type && !sc.note) continue;
    best = d;
    pick = { type: sc.type, note: sc.note };
  }
  return pick;
}

/** بيشيل النوافذ القديمة — الطابور بيتقرا بنافذة زمنية بس. */
export function pruneTypeQueue(
  queue: readonly TypeWindow[],
  nowMs: number
): TypeWindow[] {
  const cut = nowMs - TYPE_QUEUE_KEEP_MS;
  return (queue ?? []).filter((w) => w.tMs >= cut);
}


/**
 * ══════════════════════════════════════════════════════════════════════
 *  🎯 نسأل سيرفر النوع **لكل لوحة**، مش لكل نافذة
 * ══════════════════════════════════════════════════════════════════════
 *
 * المندوب بيبعت نافذة كل ١.٥ث، واللوحة الواحدة بتتغطّى بـ٣-٤ نوافذ.
 * فالسؤال عن كل نافذة معناه **٣-٤ أضعاف** الشغل اللازم — وأغلبه على
 * نوافذ مالهاش لوحة أصلاً.
 *
 * وده مهم لأن سيرفر النوع طاقته **~٤ متوازي** (قياس ٢٣ سبتمبر ٢٠٢٦: عند
 * ١٠ مناديب كان بيرفض ٦٠٪ من الطلبات). التقليل هو اللي بيخلّيه يلحق.
 *
 * ⇒ بنخزّن آخر النوافذ، وأول ما الإجماع يأكّد لوحة بنبعت **واحدة بس** —
 *   أقربها لزمن اللوحة.
 */

/** أطول مدة نحتفظ فيها بنافذة صوت مستنية لوحة تتأكّد. */
export const TYPE_BUF_KEEP_MS = 15_000;

/**
 * 🔴 أبعد ما تكون النافذة عن اللوحة وتفضل صالحة.
 * النافذة ٥ث، فاللي أبعد من كده مافيهاش صوت اللوحة أصلاً — والنوع الغلط
 * أوحش من الخانة الفاضية (قاعدة المشروع المتكرّرة).
 */
const MAX_PICK_GAP_MS = 5_000;

export interface AudioWindow<T = unknown> {
  tMs: number;
  wav: T;
}

/** أقرب نافذة للوحة — أو `null` لو كلها بعيدة. */
export function nearestWindow<T>(
  windows: readonly AudioWindow<T>[],
  atMs: number,
): AudioWindow<T> | null {
  let best: AudioWindow<T> | null = null;
  let bestGap = Infinity;
  for (const w of windows ?? []) {
    const gap = Math.abs(w.tMs - atMs);
    if (gap < bestGap) { bestGap = gap; best = w; }
  }
  return best && bestGap <= MAX_PICK_GAP_MS ? best : null;
}

/** بيشيل النوافذ القديمة من المخزن. */
export function pruneWindows<T>(
  windows: readonly AudioWindow<T>[],
  nowMs: number,
): AudioWindow<T>[] {
  return (windows ?? []).filter((w) => nowMs - w.tMs <= TYPE_BUF_KEEP_MS);
}
