/**
 * ══════════════════════════════════════════════════════════════════════
 *  «نفس الأرقام + حرفين مختلفين» خلال ثواني = نفس العربية — **والأقدم صح**
 * ══════════════════════════════════════════════════════════════════════
 *
 * جلسة المالك (٢٣ سبتمبر ٢٠٢٦ · ١٠٠ لوحة): زيادتين — `ردد5899` جنب
 * `بصد5899` و`بنق6617` جنب `دمق6617`. `sameCarTwin` بيلمّ **حرف واحد بس**
 * لو الأرقام متطابقة («مشدود عن قصد»)، فالحرفين كانوا بيطلعوا صفّين.
 *
 * 📏 **اتقاس على ٦ جلسات بحقيقة المالك (٣٣٢ لوحة)** — مش مفترض:
 *
 *     القاعدة                    صح   زيادة  ضايعة
 *     الحالي                     324   11      8
 *     الأقوى يكسب · ٥ث            323    9      9    🔴 لوحة حقيقية ضاعت
 *     الأقدم يكسب · ٥–١٢ث         324    8      8    ✅ ٣ اتشالوا · صفر خسارة
 *
 * 🔴 **ليه الأقدم مش الأقوى**: في الـ٣ أزواج (٣/٣) **الأرقام صح والحروف غلط،
 * والغلط هو المتأخّر**. الحروف في **أول** اللوحة، والنافذة اللي بتيجي بعدها
 * زاحفت لقدّام فبتقصّ بداية الكلام ⇒ الحروف تضيع والأرقام تفضل.
 * و`بنط9093` الغلط كان عنده نوافذ **أكتر** (٣ مقابل ١) — فـ«الأقوى يكسب» كان
 * بيشيل **الصح** (دي اللي خلّت «الأقوى · ٥ث» يخسر لوحة).
 *
 * ⚠️ العيّنة ٣ أزواج — الآلية منطقية بس مش قانون. تتقاس تاني مع جلسات أكتر.
 *
 * **طريقة القياس** (عشان تتعاد): الصفوف اللي **ظهرت فعلاً** في تقارير المالك
 * الـ٦ (٢٢–٢٣ سبتمبر) اتعادت بالترتيب الزمني بالقاعدة، والنتيجة اتقارنت
 * بحقيقته المكتوبة بإيده (عدّ متعدّد عشان الإعادة المقصودة). ملفات الجلسات
 * **مش في الريبو عن قصد** — فيها إحداثيات موقع المالك.
 */

const WELL = /^[ء-ي]{3}\d{4}$/;

/**
 * **٨ ثواني.** أقصى فرق بين قرايتين لنفس العربية في القياس = **٥ث**، وأقل فرق
 * بين عربيتين **حقيقيتين** بنفس الأرقام في حقيقة المالك = **٣٨ث**
 * (`ححه7518` / `حرب7518`). ٨ فوق الـ٥ بهامش وتحت الـ٣٨ بكتير — والنتيجة
 * كانت نفسها بالظبط من ٥ لـ١٢ث، فمش حسّاس للرقم.
 */
export const LETTER_TWIN_MS = 8_000;

export interface LetterTwinRow {
  id: string;
  plate: string;
  /** زمن النطق (مللي) — مش وقت الوصول. */
  atMs: number;
  provisional: boolean;
  mult: number;
  match: Record<string, string> | null;
  edited?: { plate?: boolean; type?: boolean; note?: boolean };
}

function letterDiff(a: string, b: string): number {
  let n = 0;
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) n += 1;
  return n;
}

/**
 * نفس الأرقام الأربعة بالظبط + **حرفين بالظبط** مختلفين + خلال المهلة.
 *
 * حرف واحد مش شغلتها (`sameCarTwin` بيعمله)، وتلاتة = عربية تانية غالباً
 * (`رنا6948`/`حور6948` في حقيقة المالك عربيتين حقيقيتين).
 */
export function isLetterTwin(
  a: { plate: string; atMs: number },
  b: { plate: string; atMs: number },
  windowMs: number = LETTER_TWIN_MS,
): boolean {
  const pa = String(a?.plate ?? ""), pb = String(b?.plate ?? "");
  if (!WELL.test(pa) || !WELL.test(pb)) return false;
  if (pa.slice(3) !== pb.slice(3)) return false;
  if (letterDiff(pa, pb) !== 2) return false;
  return Math.abs((a.atMs ?? 0) - (b.atMs ?? 0)) <= windowMs;
}

/**
 * يحسم التوأم: **اللي اتقال الأول يكسب** (بـ`atMs` — زمن النطق مش الوصول).
 *
 * - الـid بتاع الصف **الموجود** يفضل (نفس قاعدة `mergeTwinRow`: الهوية ثابتة
 *   عشان المنسدلة المفتوحة ماتتقفلش واختيار المندوب مايضيعش)
 * - ✋ المندوب صحّح اللوحة بإيده ⇒ تصحيحه يغلب أي حاجة
 * - 🔴 **الصف بيتأكّد لو أي واحد مؤكّد**: المتأخّر دليل إن العربية اتقالت —
 *   حروفه غلط بس وجوده صح. من غير ده، الأقدم لو مبدئي كان كنس الـ١٢ث هيمسحه
 *   ⇒ العربية تختفي خالص (ضياع بدل زيادة — أسوأ)
 */
export function resolveLetterTwin<T extends LetterTwinRow>(existing: T, fresh: T): T {
  const earlier = existing.atMs <= fresh.atMs ? existing : fresh;
  const manual = existing.edited?.plate === true;
  const winner = manual ? existing : earlier;
  return {
    ...existing,
    plate: winner.plate,
    match: winner.match,
    atMs: Math.min(existing.atMs, fresh.atMs),
    provisional: existing.provisional && fresh.provisional,
    mult: Math.max(existing.mult, fresh.mult),
  };
}
