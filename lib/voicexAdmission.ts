/** مصدر النافذة — بيحدّد أولويتها. */
export type VoicexSource = "utterance" | "window";

/**
 * · `send`  — ابعت دلوقتي
 * · `queue` — استنى دورك (لقراءة النطق **بس**)
 * · `skip`  — اتخطّى (للنافذة الزاحفة بس — ومطلوب يتسجّل، مش يتبلع)
 */
export type VoicexAdmission = "send" | "queue" | "skip";

export interface VoicexAdmissionInput {
  source: VoicexSource;
  /** كام طلب طاير دلوقتي */
  inflight: number;
  /** سقف الطلبات المتوازية — لازم يساوي سقف السيرفر أو أقل */
  maxInflight: number;
  /** فيه قراءة نطق مستنية دورها؟ */
  utteranceQueued: boolean;
}

/** سقف بايظ (صفر/سالب/NaN/∞) = ١ — أقل ضرر، مش صفر اللي بيقفل كل حاجة. */
function capOf(n: number): number {
  return Number.isFinite(n) && n >= 1 ? Math.floor(n) : 1;
}

/**
 * عدّاد بايظ = «مشغول» — تحفّظاً. ومايقدرش يرمي قراءة نطق لأن قراءة النطق
 * عمرها ما بترجّع `skip` أصلاً.
 */
function busyOf(n: number, cap: number): number {
  return Number.isFinite(n) && n >= 0 ? Math.floor(n) : cap;
}

export function planVoicexAdmission(input: VoicexAdmissionInput): VoicexAdmission {
  const cap = capOf(input?.maxInflight);
  const inflight = busyOf(input?.inflight, cap);
  const free = inflight < cap;

  if (input?.source === "utterance") {
    // 🔴 العقد: قراءة النطق **عمرها ما تترمى**. مفيش فرع بيرجّع `skip`.
    return free ? "send" : "queue";
  }

  // النافذة الزاحفة بتتنازل لقراءة النطق حتى لو فيه مكان — عشان السلوت
  // يفضل فاضي لما القراءة المستنية تلاقي دورها بدل ما نزنقها تاني.
  if (input?.utteranceQueued) return "skip";
  return free ? "send" : "skip";
}
